//
// ── 왜 따로 있나 (2026-08-20) ────────────────────────────────────────────────
// 원래 `measure-invariants.mjs` 안에 있었다. 뺀 이유는 줄 수가 아니라 **성격**이다 —
// 이 값들은 «무엇을 재는가» 가 아니라 «어디까지 재고 포기하는가» 이고, 그 판정은 씬이
// 무거워질 때마다 다시 열린다(실제로 2026-08-20 에 열렸다). 측정 절차와 섞여 있으면
// 그 판정 기록이 절차 코드 사이에 흩어지고, 절차를 읽는 사람이 예산을 못 찾는다.
//
// `frontend/js/world2/decide/` 가 «판정을 순수 함수로 떼어 둔다» 로 같은 일을 한다.
//
// ⚠ **값을 소비자에 다시 적지 않는다.** 여기가 SSOT 다.

/** 직진 구간 수. 파셀 경계를 여러 번 넘어야 스트리밍 증식이 드러난다 */
export const WALK_LEGS = 6;
/** 한 leg 를 걷는 시간(ms) */
export const WALK_MS = 1500;

// ── 커버리지 목표 — **G-COL1** (검수관 반려 B1, 2026-08-08) ──────────────────
//
// 왜 목표가 필요한가: 이 세션은 오래 *"-z 로 6번 전진"* 이었고, 그것을 **주행이라고
// 불렀을 뿐 주행인지 확인한 적이 없다.** 플레이어 충돌(#182)이 붙자 스폰 앞 분수대에서
// 6.9m 만 걷고 멈췄고 — 파셀을 한 칸도 새로 안 밟았는데 — 게이트는 **PASS 로 보고했다.**
// 개수가 늘지 않은 것은 사실이었다. 아무 데도 안 갔으니까.
//
// 그래서 "몇 미터 걸었나" 가 아니라 **"파셀을 몇 개 밟았나"** 를 판정으로 만든다.
// 미터는 배치·속도·프레임률에 흔들리지만 파셀은 스트리밍의 단위 그 자체다 — `[7]` 이
// 잡으려는 증식(슬롯 재사용 실패·재방문 누적)이 정확히 그 경계에서 일어난다.
//
// ⚠ **이 판정은 성능 축이 아니라 하드 실패다.** `SMOKE_PERF_GATES=observe` 에서도
// INFO 로 내려가지 않는다(`run.mjs` 의 `perfStatus` 가 `hard` 로 받는다). observe 의
// 정당화는 *"러너 성능 편차의 거짓 FAIL"* 인데, **세션이 안 움직인 것은 편차가 아니다.**
//

/** 고유 파셀 목표. 3 이면 "출발 칸 + 새 칸 둘" 이다 — 경계를 최소 두 번 넘는다 */
export const COVER_UNIQUE = 3;
/** 재방문 목표. 슬롯 반납 실패는 **다시 들어갈 때**만 드러난다 */
export const COVER_REVISITS = 1;
/** 이 leg 에서 실제로 움직인 거리(m)가 이보다 작으면 막힌 것으로 본다 */
export const STUCK_M = 1.0;
/**
 * 한 구간(전진·복귀)에 쓸 수 있는 **시간** 예산(ms). 상한의 목적은 «무한 대기 금지» 이고,
 * 그것은 leg 개수가 아니라 **시간**으로 표현하는 것이 맞다.
 *
 * ── 왜 개수에서 시간으로 옮겼나 (2026-08-20 실측) ────────────────────────────
 * 예전 값은 `MAX_LEGS = 24` 라는 **개수**였다. 실측(19 leg)에 여유를 얹은 값이고, 이
 * 저장소의 규율이 정확히 그 형태를 경계한다 — *"실측은 밟아본 경로의 최댓값일 뿐 도달
 * 가능한 최댓값이 아니다."* 그리고 실제로 도달했다: world2 수면에 환경맵을 켠 회차에서
 * **CI 가 24 를 소진하고 고유 파셀 2 에서 끝나** 게이트가 FAIL 했다.
 *
 *     origin/main            전진 16 leg
 *     환경맵 OFF(`?wenv=0`)  전진 17 · 17
 *     환경맵 ON(기본)        전진 20 · 21   ← 상한 24 에 여유 3
 *
 * 원인은 배치도 스폰도 아니다. `world2/kernel.ts` 가 `dt` 를 **0.1초로 클램프**한다(탭
 * 복귀 시 거대 dt 방지 — 그 자체는 옳다). 헤드리스는 CPU 래스터라이저라 환경맵이 붙으면
 * 프레임 시간이 100ms 를 넘고, **넘은 만큼이 통째로 버려져 게임 내 시간이 벽시계보다
 * 느리게 흐른다.** 같은 `WALK_MS` 에 덜 이동하니 leg 를 더 쓴다.
 *
 * 즉 개수 상한은 **개수 게이트 안에 헤드리스 프레임률 게이트를 몰래 들여놓고 있었다.**
 * 이 저장소는 성능 축을 `[7][7.6][8]` 에서 의도적으로 뺐고(§10-3), 프레임 시간은
 * *"swiftshader 는 실기기와 무관"* 이라 아예 안 잰다 — 그런데 leg 상한이 뒷문으로 그것을
 * 재고 있었다. **재는 축이 섞인 것이다.** 시간으로 두면 `WALK_MS` 를 바꿔도 따라온다.
 *
 * ── 여기서 멈춘다 ───────────────────────────────────────────────────────────
 * 60초도 유도된 값은 아니다 — 필요 leg 수는 씬 무게에 의존하고 그것은 예측 불가다.
 * **다만 개수와 달리 목적과 같은 단위다.** 이 값을 만지는 사람은 «몇 초까지 기다릴
 * 것인가» 라는 답할 수 있는 질문을 받는다. 예전 값의 질문(«몇 번까지 걸을 것인가»)에는
 * 답할 근거가 아무 데도 없었다.
 *
 * ⚠ **다시 올리기 전에 먼저 물어라 — 「무엇이 느려졌는가」.** 상한 소진은 신호이고,
 * 올리는 것은 그 신호를 끄는 일이다. 이번에는 원인을 확정한 뒤에 올렸다.
 */
export const MAX_WALK_MS = 60_000;
/** 목표를 채우려고 늘릴 수 있는 최대 leg 수. **시간 예산에서 유도한다** */
export const MAX_LEGS = Math.floor(MAX_WALK_MS / WALK_MS);

/**
 * 헤드리스에서 **실제로 관측된** 최대 전진 leg. 2026-08-20 실측(환경맵 ON, 4코어·GPU 0).
 *
 * ⚠ **이 값은 `MAX_LEGS` 의 근거가 아니다** — 그랬다면 «실측에 여유를 얹은 값» 이 되고,
 * 그것이 예전 `MAX_LEGS = 24` 를 만든 형태다(그리고 도달당했다). `MAX_LEGS` 는 위에서
 * **시간으로 유도**한다. 이 상수는 방향이 반대다: *"유도한 값이 실측을 담고도 남는가"*
 * 를 `tests/session-budget.test.ts` 가 확인하는 **대조 기준**이다.
 *
 * ⚠⚠ **이 상수는 손으로 갱신해야만 작동한다 — 자동 감지가 아니다**(검수관 조건 2,
 * 2026-08-20). 첫 판본은 이 자리에 *"씬이 무거워져 이 값이 오르면 테스트가 먼저 빨간불이
 * 된다"* 라고 적었고, 그 문장은 **자동으로 읽힌다.** 실제로는 라이브 관측과 아무 배선도
 * 없는 손기록이라, 검수관이 이 값을 `10` 으로 낮추는 뮤테이션을 돌리자
 * `tests/session-budget.test.ts` **3건이 전부 통과했다.** 낮게 적어두거나 갱신을
 * 잊으면 그 순간 이 축의 검출력은 **0** 이 된다.
 *
 * 그러므로 이것은 게이트가 아니라 **기록**이다. 새 회차에서 leg 를 실측하면 **여기를
 * 먼저 갱신하고** 테스트를 돌린다 — 그때 빨간불이 나면 «무엇이 느려졌는가» 를 묻고,
 * 답한 뒤에 예산을 다시 본다(위 `MAX_WALK_MS` 의 마지막 문단).
 *
 * 자동으로 만들 수 있나 — 스모크가 실측 leg 를 산출물로 뱉고 그것을 이 값과 대조하면
 * 된다. 안 한 이유는 이번 회차에 게이트를 더 늘리면 판정이 흐려지기 때문이고,
 * **안 했다는 사실을 여기 적어 둔다**(백로그 `G-SMK1`).
 */
export const OBSERVED_MAX_LEGS = 21;

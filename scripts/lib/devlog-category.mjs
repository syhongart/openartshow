export const FALLBACK = { id: 'misc', emoji: '🛠️', label: '기타' };

/** id → 카테고리. 소비자가 목록을 다시 순회하지 않게. */
export const BY_ID = new Map([...CATEGORIES, FALLBACK].map((c) => [c.id, c]));

/**
 * 제목 앞의 명시 태그. `[perf] 제목` 처럼 쓴다.
 * 자동 규칙이 틀리게 잡을 때의 탈출구다 — 규칙을 무한히 키우는 대신 이걸 쓴다.
 * `[법무]` 는 태그가 아니라 본래 제목의 일부이므로(기존 항목 3건) id 목록에
 * 없는 것은 태그로 치지 않는다.
 */
const TAG_RE = /^\s*\[([a-z][a-z0-9-]*)\]\s*/i;

/** 제목에서 명시 태그를 떼어낸 표시용 제목. 태그가 없으면 원문 그대로. */
export function stripTag(title) {
  const m = title.match(TAG_RE);
  return m && BY_ID.has(m[1].toLowerCase()) ? title.slice(m[0].length) : title;
}

/**
 * 제목 → 카테고리 객체. `★` 접두는 여기서 보지 않는다(표시 축과 슬러그 축은 분리).
 * @param {string} rawTitle `★` 를 이미 뗐든 안 뗐든 무관 — 여기서 한 번 더 턴다.
 */
export function categorize(rawTitle) {
  const title = String(rawTitle).replace(/^★+\s*/, '').trim();
  const tag = title.match(TAG_RE);
  if (tag) {
    const hit = BY_ID.get(tag[1].toLowerCase());
    if (hit) return hit;               // 명시 태그가 자동 규칙을 이긴다
  }
  return CATEGORIES.find((c) => c.re.test(title)) || FALLBACK;
}

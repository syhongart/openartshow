// world2/ui/stick-look.ts — 가상 조이스틱의 **룩만** 여는 노브(`?stick=`).
//
// ── 왜 노브인가 (감독 신고 2026-08-23 «조이스틱에 통일감이 없잖아. 다른것과..») ──
// 이 저장소의 의사결정 규율이 *"설명하지 말고 만들어서 배포한다 · 후보를 여럿 동시에
// (`?노브=`) · 감독이 비교할 수 있어야 판정이 빠르다"* 다. 룩은 글로 설득이 안 되고,
// 특히 이 화면은 **내가 볼 수 없다** — world2 는 WebGPU 이고 이 개발 환경에는
// `navigator.gpu` 가 없다. 헤드리스는 WebGL 폴백이라 색이 그대로라는 보장이 없다.
//
// ── 축은 「통일 강도」 하나다. 단조롭게 정렬돼 있다 ──────────────────────────
//   `jelly`   (대조군·현행) 흰 유리 링 + 2색 그라디언트 노브. 토큰을 하나도 안 쓴다
//   `outline` 토큰만 채택   — 링 투명 + `--line` 테두리, 노브 어두운 채움 + 보라 테두리
//   `tint`    world2.html 어휘 — 링 유리판 채움, 노브 보라 **틴트**(`.w2-god-row button.on`)
//   `plate`   편집 패널 어휘  — 링 유리판 + blur, 노브 **단색** `--violet`(`button[data-on="1"]`)
//
// 갈리는 것은 **노브의 강조 방식**(2색 그라디언트 / 보라 테두리 / 보라 틴트 / 보라 단색)
// 이고, 링은 `jelly` 만 흰색 계열이고 나머지 셋은 전부 어두운 유리다. 한 축에 넷을 세워야
// 감독이 «어디까지 맞출까» 를 한 번에 고른다 — 하나씩 물으면 판정이 네 번 든다.
//
// ⚠ **레이아웃은 이 노브의 사정거리 밖이다.** 원 112px · 노브 46px · 구역 44vw ·
// 조준 회피 140px 은 각각 엄지 크기 · 검수관 블로커 · 헤드리스 4기기 실측에서 나온 값이고
// 근거가 `world2.html` 의 그 값 옆에 길게 적혀 있다. 여기는 **색·질감·테두리만** 연다.
//
// ⚠⚠ CSS 는 `world2.html` 의 인라인 `<style>` 에 있다(조이스틱 규칙이 원래 거기 있고,
// 룩만 딴 파일로 떼면 다음 사람이 두 곳을 봐야 한다). 그래서 이 파일의 `STICK_LOOKS` 와
// 그쪽 셀렉터는 **미러링**이다 — 한쪽만 고치면 아무도 모른다. 그 미러링을
// `tests/world2-touch-controls.test.ts` 의 `GS-J7` 이 양방향으로 대조한다.

import { readEnum } from '../url-knob.js';

/**
 * 허용 목록. **순서가 곧 「통일 강도」 오름차순이다**(파일 헤더의 축).
 *
 * 목록 밖 값이 오면 `readEnum` 이 기본값으로 되돌린다 — 주소창에 오타를 내도 화면이
 * 깨지지 않는다(`?stick=플레이트` 가 셀렉터에 그대로 들어가면 아무 규칙도 안 걸려
 * 링이 통째로 사라진다. 그 실패는 «조이스틱이 고장났다» 로만 드러나 원인을 못 찾는다).
 */
export const STICK_LOOKS = ['jelly', 'outline', 'tint', 'plate'] as const;
export type StickLook = (typeof STICK_LOOKS)[number];

/**
 * 🔴 **화면 판정 전 시작값이다 — 「판정된 값」이 아니다.**
 *
 * 감독이 아직 네 후보를 안 봤다. 내가 `tint` 를 시작값으로 고른 근거는 둘뿐이다:
 *   ① 조이스틱은 `world2.html` 의 요소이고, **같은 파일 안의 다른 UI 여덟 개**(HUD 토글·
 *      HUD 패널·지도 책갈피·진입 바·하늘 패널·개발자 옵션 바·그 안의 활성 버튼)가 전부
 *      「어두운 유리판 + `--line` + 보라 **틴트** 강조」다. 가장 가까운 이웃과 맞추는 것이
 *      「통일」의 1차 정의다. (`plate` 의 단색 채움은 `edit/panel/css.ts` 쪽 어휘다 —
 *      그 둘이 이미 서로 다르다는 것 자체가 이번 회차의 발견이고, 보고에 올렸다.)
 *   ② 반투명이라 손가락 밑에서 세계를 덜 가린다. 조이스틱은 패널과 달리 **3D 위에 뜬다**.
 *
 * **둘 다 화면을 안 보고 한 판단이다.** 감독이 `?stick=` 으로 넷을 비교해 고르면 그 값을
 * 여기에 옮기고, 이 주석을 「감독 판정 2026-…」으로 바꾼다. 그전까지 다음 사람은 이 값을
 * 근거로 «조이스틱 룩은 정해졌다» 고 읽으면 안 된다.
 */
export const DEFAULT_STICK_LOOK: StickLook = 'tint';

/** `?stick=` 을 허용 목록 안에서 읽는다. 없거나 목록 밖이면 시작값. */
export function readStickLook(): StickLook {
  return readEnum<StickLook>('stick', DEFAULT_STICK_LOOK, STICK_LOOKS);
}

/**
 * 고른 룩을 원(`#w2-stick`)에 `data-look` 으로 새긴다. CSS 가 그것을 본다.
 *
 * ── 왜 `<html>` 이 아니라 원 자신인가 ──────────────────────────────────────
 * 루트에 새기면 이 노브가 페이지 전역 스위치처럼 보이고, 다음 사람이 «다른 것도 여기
 * 걸자» 를 하게 된다. 룩이 걸리는 요소가 하나면 그 요소가 들고 있는 것이 맞다.
 *
 * ── 왜 CSS 기본값(= `tint`)을 따로 두는가 ──────────────────────────────────
 * 이 함수가 안 돌아도(스크립트 실패·차단) 조이스틱은 시작값 룩으로 보여야 한다. 그래서
 * `world2.html` 의 **속성 없는** 규칙이 `tint` 이고, 나머지 셋만 `[data-look=…]` 로 덮는다.
 * `tint` 를 명시적으로 새기는 것도 무해하다 — 덮는 규칙이 없어 기본 규칙이 그대로 산다.
 */
export function applyStickLook(base: HTMLElement | null | undefined, look = readStickLook()): void {
  if (!base) return;
  base.dataset.look = look;
}

// world2/parts/plaza.ts — 광장 판정. 순수 함수만.
//
// ── 왜 광장인가 ──────────────────────────────────────────────────────────────
// 감독 지적 *"건물이 빽빽하다"* 의 셋째 원인이 **숨 쉴 곳이 없다** 였다. 채수 하한이 2라
// "아무것도 없는 구획" 이 구조적으로 존재할 수 없었고, 하한을 1로 내린 뒤에도 어느 파셀에나
// 최소 한 채는 선다.
//
// 광장은 그 예외다. 건물이 0인 파셀을 의도적으로 섞어, 걷다 보면 트인 곳이 나오게 한다.
//
// ── 길이 닿는 곳에만 둔다 ────────────────────────────────────────────────────
// 도로가 하나도 없는 파셀은 광장이 될 수 없다. 갈 수 없는 광장은 광장이 아니라 그냥
// 빈 땅이고, 오픈월드에서 그건 "아직 안 만든 곳" 으로 읽힌다.
//
// 실제 도시의 광장도 길이 모이는 자리에 있다. 이 조건 하나로 그 성질이 따라온다.
//
// ── 배치가 아니라 판정이다 ───────────────────────────────────────────────────
// 광장이라는 사실을 여러 파츠가 소비한다 — 건물은 서지 않고, 나무·벤치는 오히려 모인다.
// 그래서 파츠마다 따로 정하지 않고 여기서 한 번 정한다. 도로가 `road-topology.ts` 를,
// 물이 `decide/water.ts` 를 SSOT 로 두는 것과 같은 배치다.

import { roadDirs } from './road-topology.js';

/**
 * 광장 확률(길이 닿는 파셀 기준).
 *
 * 길 없는 파셀이 2.6% 이므로 전체에서 실제 광장은 `0.974 × 0.06 ≈ 5.8%` 다. 열일곱
 * 파셀에 하나꼴이라, 근거리에 16개 남짓 떠 있는 상태에서 시야에 하나쯤 들어온다.
 *
 * 이 값은 **디자이너 육안 판정으로 정할 값**이다. 너무 높으면 도시가 듬성해지고, 낮으면
 * 있으나 마나다. 6% 는 출발점이다.
 */
export const PLAZA_P = 0.06;

const SALT_PLAZA = 0x3b9aca07;

function h2(a: number, b: number, salt: number): number {
  let h = salt >>> 0;
  h = Math.imul(h ^ (a | 0), 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h ^ (b | 0), 0xc2b2ae35);
  h ^= h >>> 16;
  h = Math.imul(h, 0x27d4eb2d);
  return (h ^ (h >>> 15)) >>> 0;
}

/** 이 파셀이 광장인가. 길이 하나도 없으면 아니다 — 갈 수 없는 광장은 빈 땅이다. */
export function isPlaza(px: number, pz: number, p: number = PLAZA_P): boolean {
  if (roadDirs(px, pz).length === 0) return false;
  return h2(px, pz, SALT_PLAZA) / 4294967296 < p;
}

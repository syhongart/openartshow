// 지면 — 파셀 한 칸을 통째로 덮는 판.
//
// 유일하게 개수가 고정(1)이고 위치도 고정이다. 그래서 난수를 색조 하나에만 쓴다.
// 여기에 틈이 생기면 아래 허공이 보이므로 셀 크기를 **정확히** 덮는다(여백 적용 안 함).

import type { PartSpec } from './types.js';

/**
 * 지면 판의 두께(미터). **물가에서 보이는 흙벽의 높이**가 이 값이다.
 *
 * ── 감독 지적에서 정해졌다 ─────────────────────────────────────────────────
 * *"강과 바다 땅보다 더더 아래. 50센치 밑에있게해줘."*
 *
 * 그런데 물은 **이미** 아래에 있었다(`SEA_Y`, 당시 −1.2m). 화면에서 붙어 보인 이유는
 * 이 값이 **0.1m** 였기 때문이다. 물 파셀은 로드되지 않고 그 구멍으로 물판이 비치는
 * 구조라(`features/ocean.ts`), 물가에서 보이는 것은 육지 파셀의 **옆면**뿐이다. 그
 * 옆면이 10cm 면 원근상 없는 것과 같아서, 물이 아무리 깊어도 잔디와 수면이 한
 * 평면처럼 읽힌다.
 *
 * 그래서 고칠 것은 물 높이가 아니라 **여기**였다. 당시 `SEA_Y` 를 감독이 말한 −0.5m 로
 * 맞추고, 이 판을 그보다 깊게(0.8m) 만들어 수면 아래까지 내렸다. 그러면
 *
 * **그 뒤 물 높이가 다시 갈렸다(2026-07-30 감독 지시)** — 강 −0.5m / 바다 −1.0m 로
 * 분리됐다(`decide/water.ts` 의 `RIVER_Y`·`SEA_Y`). 위 문단의 "−0.5m" 는 그 시점의
 * 기록이고, 지금 그 값에 해당하는 것은 **강**이다. 이 판의 깊이(0.8m)는 강 수면보다
 * 깊지만 바다 수면(−1.0m)보다는 얕아졌다 — 바닷가에서 옆면이 수면 위로 20cm 드러난다.
 * 그것이 어색한지는 육안 판정 대상이다(팀장 조건 1).
 *
 *   지면 상면 0 → 수면 −0.5   : 감독이 말한 50cm 단차가 눈에 보이고
 *   판 아랫면 −0.8            : 수면보다 30cm 더 내려가 물가에 틈이 생기지 않는다
 *
 * 삼각형은 그대로다(박스의 크기만 바뀐다).
 */
export const GROUND_DEPTH = 0.8;

export const ground: PartSpec = {
  kind: 'ground',
  tiers: ['near', 'mid', 'far'], // 지면이 없으면 파셀이 구멍으로 보인다
  salt: 0x9e3779b9,
  // ── 낮 팔레트로 (감독 실기기 판정) ──────────────────────────────────────────
  // 예전 값은 `0x2a3140` 계열의 짙은 남색이었다. **도로 텍스처 베이스가 `#2a2d33`
  // 이므로 명도 차이가 3% 밖에 안 났다** — 길과 땅이 사실상 같은 색이었고, 그것이
  // 감독이 말한 *"바닥 격자 바닥이 잘 드러나지 않아"* 의 정확한 원인이다.
  //
  // 정원을 넣은 것은 증상 완화였다. 초록 판이 검은 바닥에 스티커처럼 떠 있었고,
  // 실기기 화면이 그 모습이었다. 원인은 지면 자체가 **야간 팔레트**인데 하늘은
  // 낮이라는 것이었다.
  //
  // 도로는 손대지 말라는 지시대로 두고 땅만 밝힌다. 명도 40% 대의 따뜻한 회갈색이면
  // 아스팔트(17%)와 확실히 갈리면서 잔디(정원)와도 어울린다.
  tones: [0x6b6659, 0x746f61, 0x625e52],

  // 바닥에 깔리는 평면 — 그 위에 물건이 서는 것이 정상이라 겹침 개념이 없다.
  footprint: () => 0,

  maxPerParcel: () => 1,

  place: ({ rnd, o }) => [{
    kind: 'ground',
    x: 0, z: 0, y: 0, ry: 0,
    sx: o.cellX, sy: GROUND_DEPTH, sz: o.cellZ,
    tone: Math.floor(rnd() * 3),
  }],

  // 지면만 피벗이 위쪽이다 — 판이 y=0 **아래로** 깔려야 그 위를 걷는다.
  asset: (T) => ({
    geometry: new T.BoxGeometry(1, 1, 1).translate(0, -0.5, 0),
    material: new T.MeshStandardMaterial({ roughness: 0.95, metalness: 0.05 }),
    castShadow: false,
    receiveShadow: true,
  }),
};

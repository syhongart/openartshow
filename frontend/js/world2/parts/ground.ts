// 지면 — 파셀 한 칸을 통째로 덮는 판.
//
// 유일하게 개수가 고정(1)이고 위치도 고정이다. 그래서 난수를 색조 하나에만 쓴다.
// 여기에 틈이 생기면 아래 허공이 보이므로 셀 크기를 **정확히** 덮는다(여백 적용 안 함).

import type { PartSpec } from './types.js';
import { SEABED_Y } from '../decide/water.js';

/**
 * 지면 판이 **수면 아래로 더 내려가는 여유**(미터).
 *
 * 이 값이 0 이면 판 아랫면이 수면과 정확히 같은 높이가 되고, 물결·시야각·깊이 정밀도가
 * 조금만 흔들려도 그 경계에 실틈이 보인다. 30cm 면 어느 각도에서도 판이 수면보다 확실히
 * 아래에 있다.
 */
const SUBMERGE_MARGIN = 0.3;

/**
 * 지면 판의 두께(미터). **물가에서 보이는 흙벽의 높이**가 이 값이다.
 *
 * ── 감독 지적에서 정해졌다 ─────────────────────────────────────────────────
 * *"강과 바다 땅보다 더더 아래. 50센치 밑에있게해줘."*
 *
 * 그런데 물은 **이미** 아래에 있었다(`SEA_Y`, 당시 −1.2m). 화면에서 붙어 보인 이유는
 * 이 값이 **0.1m** 였기 때문이다. 물 파셀은 로드되지 않고 그 구멍으로 물판이 비치는
 * 구조라(`features/ocean.ts`), 물가에서 보이는 것은 육지 파셀의 **옆면**뿐이다. 그
 * 옆면이 10cm 면 원근상 없는 것과 같아서, 물이 아무리 깊어도 잔디와 수면이 한
 * 평면처럼 읽힌다.
 *
 * 그래서 고칠 것은 물 높이가 아니라 **여기**였다.
 *
 * ── 왜 상수를 적지 않고 유도하는가 (검수관 블로커) ─────────────────────────
 * 이 값은 `0.8` 이라는 상수였다. 물이 −0.5m 하나였을 때 "수면보다 30cm 더 깊다" 는
 * 뜻이었고 그때는 맞았다. 그런데 감독이 물을 강 −0.5m / 바다 −1.0m 로 가르면서
 * (`decide/water.ts`) **0.8 이 바다 수면보다 얕아졌다** — 바닷가에서 판 옆면이 수면
 * 위로 20cm 드러난다. 값은 그대로인데 뜻이 바뀌었다.
 *
 * 같은 커밋의 `SEABED_Y` 는 `SEA_Y` 에서 유도해 이 사고를 피했는데 여기만 안 따랐다.
 * 한 diff 안에서 유도 규율이 한쪽만 적용된 것이고, 검수관이 그것을 블로커로 잡았다.
 *
 * ── 기준을 수면에서 **해저**로 옮긴다 (감독 실기기 2026-08-02) ─────────────
 * 감독: *"물속에서 봤을때 이런 모양인데. 벽이 쳐있고 뚫고 못들어가게해야지."*
 *
 * 위 문단이 정한 기준은 **바다 수면**(−1.0)이었다. 물 밖에서 보는 한 그것으로 족했다 —
 * 물가에 틈이 없고 단차가 보인다는 목표를 실제로 달성했다. 그런데 감독이 **물에 빠지는
 * 기능**을 요구하면서(#178) 시점이 수면 아래로 내려갔고, 거기서 보니 이렇다:
 *
 *   판 아랫면  −1.3   ← 수면에서 유도한 값
 *   해저       −3.4   ← `SEABED_Y = SEA_Y − WATER_DEPTH`
 *              ─────
 *              2.1m 가 비어 있다
 *
 * 플레이어는 물에 빠지면 해저에 앉으므로 **눈높이가 정확히 그 틈 한가운데**다. 육지가
 * "떠 있는 얇은 판" 으로 보이고, 그 밑으로 헤엄쳐 들어갈 수 있다.
 *
 * **값이 틀린 것이 아니라 기준이 낮은 시점을 못 보고 있었다.** 이 저장소가 이름 붙인
 * 형태 그대로다 — *"참인 문장에서 성립하지 않는 결론을 뽑는 것: 값이 아니라 재는 축이
 * 틀린다."* "두 수면 아래로 내려간다" 는 내내 참이었고, 물 밖 시점에서만 충분했다.
 *
 * 그래서 **바닥(해저)에서 유도한다.** 해저는 물이 닿는 가장 낮은 자리이므로, 여기를
 * 덮으면 어느 시점에서도 육지 아래가 열리지 않는다.
 *
 *   지면 상면 0 → 강 수면 −0.5      : 감독이 말한 50cm 단차는 그대로 보이고
 *   지면 상면 0 → 바다 수면 −1.0    : 바다 단차도 그대로이며
 *   판 아랫면 −3.7                  : 해저(−3.4)보다 더 내려가 물속에서도 벽이다
 *
 * `WATER_DEPTH` 를 바꾸면 흙벽이 저절로 따라온다. 상수를 다시 적을 자리가 없다.
 *
 * **`SEA_Y` 는 이제 안 읽는다** — `SEABED_Y` 가 이미 그것에서 유도되므로(`water.ts`),
 * 여기서 둘 다 읽으면 같은 사실을 두 경로로 참조하는 셈이다.
 */
export const GROUND_DEPTH = Math.abs(SEABED_Y) + SUBMERGE_MARGIN;

export const ground: PartSpec = {
  kind: 'ground',
  tiers: ['near', 'mid', 'far'], // 지면이 없으면 파셀이 구멍으로 보인다
  salt: 0x9e3779b9,
  // ── 낮 팔레트로 (감독 실기기 판정) ──────────────────────────────────────────
  // 예전 값은 `0x2a3140` 계열의 짙은 남색이었다. **도로 텍스처 베이스가 `#2a2d33`
  // 이므로 명도 차이가 3% 밖에 안 났다** — 길과 땅이 사실상 같은 색이었고, 그것이
  // 감독이 말한 *"바닥 격자 바닥이 잘 드러나지 않아"* 의 정확한 원인이다.
  //
  // 정원을 넣은 것은 증상 완화였다. 초록 판이 검은 바닥에 스티커처럼 떠 있었고,
  // 실기기 화면이 그 모습이었다. 원인은 지면 자체가 **야간 팔레트**인데 하늘은
  // 낮이라는 것이었다.
  //
  // 도로는 손대지 말라는 지시대로 두고 땅만 밝힌다. 명도 40% 대의 따뜻한 회갈색이면
  // 아스팔트(17%)와 확실히 갈리면서 잔디(정원)와도 어울린다.
  tones: [0x6b6659, 0x746f61, 0x625e52],

  // `map` 이 없으므로 알베도의 원천은 위 `tones` 뿐이다 — 바탕은 곱셈 항등원(흰색)이다.
  // 이 필드가 있다는 것 자체가 *"나는 지면 평면이다"* 라는 신고이고, 밤 알베도 배수가
  // 여기서 유도된다(`decide/ground-albedo.ts`).
  groundBase: 0xffffff,

  // 바닥에 깔리는 평면 — 그 위에 물건이 서는 것이 정상이라 겹침 개념이 없다.
  footprint: () => 0,

  maxPerParcel: () => 1,

  place: ({ rnd, o }) => [{
    kind: 'ground',
    x: 0, z: 0, y: 0, ry: 0,
    sx: o.cellX, sy: GROUND_DEPTH, sz: o.cellZ,
    tone: Math.floor(rnd() * 3),
  }],

  // 지면만 피벗이 위쪽이다 — 판이 y=0 **아래로** 깔려야 그 위를 걷는다.
  asset: (T) => ({
    geometry: new T.BoxGeometry(1, 1, 1).translate(0, -0.5, 0),
    material: new T.MeshStandardMaterial({ roughness: 0.95, metalness: 0.05 }),
    castShadow: false,
    receiveShadow: true,
  }),
};

// 정원 — 건축할 수 있는 땅을 눈에 보이게 하는 것.
//
// ── 감독 지시 ────────────────────────────────────────────────────────────────
// *"바닥 격자 바닥이 잘 드러나지 않아. 도로는 지금 수준으로. 건축 올릴 수 있는 땅은
//   정원으로 표시해."*
//
// 지시가 셋인데 사실 하나다. 격자가 안 드러나는 이유는 **지면과 도로의 명도 차이가
// 작아서**이고(둘 다 어두운 회청색이다), 도로는 손대지 말라 하셨으니 **땅 쪽을 밝혀야**
// 한다. 그 밝히는 방식이 "정원" 이다 — 색만 바꾸면 그냥 다른 색 바닥이지만, 잔디로
// 읽히면 *"여기는 지을 수 있는 땅"* 이라는 뜻이 함께 전달된다.
//
// ── 왜 사분면 넷인가 ────────────────────────────────────────────────────────
// 도로는 파셀 중심에서 십자로 뻗는다(`road-topology.ts`). 그러니 남는 땅은 **네 귀퉁이**
// 다. 사분면마다 판을 하나씩 깔면 도로를 피하는 판정이 필요 없다 — 셋백(7m) 밖에서
// 시작하면 어느 방향에 길이 나 있든 겹치지 않는다.
//
// 건물도 사분면에 1:1로 배정된다(`building.ts`). 그래서 정원 한 칸이 곧 "건물 한 채가
// 설 자리" 와 같고, 겹쳐도 문제가 없다 — 정원은 바닥이고 건물은 그 위에 선다. 오히려
// 건물 발치가 잔디인 편이 자연스럽다.
//
// ── 광장에는 깔지 않는다 ────────────────────────────────────────────────────
// 광장은 포장된 곳이다. 거기까지 잔디를 깔면 "건축 가능한 땅" 이라는 신호가 흐려지고,
// 무엇보다 중앙 광장은 지을 수 없는 자리다.

import type { PartSpec, PlacedPart, ThreeNS } from './types.js';
import { isPlaza } from './plaza.js';

export { BLADE_WIDTH, GRASS_TEX, GRASS_REPEAT };

export const garden: PartSpec = {
  kind: 'garden',
  // far 까지 그린다. **격자를 드러내는 것이 이 파츠의 목적**이라 멀리서 보일 때
  // 값어치가 가장 크다 — 가까이서는 어차피 건물과 나무가 자리를 말해 준다.
  tiers: ['near', 'mid', 'far'],
  salt: 0x7a5c3e11,
  // **흰색 근처여야 한다** — 텍스처가 이미 초록을 담고 있고 tones 는 그 위에 곱해진다.
  // 처음엔 여기에 잔디색(0x9fd48a 등)을 적었다가 "tones 는 곱셈기다" 검사에 걸렸다.
  // 옳은 지적이다. 그대로 뒀으면 초록 × 초록으로 정원이 검게 죽었을 것이다.
  //
  // 나무는 정점색이 색을 주므로 텍스처가 회색조였지만, 정원은 정점색이 없어 텍스처가
  // 색을 갖는다. 그래서 tones 는 **밝기 변주**만 맡는다 — 판마다 미세하게 달라야 잔디가
  // 한 장을 복사한 것처럼 안 보인다.
  tones: [0xffffff, 0xf0f4ea, 0xe6efe0],

  // ── 사분면 넷에서 통짜 한 장으로 (감독 판정) ──────────────────────────────
  // 감독: *"건물, 나무 있는 곳 바닥 정리가 필요해. 뭔가 건물이 어긋나있네."*
  //
  // 처음엔 사분면마다 7.5m 판을 하나씩 깔았다. 도로를 피하는 판정이 필요 없어서
  // 깔끔해 보였는데, **건물과 나무는 그 판과 아무 관계 없이 배치된다.** 건물은 크기가
  // 4~20m 로 제각각이고 자리도 사분면 안에서 흔들리므로, 정원 판을 가로질러 서거나
  // 판 밖으로 비어져 나온다. 나무도 판 사이 틈에 서서 발치가 갈색 흙이었다.
  // 화면에서는 **초록 조각이 어긋나게 흩어진** 모습이 된다.
  //
  // 통짜 한 장이면 그 문제가 통째로 사라진다. 건물이 어디에 서든 발밑이 잔디이고,
  // 이웃 파셀의 잔디와 이어져 도시 전체가 연속된 땅으로 읽힌다.
  //
  // 도로 밑에도 깔리지만 **도로가 위에 있어 안 보인다**(정원 y=0.03, 도로 y=0.06).
  // 낭비 같지만 드로우콜은 똑같다 — 인스턴스 하나가 넷보다 오히려 싸다.
  // 잔디도 평면이다. 나무·벤치가 잔디 위에 서야 한다.
  footprint: () => 0,

  maxPerParcel: () => 1,

  place: ({ px, pz, rnd, o }) => {
    if (isPlaza(px, pz)) return [];   // 광장은 포장 — 지을 수 없는 자리다
    return [{
      kind: 'garden',
      x: 0, z: 0,
      // 지면(y=0) 위, 도로(0.14) 아래.
      //
      // 예전엔 0.03 이었고 도로가 0.06 이라 **세 판이 6cm 안에 겹쳐** 있었다. 깊이
      // 버퍼는 먼 거리일수록 정밀도가 떨어지므로 그렇게 촘촘하면 어느 쪽이 앞인지
      // 못 정하는 지점이 생긴다. 간격을 벌리는 데 드는 비용은 0 이다 — 눈높이 1.7m
      // 에서 7cm 단차는 보이지 않는다.
      y: 0.07,
      ry: 0,
      // **파셀을 꽉 채운다.** 조금이라도 작으면 파셀 경계마다 갈색 띠가 생기고,
      // 그 띠가 격자를 이중으로 그려 어지럽다.
      sx: o.cellX, sy: 1, sz: o.cellZ,
      tone: Math.floor(rnd() * 3),
    }];
  },

  asset: (T) => ({
    // 도로와 같은 방식 — 평면을 미리 눕혀 두면 인스턴스 회전을 Y축 하나로만 다룬다.
    geometry: new T.PlaneGeometry(1, 1).rotateX(-Math.PI / 2),
    material: new T.MeshStandardMaterial({
      map: grassTexture(T),
      roughness: 0.95,
      metalness: 0,
    }),
    castShadow: false,
    receiveShadow: true,   // 건물·나무 그림자가 잔디에 떨어져야 자리가 읽힌다
  }),
};

/**
 * 잔디 텍스처.
 *
 * 단색 판이면 "색칠한 바닥" 이지 잔디가 아니다. 짧은 선을 촘촘히 그어 결을 만든다 —
 * 풀 한 포기를 그리는 게 아니라 **멀리서 봤을 때의 결**을 만드는 것이라, 이 정도
 * 해상도(128²)에서 선 굵기 1px 면 충분하다.
 *
 * **색은 여기서 준다.** 나무 잎은 정점색이 색을 맡아 텍스처가 회색조였지만, 정원은
 * 정점색이 없다. 그래서 초록을 텍스처에 칠하고 `tones` 는 밝기 변주만 맡는다 — 둘 다
 * 색을 가지면 곱해져서 검게 죽는다.
 */
/**
 * ── 밉맵이 감당할 크기 (감독 판정 *"울지 않는 방법 찾아보자"*) ──────────────
 *
 * 밉맵은 텍스처를 절반씩 줄여 저장한다. 그러니 **디테일이 1픽셀이면 첫 단계에서
 * 절반이 사라지고 두 번째에서 없어진다.** 카메라가 미세하게 움직이면 밉 레벨이
 * 오가면서 그 디테일이 나타났다 사라졌다 하고, 그게 **밝기의 출렁임** 으로 보인다.
 * 감독이 "밑을 보고 미세하게 움직이면 텍스처가 운다" 고 한 것의 정체다.
 *
 * 살아남으려면 디테일이 최소 2~3픽셀이어야 한다. 아래 값들은 그 기준에서 나왔다:
 *
 *   해상도 128 → 256   밉 체인이 한 단계 길어져 먼 거리에서 더 곱게 평균된다
 *   선 굵기 1 → 2.5    첫 밉에서 1.25px 로 살아남는다
 *   선 개수 900 → 500  굵어진 만큼 줄여 밀도를 유지한다
 *   불투명도 0.6 → 0.32  출렁임의 **진폭**을 낮춘다. 대비가 낮으면 밉이 바뀌어도 덜 튄다
 *   반복 12 → 8        결이 1.5배 커져 화면에서 텍셀 밀도가 낮아진다
 */
const BLADE_WIDTH = 2.5;
const BLADE_COUNT = 500;
const GRASS_TEX = 256;
const GRASS_REPEAT = 8;

function grassTexture(T: ThreeNS) {
  const S = GRASS_TEX;
  const canvas = document.createElement('canvas');
  canvas.width = S;
  canvas.height = S;
  const ctx = canvas.getContext('2d')!;

  let a = 0x67a55e;
  const rnd = () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };

  // 잔디 바탕. 색상 100° 근처의 노랑기 있는 초록 — 순수한 초록(120°)은 인공적이다.
  ctx.fillStyle = 'hsl(102, 34%, 52%)';
  ctx.fillRect(0, 0, S, S);
  // 풀결 — 짧은 선을 위쪽으로 조금 기울여 긋는다. 밝기와 색조를 함께 흔들어야
  // 한 장을 반복해 깐 티가 덜 난다.
  ctx.lineWidth = BLADE_WIDTH;
  ctx.lineCap = 'round';   // 끝이 각지면 그 모서리가 다시 1px 디테일이 된다
  for (let i = 0; i < BLADE_COUNT; i++) {
    const x = rnd() * S;
    const y = rnd() * S;
    const len = 5 + rnd() * 9;
    const lean = (rnd() - 0.5) * 4;
    const h = 96 + rnd() * 16;
    const l = 42 + rnd() * 22;
    ctx.strokeStyle = `hsla(${h}, 38%, ${l}%, 0.32)`;
    ctx.beginPath();
    ctx.moveTo(x, y);
    ctx.lineTo(x + lean, y - len);
    ctx.stroke();
  }

  const tex = new T.CanvasTexture(canvas);
  tex.colorSpace = T.SRGBColorSpace;
  // 판마다 크기가 다르므로 반복시켜야 결의 밀도가 일정하다
  tex.wrapS = T.RepeatWrapping;
  tex.wrapT = T.RepeatWrapping;
  // 판이 파셀 한 칸(32m)을 덮으므로 결을 그만큼 반복시킨다. 예전 7.5m 판 기준의
  // 3회를 그대로 두면 풀이 네 배로 늘어나 보인다.
  tex.repeat.set(GRASS_REPEAT, GRASS_REPEAT);
  // **이방성 필터가 아예 없었다**(기본값 1). 32m 판에 결을 12번 반복하므로 얕은
  // 각도에서 텍셀 밀도가 극단적으로 높아지고, 그 상태로 조금만 움직여도 잔디가
  // 지글거린다 — 도로보다 오히려 심했다. 감독이 잡은 "텍스처가 운다" 의 큰 몫이다.
  tex.anisotropy = 16;
  return tex;
}

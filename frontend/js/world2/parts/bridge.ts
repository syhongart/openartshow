// 다리 — 강을 건너는 유일한 수단.
//
// ── 감독 지시 ────────────────────────────────────────────────────────────────
// *"아. 다리 3디로 만들어. 그리고 파일 별도로 만들고"*
//
// 앞선 지시(*"주변 강. 물이 많은게 좋은듯하고"*)에서 나온 것이다. 물을 늘리려면 건널
// 수단이 있어야 하고, 디자이너가 지류 제안에서 *"이 설계가 요구하는 것"* 으로 표시해
// 두었던 항목을 감독이 확정했다.
//
// ── 왜 뭍 파셀이 다리를 놓는가 ──────────────────────────────────────────────
// 물 파셀은 **스트리밍이 아예 만들지 않는다**(`decide/stream.ts` 의 `blockedByWater`).
// 차단이 `blocked?` 옵션이라 풀 수는 있지만, 풀면 지면(`ground`)까지 깔려 **물 위에 땅이
// 생긴다.** 그래서 다리는 물 파셀에 서지 않고, **물가 뭍 파셀이 강 쪽으로 뻗어** 놓는다.
//
// 파셀 경계를 넘는 파츠는 이미 선례가 있다 — 가로등이 파셀 경계 위(±16m)에 선다
// (`road-topology.ts` 의 `lampAnchors`). 새 개념이 아니고, **스트리밍을 건드리지 않는
// 것이 이 선택의 값어치다**(감독: *"여러번 구조바꾸야할거야"* — 되돌리기 싼 쪽을 고른다).
//
// ── 양쪽이 각각 놓으면 다리가 둘이 된다 ─────────────────────────────────────
// 강 양안이 모두 물가이므로 조건을 그대로 두면 북안·남안이 각자 다리를 놓아 **같은 자리에
// 두 개**가 겹친다. 그래서 **북쪽 안(岸)만 놓는다** — 좌표만 보고 정해지는 규칙이라
// 결정론이 유지되고, 이웃과 협의할 필요가 없다.
//
// ── 길이를 이웃 파셀에서 유도한다 ───────────────────────────────────────────
// 강 폭은 파셀마다 다르다. 강 중심선이 사인파 둘로 굽이치고(`decide/water.ts` 의
// `riverCenterZ`) 판정이 파셀 중심 한 점이므로, 물 구간이 한 줄(32m)일 때도 두 줄(64m)일
// 때도 있다.
//
// **이웃 파셀을 값으로 재계산해 센다.** `parcelWater` 가 순수 함수이므로 그 파셀이 로드
// 되지 않았어도(스트리밍 밖이어도) 물인지 아닌지는 계산할 수 있다 — 레퍼런스 조사가 확인한
// Minecraft 의 방식과 같다(청크는 캐시일 뿐 진실의 원천이 아니다). 무저장·결정론을 하나도
// 깨지 않는다.
//
// ── 개수 불변식과 길이 ──────────────────────────────────────────────────────
// 파츠 종류당 `InstancedMesh` 하나이므로 지오메트리는 **한 벌**이다. 길이는 인스턴스
// 행렬의 `sz` 로 늘린다(`systems/instancing.ts` 가 `compose(_v,_q,_s)` 로 로컬 축에 곱한다).
//
// 그래서 **난간에 기둥을 넣지 않았다** — 기둥을 지오에 박으면 짧은 다리에서 촘촘하던 간격이
// 긴 다리에서 두 배로 벌어져 스트레칭이 눈에 드러난다. 연속 패러핏(긴 박스)은 늘어나도
// "긴 벽" 으로만 보인다. 도로 조각이 길이를 자유로 늘려도 어색하지 않은 것과 같은 원리다.

import type { PartSpec, PlacedPart, ThreeNS, ResolvedLayout } from './types.js';
import { bakePieces, rgb, type Piece } from './bake.js';
import { roadDirs } from './road-topology.js';
import { ROAD_Y } from './road.js';
import { parcelWater, RIVER_HALF } from '../decide/water.js';

/**
 * 지오메트리의 기준 길이(미터). 인스턴스는 `sz = 실제길이 / L0` 로 늘린다.
 *
 * 파셀 한 칸(32m)으로 잡는 이유는 **물 구간의 최소 단위가 파셀**이기 때문이다 — 강이
 * 한 줄만 걸리는 가장 짧은 다리가 곧 기준이 되고, 그때 `sz = 1` 이라 스케일 왜곡이 없다.
 */
const L0 = 32;

/**
 * 노면 폭(미터). **도로와 같다**(`road-topology.ts` 의 `ROAD_SEG`).
 *
 * 여기서 값을 다시 적지 않고 도로에서 가져오는 편이 나아 보이지만, `ROAD_SEG` 는 도로
 * **조각의 한 변**이고 다리 폭과는 바뀌는 이유가 다르다(도로를 넓히면 다리도 넓혀야
 * 하는 것은 맞지만, 다리만 넓히고 싶을 때도 있다). 값이 같은 것과 같은 값이어야 하는
 * 것은 다르다 — 지금은 8 로 맞춰 두고, 어긋나면 안 되는 관계라면 그때 유도로 바꾼다.
 */
const DECK_W = 8;

/**
 * 조각 높이 — 거더 최하단(y=0)에서 노면 상단까지.
 *
 * 피벗을 거더 최하단에 두는 것은 다른 파츠와 같은 규약이다(`PartSpec.asset` — "피벗은
 * 바닥"). 그러면 노면이 지면 높이에 오도록 **아래로** 내려야 하고, 그것이 `DECK_Y` 다.
 */
const H = 0.8;

/**
 * 노면 상단이 놓일 높이(미터). **도로에서 가져온다** — 어긋나면 진입부에 턱이 생긴다.
 *
 * ── 처음엔 0.14 를 여기 따로 적었다 (검수관 지적) ──────────────────────────
 * 주석에 *"도로와 정확히 같다"* 고 쓰면서 값은 사본으로 두었다. **그것이 값 미러링이고**,
 * `road.ts` 쪽이 바뀌면 다리만 옛 높이에 남는데 그것을 잡을 테스트가 없었다. 이 저장소가
 * 색·구름 고도·테스트 임계값에서 이미 세 번 겪은 형태다. 이제 `ROAD_Y` 를 유도한다.
 *
 * `DECK_W`(폭)를 도로에서 유도하지 않은 것과 대비된다 — 폭은 "지금 값이 같을 뿐" 이고
 * 다리만 넓히고 싶을 수 있다. 높이는 **같아야 하는 관계**다. 값이 같은 것과 같은 값이어야
 * 하는 것은 다르고, 그 구별이 무엇을 유도할지를 정한다.
 *
 * ── 왜 올리거나 아치로 만들지 않았나 ───────────────────────────────────────
 * 수면이 −0.5m 이고 지면이 0 이라 **노면 아래 여유가 0.5m 뿐**이다. 다리처럼 물 위로
 * 떠 있게 하려면 노면을 올려야 하는데, 그러면 진입부에 턱이 생긴다(우리는 플레이어
 * 충돌이 없어 걸을 때 안 걸리지만 눈에는 보인다). 아치는 세그먼트 개수가 고정인데 길이가
 * 스케일로 변해서 짧은 다리에서 각지고 긴 다리에서 완만해진다 — 스케일 종속 변수를 하나
 * 더 만드는 셈이다.
 *
 * 그래서 **노면은 지면의 연장으로 두고, 다리라는 사실은 아래로 늘어진 거더가 물에 발을
 * 담그는 것으로 표현한다.** 걷는 경험은 완전히 매끄럽고, 옆에서 볼 때·가장자리에서
 * 내려다볼 때 다리로 읽힌다(디자이너 판정).
 */
const DECK_Y = ROAD_Y;

/**
 * 다리가 걸칠 수 있는 물 구간의 최대 칸 수. **강 반폭에서 유도한다.**
 *
 * 실측에 여유를 얹지 않는다 — 물 구간은 `RIVER_HALF` 양쪽이므로 최대 폭이 `2×RIVER_HALF`
 * 이고, 파셀 중심 판정이 그것을 셀 크기로 끊으므로 칸 수 상한은 `ceil(2×RIVER_HALF/cell)`
 * 에 경계 걸침 한 칸을 더한 값이다. `RIVER_HALF` 를 키우면 저절로 따라온다.
 *
 * 상한이 필요한 이유는 방어가 아니라 **무한 루프 차단**이다 — 물 판정이 어긋나 세계 밖까지
 * 물로 나오면 세는 루프가 끝나지 않는다(세계 밖은 `parcelWater` 가 `'water'` 를 돌려준다).
 */
function maxSpan(cellZ: number): number {
  return Math.ceil((RIVER_HALF * 2) / cellZ) + 1;
}

/**
 * 이 파셀이 남쪽으로 다리를 놓는가, 놓으면 물 구간이 몇 칸인가.
 *
 * `0` 이면 놓지 않는다. **이웃 파셀을 값으로만 재계산**하므로 그 파셀이 로드되어 있지
 * 않아도 된다.
 */
function spanSouth(px: number, pz: number, o: ResolvedLayout): number {
  // 자기가 물이면 다리를 놓을 발판이 없다
  if (parcelWater(px, pz, o.cellX, o.cellZ) === 'water') return 0;
  // 바로 남쪽이 물이 아니면 건널 것이 없다
  if (parcelWater(px, pz + 1, o.cellX, o.cellZ) !== 'water') return 0;

  const lim = maxSpan(o.cellZ);
  let n = 0;
  while (n < lim && parcelWater(px, pz + 1 + n, o.cellX, o.cellZ) === 'water') n++;
  // 건너편이 뭍이어야 다리다. 상한까지 물이면 그건 강이 아니라 바다(세계의 끝)이고,
  // 거기에 다리를 놓으면 **허공으로 뻗은 다리**가 된다.
  if (n >= lim) return 0;
  return n;
}

export const bridge: PartSpec = {
  kind: 'bridge',
  // **far 까지 그린다.** 다리는 길이 32m 이상이라 멀리서도 실루엣이 읽히고, 무엇보다
  // "저기 건널 수 있다" 를 멀리서 알아야 걸어갈 목적이 생긴다. 벤치가 mid 까지인 것과
  // 반대 판단이고, 근거는 크기다.
  tiers: ['near', 'mid', 'far'],
  salt: 0x2b7f4e13,
  // 정점색이 색을 주므로 흰색 하나. 다리는 도시 시설물이라 개체 변주를 주지 않는다 —
  // 같은 강에 걸린 다리들이 서로 다른 색이면 임시 구조물처럼 보인다.
  tones: [0xffffff],

  /**
   * **겹침 판정에서 빠진다.** 도로·지면과 같은 판단이다(`PartSpec.footprint` — "바닥에
   * 깔리는 평면").
   *
   * 다리 본체는 물 위이고 그곳에는 경쟁할 파츠가 없다(스트리밍이 물 파셀을 만들지 않는다).
   *
   * 뭍 쪽 진입부는 도로 축 위라 나무·벤치가 애초에 들어오지 않는다. **기전을 정확히
   * 적는다**(검수관 지적) — 그들이 `onRoad()` 를 부르는 것이 아니라, `parcelSlots` 가
   * `SETBACK`(7m) 만큼 안쪽으로 들여 중앙 십자를 비운다. 다리 노면 반폭이 4.075m 라
   * 그 7m 안에 들어가므로, 도로가 하나라도 있는 파셀에서는 슬롯이 다리 영역에 닿지
   * 못한다. 결론은 같지만 다음에 이 근거를 읽는 사람이 엉뚱한 함수를 찾지 않게 한다.
   *
   * 원형 반경으로 잡으면 오히려 해롭다 — 64m 다리를 감싸는 원은 반경 32m 라 파셀을 통째로
   * 먹고, 그 파셀에 아무것도 못 서게 된다.
   */
  footprint: () => 0,

  maxPerParcel: () => 1,

  /**
   * 남북 도로가 강을 만나는 곳에 놓는다.
   *
   * ── 왜 남북만인가 ────────────────────────────────────────────────────────
   * 강은 x 를 따라 흐르고 z 가 굽이친다(`riverCenterZ`). 그래서 강을 가로지르는 것은
   * **남북 도로**이고, 동서 도로는 강과 평행하다. 굽이가 심한 구간에서 동서 도로가 강을
   * 건너는 경우가 있을 수 있지만 일반형이 아니므로 이번 판에서는 남북만 놓는다 —
   * 없는 다리보다 나쁜 것은 엉뚱한 방향으로 놓인 다리다.
   */
  place: ({ px, pz, o }): PlacedPart[] => {
    const dirs = roadDirs(px, pz);
    // 남쪽으로 길이 이어져야 다리가 길의 연장이 된다. 길 없는 곳의 다리는 어디서
    // 와서 어디로 가는지 알 수 없다.
    if (!dirs.includes('south')) return [];

    const span = spanSouth(px, pz, o);
    if (span === 0) return [];

    // 물 구간 span 칸 + 양안에 반 칸씩 걸친다 → 길이 (span+1)×cellZ.
    // 중심은 자기 파셀 중심에서 남쪽으로 그 절반.
    const len = (span + 1) * o.cellZ;
    return [{
      kind: 'bridge',
      x: 0,
      z: len / 2,
      // 피벗이 거더 최하단이므로 노면 상단을 도로 높이에 맞추려면 그만큼 내린다.
      y: DECK_Y - H,
      ry: 0, // 로컬 z 축이 곧 남북이다
      sx: 1,
      sy: 1,
      sz: len / L0,
      tone: 0,
    }];
  },

  asset: (T) => ({
    geometry: buildBridge(T),
    material: new T.MeshStandardMaterial({ vertexColors: true, roughness: 0.8, metalness: 0.02 }),
    // 패러핏이 노면에 그림자를 드리워야 입체감이 생긴다. 그림자를 못 받으면 붕 떠 보인다.
    castShadow: true,
    receiveShadow: true,
  }),
};

// ── 색 (디자이너 지정) ───────────────────────────────────────────────────────
// 도로와 **완전히 같으면 다리인지 모른다**(감독 우려). 아스팔트 베이스(`#2a2d33`)보다
// 밝은 중회색으로 "재질이 바뀌었다" 를 알린다.
/** 노면 — 콘크리트·석재 포장 */
const DECK = rgb(0x4d4f54);
/** 거더 — 다리 밑은 그늘이 진다. 노면과의 명암 대비가 실루엣을 만든다 */
const GIRDER = rgb(0x3a3d42);
/** 패러핏(난간벽) — 눈높이에서 가장 먼저 들어오는 면이라 밝힌다 */
const RAIL = rgb(0x5c5f66);
/** 레일캡 — 가장 밝은 톤. 상향면이라 낮에는 하늘빛, 밤에는 가로등 빛을 가장 많이 받는다 */
const RAIL_CAP = rgb(0x8f9096);

/**
 * 7조각 · 약 84삼각형.
 *
 *   노면      Box(8, 0.25, 32)     y=0.675
 *   거더 ×2   Box(0.15, 0.55, 32)  x=±3.925 · y=0.275   ← 물에 발을 담근다
 *   패러핏 ×2 Box(0.15, 0.9, 32)   x=±3.925 · y=1.25    ← 허리 높이(시야를 안 가린다)
 *   레일캡 ×2 Box(0.22, 0.08, 32)  x=±3.925 · y=1.74
 *
 * **전부 길이 축(z)이 32 다.** 그래서 `sz` 하나로 늘려도 폭·두께가 보존되고, 늘어나는
 * 것은 길이뿐이다. 기둥·세그먼트처럼 개수가 고정인 요소를 넣지 않은 것이 그 조건이다.
 *
 * 패러핏 높이 0.9m 는 눈높이 1.7m 에서 **시야를 가리지 않으면서** 좌우 경계를 표시하는
 * 값이다 — 강 건너편과 수평선이 보여야 건너는 동안 방향을 잃지 않는다.
 */
function buildBridge(T: ThreeNS) {
  const halfW = DECK_W / 2;
  // 거더·패러핏·레일캡이 같은 x 에 선다 — 노면 가장자리에서 조금 안쪽이다. 정확히
  // 가장자리에 두면 노면과 z-fighting 이 나고, 너무 안쪽이면 걸을 폭이 좁아 보인다.
  const edge = halfW - 0.075;
  const pieces: Piece[] = [
    { geo: new T.BoxGeometry(DECK_W, 0.25, L0).translate(0, 0.675, 0), color: DECK },
    { geo: new T.BoxGeometry(0.15, 0.55, L0).translate(-edge, 0.275, 0), color: GIRDER },
    { geo: new T.BoxGeometry(0.15, 0.55, L0).translate(edge, 0.275, 0), color: GIRDER },
    { geo: new T.BoxGeometry(0.15, 0.9, L0).translate(-edge, 1.25, 0), color: RAIL },
    { geo: new T.BoxGeometry(0.15, 0.9, L0).translate(edge, 1.25, 0), color: RAIL },
    { geo: new T.BoxGeometry(0.22, 0.08, L0).translate(-edge, 1.74, 0), color: RAIL_CAP },
    { geo: new T.BoxGeometry(0.22, 0.08, L0).translate(edge, 1.74, 0), color: RAIL_CAP },
  ];
  return bakePieces(T, pieces);
}


/**
 * 결정론 난수. **씨앗이 고정이다** — 지오가 하나뿐이므로 나무 모양도 하나이고, 그것이
 * 빌드마다 달라지면 골든 스냅샷이 흔들린다.
 */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * 텍스처에서 줄기 영역과 잎 영역을 가르는 U 좌표.
 *
 * 왼쪽 `[0, LEAF_U0]` 은 **완전 불투명**한 수피, 오른쪽 `[LEAF_U0, 1]` 은 알파가 뚫린
 * 잎이다. 한 장에 담는 이유는 재질을 하나로 유지하기 위해서다 — 텍스처를 둘로 나누면
 * 재질이 둘이 되고 드로우콜이 갈린다.
 *
 * 0.25 는 잎에 넓은 쪽을 준 것이다. 수피는 세로 줄무늬라 가로 해상도가 덜 필요하고,
 * 잎은 실루엣이 전부라 촘촘할수록 좋다.
 */
export const LEAF_U0 = 0.25;

// ── `treeTexture` 의 배치 상수 — **모듈 스코프인 이유가 있다** ────────────────
// 아래 `LEAF_MARGIN_U` 가 이 값들로 여백을 **유도**한다. 지역 변수로 두면 유도가
// 불가능해져 여백을 손으로 재계산하게 되고, 그것이 정확히 값 미러링이다(검수관 권고
// 1, 2026-08-22 — 그때 테스트에 박혀 있던 `76.8/512` 가 실제와 20px 어긋나 있었다).
/** 캔버스 높이. 폭은 이것의 2배다(왼쪽 `LEAF_U0` 만큼이 수피). */
const TEX_S = 256;
const TEX_W = TEX_S * 2;
/** 타원 중심이 퍼지는 최대 거리의 계수 — 이 한 값이 수관 실루엣의 크기를 정한다. */
const LEAF_DIST_K = 0.45;
/** 타원 반축(`len`)의 범위. 최댓값이 여백 유도에 직접 들어간다. */
const LEAF_LEN_MIN = 7;
const LEAF_LEN_RAND = 13;

/**
 * 잎 잉크가 **절대 침범하지 않는 것이 유도로 보장되는** 여백(U 단위).
 *
 * ── 왜 실측이 아니라 유도인가 ───────────────────────────────────────────────
 * 첫 판본은 이 자리를 테스트에 박은 `76.8 / 512` 로 대신했고 **두 번 틀렸다**:
 *
 *   ① 타원 **반축을 빼먹었다.** 중심이 도달하는 최대 거리만 셌고 타원 자체가 그
 *      중심에서 `len` 만큼 더 퍼진다는 것을 안 더했다 — 20px 낙관.
 *   ② 그 값이 코드가 아니라 **테스트에 리터럴로** 있었다. `TEX_S` 나 `LEAF_DIST_K`
 *      를 만지면 안전 마진 검사가 **조용히 낡는다**(검수관 권고 1).
 *
 * CLAUDE.md 가 이 형태를 이미 못 박고 있다 — *"실측에 여유를 얹은 값은 근거가
 * 아니다. 유도할 수 있으면 유도한다 — 그러면 전제를 바꿔도 저절로 따라온다."*
 * 그래서 배치 상수에서 **최악치를 계산**한다. 시드·타원 개수·분포 지수가 바뀌어도
 * 따라온다(지수 0.6 은 분포만 바꾸고 최대 거리는 안 바꾼다).
 *
 * ⚠ **유도값과 시드 실측은 다르고, 그것이 정상이다.** 검수관이 시드 `0x1eaf` 를
 * 그대로 시뮬레이션해 실제 잉크 여백 **64.06px(좌)·81.83px(우)** 를 냈다. 유도는
 * 56.8px 로 그보다 **작다** — 유도는 도달 가능한 최악이고 실측은 밟아본 값이므로
 * 이 순서가 맞다. 뒤집혀 있으면 유도가 틀린 것이다.
 */
export const LEAF_MARGIN_U = (() => {
  const barkW = TEX_W * LEAF_U0;
  const leafW = TEX_W - barkW;
  const distMax = Math.min(leafW, TEX_S) * LEAF_DIST_K;   // 중심이 퍼지는 최대
  const lenMax = LEAF_LEN_MIN + LEAF_LEN_RAND;            // 타원이 중심에서 더 퍼지는 최대
  const inkMin = barkW + leafW / 2 - distMax - lenMax;    // 가장 왼쪽 잉크
  return (inkMin - barkW) / TEX_W;
})();

/**
 * 🔴 **아틀라스 경계에서 안쪽으로 물리는 폭**(감독 신고 2026-08-22 스크린샷
 * *"나뭇잎 알파가 정확히 가려지지 않네"*).
 *
 * ── 유도 — 이 값은 취향이 아니라 **텍셀 산술**이다 ──────────────────────────
 * 잎 카드는 `remapU(geo, LEAF_U0, 1)` 로 UV 를 잎 영역에 눌러 넣는데, 그러면
 * `u = LEAF_U0` 가 **수피(완전 불투명)와 잎(투명)의 경계에 정확히 놓인다.**
 *
 *   픽셀 127 = 수피, 알파 **1**   ·   픽셀 128 = 잎 영역 시작, 알파 **0**
 *   선형 필터가 경계에서 반반을 섞으면  →  알파 **정확히 0.5**
 *
 * ⚠ **첫 판본은 여기서 «three 의 컷아웃은 `a < alphaTest` 라 0.5 는 통과한다» 로
 * 끝냈고, 그것은 감독이 보는 화면에서 참이 아니었다**(소스 실측 2026-08-22 — 나는 그
 * 한 줄을 소스가 아니라 기억으로 적었고 PR 본문에 그렇게 밝혀 뒀다가 되짚었다).
 * three 는 **백엔드마다 비교 연산자가 다르다**:
 *
 *   WebGL   `alphatest_fragment.glsl.js`  `if ( diffuseColor.a < alphaTest ) discard`
 *   WebGPU  `NodeMaterial.js:414`         `diffuseColor.a.lessThanEqual( … ).discard()`
 *
 * 즉 알파 0.5 는 **WebGL 에서 통과하고 WebGPU 에서 잘린다.** world2 는 `three/webgpu`
 * 를 쓰고 감독 실기기는 WebGPU 다 — 그러므로 「0.5 가 통과해서」는 **감독이 본 선의
 * 설명이 될 수 없다.** 헤드리스(swiftshader WebGL)에서만 참인 문장을 실기기 진단으로
 * 쓸 뻔했고, 그것은 이 저장소가 이미 규율로 적어 둔 사각이다.
 *
 * ── 두 백엔드 어디서도 성립하는 축은 **밉맵**이다 ──────────────────────────
 * 밉 레벨 k 의 텍셀 하나는 원본 `2^k` px 를 덮는다. 그래서 `u` 가 경계보다 안쪽이어도
 * **샘플이 경계 너머 수피를 함께 먹고**, 알파가 0.5 를 **넘는** 표본이 카드 가장자리에
 * 생긴다. 그 픽셀은 `<` 든 `<=` 든 살아남아 **수피 색으로 그려진다.** 잎 카드가 3장씩
 * 다른 각도로 서 있으니 화면에서는 **여러 방향으로 뻗는 가는 선**이 되고, 색이 어두운
 * 갈녹색인 것도 설명된다 — 수피 텍스처에 잎 정점색이 곱해진 것이다.
 *
 * **값은 이 정정으로 안 바뀐다** — 물릴 폭은 처음부터 이 밉 축에서 유도했다. 텍스처
 * 폭이 `S*2 = 512` 이고 밉 5레벨의 텍셀이 원본 32px 이므로 **32/512 = 0.0625** 다.
 * 틀렸던 것은 값이 아니라 **왜 그 값인가의 설명**이고, 설명이 틀리면 다음 사람이 이
 * 상수를 엉뚱한 축에서 만진다(문턱을 올리거나 필터를 끄는 쪽으로 간다).
 *
 * ── 잎이 잘리지 않는가 ─────────────────────────────────────────────────────
 * 여백은 위 `LEAF_MARGIN_U` 가 배치 상수에서 **유도**한다 — **56.8px(0.1109)**.
 * 32px 는 그 안이다.
 *
 * ⚠ **첫 판본은 여기에 «양쪽에 약 77px» 이라고 적었고 20px 낙관이었다** — 타원
 * 중심이 도달하는 거리만 셌고 **타원 자체가 그 중심에서 `len` 만큼 더 퍼진다**는
 * 것을 안 더했다(검수관 독립 실측이 열었다, 2026-08-22). 그 낙관값이 테스트에
 * 리터럴로 박혀 있어서 `ATLAS_INSET_MAX` 의 결함까지 함께 통과시켰다.
 *
 * ⚠ **수피 쪽도 같은 결함이었다.** `remapU(geo, 0, LEAF_U0)` 의 오른쪽 끝이 같은
 * 경계라 수피 가장자리가 반투명해진다. 눈에 덜 띌 뿐 원인이 같으므로 함께 물린다.
 *
 * ⚠⚠ **수피가 치르는 대가는 「조금」이 아니다**(검수관 계산, 2026-08-22 — 나는
 * *"조금 좁아진다"* 라고 적었고 과소평가였다). 수피 영역은 128px 폭인데 양쪽에서
 * 32px 씩 물리므로 **폭의 50% 가 잘린다**(잎 쪽은 384px 중 64px ≈ 16.7%, 3배 차이).
 * 줄무늬가 균일분포 노이즈라 실린더에 다시 늘려 매핑되면 밀도는 유지되고 **폭만 약
 * 2배로 굵어진다** — 기능 결함은 아니지만 룩이 변한다.
 *
 * 이 대가는 **줄일 수 있다.** 물림이 필요한 것은 아틀라스 **내부** 경계(`LEAF_U0`)
 * 뿐이고, 캔버스 양 끝(`u=0`·`u=1`)은 `wrapS` 가 `ClampToEdgeWrapping` 기본값이라
 * 이웃 텍셀 불연속이 없다(three `Texture.js:22` 실측). 대칭 물림을 비대칭으로
 * 바꾸면 수피 크롭이 50%→25% 로 준다. **이번 회차에 넣지 않았다** — 감독이 신고한
 * 것은 잎 선이고, 수피 룩을 바꾸는 것은 감독 화면 판정이 붙는 별개 축이다(태스크).
 *
 * 되돌릴 문은 `?leafinset=0` 이다(신고 이전 화면).
 *
 * ── ✅ 감독 판정 (2026-08-22) — **여기서 멈춘다** ──────────────────────────
 * 배포본을 화면에서 보시고 *"잘했어. 개선 되었어."* 그러므로 이 값은 더 이상
 * 「근거는 있으나 화면 판정 전」이 아니다. **확정값이다.**
 *
 * 이 판정이 실제로 확정한 것은 숫자 하나가 아니라 **전제**다: 물림 폭을 유도할 때
 * 쓴 「밉 5레벨(원본 32px)」이 감독 기기에서 **실제로 충분했다.** 그 전제는 여전히
 * 직접 측정한 것이 아니지만(태스크 #128), 이제 「가정」이 아니라 「화면으로 한 번
 * 확인된 가정」이다 — 둘은 다르다.
 *
 * ⚠ **판정이 닫은 것과 안 닫은 것을 갈라 적는다.** 닫힌 것은 *"선이 남는가"* 하나다.
 * 안 닫힌 것: ① 밉 레벨의 직접 측정(#128) ② 수피 줄무늬가 2배 굵어진 것을 감독이
 * 보고 판단하신 적은 **없다** — 신고도 판정도 잎에 대한 것이었고, 수피는 내가 같은
 * 커밋에 끼워 넣은 부수효과다. 그것을 「승인됐다」로 읽지 마라.
 *
 * ⚠⚠ **그러므로 이 값을 다시 만지는 이유는 하나뿐이다** — 감독이 화면에서 새 문제를
 * 신고하는 것. 수치가 이상해 보인다는 이유로 열지 않는다. 이 저장소가 가장 비싸게
 * 치른 실수가 «수치가 이상한 것»과 «화면이 잘못된 것»을 같게 본 것이다(CLAUDE.md).
 */
export const ATLAS_INSET = 0.0625;
/** `?leafinset=` — 0 이면 신고 이전 화면. */
export const ATLAS_INSET_KNOB = 'leafinset';
/**
 * 🔴 상한은 **잎 잉크에 닿기 직전**이다 — 손으로 고른 값이 아니라 `LEAF_MARGIN_U` 다.
 *
 * ⚠ **첫 판본은 `0.12` 하드코딩이었고 그것은 유도 여백 밖이었다**(검수관 권고 1 이
 * 연 실측, 2026-08-22). `0.12 × 512 = 61.4px` 인데 유도 여백은 **56.8px** 이다 —
 * 즉 감독이 노브를 상한까지 밀면 **잎 실루엣이 잘리기 시작한다.** 고치려고 만든
 * 노브가 상한에서 새 결함을 내는 형태였다.
 *
 * 그 값이 통과한 이유도 남긴다: 당시 검사가 대조하던 여백이 `76.8/512`(20px 낙관)라
 * `0.12 < 0.15` 로 **통과했다.** 틀린 기준값이 틀린 상한을 통과시킨 것이다 — 이
 * 저장소가 「값 미러링」으로 반복해서 겪은 형태 그대로다.
 *
 * 상한에서 정확히 경계인 것은 의도한 것이다. 유도값은 **최악치**라 실제 잉크는 그보다
 * 안쪽이고(시드 실측 64.06px), 노브의 의미가 «0 = 신고 이전 · 상한 = 한계» 로 선다.
 */
export const ATLAS_INSET_MAX = LEAF_MARGIN_U;

/** 지오메트리의 U 좌표를 `[u0,u1]` 구간으로 눌러 넣는다 */
export function remapU(geo: InstanceType<ThreeNS['BufferGeometry']>, u0: number, u1: number): void {
  const uv = geo.attributes.uv.array as Float32Array;
  for (let i = 0; i < uv.length; i += 2) uv[i] = u0 + uv[i] * (u1 - u0);
}

/**
 * 줄기 + 잎 한 장. **world1 `createLeafClusterTexture` 의 알고리즘 그대로다.**
 *
 * 투명 배경 위에 타원을 150개 흩뿌리되 중앙에 밀집시킨다(`pow(rand, 0.6)` — 지수가 1보다
 * 작으면 분포가 안쪽으로 쏠린다). 그래야 가장자리가 성겨서 **실루엣이 뚫려 보인다.**
 * 잎맥 하이라이트도 같은 확률로 긋는다.
 *
 * 감독 판정 *"나뭇잎 퀄리티 너무 떨어진다"* 의 처방이 이것이다. 앞서 잎을 정팔면체
 * 덩어리로 만들었는데, 잎은 얇고 성긴 것이라 각진 입체로는 절대 안 보인다. **잎의
 * 정체는 형태가 아니라 뚫린 실루엣이다.**
 */
export function treeTexture(T: ThreeNS) {
  const S = TEX_S;   // 여백 유도(`LEAF_MARGIN_U`)와 **같은 값이어야 한다** — 그래서 참조다
  const canvas = document.createElement('canvas');
  canvas.width = S * 2;   // 왼쪽 절반의 절반이 수피, 나머지가 잎
  canvas.height = S;
  const ctx = canvas.getContext('2d')!;
  const rnd = rng(0x1eaf);

  // ── 왼쪽: 수피 ──────────────────────────────────────────────────────────
  const barkW = S * 2 * LEAF_U0;
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, barkW, S);
  // 세로 줄무늬. 색이 아니라 **밝기 변주**다 — 실제 색은 정점색이 정한다.
  for (let i = 0; i < 90; i++) {
    const x = rnd() * barkW;
    const w = 1 + rnd() * 3;
    const a = 0.06 + rnd() * 0.12;
    ctx.fillStyle = `rgba(0,0,0,${a})`;
    ctx.fillRect(x, 0, w, S);
  }

  // ── 오른쪽: 잎 클러스터 ─────────────────────────────────────────────────
  const leafX = barkW;
  const leafW = S * 2 - barkW;
  for (let i = 0; i < 150; i++) {
    const ang = rnd() * Math.PI * 2;
    // 지수 0.6 — 중앙 밀집, 가장자리 성김. 이 한 값이 실루엣을 만든다.
    const dist = Math.pow(rnd(), 0.6) * Math.min(leafW, S) * LEAF_DIST_K;
    const x = leafX + leafW / 2 + Math.cos(ang) * dist;
    const y = S / 2 + Math.sin(ang) * dist;
    const len = LEAF_LEN_MIN + rnd() * LEAF_LEN_RAND;
    const wid = len * (0.4 + rnd() * 0.25);
    // 밝기만 흔든다. 색조는 정점색이 준다 — 여기서 초록을 칠하면 정점색과 곱해져
    // 두 번 어두워진다(값 미러링과 같은 형태의 함정이다).
    const l = 62 + rnd() * 34;
    ctx.fillStyle = `hsla(0, 0%, ${l}%, ${0.78 + rnd() * 0.22})`;
    ctx.save();
    ctx.translate(x, y);
    ctx.rotate(rnd() * Math.PI);
    ctx.beginPath();
    ctx.ellipse(0, 0, len, wid, 0, 0, Math.PI * 2);
    ctx.fill();
    if (rnd() > 0.6) {   // 잎맥
      ctx.strokeStyle = `hsla(0, 0%, ${Math.min(100, l + 18)}%, 0.5)`;
      ctx.lineWidth = 1;
      ctx.beginPath();
      ctx.moveTo(-len * 0.8, 0);
      ctx.lineTo(len * 0.8, 0);
      ctx.stroke();
    }
    ctx.restore();
  }

  const tex = new T.CanvasTexture(canvas);
  tex.colorSpace = T.SRGBColorSpace;
  return tex;
}

// world2/decide/history.ts — **되돌리기 스택.** 순수 함수만, import 0.
//
// ── 감독 지시 2026-08-22 ────────────────────────────────────────────────────
// *"워크래프트3 편집기 보니깐. 오픈월드 수정할수있던데. 우리 편집기 보고 개선해봐."*
//
// 그 편집기와 우리 편집기를 나란히 놓고 세었을 때 **없는 것 중 가장 위험한 것**이
// 실행취소였다. 우리 편집기(`?edit=1`)는 놓기·삭제·이동·회전·크기·색·구역되돌리기를
// 전부 할 수 있는데 **되돌리는 문이 하나도 없었다**(실측: `edit/` 전체에서 `undo`
// 식별자 0건, `Ctrl+Z` 바인딩 0건 — `KeyZ` 는 「높이 내리기」에 이미 쓰이고 있었다).
//
// ⚠ 「고른 것 취소」(`actions.cancelPending`, 태스크 #97)와 다른 축이다. 그것은 **아직
// 안 일어난 일**을 취소하고, 이것은 **이미 일어난 일**을 되돌린다.
//
// ── 왜 이것이 다른 어떤 개선보다 먼저인가 ───────────────────────────────────
// 삭제가 되돌아가지 않는다는 것은 「실수 한 번 = 데이터 손실」이다. 게다가 손실의 크기가
// 조작마다 다르다 — 드래그드롭한 GLB 를 지우면 `blob:` 미리보기가 사라져 **감독이 그
// 파일을 다시 떨어뜨려야** 하고(`edit/target-art.ts` 의 B1 절이 같은 형태를 «되돌릴
// 수단이 없는 손실» 이라고 부른다), 마을 파츠를 지우면 그 파셀이 「손본 구역」으로
// 굳는다. 화면이 그 사실을 말해 주고는 있지만(`actions.ts` 의 `panel.say`), **말해
// 주는 것과 되돌릴 수 있는 것은 다른 일이다.**
//
// 그리고 이것은 **다음 개선의 선결 조건**이다. 붓으로 여러 개를 한 번에 뿌리는 조작
// (워크래프트3 의 도장 브러시)이나 지형 조각처럼 «한 동작이 여러 개를 바꾸는» 것을
// 되돌릴 수 없는 편집기에 얹으면, 편집이 아니라 도박이 된다.
//
// ── 이 파일이 아무것도 모르는 것이 요점이다 ─────────────────────────────────
// 스택은 «무엇을 되돌리는가» 를 모른다 — `Undoable` 둘(`undo`/`redo`)만 부른다. 그래서
// 오버레이 항목·마을 파셀·걸린 작품이라는 **서로 다른 세 저장소**가 같은 스택에 섞여도
// 여기는 안 바뀐다(집행은 `edit/history-ops.ts`). three·DOM 무의존이라 노드 테스트가
// 실제 코드를 그대로 돌린다.

/**
 * 되돌릴 수 있는 조작 하나.
 *
 * ⚠ **`undo`/`redo` 는 비동기일 수 있다** — 걸린 작품은 `ArtsPort.set()` 이 텍스처를
 * 다시 물리므로 `Promise` 다. 스택은 그것을 **기다리지 않는다**(아래 `undo()` 주석).
 */
export interface Undoable {
  /** 화면에 그대로 뜬다 — 「되돌렸습니다: **삭제**」. 조작 이름이지 문장이 아니다 */
  readonly label: string;
  undo(): void | Promise<void>;
  redo(): void | Promise<void>;
}

export interface History {
  /**
   * 조작을 쌓는다. **다시하기 가지는 이 순간 버려진다**(선형 히스토리).
   *
   * 되돌린 뒤 다른 조작을 하면 그 이후로 다시 갈 수 없다 — 블렌더·워크래프트3 편집기·
   * three.js editor(`frontend/editor/js/History.js`) 가 전부 같다. 가지를 남기면
   * 「다시하기가 내가 안 한 일을 한다」가 성립하고, 그것을 화면에 설명할 방법이 없다.
   */
  push(e: Undoable): void;
  /** 하나 되돌린다. 되돌린 것의 `label`, 되돌릴 것이 없으면 `null` */
  undo(): string | null;
  /** 하나 다시 한다. 다시 한 것의 `label`, 없으면 `null` */
  redo(): string | null;
  canUndo(): boolean;
  canRedo(): boolean;
  /** 쌓인 개수(되돌리기 쪽). 화면이 「되돌리기 (3)」 로 쓴다 */
  depth(): number;
  /** 다시하기 가지의 개수 */
  redoDepth(): number;
  /**
   * 다음에 되돌아갈 것을 **꺼내지 않고** 본다.
   *
   * 왜 필요한가: 되돌릴 수 없는 조작(`edit/history-ops.ts` 의 `barrier`)은 **되돌리기
   * 전에** 화면이 사유를 말해야 한다. `undo()` 가 `label` 만 내면 그 구별이 불가능하고,
   * 「되돌렸습니다」라고 적은 뒤 아무 일도 안 일어나는 형태가 된다.
   */
  peekUndo(): Undoable | null;
  /** 전부 버린다. 편집 세션이 끝날 때 — 붙들고 있던 삭제 항목을 놓아 준다 */
  clear(): void;
}

/**
 * 기본 상한(조작 개수).
 *
 * ── 왜 무한이 아닌가 ───────────────────────────────────────────────────────
 * **삭제를 되돌릴 수 있게 하려고 지운 것을 붙들고 있기 때문이다.** `features/overlay.ts`
 * 의 `remove()` 는 `entries` 에서 빼고 `root` 에서 뗄 뿐 `dispose()` 를 부르지 않으므로
 * (실측 2026-08-22, 그 함수 전체가 3줄이다), 지금은 참조가 끊기는 순간 GC 가 가져간다.
 * 스택이 그 참조를 들면 **GC 가 못 가져간다** — 즉 이 파일이 없던 시절엔 없던 누수
 * 경로를 여는 셈이고, 상한이 그 경로의 마개다.
 *
 * ── 왜 50 인가 ─────────────────────────────────────────────────────────────
 * 「지운 GLB 50개를 동시에 들고 있어도 되는가」로 잡았다. 이 저장소가 실제로 겪은 최악
 * 자산이 12.9MB(`edit/state.ts` 의 `busy` 절 — 감독이 탭을 닫아야 했던 그 회차)인데,
 * 그것을 50개 **연속으로 지우는** 세션은 편집 조작으로 성립하지 않는다(놓는 데만 로드가
 * 50회 든다). 실제 상한을 미는 것은 **포즈 조작**이고 그것은 숫자 다섯 개짜리다.
 *
 * ⚠ **이 값은 실측이 아니라 유도다.** 「실측에 여유를 얹은 값은 근거가 아니다」(CLAUDE.md
 * 검증 규율)의 반대쪽 — 잴 수 있는 최악치가 세션마다 다르므로 **잰 값이 아니라 「무엇을
 * 보장하는가」를 적는다**: *넘치면 가장 오래된 것부터 버린다*. 버려진 조작은 영영 못
 * 되돌아가고, 그 순간 그것이 들고 있던 삭제 항목은 GC 대상이 된다.
 */
export const HISTORY_LIMIT = 50;

/**
 * @param limit 쌓을 수 있는 조작 개수. **1 미만은 1 로 올린다** — 0 을 허용하면
 *              「누르면 되돌아가는데 아무 일도 안 일어나는」 상태가 되고, 그것이
 *              이 저장소가 가장 경계하는 «가끔 안 먹는다» 의 한 형태다.
 */
export function createHistory(limit: number = HISTORY_LIMIT): History {
  const cap = Math.max(1, Math.floor(limit));
  const done: Undoable[] = [];
  const undone: Undoable[] = [];

  return {
    push(e) {
      done.push(e);
      // 가장 오래된 것부터 버린다 — 최근 것을 버리면 「방금 한 일이 안 되돌아간다」가 된다.
      if (done.length > cap) done.splice(0, done.length - cap);
      undone.length = 0;
    },
    undo() {
      const e = done.pop();
      if (!e) return null;
      // ⚠ **결과를 기다리지 않는다.** 비동기 되돌리기(작품)를 기다리면 이 함수가
      // `Promise` 를 내야 하고, 그러면 키 핸들러부터 패널 버튼까지 전부 async 가 된다.
      // 대신 순서를 스택이 보장한다 — 되돌리기는 사람이 누르는 속도로 일어나고, 같은
      // 대상을 두 번 연속 되돌리는 경우에도 **뒤에 쌓인 것이 먼저 나온다**(LIFO).
      void e.undo();
      undone.push(e);
      return e.label;
    },
    redo() {
      const e = undone.pop();
      if (!e) return null;
      void e.redo();
      done.push(e);
      return e.label;
    },
    peekUndo: () => done[done.length - 1] ?? null,
    canUndo: () => done.length > 0,
    canRedo: () => undone.length > 0,
    depth: () => done.length,
    redoDepth: () => undone.length,
    clear() {
      done.length = 0;
      undone.length = 0;
    },
  };
}

// world2/decide/leaf-color.ts — **나무 잎**의 색 판정. 순수 함수, three 의존 0.
//
// ── 왜 생겼나 (감독 신고 2026-08-22) ────────────────────────────────────────
// *"나무의 나뭇잎 초록색 채도가 낮은 것 같아."*
//
// 실측이 그것을 그대로 확인했다 — 같은 화면에 있는 잔디와 나란히 재면:
//
//   대상            R     G     B     hue      S(HSV)   V
//   LEAF_BASE_A    0.34  0.52  0.30   109.1°   0.423   0.520
//   LEAF_BASE_B    0.26  0.42  0.24   113.3°   0.429   0.420
//   잔디 0x78d833  0.47  0.85  0.20    94.9°   0.764   0.847
//   잔디 0x54b92c  0.33  0.73  0.17   103.0°   0.762   0.725
//   잔디 0x328c2a  0.20  0.55  0.16   115.1°   0.700   0.549
//
//   나뭇잎 평균 S = 0.426  ·  잔디 평균 S = 0.742  →  **잔디가 1.74배**
//
// ⚠ **이 표는 시작값의 근거일 뿐 최종 판정이 아니다**(검수관 P2). 잔디와 잎은 재질·
// 조명·보는 거리가 다르고, 잔디에는 `?gpal=` 이라는 별도 팔레트 축까지 있다. 즉 두
// 수치가 같아야 할 이유는 없다 — 이 표가 말하는 것은 **한쪽이 눈에 띄게 낮다**는
// 것까지이고, 얼마가 맞는지는 감독 화면이 정한다.
//
// ── 왜 이렇게 벌어져 있었나 ─────────────────────────────────────────────────
// 잔디 팔레트는 **감독이 직접 준 값**이다(`blade-shape.ts` 의 `DIRECTOR_TONES`,
// 2026-08-18). 나뭇잎은 그런 판정을 **한 번도 거친 적이 없다** — `parts/tree.ts` 의
// 주석이 *"두 톤을 섞어 수관이 단색 덩어리로 안 보이게 한다"* 라고만 적고 있고, 색
// 자체의 근거는 어디에도 없다. 즉 한쪽만 감독 손을 탄 것이다.
//
// ⚠ **그리고 이 저장소에서 채도는 내가 반복해서 틀린 축이다.** `blade-shape.ts` 가
// 그 이력을 적고 있다 — *"나는 «수치상 밝기·채도가 높으면 화면이 잘못된다» 를 세 번
// 규정했고 세 번 다 [틀렸다]"*. 그러므로 여기서도 **내가 값을 정하지 않는다.**
// 노브(`?leafsat=`)로 열고 감독이 화면에서 고른다.

import { saturateAroundLuma } from './blade-shape.js';

/** 채도를 만지기 전의 잎 색. `parts/tree.ts` 가 정점색으로 넣던 값 그대로다. */
export const LEAF_BASE_A: readonly [number, number, number] = [0.34, 0.52, 0.30];
/** 두 톤을 섞어 수관이 단색 덩어리로 안 보이게 한다 — 그 취지는 그대로 둔다. */
export const LEAF_BASE_B: readonly [number, number, number] = [0.26, 0.42, 0.24];

/**
 * 잎 채도 배수. `1` 이 항등원(신고 이전 화면).
 *
 * ── 값 (⚠ 화면 판정 전이라 근거가 없는 시작값) ─────────────────────────────
 * 1.6 은 위 표의 격차(1.74배)보다 **조금 낮게** 잡은 것이다 — 잔디와 똑같이 맞추면
 * 나무가 잔디에 묻히고, 신고는 *"낮다"* 였지 *"잔디와 같게"* 가 아니었다.
 *
 * ⚠ **그런데 이 시작값에는 근거가 없다.** 같은 날 낮 번짐에서 내가 0.15 를 잡았다가
 * 감독이 **두 배인 0.3** 을 골랐다 — 「없다/죽었다」는 신고에서 나는 낮게 잡는
 * 경향이 있고, 그 회차에 그것을 *"신고의 방향을 보지 않고 직전 회차의 방향을 관성으로
 * 옮긴 것"* 이라고 적었다. 그래서 이번엔 **넉넉한 쪽으로** 출발하되, 확정은 감독
 * 화면 판정이다. `?leafsat=` 후보를 비교한 뒤 이 자리에 판정을 적는다.
 */
export const LEAF_SAT = 1.6;

/** `?leafsat=` — 키와 범위를 여기 한 곳에 둔다(소비자가 각자 적으면 미러링이다). */
export const LEAF_SAT_KNOB = 'leafsat';
/** 0 = 완전 무채색(회색 잎), 3 = 과포화. 감독이 양 끝을 볼 수 있어야 판정이 선다. */
export const LEAF_SAT_MAX = 3;

/**
 * 채도만 밀고 **휘도는 보존한다**(Rec.709).
 *
 * 휘도를 보존하는 이유는 `blade-shape.ts` 의 `bladeToneHex` 와 같다 — *"채도만 미는데
 * 화면이 같이 밝아지면 감독이 두 축을 한 화면에서 못 가른다."* 그 파일은 `0xRRGGBB`
 * 정수를 다루고 여기는 0~1 정점색이라 입출력이 다르지만, **계수와 식은 같아야 한다.**
 *
 * ⚠ 그래서 계수를 여기에 다시 적지 않고 `blade-shape.ts` 의 `saturateAroundLuma` 를
 * **실제로 import 해서 쓴다.** ⚠⚠ 첫 판본은 이 문장을 적어 놓고 **계수를 복사한 자체
 * 구현**을 두고 있었다 — 문장이 참이 아니었다. 값 미러링을 없앴다고 적으면서 만들면
 * 다음 사람은 확인을 생략한다.
 *
 * 클램프 상한이 `1` 인 것은 여기가 **0~1 정점색**이기 때문이다(잔디는 0~255 정수).
 */
export function leafTone(
  base: readonly [number, number, number], sat: number,
): [number, number, number] {
  return saturateAroundLuma(base, sat, 1);
}

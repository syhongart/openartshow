export const RIPPLE_MIX = 0;

/**
 * 마루가 임계 이상인 구간이 주기에서 차지하는 비율.
 *
 * `band = sin(2πp)·0.5 + 0.5 ≥ lo` 는 `sin(θ) ≥ 2lo−1` 이고, 그 θ 구간은
 * `[asin(s), π−asin(s)]` 로 폭이 `π − 2·asin(s)` 다. 주기가 `2π` 이므로
 * 정규화 폭은 `0.5 − asin(s)/π`.
 *
 * 값을 고를 때 읽으라고 둔 것이지 런타임 경로가 아니다 — 위 `RIPPLE_CREST_*` 의 실측표가
 * 이 함수의 출력이다.
 */
export function rippleCrestWidth(lo: number): number {
  const s = 2 * lo - 1;
  if (s >= 1) return 0;
  if (s <= -1) return 1;
  return 0.5 - Math.asin(s) / Math.PI;
}

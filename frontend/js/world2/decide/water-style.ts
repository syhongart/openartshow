/**
 * 층2 수면. `?wlayer2` 가 `1` 이면 **대역하고** `0` 이면 숨긴다.
 *
 * ── 왜 대역으로 돌아왔나 (감독 판정 2026-08-20) ──────────────────────────────
 * 감독: *"2개 레이어로 움직이는것같은데. **아래것은 그래로있어서** 어색해"* (강가에서,
 * 아래 것은 «또 다른 물»). 그 아래 것이 **층1 바다 판**이다 — 세계 전체를 덮는
 * `PlaneGeometry(PLANE, PLANE, 1, 1)` 이라 정점이 네 귀퉁이뿐이고 강(−0.90) 밑
 * 50cm(−1.40)에 깔려 있다. 여태 안 보인 이유는 강이 불투명(0.82)이었기 때문이고,
 * **맑음(`?wclear`)을 켜서 물가 알파가 0.3 이 되자 드러났다.**
 *
 * 파동을 가진 것은 층2(`ocean-wave2` — 181m 패치·정점 2500)인데 그것을 우리가 숨기고
 * 있었다. 즉 **내가 연 맑음이 내가 숨긴 층의 부재를 드러냈다.**
 *
 * ── 숨긴 근거 둘, 그리고 각각의 해소 ────────────────────────────────────────
 * ① **트랜스폼 비공유** — `features/ocean.ts` 가 `sea2` 의 `position` 을 매 프레임
 *    플레이어에게 스냅 추종시키는데 대역은 `create()` 에서 한 번만 복사했다. 그러면
 *    대역이 스폰 자리에 남고 파형이 월드와 어긋난다. **해소**: 대역에 `system.update`
 *    를 붙여 매 프레임 원본 트랜스폼을 따라간다(메시 둘의 `position` 복사).
 * ② **반투명 이중 곱** — 같은 재질을 두 겹 얹으면 실효 불투명도가
 *    `1-(1-0.82)² = 0.967` 이 된다. **해소**: `features/ocean.ts` 의 `layerOpacity()`
 *    를 쓴다 — 기존 물이 `sea`/`sea2` 에 **이미 쓰고 있는 바로 그 함수**다. 새로 설계한
 *    것이 아니라 이 저장소가 같은 문제를 이미 푼 자리를 찾아 쓴 것이다.
 *
 * ⚠ 위 둘은 *"게임풍 수면은 자체 룩이 인상을 만드므로 층2 간섭무늬가 없어도 된다"* 는
 * 결론으로 이어져 있었다. **간섭무늬는 없어도 됐지만 정점 파동은 아니었다** — 그 둘이
 * 같은 메시에 실려 있다는 것을 그때 안 갈랐다.
 */
export const LAYER2_NAMES = ['ocean-wave2', 'river-wave2'] as const;


// world2/decide/fog.ts — **세계가 어디까지 보이는가.** 순수 함수만, import 0.
//
// ── 왜 생겼나 (팀장 판정 2026-08-02, 본편 ①) ────────────────────────────────
// 안개 밴드가 `main.ts` 안에 인라인으로 계산돼 있었다:
//
//     scene.fog = new THREE.Fog(0x0b0d12, CELL_X * 1.6, CELL_X * 2.4);
//
// **저장소에서 이 두 배수를 아는 곳은 그 한 줄뿐이었다.** 그래서 "안개 밖" 을 판단해야
// 하는 다른 모듈은 그것을 알 방법이 없었고, 실제로 NPC 가 자기 나름의 거리를 썼다 —
// 그 어긋남이 이번 회차가 찾아낸 결함이다:
//
//   `npc.ts` 의 은닉 임계  = RECYCLE_CELLS × cell = 102.4m   ← 재배치 거리
//   실제 안개 차단          = 2.4 × cell           =  76.8m
//
// 주석은 *"안개 밖이면 끈다"* 라고 적혀 있었다. **문장은 옳았고 값이 딴 것을 가리켰다.**
// 그 사이 25.6m 구간의 NPC 는 화면에 한 픽셀도 기여하지 못하면서 체당 45 드로우콜을
// 냈고, 그 수가 `shown` 진단으로 나가 **부팀장의 판정을 한 번 오도했다**(`shown=7` 을
// "안개 안" 으로 읽어 "멀어서 안 보인다는 배제됐다" 고 적었다 — 틀렸다).
//
// ── 그래서 배수를 여기 한 곳에 둔다 ─────────────────────────────────────────
// 소비자는 **거리 숫자를 자기 파일에 적지 않는다.** `fogBand(cell)` 을 부른다.
// 팀장 조건: *"51.2 / 76.8 을 NPC 쪽에 숫자로 적지 않는다. 주석에 거리 숫자를 적는
// 것도 미러링이다 — 이번 사고가 정확히 '주석이 안개를 말하는데 값은 102.4' 였다."*
//
// ── 무엇을 안 정하는가 ──────────────────────────────────────────────────────
// 안개 **색**은 여기 없다. 색은 시간대·날씨에 따라 `sky.js` 가 크로스페이드로 바꾸고,
// 밤 하한은 `decide/night.ts` 가 따로 본다. 여기가 정하는 것은 **거리**뿐이다 —
// 거리는 시간대와 무관하게 고정이고, 그래서 가시성 판단의 기준이 될 수 있다.

/** 안개 밴드. 셀 크기의 배수로 정의한다 — 세계가 커지면 시야도 같이 커진다 */
export interface FogBand {
  /** 여기서부터 대비가 깎이기 시작한다(m) */
  near: number;
  /** 여기서 완전히 닫힌다. **이 밖은 정의상 화면 기여 0**(m) */
  far: number;
}

/**
 * 안개가 시작되는 거리 = 셀의 몇 배인가.
 *
 * **가시성의 상한이 아니라 "온전히 보이는" 구간의 상한이다.** 이 밖에 놓인 것은
 * 대비가 깎인 채로 등장하고, 스스로 걸어서 회복할 수 없다면 영원히 그 상태다 —
 * NPC 스폰이 정확히 그 함정에 빠져 있었다(스폰 링의 절반이 이 밖이었다).
 */
export const FOG_NEAR_CELLS = 1.6;

/**
 * 안개가 완전히 닫히는 거리 = 셀의 몇 배인가.
 *
 * **이 밖을 그리는 것은 낭비다.** 화면에 기여할 수 없다는 것이 안개의 정의이므로,
 * 은닉·컬링 임계를 여기보다 멀리 잡으면 그만큼이 그대로 버려진다.
 */
export const FOG_FAR_CELLS = 2.4;

/**
 * 셀 크기에서 안개 밴드를 유도한다.
 *
 * @param cell 파셀 한 변(m). `DEFAULT_LAYOUT.cellX`
 */
export function fogBand(cell: number): FogBand {
  return { near: cell * FOG_NEAR_CELLS, far: cell * FOG_FAR_CELLS };
}

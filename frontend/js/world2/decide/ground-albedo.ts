// 지면 파츠의 **알베도** — 낮 휘도를 레지스트리에서 유도하고 밤 보정을 판정한다.
// 순수 판정이라 three 도 씬도 모른다.
//
// ── 무엇을 고치는가 (감독 지시 2026-08-05) ─────────────────────────────────
// *"정상적으로 밝은 느낌 나게 해."* / *"밤이여도 밤 분위기면 되지. 밤 하늘, 가로등만
// 있으면 되지.."*
//
// 밤 처방은 지금까지 전부 **빛**이었다(조명 하한·노출·안개). 빛은 알베도에 **곱해지
// 므로**, 알베도가 낮은 파츠는 밤 조명 아래에서 검정으로 죽는다 — 도로(선형 휘도
// 0.026)가 화면에서 4/255 다. 순검정과 구별되지 않는다.
//
// 노출·조명을 더 올려서 고칠 수 없다. 그것들은 **화면 전체**를 밝히므로 하늘과 안개가
// 함께 떠서 밤이 밤이 아니게 된다(`decide/night.ts` 의 노출 스윕이 정확히 그 벽에서
// 1.6 을 1.4 로 내렸다). 감독이 원하는 것은 그 반대다: **하늘은 밤인 채로, 지면만
// 정상적으로 보이는 것.**
//
// 알베도를 올리면 정확히 그것이 된다 — `material.color` 는 그 재질에만 걸리므로
// 하늘 돔·안개·물은 한 톨도 안 움직인다.
//
// ── 왜 파츠마다 다른 배수를 주지 않는가 (되돌아온 자리다) ──────────────────
// 첫 판본은 파츠별로 다른 배수를 걸어 **밤에 잔디를 눌렀다**(알베도 12배 차를 좁히는
// 방향). 감독 판정으로 철회됐다: *"밤이여도 이전이 더 좋은데?"* — 밤에도 잔디가 초록인
// 것이 이 세계의 룩이다. 대비를 건드리는 것 자체가 룩의 판단이었고, 그것을 수치만 보고
// "문제" 로 규정한 것이 잘못이었다.
//
// 그래서 지금은 **전 파츠에 같은 배수**다. 파츠 사이의 비가 산술적으로 보존되므로 감독이
// 승인한 대비(지면 대 도로 5.2배, *"바닥 격자 바닥이 잘 드러나지 않아"* 의 처방)도,
// 잔디의 초록도 그대로다. 바뀌는 것은 **밝기 하나**뿐이다.
//
// ── 무엇을 만지는가 ─────────────────────────────────────────────────────────
// `MeshStandardMaterial.color` 하나다. **uniform 이라 파이프라인 캐시키에 안 들어간다** —
// 매 프레임 바꿔도 재컴파일이 없다(`systems/instancing.ts` 의 `materialOf` 규약이고,
// 가로등 `emissiveIntensity` 가 첫 소비자였다). 실측으로도 확인했다: `smoke:vite` `[7]`
// 이 회전·주행·복귀 내내 `pipe 30` 상수, `[8]` 이 시간대×날씨 12조합에 증가 0.
// `map`·`transparent` 같은 구조 신호는 여기서 절대 건드리지 않는다.
//
// ── 목록을 여기에 적지 않는다 ───────────────────────────────────────────────
// 처음엔 지면 파츠 세 이름을 배열 리터럴로 이 파일에 적었고, `world2-parts-registry`
// 테스트가 그것을 잡았다(그 검사는 파츠 이름이 한 줄에 둘 이상 인용되면 목록을 다시 적은
// 것으로 본다 — 이 주석이 이름을 나열하지 않는 이유이기도 하다). 옳은 지적이다: 새 지면
// 파츠가 생기면 그 목록이 조용히 낡고, 증상은 *"그 파츠만 밤에 안 밝아짐"* 이라 원인을
// 짐작하기 어렵다.
//
// 그래서 파츠가 **자기 성질을 신고**하고(`PartSpec.groundBase`) 여기서는 레지스트리를
// 걸러내기만 한다. 색의 원천도 파츠 쪽에 있다 — 텍스처를 굽는 것이 파츠이므로 거기가
// 원래 자리이고, 이 방향(`decide → parts`)이 기존 의존과도 같다.

import { PARTS } from '../parts/index.js';

/** 지면을 덮는 파츠 이름. **레지스트리에서 유도된다** — 여기 목록을 적지 않는다 */
export const GROUND_KEYS: readonly string[] =
  PARTS.filter((p) => p.groundBase !== undefined).map((p) => p.kind);

/** sRGB 채널(0~1) → 선형. IEC 61966-2-1 의 역전달함수 */
function toLinear(c: number): number {
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

/**
 * sRGB hex 의 **선형 휘도**(Rec.709). 0~1.
 *
 * 감마를 반드시 푼다. sRGB 채널값을 그대로 가중합하면 어두운 색이 실제보다 훨씬 밝게
 * 나오고, 그러면 아래 상한이 통째로 틀린다 — 아스팔트(`#2a2d33`)는 sRGB 평균 0.18 이지만
 * 선형 휘도는 **0.026** 이다. 7배 차이다.
 */
export function srgbLuminance(hex: number): number {
  const r = toLinear(((hex >> 16) & 0xff) / 255);
  const g = toLinear(((hex >> 8) & 0xff) / 255);
  const b = toLinear((hex & 0xff) / 255);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** `tones` 의 평균 휘도. 배치가 균등 확률로 고르므로 기대값이 이것이다 */
function meanLuminance(tones: readonly number[]): number {
  let s = 0;
  for (const t of tones) s += srgbLuminance(t);
  return s / tones.length;
}

/**
 * 각 파츠의 **낮 대표 알베도 휘도.**
 *
 * 최종 알베도 = `map` 샘플 × `material.color` × `instanceColor`(=`tones`) 이므로
 * `groundBase × tones 평균` 으로 잡는다. `map` 이 없는 파츠는 `groundBase` 가 흰색(=1)
 * 이라 `tones` 만 남는다 — 같은 식이 양쪽을 덮는다.
 *
 * 실측(2026-08-05): 잔디 0.3163 · 지면 판 0.1350 · 도로 0.0261.
 *
 * ⚠ **근사다.** 텍스처는 바탕색 위에 풀결·자갈·얼룩을 덧그리므로 실제 텍셀 평균은
 * 바탕과 조금 다르다. 그 편차를 재려면 캔버스를 실제로 굽고 픽셀을 평균 내야 하는데,
 * 그것은 순수 판정이 아니고 DOM 이 필요하다. 여기서 쓰는 용도는 **상한 유도**뿐이고
 * 덧그림은 저대비·저면적이라(불투명도 0.32/0.45 상한) 그 자릿수를 바꾸지 않는다.
 */
export const DAY_ALBEDO: Record<string, number> = Object.fromEntries(
  PARTS.filter((p) => p.groundBase !== undefined)
    .map((p) => [p.kind, srgbLuminance(p.groundBase as number) * meanLuminance(p.tones)]),
);

/**
 * 배수의 **물리적 상한.** 알베도는 1을 넘을 수 없다 — 표면이 받은 빛보다 많이 반사하면
 * 에너지 보존이 깨지고, 화면에서는 밤인데 지면이 자체발광처럼 뜬다.
 *
 * **가장 밝은 파츠가 상한을 정한다.** 전 파츠에 같은 배수를 거니까 잔디가 1에 닿는
 * 순간이 한계다. 실측값으로는 `1 / 0.3163 ≈ 3.16`.
 *
 * 값을 적지 않고 유도하는 이유는 늘 같다 — 잔디 색이나 `tones` 가 바뀌면 상한도 따라
 * 움직여야 하는데, 상수로 박으면 그날 조용히 어긋난다.
 */
export const MAX_LIFT = 1 / Math.max(...Object.values(DAY_ALBEDO));

/**
 * 한밤의 지면 알베도 배수. **1 이면 아무 일도 안 한다.**
 *
 * ── 감독이 고른 값이다. 단 **잠정**이다 (2026-08-05) ──────────────────────
 * 라이브에 1.0·1.5·2.0·2.6 네 판본을 링크로 올려 감독이 2.0 을 골랐고, 그때 말이
 * *"일단 해보고. 나중에 변경하지"* 였다. **확정이 아니라 채택이다** — 쓰다가 바꾼다.
 *
 * 왜 이 자리인가: **도로를 검정에서 꺼내되 잔디가 상한에 닿지 않는다.** 도로 알베도
 * 0.026 → 0.052, 잔디 0.316 → 0.633(상한까지 37% 여유). 세 파츠의 비는 어느 값에서도
 * 정확히 보존되므로 이 값을 옮겨도 대비는 안 흔들린다.
 *
 * 헤드리스 실측(1280×720, `?at=river&time=night`, 구역 평균 휘도):
 *
 *   배수    1.0    1.5    2.0    2.6
 *   잔디   59.5   80.6   98.2  116.2
 *   도로    4.4    7.9   10.1   16.7
 *   하늘   30.7   30.7   30.7   30.7   ← **전부 동일**(지면만 움직인다)
 *
 * ⚠️ 헤드리스는 WebGL(swiftshader)이고 감독 기기는 WebGPU 라 톤매핑을 거친 최종 밝기가
 * 같지 않다. 바꾸려면 `?glift=` 로 다시 돌려 본다 — `?glift=1` 이면 완전한 no-op 이다.
 */
export const NIGHT_GROUND_LIFT = 2.0;

/**
 * 시간대별 지면 알베도 배수. `material.color` 에 곱할 **회색 스칼라 하나**다.
 *
 * ── 낮에는 정확히 1 ─────────────────────────────────────────────────────────
 * `n=0` 이면 1(곱셈 항등원)이라 낮 룩을 건드릴 여지가 원천적으로 없다. 노을(0.4)에서는
 * 부분적으로 올라간다 — 해가 기울며 지면이 먼저 죽는 것을 그만큼 되받는다.
 *
 * ── 왜 파츠별로 나누지 않는가 ───────────────────────────────────────────────
 * 파츠마다 다른 배수를 주면 **대비가 바뀐다.** 그것은 룩의 판단이고, 한 번 해봤다가
 * 감독 판정으로 철회했다(파일 머리 참조). 하나의 스칼라면 비가 산술적으로 보존된다 —
 * 아래 테스트가 그것을 못 박는다.
 *
 * ── 왜 색조가 아니라 밝기만인가 ─────────────────────────────────────────────
 * 밤에 지면 색조를 푸르게 미는 것도 룩의 판단이다. 여기서 하는 것은 **밝기 하나**이고,
 * 축을 섞으면 어느 쪽이 화면을 움직였는지 못 가른다.
 */
export function groundLift(n: number, lift: number = NIGHT_GROUND_LIFT): number {
  const k = Math.max(0, Math.min(1, n));
  // 상한을 넘겨 받으면 눌러 담는다 — 노브로 3.16 을 넘기면 잔디가 자체발광처럼 뜬다.
  // 1 미만도 막는다: 지면을 **어둡게** 하는 방향은 철회된 설계다.
  const l = Math.max(1, Math.min(MAX_LIFT, lift));
  return 1 + (l - 1) * k;
}

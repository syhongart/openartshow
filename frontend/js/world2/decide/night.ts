// 밤의 밝기와 가로등 점등 — **순수 판정.** 씬도 재질도 모른다.
//
// ── 감독 지시 ────────────────────────────────────────────────────────────────
// *"밤에는 가로등이 켜져야 하고… 지금 밤이 너무 어두워."*
//
// ── 왜 어두웠나 ─────────────────────────────────────────────────────────────
// `sky.js` 의 `LIGHT.night.clear` 를 열어 보면 원인이 **밝기가 아니라 색**이다:
//
//   sunI 0.24 · hemiI 0.55   ← 낮(0.95 / 1.0) 대비 그리 낮지 않다
//   hemiS 0x39445c (명도 27%)
//   hemiG 0x232a24 (명도 **15%**)  ← 지면을 비추는 색이 거의 검정이다
//
// `HemisphereLight` 의 `groundColor` 는 **아래에서 올라오는 빛**이다. 그것이 검정이면
// 위를 향한 면(바닥·도로·정원)에 닿는 빛이 없다. 감독이 앞서 *"바닥이 검다"* 고 한 것과
// 같은 뿌리다. 밝기를 올려도 검정을 곱하면 검정이라 안 밝아진다.
//
// ── 왜 `sky.js` 를 안 고치는가 ──────────────────────────────────────────────
// 라이브 world1 이 같은 파일을 쓴다. 밤 팔레트를 거기서 바꾸면 미술관 오픈월드의 룩이
// 함께 바뀐다. world2 쪽 어댑터에서만 **하한**을 얹는다 — 그것이 어댑터가 있는 이유다.
//
// ── 왜 하한(max)인가 ────────────────────────────────────────────────────────
// 보정을 곱셈으로 하면 매 프레임 곱해져 발산한다. 하한은 **몇 번 적용해도 결과가 같다**
// (멱등). `sky.js` 가 값을 덮어쓰든 안 쓰든, 크로스페이드 중이든 아니든 안전하다.
// 이 성질이 없으면 "언제 적용되는가" 를 정확히 알아야 하고, 그 지식은 곧 어긋난다.

/** 하늘이 아는 시간대. `sky.js` 의 `LIGHT` 최상위 키와 같다 */
export type SkyTime = 'day' | 'sunset' | 'night';

/**
 * 유효한 시간대 목록. **타입과 같은 곳에 둔다.**
 *
 * `features/sky.ts` 안에 사본으로 있던 것을 옮겼다. 시간대를 읽는 곳이 하나였을 때는
 * 문제가 없었으나, 조립부가 시간대를 소유하게 되면서 목록을 보는 곳이 둘이 됐다 — 그
 * 순간 사본은 값 미러링이다(목록 밖 값이 넘어가면 팔레트 조회가 `undefined` 가 된다).
 */
export const TIMES = ['day', 'sunset', 'night'] as const;

/**
 * 밤 정도 0~1. 모르는 값은 낮으로 본다 — 밝은 쪽이 안전한 기본값이다(어두워서 아무것도
 * 안 보이는 것보다 밝아서 밋밋한 편이 낫다).
 */
export function nightness(time: string): number {
  if (time === 'night') return 1;
  // 노을은 이미 어둑하지만 가로등이 완전히 켜질 시간은 아니다. 실제 도시도 이때
  // 하나둘 켜지기 시작한다.
  if (time === 'sunset') return 0.4;
  return 0;
}

/** 조명 하한. 이보다 어두우면 끌어올린다 */
export interface NightFloor {
  /** `HemisphereLight.intensity` 하한 */
  hemiI: number;
  /** `DirectionalLight.intensity` 하한 — 달빛 */
  sunI: number;
  /** `HemisphereLight.groundColor` 채널 하한(0~1 RGB) */
  ground: readonly [number, number, number];
  /** `HemisphereLight.color` 채널 하한(0~1 RGB) */
  sky: readonly [number, number, number];
  /**
   * `renderer.toneMappingExposure` 하한.
   *
   * 다른 넷과 **성질이 다르다** — 조명은 재질에 닿는 빛을 키우지만 노출은 그 결과를
   * 포함해 **화면 전체**를 키운다. 하늘 돔·안개·물까지 같이 올라간다.
   */
  exposure: number;
  /** `scene.fog.color` 채널 하한(0~1 RGB) */
  fog: readonly [number, number, number];
}

/**
 * 밤 밝기 축의 **튜닝값**. 전부 선택이고, 없으면 아래 상수를 쓴다.
 *
 * ── 왜 인자로 여는가 ────────────────────────────────────────────────────────
 * 판정은 순수해야 하니 URL 을 여기서 읽을 수 없다. 그런데 값은 감독 실기기(WebGPU)에서
 * 골라야 한다 — 헤드리스는 WebGL 이라 톤매핑을 거친 최종 밝기가 같지 않다. 그래서
 * **읽는 것은 배선(`features/sky.ts`)이 하고, 쓰는 것은 여기가 한다.**
 */
export interface NightTune {
  hemiI?: number;
  sunI?: number;
  exposure?: number;
  /** 안개 목표색의 밝기 배수. 1이면 `sky.js` 값 그대로라 하한이 걸리지 않는다 */
  fogScale?: number;
  /** 지면색(`hemiG`) 목표의 밝기 배수 */
  groundScale?: number;
}

/**
 * 한밤의 목표 지면색 — `0x3a4250`.
 *
 * 명도 약 25% 로, 원래 값(15%)보다 밝지만 낮(0x8fa385, 60%)에는 한참 못 미친다.
 * 밤을 밤으로 두면서 바닥의 형태만 읽히게 하는 선이다. 푸른 기를 남긴 것은 달빛
 * 아래 지면이 중성 회색으로 보이면 시간대가 사라지기 때문이다.
 */
const NIGHT_GROUND = [0x3a / 255, 0x42 / 255, 0x50 / 255] as const;

/** 한밤의 목표 천공색 — `0x4a5878`. 원래 0x39445c 보다 한 단계 밝다 */
const NIGHT_SKY = [0x4a / 255, 0x58 / 255, 0x78 / 255] as const;

/**
 * 한밤의 반구광 하한. `sky.js` 원래 값은 0.55.
 *
 * 0.85 로 한 번 올렸는데 감독 판정이 또 *"어둡다"* 였다. 헤드리스 스윕(390×844,
 * 구역별 평균 휘도)에서 1.2 가 다른 축과 함께 쓸 때 가장 나았다 — 단독으로는 조명이
 * 화면 전체를 그리 못 움직인다(1.5 로 올려도 +13%).
 */
export const NIGHT_HEMI_I = 1.2;
/** 한밤의 달빛 하한. 원래 0.24 */
export const NIGHT_SUN_I = 0.34;

/**
 * 한밤의 안개색 하한 — `sky.js` 의 밤 맑음 `fog: 0x3d4762` **와 같은 값**.
 *
 * 같은 값을 적어 둔 것이 요점이다. `fogScale` 1 이면 하한이 현재 색과 같아 **아무 일도
 * 일어나지 않는다.** 축을 열되 기본 동작은 바꾸지 않는 것 — 무엇이 밤을 어둡게 하는지
 * 아직 재지 않았는데 값부터 올리면, 그게 이 프로젝트가 열 번 반복한 "처방 먼저" 다.
 *
 * ⚠️ `sky.js` 의 값을 **복제**한 것이라 미러링이다. 저쪽이 바뀌면 여기가 조용히
 * 어긋난다 — 그래서 `tests/world2-night.test.ts` 가 두 값이 같은지 검사한다.
 */
const NIGHT_FOG = [0x3d / 255, 0x47 / 255, 0x62 / 255] as const;

/**
 * 한밤의 톤매핑 노출.
 *
 * ── 스윕이 고른 값이다 ──────────────────────────────────────────────────────
 * 헤드리스 390×844 세로 화면에서 조건 9개를 재고 정했다(구역별 평균 휘도, Rec.709):
 *
 *   기본 밤      상단 19 · 중단 39 · 하단 10 · 전체 23
 *   낮(대조군)   상단 200 · 중단 115 · 하단 27 · 전체 114
 *   노출 1.6     상단 31 · 중단 52 · 하단 13 · 전체 32   (+39%)
 *   안개 2.2     상단 19 · 중단 45 · 하단 10 · 전체 25   (+9%)
 *   조명 1.5     상단 19 · 중단 45 · 하단 12 · 전체 26   (+13%)
 *
 * 노출이 압도적이다. 다른 축은 재질에 닿는 빛이나 특정 거리대만 건드리는데, 노출은
 * 톤매핑 앞단이라 **하늘 돔·안개·지면·물이 한꺼번에** 올라간다.
 *
 * ── 왜 1.6이 아니라 1.4인가 ────────────────────────────────────────────────
 * 노출만 올리면 하늘이 가장 많이 밝아진다(19 → 31). 밤하늘이 밝아지는 것은 밤을
 * 밝히는 게 아니라 **밤이 아니게 만드는 것**이다. 1.4 에 안개·조명을 섞으면 같은
 * 전체 밝기(32)를 내면서 하늘은 덜 뜨고(27) 원경이 더 살아난다(56) — 볼 것이 있는
 * 구간을 밝히는 쪽이다.
 */
export const NIGHT_EXPOSURE = 1.4;

/**
 * 한밤의 안개 밝기 배수. **1.0 — 손대지 않는다.**
 *
 * ── 1.6 이었고, 그것이 안개를 없앴다 (감독 스크린샷) ──────────────────────
 * 감독: *"안개가 안보여"* — 원경 건물이 또렷하게 떠 있었다.
 *
 * `sky.js` 는 **하늘 돔의 지평선을 안개색으로 칠한다**(그 파일 주석 ⑨ *"지평선 =
 * fog색 — 이음새 제거의 핵"*). 안개색과 지평선이 같아야 먼 것이 하늘로 **녹아든다.**
 *
 * 밤을 밝히면서 안개색에만 1.6 을 곱했다. 지평선은 그대로인데 안개만 밝아지니,
 * 원경이 하늘에 섞이는 대신 **하늘보다 밝게 떠서 도드라졌다.** 안개가 안 보이는 게
 * 아니라 안개가 안개 노릇을 못 하게 된 것이다.
 *
 * 잃는 것도 적다 — 스윕에서 이 축 단독 효과는 2.2 로 올려도 **+9%** 였다(노출은
 * +39%). 효과는 작고 부작용은 컸다.
 *
 * 축은 열어 둔다(`?nfog=`). 나중에 `sky.js` 의 지평선까지 함께 밝히는 방법을 찾으면
 * 그때 값을 올릴 수 있다 — **둘을 함께 움직여야** 한다는 것이 이번에 배운 것이다.
 */
export const NIGHT_FOG_SCALE = 1.0;

/**
 * 한밤의 지면색 배수 — **재지 못한 축이다.**
 *
 * 스윕에서 하단(지면)이 가장 안 움직였다. 기본 10, 노출 1.6 에서도 13, 조명을 1.5 +
 * 달빛 0.7 까지 올려야 15였다. 그런데 **낮 대조군의 하단도 27**이다 — 한낮의 태양광
 * 에서도 그 정도라면 밤에 어두운 원인은 조명이 아니라 **지면 알베도 자체**다(도로
 * 텍스처 베이스가 `#2a2d33`, 명도 17%).
 *
 * 그것은 낮·밤 공통 사안이라 밤 처방으로 고칠 것이 아니다. 다만 `hemiG` **색** 하한은
 * 스윕에서 축으로 열지 않아 못 쟀으므로, 1(무변경)으로 두고 `?nground=` 로 열어 둔다.
 * 재지 않은 것을 기본값으로 박지 않는다.
 */
export const NIGHT_GROUND_SCALE = 1.0;

/**
 * 밤 정도에 비례한 하한. 낮(`n=0`)에는 전부 0이라 **아무 일도 하지 않는다** —
 * 낮 값이 이미 하한보다 높으므로 자연히 no-op 이 되는 것이 아니라, 하한 자체가
 * 0 이라 계산도 무의미해진다. 낮 룩을 건드릴 여지를 원천적으로 없앤다.
 *
 * `exposure` 만 예외로 **1에서 출발한다.** 노출은 하한이 아니라 배수라서, 0 으로
 * 내려가면 화면이 검어진다. 낮에는 1(항등원)이어야 손대지 않은 것이 된다.
 */
export function nightFloor(n: number, tune?: NightTune): NightFloor {
  const k = Math.max(0, Math.min(1, n));
  const lerp = (v: number) => v * k;
  const hemiI = tune?.hemiI ?? NIGHT_HEMI_I;
  const sunI = tune?.sunI ?? NIGHT_SUN_I;
  const exposure = tune?.exposure ?? NIGHT_EXPOSURE;
  const fogScale = tune?.fogScale ?? NIGHT_FOG_SCALE;
  const gs = tune?.groundScale ?? NIGHT_GROUND_SCALE;
  return {
    hemiI: lerp(hemiI),
    sunI: lerp(sunI),
    ground: [lerp(NIGHT_GROUND[0] * gs), lerp(NIGHT_GROUND[1] * gs), lerp(NIGHT_GROUND[2] * gs)],
    sky: [lerp(NIGHT_SKY[0]), lerp(NIGHT_SKY[1]), lerp(NIGHT_SKY[2])],
    // 1 → exposure 로 보간한다. 낮이면 정확히 1이라 집행 쪽에서 no-op 이 된다.
    exposure: 1 + (exposure - 1) * k,
    fog: [lerp(NIGHT_FOG[0] * fogScale), lerp(NIGHT_FOG[1] * fogScale), lerp(NIGHT_FOG[2] * fogScale)],
  };
}

/**
 * 등불색(`parts/lamp.ts` 의 `LAMP_LIGHT` = `0xffc86e`)의 **휘도**.
 *
 * Rec.709 가중치로 계산한 값이고, 블룸 문턱과 비교하는 기준이라 여기 상수로 둔다.
 * 등불색을 바꾸면 이 값도 함께 바꿔야 한다 — 그 정합은 테스트가 지킨다.
 */
export const LAMP_LUMINANCE = 0.2126 * (0xff / 255) + 0.7152 * (0xc8 / 255) + 0.0722 * (0x6e / 255);

/**
 * 한밤의 가로등 발광 배수.
 *
 * ── 왜 1을 넘는가 (감독 지적에서 고쳤다) ────────────────────────────────────
 * 감독: *"가로등 똑같은데."* 블룸을 켰는데 화면이 그대로였다.
 *
 * 원인은 **가로등이 블룸 문턱을 못 넘은 것**이었다. 등불색의 휘도가 0.805 인데 문턱을
 * 0.85 로 잡아서, 블룸이 돌아도 걸리는 픽셀이 하나도 없었다. 문턱을 "별까지 안 걸리게
 * 좁게" 정하면서 정작 **가로등이 그 문턱을 넘는지 계산하지 않았다.**
 *
 * 고치는 방법이 둘이었다 — 문턱을 낮추거나, 등을 밝히거나. 후자를 골랐다. 문턱을
 * 낮추면 밤하늘 별과 물 하이라이트까지 함께 걸려 화면이 뿌예지는데, 감독이 원한 것은
 * "가로등 조명 옆" 이다. **등만 선택적으로 문턱 위로 올리는 것**이 그 요구에 맞는다.
 *
 * 1.8 이면 휘도가 0.805 × 1.8 = 1.45 로 문턱(0.75)을 확실히 넘는다. 렌더는 톤매핑
 * 전까지 HDR 이라 1 을 넘겨도 값이 잘리지 않고, ACES 톤매핑이 롤오프로 받아 준다.
 */
export const LAMP_MAX_GLOW = 1.8;

/**
 * 가로등 발광 강도(`emissiveIntensity`). 0 이면 꺼진 것.
 *
 * 낮에 **완전히 0** 인 것이 중요하다. 약하게라도 켜 두면 대낮에 가로등이 누렇게 떠서
 * 고장난 것처럼 보인다 — 켜진 것도 꺼진 것도 아닌 상태가 가장 나쁘다.
 */
export function lampGlow(n: number): number {
  const k = Math.max(0, Math.min(1, n));
  if (k <= 0) return 0;
  // 노을(0.4)에서 이미 절반 넘게 올라온다 — 해가 지기 시작하면 먼저 켜지는 편이
  // 자연스럽고, 어두워진 뒤에 켜지면 "늦게 켜졌다"는 인상이 남는다.
  return LAMP_MAX_GLOW * Math.min(1, 0.35 + k * 0.65);
}

// world2/decide/edit-tabs.ts — 편집 패널의 **카테고리 탭** 판정. DOM 을 안 만진다.
//
// 감독 지시 2026-08-19: *"우리 개발용 편집창도 카테고리 탭. 공용기능. 블렌더 유니티 창을
// 참조해서 만들어봐. **막 나열하니 정신없잖아**"*
//
// ── 무엇이 문제였나 — 세어 보면 드러난다 ───────────────────────────────────
// 개편 전 `#w2-edit` 은 컨트롤을 **세로로 한 줄씩 32개** 쌓고 있었다(실측, `panel/dom.ts`
// 의 `body.append` 순서):
//
//   팔레트(검색 + 마을 파츠 8 + GLB 1) · 사진 걸기 · 선택 줄 · 수치칸 5 · 크기 슬라이더 ·
//   회전 2 · 크기 2 · 높이 3 · 격자/복제/삭제/구역되돌리기 4 · 시점 5 · 셰이딩 3 ·
//   표면 재질(슬롯 6 + 배율 + 각도 4 + 반짝임 + 메탈릭 + 맵 2) · 내보내기 · 상태 2
//
// 폭이 212px 이라 세로로만 자라고, 그래서 **지금 하려는 일과 무관한 컨트롤이 늘 화면의
// 90%를 차지한다.** 작품 하나를 옮기려고 들어와도 표면 재질 슬라이더 넷이 함께 보인다.
//
// ── 블렌더·유니티가 같은 문제를 푼 방식 (감독이 참조하라고 지목) ────────────
// 둘 다 **두 층으로 가른다.**
//
//   ① **상시 툴바** — 뷰포트 자체를 다루는 것. 무엇을 골랐든 늘 필요하다.
//      블렌더는 뷰포트 헤더(시점·셰이딩 아이콘 4개), 유니티는 씬뷰 좌상단 툴바.
//   ② **탭/섹션** — 지금 다루는 대상에 따라 갈리는 것.
//      블렌더 Properties 의 세로 아이콘 탭, 유니티 Inspector 의 컴포넌트 접이식 섹션.
//
// 감독 문언의 *"공용기능"* 이 ①이다. 그래서 시점·셰이딩은 **탭 안에 넣지 않는다** —
// 넣으면 「표면을 만지다가 위에서 보려면 탭을 옮겨야」 하고, 그것이 정확히 두 도구가
// 피한 형태다.
//
// ── 탭을 넷으로 가른 기준 — 「무엇을 다루는가」 ─────────────────────────────
// 라벨이 아니라 **대상**으로 갈랐다. 대상이 같으면 한 탭에 있고, 다르면 갈린다:
//
//   놓기   아직 없는 것을 만든다        (팔레트 · 사진 걸기)
//   속성   고른 것 하나를 만진다        (수치 · 크기 · 회전 · 높이 · 복제 · 삭제)
//   표면   세계 전체의 재질을 만진다     (종류당 하나를 온 세계가 공유한다)
//   파일   이 문서를 다룬다             (내보내기)
//
// 「표면」이 「속성」과 갈리는 이유가 이 기준을 가장 잘 보여 준다 — 둘 다 «값을 만진다»
// 지만 **대상이 다르다**(고른 것 하나 vs 온 세계). 실제로 표면 재질은 아무것도 안 골라도
// 동작하고, 속성은 골라야만 동작한다. 그 차이가 화면에서 갈려 있어야 한다.
//
// ⚠ **아웃라이너는 탭에 안 들어간다** — 그것은 패널 밖(왼쪽)에 별도로 산다. 블렌더도
// 아웃라이너를 Properties 안에 넣지 않는다. 「무엇이 있나」와 「그것을 어떻게 만지나」는
// 다른 물음이고, 둘을 함께 보는 것이 편집의 기본 자세다.

/** 탭 하나의 식별자. 화면 문자열이 아니라 **키**다 — 라벨은 아래 표가 소유한다 */
export type EditTab = 'place' | 'props' | 'surface' | 'file';

export interface TabDef {
  readonly id: EditTab;
  /** 화면에 보이는 글. 폭 212px 을 넷이 나누므로 **두 글자**가 상한이다 */
  readonly label: string;
  /**
   * 앞에 붙는 그림글자. 글자만으로는 넷이 비슷해 보여 눈이 자리를 못 외운다 —
   * 블렌더가 Properties 탭을 **아이콘만**으로 두는 이유이고, 우리는 폭이 있어 둘 다 쓴다.
   */
  readonly icon: string;
}

/**
 * 탭 표. **순서가 곧 화면 순서**다.
 *
 * 「놓기」가 처음인 이유: 빈 세계에서 편집을 켜면 할 수 있는 일이 그것뿐이다. 「파일」이
 * 끝인 이유: 내보내기는 작업의 마지막이고, 실수로 누르면 안 되는 것을 손이 먼저 닿는
 * 자리에 두지 않는다.
 */
export const EDIT_TABS: readonly TabDef[] = [
  { id: 'place', label: '놓기', icon: '➕' },
  { id: 'props', label: '속성', icon: '⚙️' },
  { id: 'surface', label: '표면', icon: '🎨' },
  { id: 'file', label: '파일', icon: '💾' },
];

/** 처음 열었을 때. 빈 세계에서 할 수 있는 일이 「놓기」뿐이라 거기서 시작한다 */
export const TAB_DEFAULT: EditTab = 'place';

/**
 * **무언가를 골랐을 때** 갈 탭. 유니티가 계층 뷰 선택에 Inspector 를 맞추는 그 동작이다.
 *
 * 안 옮기면 골라 놓고 수치칸이 안 보여 「골랐는데 아무것도 안 뜬다」가 된다 — 창이 둘인
 * 유니티와 달리 우리는 **탭 하나**라 보이지 않는 것은 없는 것과 같다.
 *
 * ── ⚠ 「놓은 직후에는 안 옮긴다」 분기를 만들었다가 **걷어냈다** ─────────────
 * 첫 판본은 *"「놓기」 탭에서 나무를 연달아 심는데 놓을 때마다 속성으로 튀면 안 된다"*
 * 는 근거로 `justPlaced` 인자를 뒀다. 유니티·블렌더를 쓰던 감각에서 나온 유추였고
 * **이 코드베이스에서는 그 상황이 성립하지 않는다.**
 *
 * 실측(`edit/actions.ts` 의 `placeAt`·`placePartAt`): 놓기는 `select()` 를 **안 부른다.**
 * 놓은 뒤 화면은 *"놓았습니다 — 클릭해 고르면 옮길 수 있습니다"* 라고 말할 뿐이고
 * `st.target` 은 `null` 로 남는다. 즉 **놓아서 생기는 선택이 없으므로** 탭이 튈 일도 없다.
 *
 * 죽은 분기를 남기면 다음 사람이 그것을 근거로 읽는다 — 이 저장소가 「참인 문장에서
 * 성립하지 않는 결론」이라고 이름 붙인 형태다. 그래서 분기 대신 **이 기록**을 남긴다:
 * 놓기가 선택을 만들도록 바뀌는 날, 이 문단이 그때 무엇을 다시 봐야 하는지 알려 준다.
 */
export const TAB_ON_PICK: EditTab = 'props';

/**
 * 이 탭이 **지금 쓸 것이 있는가**. 없으면 화면이 그렇다고 말해야 한다.
 *
 * ⚠ **비활성으로 만들지 않는다** — 누를 수 없는 탭은 «왜 안 눌리지» 가 되고, 그 답이
 * 화면에 없다. 대신 눌리게 두고 **탭 안에서 이유를 말한다**(「먼저 물건을 클릭해
 * 고르세요」). 이 저장소가 「거짓 UI」라고 부르는 것의 반대편이다.
 *
 * 지금 쓰는 곳은 탭 라벨의 흐림 표시 하나다 — 「여기 지금 볼 게 없다」를 **미리** 알리면
 * 헛걸음이 준다.
 */
export function tabHasContent(tab: EditTab, hasTarget: boolean): boolean {
  return tab === 'props' ? hasTarget : true;
}

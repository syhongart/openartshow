// `decide/water.ts` 에서 떼어냈다(2026-08-20). 그 파일은 «어디가 물인가»(격자·강 경로·
// 깊이·흐름)를 판정하는데 광택은 **«물이 어떻게 보이는가»** 라 축이 다르고, 환경맵
// 세기가 붙으면서 이 절만 넉넉히 커졌다. `check:filesize` 가 그 신호를 냈다.
//
// ⚠ 소비자는 여전히 `decide/water.js` 를 통해 받는다(그 파일이 재수출한다) — import
// 경로를 한꺼번에 갈면 이 회차의 diff 가 광택과 무관한 파일까지 번진다.

import { paletteTime, type SkyTime } from './night.js';

// ── 수면 광택 — 시간대별 (감독 지시 2026-07-31 "반짝임부터 살려봐") ────────────
//
// ── 왜 시간대로 나누는가 ────────────────────────────────────────────────────
// 예전에 감독이 *"밤 강에서 반사가 어색하네. 밤인데 빛이 이렇게 많지 않잖아"* 라고
// 해서 `normalScale` 을 0.85→0.35, `roughness` 를 0.28→0.62 로 올렸다. **전역으로.**
// `ocean.ts` 주석은 그 선택을 이렇게 정당화했다:
//
//   "시간대로 분기하지 않는다. 낮에도 이 정도가 과하지 않고, 분기를 넣으면 바다가
//    하늘의 상태를 알아야 해서 기능 사이에 결합이 생긴다."
//
// 두 문장 다 지금은 성립하지 않는다:
//
//   ① *"낮에도 과하지 않다"* — 검증 없이 들어간 판단이었고, 감독이 낮 화면을 보고
//      *"진짜 리얼하게 빤짝빤작"* 을 요구했다. `normalScale 0.35` 는 기본값의 1/3 이라
//      물결 기울기가 거의 평평하다. 빛이 튈 각도 자체가 없으니 반짝일 수가 없다.
//   ② *"결합이 생긴다"* — **이미 계약에 있다.** `FeatureEnv.time()` 이 그것이다.
//      후보정이 똑같은 문제를 겪었고(반구광으로 낮/밤을 추측하다 밤이 낮으로 읽혔다)
//      팀장 판정 A-2 로 공식 경로가 열렸다. 그 뒤로 이 주석만 낡은 채 남아 있었다.
//
// 밤을 고치려고 전역을 낮춘 것이 낮을 죽였다. **한 축으로 두 시간대를 맞추려던 것이
// 애초에 무리였다** — 밤 물은 광원이 달·가로등뿐이라 좁고 약해야 하고, 낮 물은 태양이
// 하나뿐이라 좁고 강해야 한다. 같은 값일 이유가 없다.
//
// ── 왜 순수 함수인가 ────────────────────────────────────────────────────────
// 판정(어떤 시간대에 어떤 광택인가)과 집행(재질에 넣기)을 가른다. 이 저장소가 "경계를
// 건너는 지점은 아무도 안 본다" 로 데였으므로, **집행 쪽 통합 테스트를 함께** 붙인다
// (`tests/world2-water-gloss.test.ts`).

/** 수면 광택 파라미터. `MeshStandardMaterial` 의 두 필드에 그대로 들어간다. */
export interface WaterGloss {
  /**
   * 물결 기울기 배수. **반짝임의 1차 원인이다** — 이 값이 낮으면 법선이 평평해져
   * 빛이 튈 각도가 사라진다. 0.35(구 전역값)에서는 사실상 반짝임이 없다.
   */
  readonly normalScale: number;
  /**
   * 거칠기. 낮을수록 하이라이트가 **좁고 밝다**(반짝이는 점), 높을수록 넓고 흐리다(은은한 띠).
   * 밤에 이 값을 올린 것은 옳았다 — 달빛은 넓게 번진다. 낮에까지 적용한 것이 문제였다.
   */
  readonly roughness: number;
  /**
   * 흰 윤슬의 발광 세기(감독 지시 2026-07-31 *"흰 반짝임효과 해줘"*).
   *
   * ── 이 값이 팀장 조건 4 를 대신한다 ──────────────────────────────────────
   * 2026-07-30 팀장 판정은 *"`emissive` 로 내지 않는다 — 스스로 빛나는 물은 광원과
   * 무관해져 밤 지적과 정면 충돌한다"* 였다. 그 판정이 **지키려던 것**은 감독의 예전
   * 지적(*"밤인데 빛이 이렇게 많지 않잖아"*)이지 `emissive` 금지 자체가 아니었다 —
   * 그것은 목적이 아니라 수단이었다. 수단을 바꾸고 목적은 여기서 지킨다: 밤 값이 낮의
   * 1/4 이하라 물 전체가 밝아지지 않는다(달빛에 잔물결 몇 개가 튀는 정도).
   *
   * 광원 방향 의존을 잃은 것이 대가다. 그 대신 **실제로 보인다** — 광원에 의존하던 예전
   * 수단(거칠기 변조)은 반사할 환경맵이 없어 실기기에서 반짝임이 0 이었고, 같은 구조가
   * 검은 줄기까지 만들고 있었다(`features/ocean.ts` 의 슬롯 주석).
   */
  readonly sparkle: number;
  /**
   * 환경맵 반사 세기(`envMapIntensity`). 2026-08-20 에 수면이 반사할 것을 갖게 되면서
   * 생겼다(`decide/water-env.ts`).
   *
   * ⚠ **이 값이 밤을 지키는 유일한 축이다.** 환경맵 텍스처는 **부팅 시각의 하늘에
   * 고정**되기 때문이다 — three 가 equirect 환경맵을 PMREM 큐브맵으로 변환해 캐시하고
   * 그 캐시가 픽셀 갱신을 안 본다(두 백엔드 소스 실측은 `features/water-env.ts` 헤더
   * 한 곳, 안 고른 대안과 재론 조건은 백로그 `G-STYL28`). 그래서 색조·태양 위치는
   * 못 따라가고 **세기만** 따라간다. 팀장 조건 4 가 지키려던 것(*"밤인데 빛이 이렇게
   * 많지 않잖아"*)을 **백엔드 동작에 의존하지 않고** 보존하는 자리다.
   */
  readonly envIntensity: number;
}

/**
 * 시간대별 수면 광택.
 *
 * @param time 지금 시간대. `FeatureEnv.time()` 이 준다 — 추측하지 않는다.
 */
export function waterGloss(time: SkyTime): WaterGloss {
  // 물 광택은 **밝기를 따라간다** — 복합씬(`daylit`)은 밝기가 낮이므로 낮 값을 빌린다.
  // 접는 자리는 `decide/night.ts` 의 `paletteTime` **한 곳**이다(팀장 조건 c1).
  switch (paletteTime(time)) {
    // 태양 하나가 강하게 내리쬔다. 물결이 서면 그 각도마다 점이 박힌다 —
    // **좁고(roughness↓) 강하게(normalScale↑)** 가 한낮 물의 문법이다.
    case 'day': return { normalScale: 0.9, roughness: 0.18, sparkle: 0.85, envIntensity: 1 };
    // 노을은 광원이 낮고 크다. 물 위로 **길게 끌리는 띠**가 생긴다 —
    // 기울기는 살리되 거칠기를 중간에 둬 띠가 끊기지 않게 한다.
    case 'sunset': return { normalScale: 0.7, roughness: 0.3, sparkle: 0.55, envIntensity: 0.6 };
    // 밤은 달·가로등뿐이다. 감독이 지적한 그 화면 — 여기서는 예전 값을 지킨다.
    // **이 줄이 예전 지시를 보존하는 자리다.** 낮을 살리려다 밤을 되돌리면 안 된다.
    // 환경맵 세기는 `sparkle` 과 **같은 비율**로 내린다(0.85→0.18 = 0.21배). 새 값을
    // 지어내지 않고, 밤을 이미 통과한 축에서 유도한다.
    case 'night': return { normalScale: 0.35, roughness: 0.62, sparkle: 0.18, envIntensity: 0.21 };
  }
}

// `grass.ts` 는 «어디에 몇 포기를 심는가», `gust.ts` 는 «돌풍이 언제 어떻게 지나가는가»,
// 그리고 여기는 «평상시 바람이 어떻게 부는가» 다. 감독 판정도 이 셋을 따로 때렸다.

// world2/decide/shadow-decal.ts — 파츠 접촉그림자(AO 블롭)의 **판정**. 순수 함수만.
//
// ── 왜 방향성 그림자를 폐기했나 (감독 지시 2026-08-11) ──────────────────────
// 앞 회차에 방향성 penumbra 데칼을 재설계해 배포했다(태양 반대쪽으로 길게 눕고, 접지부는
// 또렷하고 끝은 번지는 룩). 감독 판정:
//
//   *"팀장. 이거 폐기하고. 그.. 전시공간 만들기에서 가짜로 그림자 만드는것 있잖아.
//     그것을 적용하는게 좋을거 같애."*
//
// 지목된 것은 빌더의 접촉그림자다 — `frontend/js/space-assembler.ts` 의 `aoTexture()` +
// `AO_GROUNDED`. **방사형 그라디언트를 파츠 발밑에 눕힌 원형 블롭**이고, 핵심 성질은
// **방향이 없다**는 것이다. 태양이 어디 있든 발밑에 동그란 그늘이 깔릴 뿐이다.
//
// 그래서 이 파일에서 **태양 축이 통째로 사라졌다**: `sunGround`·`SunGround`·`shadowSpan`·
// `decalTransform` 의 방위 회전·후방 오프셋·`SHADOW_MAX_LEN`·`penumbraPlan`·`tailAlpha`·
// `STYLE_PROFILES` 가 전부 없다. 재설계가 나빠서가 아니라 **축이 바뀌었다.**
//
// ── 이 파일이 소유하는 것 ───────────────────────────────────────────────────
// 그라디언트 스톱, 블롭 크기 배수, 데칼 자세, 아틀라스 격자, 시간대 농도. **전부 산술이고
// three 를 모른다.** 굽는 쪽(`parts/shadow.ts`)과 놓는 쪽(`systems/shadow-decal.ts`)이
// 같은 상수를 보게 하는 것이 요점이다 — 한쪽이 자기 식으로 다시 계산하면 그림자 크기가
// 어긋나고, 그것은 화면에서 "그림자가 물건보다 크다/작다" 로만 드러난다.
//
// ── 인스턴싱 구조는 그대로다 ────────────────────────────────────────────────
// world2 는 파셀 스트리밍이라 빌더처럼 파츠마다 `new Mesh` 를 만들 수 없다 — 파셀을 넘을
// 때마다 메시 수백 개가 났다 사라져 개수 불변식(`[7]` 게이트)이 정면으로 깨진다. 그래서
// 아틀라스 1장·재질 1개·지오 8개 구조와 굽기 버튼은 유지하고, **셀에 그리는 그림만**
// 길쭉한 penumbra 에서 원형 블롭으로 갈아 끼웠다.


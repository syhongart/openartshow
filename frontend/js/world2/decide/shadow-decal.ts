/**
 * 그림자 농도(알파 배수). `?shdark`
 *
 * ⚠ **기본값이 0.45 → 1 로 바뀌었다.** 예전에는 이 값이 실루엣 알파 1 을 눌러 최종 농도를
 * 만드는 유일한 축이었다. 지금은 농도가 **그라디언트 스톱 자체**(`BLOB_CORE_ALPHA` 0.62)에
 * 들어 있고 — 그것이 감독이 지목한 빌더의 룩이다 — 이 값은 그 위에 곱하는 배수다. 1 이
 * 아니면 빌더 룩이 그대로 재현되지 않는다.
 */
export const SHADOW_DENSITY = 1;

/**
 * `?shdark` 상한. 1 이 아니라 **1 을 넘긴다** — 기본값이 이미 1 이라 상한을 1 로 두면
 * 노브가 한쪽으로만 열리고, 그러면 "더 진하게" 를 화면으로 판정할 수단이 없어진다
 * (이 저장소의 판정 사이클은 후보를 **비교**할 수 있을 때만 돈다).
 *
 * 최종 알파는 `blobStops` 가 1 로 자르므로 이 상한을 올려도 흰색이 되지는 않는다.
 */
export const SHADOW_DENSITY_MAX = 1.6;

/**
 * 데칼이 놓이는 높이(m). 도로(0.14)보다 위여야 도로 위에도 그림자가 진다. `?shy`
 *
 * z-fighting 은 기기마다 깊이 정밀도가 달라 여기서 다 막을 수 없다 — 그래서 노브로 연다.
 * 재질 쪽 `depthWrite:false` 가 1차 방어이고 이 높이가 2차다.
 *
 * ⚠ 빌더는 `밑면 + 0.015` 를 쓴다(`space-assembler.ts`). 그 값을 옮겨 적지 않는다 —
 * 빌더는 평평한 실내 바닥이고 world2 는 도로·잔디가 높이차를 갖는 실외라 전제가 다르다.
 */
export const SHADOW_Y = 0.20;

// ── 그라디언트 — **빌더 값을 그대로 옮긴다** ────────────────────────────────
//
// 감독이 지목한 것이 빌더의 그 룩이므로 출발점은 빌더 값이다. 원본
// (`space-assembler.ts` 의 `aoTexture()`, 128² 캔버스):
//
//   createRadialGradient(64, 64, 4, 64, 64, 60)
//   0    → rgba(0,0,0,0.62)
//   0.55 → rgba(0,0,0,0.30)
//   1    → rgba(0,0,0,0)
//
// **비로 옮긴다.** 절대 픽셀을 그대로 쓰면 `?shres` 를 낮출 때 무너진다(그 성질은 앞
// 회차에서 이미 지켰고 여기서도 지킨다 — 굽는 쪽에 절대 픽셀이 한 군데도 없다).

/** 방사형 그라디언트 **안쪽** 반경 ÷ 셀 한 변. 빌더의 `4/128` */
export const BLOB_INNER_R = 4 / 128;

/**
 * 방사형 그라디언트 **바깥** 반경 ÷ 셀 한 변. 빌더의 `60/128`.
 *
 * 이것이 곧 **그림자 원의 월드 반경**이 되는 자리다(알파가 0 이 되는 지점). 놓는 쪽은
 * 여기서 유도한 `DECAL_SCALE` 로 평면을 키운다 — 양쪽이 같은 상수를 본다.
 */
export const BLOB_OUTER_R = 60 / 128;

/** 중심 알파. 빌더 원본 0.62 */
export const BLOB_CORE_ALPHA = 0.62;

/** 중간 스톱 알파. 빌더 원본 0.30 */
export const BLOB_MID_ALPHA = 0.30;

/** 중간 스톱 **위치**(0~1). 빌더 원본 0.55. `?shsoft` 가 이것을 앞뒤로 민다 */
export const BLOB_MID_STOP = 0.55;

/**
 * `?shsoft = 0` 일 때의 중간 스톱 위치. 클수록 알파가 바깥까지 버티다 마지막에 급락해
 * **가장자리가 또렷**해진다.
 *
 * 0.95 를 넘기지 않는다 — 마지막 5% 구간에서 0.30 → 0 이면 그 자리에 얇은 하드 링이
 * 서고, 그것이 감독이 앞 회차에 반려한 *"딱딱하다"* 와 같은 결함이다.
 */
export const MID_STOP_HARD = 0.85;

/**
 * `?shsoft = 1` 일 때의 중간 스톱 위치. 작을수록 중심에서 급히 떨어진 뒤 긴 완만한 꼬리가
 * 남아 **넓게 번진다.**
 *
 * 0.25 아래로 내리지 않는다 — 코어가 사실상 사라져 균일한 옅은 얼룩이 되고, 그러면
 * "물건이 땅에 붙어 있다" 는 신호가 사라진다(접지그림자를 넣는 이유 그 자체다).
 */
export const MID_STOP_SOFT = 0.25;

/**
 * 부드러움 손잡이 0~`SHADOW_SOFT_MAX`. `?shsoft`
 *
 * ⚠ **의미가 또 바뀌었다 — 이번이 세 번째다.** 근거를 남기지 않으면 다음 사람이 옛
 * 의미로 읽는다:
 *   ① 최초: `blur(soft·res)` 의 **블러 반경**(실루엣 전체가 균일하게 흐려졌다).
 *   ② 2026-08-11 penumbra 재설계: **반그림자 확산 폭**(등고선이 원본에서 밀려나는 정도).
 *   ③ **지금**: 방사형 그라디언트의 **중간 스톱 위치**. 등고선 스택도 블러도 없어졌으므로
 *      ①②의 의미가 가리킬 대상이 아예 없다.
 *
 * **기본값을 손으로 적지 않는다** — `MID_STOP_HARD`↔`MID_STOP_SOFT` 구간에서 빌더 원본
 * (`BLOB_MID_STOP`)이 나오는 지점을 역산한다. 셋 중 무엇을 바꿔도 기본값이 저절로
 * 빌더 룩을 재현한다. 0.5 를 여기 박아 두면 구간을 조정하는 날 기본 룩이 조용히 바뀐다.
 */
export const SHADOW_SOFT = (MID_STOP_HARD - BLOB_MID_STOP) / (MID_STOP_HARD - MID_STOP_SOFT);

/**
 * `?shsoft` 노브 상한. `main.ts` 의 `readNum` 과 슬라이더가 **이것을 읽는다** — 1 을
 * 세 곳에 적어 두면 한쪽만 고쳐도 아무도 모른다(값 미러링).
 */
export const SHADOW_SOFT_MAX = 1;

/**
 * 0~`hi` 로 자르되 **NaN 을 0 으로 떨어뜨린다.**
 *
 * ⚠ `Math.min(hi, Math.max(0, x))` 만으로는 NaN 이 그대로 통과한다(`Math.max(0, NaN)`
 * = NaN). 그 NaN 이 `addColorStop` 의 오프셋으로 가면 캔버스가 **예외를 던져** 굽기가
 * 통째로 죽고, 화면에서는 "어느 순간부터 그림자가 안 나온다" 로 나타난다. 노브 파서
 * (`readNum`)가 이미 거르지만 판정이 그것에 기대면 안 된다 — 이 함수는 테스트·다른
 * 호출자에서도 불린다. **실제로 이 방어가 없어서 단위 테스트가 빨간불이 났다.**
 */
function clamp(x: number, hi = 1): number {
  return Number.isFinite(x) ? Math.min(hi, Math.max(0, x)) : 0;
}

/**
 * `?shsoft` → 중간 스톱 위치.
 *
 * 값이 **클수록 부드럽다**(스톱이 안쪽으로 간다). 노브 이름·슬라이더 라벨(「번짐」)과
 * 방향이 일치한다 — 스톱 위치를 그대로 노브로 열면 반대가 되므로 여기서 뒤집는다.
 */
export function midStopFor(soft: number): number {
  const k = clamp(soft / SHADOW_SOFT_MAX);
  return MID_STOP_HARD + (MID_STOP_SOFT - MID_STOP_HARD) * k;
}

/** 정규화 스톱 위치(0~1) → 셀 한 변에 대한 반경비 */
export function blobRadiusAt(stop: number): number {
  return BLOB_INNER_R + clamp(stop) * (BLOB_OUTER_R - BLOB_INNER_R);
}

/** 그라디언트 스톱 하나 */
export interface BlobStop {
  /** `createRadialGradient` 의 오프셋 0~1 */
  t: number;
  /** 알파 0~1 */
  a: number;
}

/**
 * 방사형 그라디언트 스톱 셋을 낸다. **굽는 쪽은 이것을 그대로 칠하기만 한다.**
 *
 * ── 스톱이 왜 셋뿐인가 ──────────────────────────────────────────────────────
 * 앞 회차에서 스톱 12개가 화면에 가로 줄무늬로 보였고 48로 늘려도 그대로였다. 원인은
 * 스톱 수가 아니라 **겹 합성마다 소스 알파가 8비트로 양자화되던 것**이었다(등고선 스택
 * 12겹 × 겹당 알파 0.046). 지금은 겹이 없다 — 그라디언트를 **한 번** 칠하므로 양자화가
 * 한 번뿐이고, 스톱 사이 선형 보간은 캔버스가 부동소수로 한다. 그래서 빌더와 같은 3스톱이
 * 그대로 성립한다(빌더가 실제로 그 룩으로 서비스 중인 것이 실물 근거다).
 *
 * @param soft    `?shsoft`
 * @param density 시간대 배수가 이미 곱해진 농도. 1 이 빌더 원본
 */
export function blobStops(soft: number, density: number): BlobStop[] {
  const d = Number.isFinite(density) ? Math.max(0, density) : 0;
  const a = (v: number) => clamp(v * d);
  return [
    { t: 0, a: a(BLOB_CORE_ALPHA) },
    { t: midStopFor(soft), a: a(BLOB_MID_ALPHA) },
    { t: 1, a: 0 },
  ];
}

// ── 크기 ────────────────────────────────────────────────────────────────────

/**
 * 실루엣이 셀 가장자리에서 물러나는 **여백**(셀 한 변에 대한 비, 각 변).
 *
 * **유도값이다** — 그라디언트 바깥 반경 바깥은 이미 알파 0 이므로 여백이 저절로 생긴다.
 * 앞 회차처럼 별도 상수로 잡을 필요가 없어졌다(그때는 하드 실루엣이 캔버스 경계에 닿아
 * 있는 것이 감독 반려의 직접 원인이었고, 여백을 손으로 넣어 막아야 했다).
 */
export const SHADOW_PAD = 0.5 - BLOB_OUTER_R;

/**
 * 데칼 평면 한 변 ÷ 그림자 원 지름. 여백을 상쇄한다.
 *
 * 그림자 원 반경이 셀 한 변의 `BLOB_OUTER_R` 이므로, 원 지름을 셀 한 변으로 되돌리는
 * 배수가 `1 / (2·BLOB_OUTER_R)` 이다. 굽는 쪽과 놓는 쪽이 각각 숫자를 적으면 그것이 이
 * 저장소가 색·수치·임계값에서 세 번 데인 값 미러링이고, 증상은 "그림자가 물건보다 조금
 * 크다/작다" 로만 나타나 아무 테스트도 안 걸린다.
 */
export const DECAL_SCALE = 1 / (2 * BLOB_OUTER_R);

/**
 * 캐스터 밑동 반경 → 그림자 원 반경 배수.
 *
 * ── 왜 빌더의 `AO_GROUNDED` 표를 옮겨 적지 않는가 ──────────────────────────
 * 빌더 표는 파츠 종류마다 손으로 적은 **절대 미터**다(`pedestal: 1.2`, `bench: 2.0`, …).
 * world2 는 캐스터 지오의 `boundingBox` 에서 밑동 반경을 **실측**한다
 * (`systems/shadow-decal.ts` 의 `measure`). 표를 복사하면 그 실측이 무의미해지고, 파츠
 * 지오를 고치는 날 그림자만 옛 크기로 남는다 — 그 증상은 "그림자가 물건보다 크다" 로만
 * 드러난다(시계탑을 새로 만든 2026-08-09 에 실제로 겪을 뻔한 형태다).
 *
 * ── 값의 근거 ① — 원리에서 유도한다 ─────────────────────────────────────────
 * 사람이 "그림자의 가장자리" 로 읽는 것은 알파 0 지점이 아니라 **중간 스톱**(0.30)이다.
 * 그 바깥은 이미 거의 안 보인다. 접지로 읽히려면 그 가장자리가 **캐스터 밑동 반경과
 * 일치**해야 한다. 그 조건을 풀면 배수가 바로 나온다:
 *
 *     중간 스톱 반경 = blobRadiusAt(BLOB_MID_STOP) · L        (L = 평면 한 변)
 *     그림자 원 반경 = BLOB_OUTER_R · L = r · BLOB_SCALE
 *     둘째를 첫째에 대입하고 「중간 스톱 반경 = r」을 걸면
 *     BLOB_SCALE = BLOB_OUTER_R / blobRadiusAt(BLOB_MID_STOP) ≈ 1.724
 *
 * ── 값의 근거 ② — 빌더 표를 **대조군으로** 실측했다 ────────────────────────
 * 빌더 표를 같은 정의(그림자 원 반경 ÷ 밑동 외접 반경)로 환산한 실측표. 밑동 반경은
 * `PART_TYPES[t].size` 의 `max(x, z)/2` 이고 그림자 원 반경은 `AO_GROUNDED[t] ·
 * BLOB_OUTER_R` 이다:
 *
 *   | 파츠       | s    | 밑면 x,z   | 밑동 r | 배수 |
 *   |------------|------|-----------|--------|------|
 *   | stair      | 1.6  | 2.0, 3.0  | 1.50   | 0.50 |
 *   | reception  | 2.0  | 1.8, 0.62 | 0.90   | 1.04 |
 *   | lounge     | 1.9  | 1.7, 0.78 | 0.85   | 1.05 |
 *   | stool      | 0.55 | 0.36,0.36 | 0.18   | 1.43 |
 *   | bench      | 2.0  | 1.2, 0.5  | 0.60   | 1.56 |
 *   | succulent  | 0.5  | 0.3, 0.3  | 0.15   | 1.56 |
 *   | vitrine    | 1.4  | 0.8, 0.5  | 0.40   | 1.64 |  ← 중앙값
 *   | vase       | 0.5  | 0.26,0.26 | 0.13   | 1.80 |
 *   | planter    | 1.3  | 0.6, 0.6  | 0.30   | 2.03 |
 *   | sign       | 1.1  | 0.5, 0.4  | 0.25   | 2.06 |
 *   | pedestal   | 1.2  | 0.5, 0.5  | 0.25   | 2.25 |
 *   | labelStand | 1.0  | 0.4, 0.3  | 0.20   | 2.34 |
 *   | pillar     | 1.5  | 0.4, 0.4  | 0.20   | 3.52 |
 *
 * 중앙값 **1.64** 로 ①의 1.724 와 5% 차이다. 서로 다른 두 근거가 같은 구간에 떨어졌으므로
 * ①을 쓴다 — ①은 **유도되므로** 스톱 위치나 반경비를 바꿔도 저절로 따라오고, ②는 실측을
 * 다시 떠야 한다.
 *
 * ⚠ 표의 배수가 0.50~3.52 로 크게 흩어진 것은 빌더 표가 **크기 의존**이기 때문이다(작은
 * 파츠일수록 배수가 크다 — `s` 에 사실상 바닥이 있다). 배수 하나로 가는 이상 이 편차는
 * 근사로 남는다. world2 캐스터는 전부 밑동 0.3m 이상이라 표의 큰 쪽 구간에 든다.
 *
 * ⚠ `?shsoft` 로 스톱을 밀어도 이 배수는 **안 따라간다**(`BLOB_MID_STOP` 고정을 쓴다).
 * 따라가게 하면 번짐 노브를 밀 때 그림자 **크기**가 같이 변해 축이 둘로 섞인다.
 */
export const BLOB_SCALE = BLOB_OUTER_R / blobRadiusAt(BLOB_MID_STOP);

/** 데칼 인스턴스 하나의 자세. y 는 호출자가 `SHADOW_Y` 로 준다 */
export interface DecalPose {
  x: number;
  z: number;
  ry: number;
  sx: number;
  sz: number;
}

/**
 * 데칼 평면의 자세를 유도한다.
 *
 * ── 태양이 인자에 없다 ──────────────────────────────────────────────────────
 * 그것이 이번 교체의 전부다. 접촉그림자는 **캐스터 발밑 그 자리**에 놓이고, 방위도 길이도
 * 없다. 앞 회차의 `decalTransform` 은 `SunGround` 를 받아 후방 오프셋(`len/2 − width/2`)과
 * 방위 회전(`atan2(ux, uz)`)을 냈고, 그 둘이 여기서 사라졌다.
 *
 * ── `ry = 0` 인 이유 ────────────────────────────────────────────────────────
 * 원이라 회전이 화면에 안 나타난다. 그래도 캐스터의 `ry` 를 **넘기지 않는다** — 빌더가
 * 접촉그림자를 파츠의 자식이 아니라 group 직속에 두는 것과 같은 근거다
 * (`space-assembler.ts`: *"자식화하면 파츠 회전을 따라 그림자도 돌아 룩이 바뀐다"*).
 * 언젠가 블롭을 타원으로 바꾸는 날 이 한 줄이 없으면 그림자가 파츠를 따라 돌기 시작하고,
 * 그 변경을 한 사람은 왜 그렇게 됐는지 모른다.
 *
 * @param casterX,casterZ 캐스터 중심
 * @param r               캐스터 밑동 반경(m). 인스턴스 스케일이 이미 곱해진 값
 */
export function decalTransform(casterX: number, casterZ: number, r: number): DecalPose {
  // 평면 한 변 = 그림자 원 지름 × 여백 상쇄.
  // NaN 반경(자산 누락·bounding box 실패)은 0 으로 떨어뜨린다 — 그대로 흘리면 인스턴스
  // 행렬이 NaN 이 되고, three 는 그것을 조용히 그려 **화면 전체가 검게 덮인다.**
  const rr = Number.isFinite(r) ? Math.max(0, r) : 0;
  const side = 2 * rr * BLOB_SCALE * DECAL_SCALE;
  return { x: casterX, z: casterZ, ry: 0, sx: side, sz: side };
}

// ── 아틀라스 격자 ───────────────────────────────────────────────────────────

export interface AtlasCell {
  /** 캔버스 픽셀 사각 */
  px: number; py: number; size: number;
  /** UV 사각(0~1). 지오메트리에 구워 넣는다 */
  u0: number; v0: number; u1: number; v1: number;
}

export interface AtlasGrid {
  cols: number;
  cellPx: number;
  cellOf(i: number): AtlasCell;
}

/**
 * 아틀라스 격자를 유도한다. 셀 수가 늘어도 넘치지 않는다.
 *
 * ⚠ **모든 셀이 같은 그림이 됐는데도 격자를 유지하는 이유**: 인스턴스별 UV 가 불가능해
 * 그림자 파츠마다 **자기 지오**에 UV 를 구워 넣는 구조이고(`parts/shadow.ts` 의
 * `applyCellUV`), 그 구조가 곧 개수 계약(텍스처 1·재질 1·지오 8)이다. 셀을 하나로 합치는
 * 것은 지오를 하나로 합치는 것과 다른 문제이고, 합치면 파츠 종류별 실루엣을 다시 열
 * 수 없게 된다. **굽기 비용은 이미 셀 수와 무관하다** — `bakeAtlas` 가 한 번 그려서
 * 셀마다 복사한다.
 *
 * 격자를 `4×4` 처럼 **고정으로 적지 않는 이유**: 캐스터 파츠는 늘어난다(다리·간판 같은
 * 것이 백로그에 있다). 고정 격자는 아홉 번째 캐스터가 생기는 날 조용히 남의 셀을 읽고,
 * 그 증상은 "특정 물건의 그림자만 이상하다" 로 나타난다.
 *
 * ⚠ 셀 픽셀에 하한을 두지 않는다 — 캐스터가 아주 많아지면 셀이 작아져 실루엣이 뭉개진다.
 * 그때 늘려야 하는 것은 아틀라스 크기이고, 그 판단을 여기서 삼키면 안 된다. 대신
 * 레지스트리 테스트가 `cellPx` 하한을 단언해 **넘어가는 순간 빨간불**이 되게 한다.
 */
export function atlasGrid(count: number, atlasPx: number): AtlasGrid {
  const n = Math.max(1, Math.ceil(count));
  const cols = Math.ceil(Math.sqrt(n));
  const cellPx = Math.floor(atlasPx / cols);
  return {
    cols,
    cellPx,
    cellOf(i: number): AtlasCell {
      const cx = i % cols;
      const cy = Math.floor(i / cols);
      const px = cx * cellPx;
      const py = cy * cellPx;
      // UV 를 셀 경계에서 **반 텍셀 안쪽으로** 물린다. 경계를 정확히 쓰면 선형 필터링이
      // 이웃 셀을 반 텍셀 빨아들여, 밑동 옆에 남의 그림자 자락이 비친다(밉맵에서 더 심하다).
      const inset = 0.5 / atlasPx;
      return {
        px, py, size: cellPx,
        u0: px / atlasPx + inset,
        v0: 1 - (py + cellPx) / atlasPx + inset,
        u1: (px + cellPx) / atlasPx - inset,
        v1: 1 - py / atlasPx - inset,
      };
    },
  };
}

// ── 농도 ────────────────────────────────────────────────────────────────────

/**
 * 시간대별 농도 배수.
 *
 * 반구광 세기로 시간대를 추측하지 않는다 — `features/types.ts` 가 그 규약을 명시한다.
 * 밤에 0.35 인 것은 달빛 그림자가 실제로 옅기 때문이고, 이 값이 0 이 아닌 것은 밤에도
 * 접지감이 필요하기 때문이다(그림자가 통째로 사라지면 밤에만 물건이 다시 뜬다).
 *
 * ⚠ 접촉그림자는 방향이 없으므로 **시간대가 자세를 안 바꾼다** — 예전에는 밤에 달 방위로
 * 넘어가면서 그림자가 통째로 돌았다. 지금 시간대가 움직이는 것은 이 농도 하나뿐이다.
 */
export const DENSITY_BY_TIME: Readonly<Record<SkyTime, number>> = {
  day: 1, sunset: 0.8, night: 0.35,
};

/**
 * 시간대 배수를 곱한 최종 농도.
 *
 * ⚠ **1 로 자르지 않는다.** 이것은 최종 알파가 아니라 스톱 알파에 곱하는 **배수**이고,
 * 여기서 1 로 자르면 `?shdark` 의 1 초과 구간이 통째로 죽는다(기본값이 이미 1 이다).
 * 자르는 자리는 `blobStops` 하나다 — 알파가 되는 지점이 거기다.
 */
export function densityFor(time: SkyTime, base: number): number {
  const m = DENSITY_BY_TIME[time] ?? 1;
  return Math.min(SHADOW_DENSITY_MAX, Math.max(0, base * m));
}

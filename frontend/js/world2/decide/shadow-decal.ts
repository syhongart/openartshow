/**
 * 그라디언트 스톱 곡선을 **거리로** 평가한다. 원형이 쓰는 `createRadialGradient` 와 **같은
 * 곡선**이어야 한다 — 사각·얼룩만 다른 프로파일을 쓰면 한 화면에서 두 종류의 페이드가
 * 섞여 보인다.
 *
 * @param s       그라디언트 오프셋 0~1 (= `createRadialGradient` 의 스톱 위치)
 * @param soft    `?shsoft`
 * @param density 시간대 배수가 곱해진 농도
 */
export function alphaAtStop(s: number, soft: number, density: number): number {
  return alphaCurve(soft, density)(s);
}

/**
 * 스톱 곡선을 **한 번 굳혀** 재사용하는 팩토리. 픽셀 루프가 이것을 쓴다.
 *
 * ⚠ `alphaAtStop` 을 픽셀마다 부르면 `blobStops` 가 매번 **배열 셋을 새로 만든다** —
 * 사각·얼룩 셀이 `res²` 까지 128²=16,384 픽셀이라 굽기 한 번에 수만 개의 임시 객체가 나고,
 * 그것이 그대로 굽기 예산(8ms 경고)과 GC 압력이 된다. 이 저장소는 "매 프레임 같은 배열을
 * 두 번 순회한다" 를 이미 비블로커로 받은 적이 있다(태스크 #209) — 같은 형태다.
 */
export function alphaCurve(soft: number, density: number): (s: number) => number {
  const stops = blobStops(soft, density);
  return (s: number): number => {
    const t = clamp(s);
    // 스톱 셋(0 · mid · 1) 사이 선형 보간. 캔버스 그라디언트가 하는 것과 같은 보간이다.
    for (let i = 1; i < stops.length; i++) {
      const a = stops[i - 1]!;
      const b = stops[i]!;
      if (t <= b.t) {
        const span = b.t - a.t;
        // 스톱이 겹치면(soft 극단에서 mid 가 0 이나 1 에 붙는 경우) 뒤 스톱을 쓴다.
        // 0 으로 나누면 NaN 이 알파로 흘러가고, 그 NaN 은 ImageData 에서 0 으로 잘려
        // **그 픽셀만 조용히 투명**해진다 — 화면에서 점무늬로만 드러나는 형태다.
        return span > 0 ? a.a + (b.a - a.a) * ((t - a.t) / span) : b.a;
      }
    }
    return 0;
  };
}

/**
 * 둥근 사각의 **부호 있는 거리**(SDF). 0 이 경계, 음수가 내부, 양수가 바깥.
 *
 * 표준 2D 라운드박스 SDF 다. `length(max(q,0)) + min(max(q.x,q.y),0) − r` 에서 뒤 항이
 * 내부 거리를 만든다 — 그 항이 없으면 내부가 전부 0 이 되어 **코어가 평평해진다**(그림자
 * 한가운데가 균일한 검정 판이 되고, 접지감이 사라진다).
 *
 * @param u,v   중심 기준 좌표
 * @param hx,hz 반폭(모서리 반경을 **빼기 전** 값)
 * @param r     모서리 반경
 */
export function roundBoxSD(
  u: number, v: number, hx: number, hz: number, r: number,
): number {
  // 모서리 반경이 반폭보다 크면 사각이 뒤집힌다. 짧은 변 기준으로 자른다.
  const rr = Math.max(0, Math.min(r, Math.min(hx, hz)));
  const qx = Math.abs(u) - (hx - rr);
  const qz = Math.abs(v) - (hz - rr);
  const ox = Math.max(qx, 0);
  const oz = Math.max(qz, 0);
  return Math.hypot(ox, oz) + Math.min(Math.max(qx, qz), 0) - rr;
}

/**
 * 잎 그림자 노이즈 0~1. **결정론이다** — 같은 좌표면 언제나 같은 값이다.
 *
 * 값 노이즈(격자 해시 + 부드러운 보간) 한 겹이다. 프랙탈로 겹치지 않는 이유: 겹을 쌓으면
 * 큰 얼룩 위에 잔털이 얹혀 저해상도(`?shres=16`)에서 잔털이 픽셀 이하로 떨어지고, 그러면
 * **해상도에 따라 무늬가 달라진다.** 해상도 노브는 뭉개짐만 움직여야 한다(그 계약은
 * `SHADOW_DRAW_MIN` 주석이 이미 못 박고 있다).
 */
export function leafNoise(u: number, v: number): number {
  const gx = Math.floor(u);
  const gz = Math.floor(v);
  const fx = u - gx;
  const fz = v - gz;
  // smoothstep — 격자 경계에서 기울기가 이어져 격자무늬가 안 보인다.
  const sx = fx * fx * (3 - 2 * fx);
  const sz = fz * fz * (3 - 2 * fz);
  const h = (ix: number, iz: number): number => {
    // 32비트 정수 해시. `Math.random` 을 쓰면 굽기마다 무늬가 달라진다(위 `LEAF_SEED` 절).
    let n = (Math.imul(ix, 0x27d4eb2d) ^ Math.imul(iz, 0x165667b1) ^ LEAF_SEED) >>> 0;
    n = Math.imul(n ^ (n >>> 15), 0x2c1b3c6d) >>> 0;
    n = Math.imul(n ^ (n >>> 12), 0x297a2d39) >>> 0;
    return ((n ^ (n >>> 15)) >>> 0) / 0xffffffff;
  };
  const a = h(gx, gz);
  const b = h(gx + 1, gz);
  const c = h(gx, gz + 1);
  const d = h(gx + 1, gz + 1);
  return (a + (b - a) * sx) + ((c + (d - c) * sx) - (a + (b - a) * sx)) * sz;
}

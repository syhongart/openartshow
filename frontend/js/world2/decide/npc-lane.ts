// ── 그래서 여기가 정하는 것 ─────────────────────────────────────────────────
// 진행방향 오른쪽으로 얼마나 비켜설 것인가, 그 거리 하나다. **우측통행**이므로 마주
// 오는 두 체는 서로 반대편 차선에 놓이고, 실제 분리 거리는 오프셋의 **두 배**다.
//
// 상태가 없다. 프레임마다 도는 쌍 검사도 없다. 되돌리려면 이 파일을 안 부르면 된다.

import { ROAD_SEG } from '../parts/road-topology.js';

/**
 * 차선 중심이 놓일 수 있는 한계 거리(m) — **차도 반폭.**
 *
 * `ROAD_HALF`(도로 *판정* 반폭)가 아니라 그려진 차도의 반폭에서 유도한다. 둘은 다른
 * 값이고(`ROAD_HALF = ROAD_SEG/2 + CURB`) 역할도 다르다 — 판정 쪽은 "여기가 길인가" 에
 * 답하려고 연석만큼 넓게 잡은 값이라, 그 끝에 사람을 세우면 **그려진 아스팔트 밖**에
 * 선다. 사람은 눈에 보이는 길 위를 걸어야 한다.
 *
 * 좁게 잡은 덕에 `onRoad`(`ROAD_HALF` 기준) 판정은 자동으로 만족된다 — 그 사실은
 * `tests/world2-npc-lane.test.ts` 가 단언한다(팀장 조건 3).
 */
export const LANE_BOUND = ROAD_SEG / 2;

/**
 * 이 몸집이 걸을 차선 오프셋(m). 성립하지 않으면 **0**(= 지금까지의 동작).
 *
 * ── 두 부등식에서 유도한다 (팀장 조건 1) ────────────────────────────────────
 * *"±0.8~1.2 느낌" 으로 고르지 않는다.* 규율이 이미 이름 붙인 자리다 — **"실측에 여유를
 * 얹은 값은 근거가 아니다."** 만족해야 할 것은 둘뿐이고, 둘 다 부등식으로 적힌다:
 *
 *   ① **대향 두 체가 안 겹친다.** 분리 거리 `2L` 이 두 몸 폭의 합 `2r` 보다 커야 한다.
 *      → `L > r`
 *   ② **차도를 벗어나지 않는다.** 차선 중심에서 몸 반쪽이 더 나가므로
 *      → `L + r ≤ LANE_BOUND`
 *
 * 두 제약의 **중점**을 취한다. 어느 쪽에 붙일 이유가 없기 때문이다 — ①에 붙이면 겨우
 * 안 겹치고, ②에 붙이면 겨우 안 벗어난다.
 *
 * 정리하면 중점은 `LANE_BOUND / 2` 로 **몸집과 무관해진다**(두 제약이 `r` 에 대해
 * 대칭이라 그렇다). 그런데도 식을 그대로 두는 이유가 둘 있다:
 *   · 창이 비는지(`hi > lo`)를 결정하는 것은 여전히 `r` 이다 — 몸집이 차도 1/4 보다
 *     크면 두 부등식을 동시에 만족하는 `L` 이 **존재하지 않는다.**
 *   · 제약이 비대칭으로 바뀌면(한쪽에 여유를 두게 되면) 값이 저절로 따라온다.
 *     정리된 숫자를 적어 두면 그때 갈라지고, 그 갈라짐은 아무도 못 본다.
 *
 * @param bodyRadius 몸의 XZ 반경(m). **실측해서 넘긴다** — 아바타가 바뀌면 따라온다.
 */
export function laneOffset(bodyRadius: number, bound: number = LANE_BOUND): number {
  const lo = bodyRadius; // ① 이보다 커야 대향이 안 겹친다
  const hi = bound - bodyRadius; // ② 이보다 크면 차도를 벗어난다
  if (!(hi > lo)) return 0; // 창이 비었다 — 이 몸집에 차선은 성립하지 않는다
  return (lo + hi) / 2;
}

/**
 * yaw 로부터 **진행방향 오른쪽** 단위벡터.
 *
 * 걷기 코드가 이미 `w.ry` 를 진행방향으로 유지하고 있으므로(`yaw=0 → -Z` 관례,
 * world1 `world.js:1752` 계승) 따로 방향을 들고 다닐 필요가 없다. 상태를 늘리지 않는
 * 것이 이 처방의 핵심이라 여기서도 늘리지 않는다.
 *
 * 유도: `ry = atan2(-fx, -fz)` 이므로 전방은 `f = (-sin ry, -cos ry)` 다.
 * Y-up 오른손 좌표계에서 오른쪽은 `f × up = (-fz, 0, fx)` → `(cos ry, -sin ry)`.
 *
 * 검산(부호를 한 번 틀리면 전원이 좌측통행이 된다): 북쪽으로 걸으면 `ry = 0` 이고
 * 전방은 `-Z`. 이때 오른쪽은 동쪽 `+X` 여야 한다 → `(cos 0, -sin 0) = (1, 0)`. ✔
 */
export function rightOf(ry: number): { x: number; z: number } {
  return { x: Math.cos(ry), z: -Math.sin(ry) };
}

// world2/decide/water.ts — 어디가 물인가. 순수 함수만.
//
// ── 이 파일이 SSOT 인 이유 ───────────────────────────────────────────────────
// 물이라는 사실을 **여러 계층이 함께 소비한다**:
//
//   · 수면 렌더(`features/ocean.ts`)  — 물을 그린다
//   · 스트리밍(`decide/stream.ts`)    — 물 파셀을 아예 만들지 않는다(`'water'`만 본다)
//   · 미니맵(`decide/minimap.ts`)     — 물·물가를 색으로 칠한다(`'shore'`를 쓰는 유일한 곳)
//
// **`parts/*.ts` 중 물을 아는 것은 `ground.ts` 하나다** — 지면 판 두께(`GROUND_DEPTH`)를
// `SEA_Y` 에서 유도한다(판이 수면까지 안 내려가면 바닷가에서 옆면이 드러난다).
//
// 이 줄이 두 번 틀렸다. 처음에는 "파셀 배치가 물을 피한다"고 현재형으로 적혀 있었는데
// 부품 셋백이 미구현이었고(검수관이 잡았다), 그것을 "`parts/*.ts` 는 아직 물을 모른다"로
// 고쳤더니 같은 커밋에서 `ground.ts` 가 `SEA_Y` 를 import 하면서 **다시 거짓이 됐다**
// (검수관이 또 잡았다 — 내가 "갱신했다"고 보고한 줄이 실제로는 이 줄이 아니었다).
//
// **배치는 여전히 물을 모른다** — 물가 파셀에도 건물·나무가 평소대로 선다. 아는 것은
// 지면 판의 두께 하나다. 아래 `'shore'` 설명도 같은 착각을 담고 있었다.
//
// 두 곳에 따로 적으면 강 경로를 바꿨을 때 한쪽만 따라오고, 증상은 **건물이 물 위에 서는**
// 것으로 나타난다. 이 프로젝트가 값 미러링으로 이미 세 번 겪은 형태라(캔버스 색 vs 상수 ·
// 구름 고도 두 곳 · 테스트 임계값), 팀장이 바다를 승인하며 조건으로 건 것도 이 구조다.
//
// 도로가 `parts/road-topology.ts` 를 SSOT 로 두고 네 파츠가 그것만 보는 것과 같은 배치다.
//
// ── 지형: 섬 하나 + 그것을 가로지르는 강 ────────────────────────────────────
// 감독 확정. 반경 밖은 바다(세계의 끝), 강이 도시를 가로질러 그 바다로 흘러나간다.
//
// 육지 파셀이 지면(`y = 0`)으로 물 위를 덮고, 물인 파셀은 지면을 안 그려서 **그 구멍으로
// 아래 수면이 드러난다.** 물을 그리는 쪽이 강 모양을 알 필요가 없는 이유다.
//
// 수면이 **하나의 평면**이라고 오래 적혀 있었으나(`y = SEA_Y` 하나, 드로우콜 하나),
// 감독이 강과 바다에 다른 높이를 지시하면서 그 전제가 깨졌다(아래 `RIVER_Y`·`SEA_Y`).
// 지금은 판이 셋이다 — 해저·바다·강. 강 판은 세계 전체가 아니라 **물로 분류된 파셀 위에만**
// 깔린다(`features/ocean.ts` 의 `riverGeometry`); 큰 판 두 장을 겹치면 반투명이 이중으로
// 곱해져 물빛 캘리브레이션이 무효가 되기 때문이다.

import { GRID_MIN_X, GRID_MAX_X, GRID_MIN_Z, GRID_MAX_Z, inGrid } from './grid.js';

// ── 강과 바다는 높이가 다르다 (감독 지시 2026-07-30) ────────────────────────
// *"바다, 강은 중요해. 지금 보다 더 밑에 있게 하고 강은 땅보다 50 cm 밑, 바다는 땅보다
//   1미터 밑에 있게해."*
//
// 예전에는 **하나의 평면**이었다(`SEA_Y` 하나를 바다·강이 공용). 감독이 두 높이를
// 지시했으므로 그 전제가 깨졌고, 상수도 둘로 나뉜다.
//
// **world1 이 같은 요구를 이미 이 구조로 풀었다** — `world.js:57,60` 에 `SEA_Y = -1.2`
// (바다) / `RIVER_Y = -0.3`(강)이 있고 주석이 *"[해안] 바다를 지면 0보다 SEA_Y 만큼
// 낮춰 확실한 단차(감독: '바다=땅 높이 어색')"* 라고 적고 있다. world2 가 단일 평면으로
// 후퇴했던 것을 되돌리는 셈이다(이름까지 그 선례를 따른다).
//
// 지면이 y=0 이므로 둘 다 그보다 낮아야 육지가 물을 덮는다. 그리고 **강이 바다보다
// 높다** — 강물이 바다로 흘러나가는 지형이므로 그 방향이 맞다(`tests` 가 관계를 지킨다).

/** 강(내수면) 수면 높이(미터). 지면보다 50cm 아래 — 감독 지시 */
export const RIVER_Y = -0.5;

/** 바다(외해) 수면 높이(미터). 지면보다 1m 아래 — 감독 지시. 강보다 50cm 낮다 */
export const SEA_Y = -1.0;

/**
 * 물의 깊이(미터) — 수면에서 해저까지.
 *
 * 감독 지시(Voxels 참조)로 수면을 반투명으로 만들면서 필요해졌다 — 물이 반투명인데
 * 아래에 아무것도 없으면 하늘이 비쳐 **물이 아니라 유리 구멍**으로 보인다. 비칠 바닥이
 * 있어야 반투명이 물로 읽힌다.
 *
 * 얕을수록 바닥이 또렷해 물빛이 밝고, 깊을수록 물색에 묻힌다. 2.4m 는 물가에서 바닥이
 * 어렴풋이 비치고 조금만 나가도 물색이 이기는 깊이다. 더 깊게 잡으면 반투명으로 만든
 * 의미가 사라지고, 더 얕으면 바닥이 너무 또렷해 물웅덩이처럼 보인다.
 */
export const WATER_DEPTH = 2.4;

/**
 * 해저 높이(미터). **바다 수면에서 유도한다.**
 *
 * 예전에는 `-2.9` 를 직접 적고 주석에 "수면보다 2.4m 아래" 라고 썼다. 그 유도는 수면이
 * `-0.5` 일 때만 참이었고, 감독이 바다를 `-1.0` 으로 내리자 **주석과 값이 어긋났다**
 * (실제로는 1.9m). 이 저장소가 "실측치를 적어두고 유도를 주석에만 남기는" 형태로 이미
 * 사고를 냈으므로(팀장 조건 3: 유도 없는 실측치 잔류 금지) 산술로 바꾼다 — 수면을
 * 옮기면 해저가 따라오고, 깊이의 의미는 그대로 유지된다.
 *
 * 기준은 **바다**다(더 낮은 쪽). 강은 바다보다 50cm 높으므로 강에서 본 깊이는 그만큼
 * 깊어진다 — 하나의 해저 판을 공유하면서 강이 조금 더 깊게 읽히는 것은 자연스럽다.
 */
export const SEABED_Y = SEA_Y - WATER_DEPTH;

/**
 * 세계의 바깥 가장자리(미터). 이 밖은 전부 바다다. **world2 는 유한 세계다**(감독 확정).
 *
 * ── 원에서 격자로 ───────────────────────────────────────────────────────────
 * 예전에는 반경 240m 의 **원형 섬**(`ISLAND_R`)이었다. 감독이 격자를 30×30 으로 확정
 * 하면서(`decide/grid.ts`) 그 원이 **세계를 잘라 버렸다** — 격자는 960m 사방인데 반경
 * 240m 밖이 전부 바다라, 지시대로 넓혀도 걸을 수 있는 땅은 예전 그대로였다.
 *
 * **지형 판정 둘이 서로 다른 세계 크기를 들고 있으면 넓은 쪽이 조용히 무시된다.** 어느
 * 쪽 단위 테스트에도 안 걸린다 — 격자는 "30×30 이다"를 통과하고, 물은 "반경 밖은
 * 바다다"를 통과한다. 그래서 크기를 격자에서 **유도한다.** 격자를 40×40 으로 바꾸면
 * 바다도 저절로 물러난다.
 *
 * 파셀 `px` 가 덮는 범위는 `[px·cell − cell/2, px·cell + cell/2]` 이므로, 바깥 가장자리는
 * 가장 먼 파셀 중심에서 **반 칸 더 나간 곳**이다. 좌표가 -15…14 로 비대칭이라(짝수
 * 격자) 양쪽 절댓값 중 큰 쪽을 쓴다 — 작은 쪽을 쓰면 한쪽 끝 파셀이 바다에 잠긴다.
 */
export function worldHalfExtent(cell: number): number {
  return Math.max(-GRID_MIN_X, GRID_MAX_X + 1, -GRID_MIN_Z, GRID_MAX_Z + 1) * cell;
}

/**
 * 강 중심선. x 를 따라 흐르고 z 가 굽이친다.
 *
 * 사인파 **둘**을 겹친다. 하나면 규칙적인 물결이라 인공물처럼 보이고, 주기가 다른 둘을
 * 더하면 되풀이 주기가 최소공배수로 밀려나 눈에 안 띈다. 도로에서 "바둑판 말고"를 풀 때와
 * 같은 문제이고 같은 해법이다.
 *
 * 진폭 합이 130m — 파셀 4개분이라 도시를 가로지르며 눈에 띄게 휜다.
 */
export function riverCenterZ(wx: number): number {
  // ── 상수 180 은 **중앙 광장을 비켜 가려는 것**이다 ─────────────────────────
  // 예전 값은 45 였고, 그때 이 주석은 "원점을 강에서 비켜 놓는다"고 적고 있었다.
  // 원점 한 점만 보면 맞는 말이다 — `riverCenterZ(0) = 59.45` 라 반폭 24 밖이다.
  //
  // **그런데 최솟값을 안 봤다.** 45 − 34 − 15 = −4 이므로 사인이 바닥을 치는 x 에서는
  // 강 중심이 원점 아래를 지나고, 반폭 24 를 더하면 z ∈ [−28, 20] 이 물이 된다.
  // 중앙 광장은 2×2 파셀(±32m)이므로 **강이 광장을 관통한다.** 스폰 지점 한 점만
  // 검사하던 테스트는 이것을 놓쳤다 — 한 점이 마른 땅인 것과 광장 전체가 마른 것은
  // 다른 명제다.
  //
  // 이제 최솟값이 180 − 70 − 30 = 80 이고, 강 가장자리는 80 − 24 = 56 이다. 광장
  // 가장자리(32)에서 24m 떨어져 있다.
  //
  // 사인파 **둘**을 겹치는 이유는 그대로다. 주 파동의 주기는 2π×150 ≈ 942m 로 세계
  // 폭(960m)과 비슷해 가로지르며 한 번 크게 굽이치고, 부 파동(2π×61 ≈ 383m)이 그
  // 위에 잔물결을 얹어 되풀이가 눈에 안 띈다.
  return 180 + 70 * Math.sin(wx / 150) + 30 * Math.sin(wx / 61 + 1.3);
}

/** 이 월드 좌표가 **강** 위인가. 바다와 나눠 둔다 — 강은 세계 안에만 있다 */
export function isRiver(wx: number, wz: number): boolean {
  return Math.abs(wz - riverCenterZ(wx)) < RIVER_HALF;
}

/**
 * 강 반폭(미터). **셀 크기에서 유도한 값이다.**
 *
 * 지면은 파셀 한 칸을 통째로 덮는 판이므로 **파셀이 물의 최소 해상도**다. 강이 보이려면
 * 강이 지나는 x 열마다 물로 분류된 파셀이 최소 하나 있어야 한다.
 *
 * `parcelWater` 가 파셀 **중심 한 점**으로 판정하므로(아래 참고), 필요한 부등식은:
 *
 *     파셀 중심 간격 32m → 강 중심선에서 최근접 파셀 중심까지 거리 ≤ 16m
 *     그 중심이 강(±반폭) 안에 들려면   반폭 > 16
 *
 * 24 는 그 하한의 1.5배다. 여유를 준 이유는 안전마진이 아니라 **강 폭에 변화를 주려는
 * 것**이다 — 24 면 대부분 한 줄(32m), 굽이가 완만한 구간에서 두 줄(64m)이 되어 강이
 * 넓어졌다 좁아졌다 한다. 20 이면 거의 항상 한 줄로 균일하고, 32 면 거의 항상 두 줄이라
 * 강이 far 렌더 반경(76.8m)을 거의 채워 건너편이 안 보이는 벽이 된다.
 *
 * ── 앞선 유도가 왜 틀렸나 ───────────────────────────────────────────────────
 * 처음에는 파셀 **다섯 점**(중심 + 네 귀퉁이)이 전부 잠겨야 물로 쳤고, 거기서
 * `반폭 − 16 ≥ 16 → 반폭 ≥ 32` 를 유도했다. **그 유도는 강 중심선이 수평일 때만 참이다.**
 * `riverCenterZ` 의 최대 기울기는 0.4455 라 파셀 한 칸(32m)을 지나는 동안 중심선이 14.3m
 * 움직인다. 그것까지 넣으면 `16 + 16 + 16×0.4455 = 39.1` — 반폭 32 는 부등식을 어긴 값이고,
 * 실제로 두 개의 x 열에서 강이 지면에 덮여 끊겼다.
 *
 * 그때 고를 수 있던 길은 둘이었다. 반폭을 40 으로 키우거나(폭 80m — 섬 지름의 1/6),
 * 판정을 지면 해상도에 맞추거나. **뒤쪽이 맞다** — 5점 표본은 지면이 표현할 수 없는
 * 정밀도를 가진 척했고, 그 척함의 대가가 "강 폭을 두 배로 키워라" 였다.
 */
export const RIVER_HALF = 24;

/**
 * 월드 좌표가 물인가. **이 함수가 유일한 답이다.**
 *
 * `cell` 을 받는 이유는 세계 경계가 격자에서 유도되기 때문이다 — 격자는 파셀 단위로
 * 세어지고 여기는 미터로 묻는다. 셀 크기를 이 파일이 알면 그것이 곧 값 미러링이다.
 */
export function isWater(wx: number, wz: number, cell: number): boolean {
  const half = worldHalfExtent(cell);
  if (Math.abs(wx) > half || Math.abs(wz) > half) return true;  // 세계 밖 = 바다
  return isRiver(wx, wz);
}

/**
 * 파셀이 물과 어떤 관계인가.
 *
 *   'dry'   — 뭍이다. 평소대로 짓는다
 *   'shore' — 물에 닿은 뭍이다. **지금은 미니맵 색으로만 쓴다**(부품 셋백은 미구현)
 *   'water' — 물이다. 스트리밍이 아예 만들지 않는다 — 지면도 부품도 없다
 *
 * ── 왜 중심 한 점인가 ───────────────────────────────────────────────────────
 * 지면은 파셀 한 칸을 통째로 덮는 판이다. 그러니 물의 최소 단위도 파셀이고, **파셀보다
 * 정밀한 판정은 그릴 방법이 없다.** 중심이 강 안이면 그 칸은 물이다 — 그게 전부다.
 *
 * 처음에는 중심 + 네 귀퉁이 다섯 점을 보고 "전부 물이면 water" 로 했는데, 그러면 강이
 * 파셀 대각선을 비스듬히 지나는 구간에서 다섯 점이 다 잠기지 않아 **강이 지면에 덮여
 * 끊겼다.** 그것을 막으려면 강 폭을 80m 까지 키워야 했다 — 판정의 허구적 정밀도를 맞추려
 * 세계 지형을 바꾸는 꼴이다. 판정을 지면 해상도로 내리는 쪽이 맞다.
 *
 * 'shore' 는 자기는 뭍인데 **네 이웃 중 하나가 물인** 칸이다. 강 양옆으로 정확히 한 줄씩
 * 생기고, 바다에 닿는 섬 가장자리에도 한 줄 두른다.
 *
 * **현재 소비처는 미니맵 하나다**(`features/minimap.ts` 가 물가를 다른 색으로 칠한다).
 * 원래 의도는 "부품이 물가를 피하게" 하는 것이었고 주석도 그렇게 적혀 있었으나, 그 셋백은
 * 구현된 적이 없다. 물가에 건물이 물에 닿아 서는 것이 눈에 걸리면 그때 붙인다 — 그전까지
 * 이 값이 배치를 바꾼다고 적어두면 다음 사람이 "이미 처리됐다"고 믿고 지나간다.
 *
 * `cellX`/`cellZ` 를 인자로 받는 것은 셀 크기를 이 파일이 알지 않기 위해서다 — 셀은
 * 레이아웃의 소유이고 여기는 좌표만 안다.
 */
export type WaterClass = 'dry' | 'shore' | 'water';

export function parcelWater(px: number, pz: number, cellX: number, cellZ: number): WaterClass {
  // 세계 밖은 파셀 좌표로 바로 답한다 — 미터로 환산해 경계와 비교하면 반 칸 어긋나
  // 가장자리 한 줄이 바다에 잠기거나 바다가 한 줄 육지가 된다.
  if (!inGrid(px, pz)) return 'water';
  // 여기 "광장은 무조건 dry" 를 한 줄 넣었다가 **뮤테이션이 죽은 코드임을 드러내** 뺐다.
  // 강이 광장에서 24m 떨어져 있어 그 분기는 한 번도 실행되지 않는다 — 지워도 테스트가
  // 전부 통과했다. 방어선인 척하면서 아무것도 안 막고 있었고, 있으면 오히려 "여기서
  // 막고 있으니 강 위치는 신경 안 써도 된다"는 잘못된 안심을 준다.
  //
  // 광장을 지키는 것은 `tests/world2-water.test.ts` 의 "강 중심선이 광장에 닿지 않는다"
  // 다. 누가 진폭을 키우면 그 테스트가 깨진다(실제로 강을 옛 위치로 되돌리는 뮤테이션을
  // 잡았다).
  if (isRiver(px * cellX, pz * cellZ)) return 'water';
  // 물가 — 자기는 뭍인데 네 이웃 중 하나가 물인 칸
  if (
    parcelIsWater(px + 1, pz, cellX, cellZ) ||
    parcelIsWater(px - 1, pz, cellX, cellZ) ||
    parcelIsWater(px, pz + 1, cellX, cellZ) ||
    parcelIsWater(px, pz - 1, cellX, cellZ)
  ) return 'shore';
  return 'dry';
}

/** 이웃 판정용 — `parcelWater` 를 재귀 호출하면 물가의 물가까지 번진다 */
function parcelIsWater(px: number, pz: number, cellX: number, cellZ: number): boolean {
  if (!inGrid(px, pz)) return true;
  return isRiver(px * cellX, pz * cellZ);
}

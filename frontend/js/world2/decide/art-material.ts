// **이 값이 WebGPU 실기기에서도 같은지는 감독 실기기가 유일한 축이다.**
// 편차가 눈에 띈다는 보고가 오면 그때 **수단 교체를 팀장 분기로 올린다**(팀장 지시).

import { readNum } from '../url-knob.js';

/**
 * 그림 평면 재질의 명세. **테두리는 여기 없다** — 감독이 "사진은" 이라고 특정했고,
 * 테두리까지 발광시키면 액자가 공간에서 붕 뜬다(그림자·주변광과 어긋난다).
 */
export interface ArtMatSpec {
  /** `basic` 은 조명을 아예 안 받는다. `standard` 는 예전 동작(대조군) */
  readonly kind: 'basic' | 'standard';
  /**
   * `false` 면 시간대 노출·톤매핑도 안 받는다.
   *
   * ⚠ **WebGL 에서만 먹는다** — 아래 「백엔드」 절 참조.
   */
  readonly toneMapped: boolean;
  /**
   * `false` 면 **씬 안개도 안 받는다**(팀장 판정 (B), 2026-08-18).
   *
   * ── 왜 이 필드가 생겼나 ──────────────────────────────────────────────────
   * `MeshBasicMaterial` 의 `fog` 기본값은 **`true`** 다(three r171, 두 빌드 모두).
   * 즉 조명·톤매핑을 다 떼어내도 **안개는 그대로 받고 있었다** — `main.ts:435` 가
   * `scene.fog` 를 켜고 밴드는 `decide/fog.ts` 의 near 51.2m / far 76.8m 이며, 밤
   * 안개색은 `0x0b0d12`(거의 검정)이다. 먼 작품은 검게 물든다.
   *
   * 팀장 판정 근거: *"감독이 두 번 지적한 증상은 「작품이 주변환경에 물든다」이고
   * … 0번 실수(감독이 안 연 축을 내가 여는 것)가 아니라 **감독이 연 축을 덜 닫은
   * 것**이다. (A)는 같은 지적을 세 번째 받는 창을 남긴다."*
   *
   * 📊 **원거리 실측**(팀장 조건 1, 2026-08-18 밤·헤드리스). 벽에 건 작품을 정면에 둔
   * 채 **뒤로 물러나며** 그림 픽셀의 평균 밝기를 잰다. 톤매핑이 섞이지 않게 **세션 안의
   * 「근거리 대비」 비**를 쓴다 — 톤매핑은 한 세션에서 상수라 비에서 상쇄된다.
   *
   *   물러난 거리 │ fog:false(0) │ fog:true(1) │ 안개 몫
   *   ───────────┼──────────────┼─────────────┼──────────────────────────
   *      ~4.5m   │    1.017     │    0.964    │  5%
   *      ~9m     │    1.000     │    0.827    │ 17%
   *      ~12m    │    0.744     │    0.586    │ 21%
   *      ~16m    │    0.839     │    0.596    │ 29%
   *      ~22m    │    0.893     │  **묻힘**   │ 100% — 그림 픽셀이 **한 개도** 안 잡힌다
   *
   * 마지막 행이 이 판정의 근거다. `fog:true` 는 그 거리에서 작품이 **안개색에 완전히
   * 먹혀** 색 판정을 하나도 통과하지 못했고, `fog:false` 는 194px 가 남아 0.893 을
   * 유지했다.
   *
   * ⚠ **못 잰 것 둘**(통과로 적지 않는다):
   * ① 두 열 모두 거리가 늘면 값이 떨어지는데 **그 일부는 안개가 아니다** — 원근으로
   *    그림이 작아지면 가장자리 안티앨리어싱 픽셀의 비중이 커진다(표본이 670→194 로
   *    준다). 그래서 절대값이 아니라 **두 열의 차이**만 안개 몫으로 읽는다.
   * ② **카메라–작품 실거리를 못 쟀다.** 표의 거리는 「걸기 지점에서 물러난 거리」이고
   *    작품까지 실거리는 그보다 크다(조준이 먼 벽을 맞출 수 있다). 그래서 이 표를
   *    `decide/fog.ts` 의 밴드(near 51.2m)와 직접 대조하면 안 된다.
   *
   * ⚠ **재론 트리거**(팀장 조건 1): 감독이 **원거리 작품 화면을 처음 실견하는 시점**에
   * 이 판정은 뒤집힐 수 있다 — 안개 밖에서 마을은 묻히는데 **작품만 선명하게 뜨는 룩**은
   * 아직 아무도 못 봤다(라이브 작품 0개). 그때 링크로 드린다.
   */
  readonly fog: boolean;
}

/** 노브 이름. 「사진이 환경(env) 영향을 받는가」 */
export const ART_ENV_KNOB = 'artenv';
/**
 * 기본값 — 팀장 채택 (다), **감독이 문언으로 확정했다**(2026-08-18 두 번째 발화).
 *
 * ⚠ **감독 카드는 안 올린다**(팀장 동의). *"작품에는 재질감 전혀없이. 그냥 뷰어처럼
 * 밝기가 보였으면해. 그림자 영역에서도 작품은 그대로. 밝은 곳에서도 그대로."* 가
 * 후보 셋 중 하나를 지목한 것이라, 다시 묻는 것은 **이미 답한 것을 되묻는 일**이다.
 * 그래서 1·2 는 이제 「감독이 고를 후보」가 아니라 **회귀를 재는 대조군**이다.
 */
export const ART_ENV_DEFAULT = 0;
export const ART_ENV_MAX = 2;

/**
 * 노브 값 → 재질 명세. **순수** — 이 함수가 판정의 전부다.
 *
 *   0  (다) 조명·톤매핑·안개 전부 안 받는다   ← 기본값, 감독 확정
 *   1  (가) 조명만 안 받는다(톤매핑·안개는 받음)
 *   2  예전 동작 — 셋 다 받는다(**대조군**)
 *
 * ⚠ **범위 밖은 기본값으로 떨어진다**(fail-safe). 링크를 손으로 고치다 오타가 나면
 * 감독이 «왜 안 바뀌지» 를 겪는데, 그때 보이는 것이 **요구대로 동작하는 기본값**인 편이
 * 낫다 — 오타 때문에 예전 동작(어두운 사진)으로 되돌아가면 그것이 더 나쁜 오해를 낳는다.
 */
export function artMatSpec(mode: number): ArtMatSpec {
  if (mode === 2) return { kind: 'standard', toneMapped: true, fog: true };
  if (mode === 1) return { kind: 'basic', toneMapped: true, fog: true };
  return { kind: 'basic', toneMapped: false, fog: false };
}

/**
 * 지금 세션의 노브 값. `location` 이 없으면(노드) 기본값이다.
 *
 * ⚠ **읽기와 판정을 가른 이유**: 판정(`artMatSpec`)은 순수라 테스트·뮤테이션이 닿고,
 * 읽기는 URL 에 의존한다. 합쳐 두면 테스트가 URL 을 흉내 내야 하고 그 순간 축이 흐려진다.
 */
export function readArtEnv(): number {
  return readNum(ART_ENV_KNOB, ART_ENV_DEFAULT, 0, ART_ENV_MAX);
}

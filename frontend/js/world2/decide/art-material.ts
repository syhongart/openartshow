// **헤드리스 통과를 WebGPU 근거로 쓰지 않는다** — 감독 실기기가 유일한 축이다.

import { readNum } from '../url-knob.js';

/**
 * 그림 평면 재질의 명세. **테두리는 여기 없다** — 감독이 "사진은" 이라고 특정했고,
 * 테두리까지 발광시키면 액자가 공간에서 붕 뜬다(그림자·주변광과 어긋난다).
 */
export interface ArtMatSpec {
  /** `basic` 은 조명을 아예 안 받는다. `standard` 는 예전 동작(대조군) */
  readonly kind: 'basic' | 'standard';
  /** `false` 면 시간대 노출·톤매핑도 안 받는다 */
  readonly toneMapped: boolean;
}

/** 노브 이름. 「사진이 환경(env) 영향을 받는가」 */
export const ART_ENV_KNOB = 'artenv';
/** 기본값 — 팀장 채택 (다). 감독 카드가 뒤집으면 그것이 최종이다 */
export const ART_ENV_DEFAULT = 0;
export const ART_ENV_MAX = 2;

/**
 * 노브 값 → 재질 명세. **순수** — 이 함수가 판정의 전부다.
 *
 *   0  (다) 조명도 톤매핑도 안 받는다     ← 기본값, 팀장 채택
 *   1  (가) 조명만 안 받는다(톤매핑은 받음)
 *   2  예전 동작 — 조명을 그대로 받는다(**대조군**)
 *
 * ⚠ **범위 밖은 기본값으로 떨어진다**(fail-safe). 링크를 손으로 고치다 오타가 나면
 * 감독이 «왜 안 바뀌지» 를 겪는데, 그때 보이는 것이 **요구대로 동작하는 기본값**인 편이
 * 낫다 — 오타 때문에 예전 동작(어두운 사진)으로 되돌아가면 그것이 더 나쁜 오해를 낳는다.
 */
export function artMatSpec(mode: number): ArtMatSpec {
  if (mode === 2) return { kind: 'standard', toneMapped: true };
  if (mode === 1) return { kind: 'basic', toneMapped: true };
  return { kind: 'basic', toneMapped: false };
}

/**
 * 지금 세션의 노브 값. `location` 이 없으면(노드) 기본값이다.
 *
 * ⚠ **읽기와 판정을 가른 이유**: 판정(`artMatSpec`)은 순수라 테스트·뮤테이션이 닿고,
 * 읽기는 URL 에 의존한다. 합쳐 두면 테스트가 URL 을 흉내 내야 하고 그 순간 축이 흐려진다.
 */
export function readArtEnv(): number {
  return readNum(ART_ENV_KNOB, ART_ENV_DEFAULT, 0, ART_ENV_MAX);
}

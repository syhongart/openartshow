// world2/decide/horizon.ts — **바다와 하늘이 어디서 갈라지는가.** 순수 함수만, three import 0.
//
// ── 왜 생겼나 (감독 실기기 2026-08-05, 태스크 #202) ─────────────────────────
// 감독: *"그 구가 너무 작아 … 별이 보이는 게 아니라 바로 앞에 있는 벽지가 보이는 것
// 같아."* 돔 카메라 추종과 별 각크기(`?star=`)로 두 축은 닫혔고, **바다와 하늘의 경계가
// 없다**는 축이 남았다(팀장 판정 B — 그 원문은 게시판에 없다, 위임 프롬프트가 전한 것이
// 전부다).
//
// ── 무엇이 경계를 지우고 있었나 (헤드리스 실측 2026-08-07) ──────────────────
// `?at=sea` 에서 화면 가운데 열(폭 10%)의 세로 휘도 프로파일을 떴다. 900×560, pitch 0,
// 시선은 바다 쪽(yaw π). 수평선은 화면 y≈283 이다.
//
//   시간대  하늘(y=280)  수평선 아래 띠(y≈290)  물(y=320)
//   ──────┼────────────┼──────────────────────┼──────────
//   낮      217          219                    114
//   **밤**  **98**       **143**                **85**
//
// **낮은 수평선이 있고 밤은 없다.** 낮은 안개색(`0xe9eef2`)이 하늘 지평선과 같아서 띠가
// 하늘의 연장으로 읽히고, 물(114)과의 대비로 경계가 선다. 밤은 다르다 — 띠(143)가
// **하늘(98)과 물(85) 둘 다보다 밝다.** 하늘도 바다도 아닌 밝은 회백 막이 그 사이에
// 끼어 있어, 경계가 선이 아니라 **번진 띠**가 된다. 감독이 보는 기본 시간대가 밤이다.
//
// ⚠ **그 띠는 안개가 100% 로 덮은 구간이고, 밝은 이유는 따로 있다.** `?wopa=0`(수면
// 완전 투명) 대조군에서 띠가 그대로 남았다 — 물이 아니다. 실측 픽셀 `rgb(134,144,167)`
// 은 `decide/night.ts` 의 `NIGHT_FOG` 를 **선형 채널 값으로 읽었을 때**의 sRGB 환산과
// 소수점까지 일치한다(0.2392·0.2784·0.3843 → 134.2·143.9·166.6). 즉 밤 안개 하한이
// sRGB 숫자를 `THREE.Color` 의 선형 채널에 얹고 있고, 그래서 *"`fogScale` 1 이면 아무
// 일도 일어나지 않는다"* 는 그 파일의 주석이 **거짓**이다. 안개가 의도(`0x3d4762`)보다
// 크게 밝아져 `sky.js` ⑨(지평선 = fog색) 정합이 깨져 있다.
//
// **그런데 여기서 그것을 고치지 않는다.** 밤 밝기는 감독이 *"사람 눈은 밝기에
// 적응하잖아"* 로 닫은 축이고(게시판 2026-08-05), 안개색을 되돌리면 밤 전체가 어두워진다
// — 이 태스크가 받은 것은 수평선이지 밤 밝기가 아니다. 아래 밴드는 **수평선 아래 3°만**
// 덮으므로 그 경계를 넘지 않는다. 색공간 건은 관측으로 올린다.
//
// ── 그래서 무엇을 만드는가 ──────────────────────────────────────────────────
// 실제 바다에 수평선이 보이는 이유는 대기원근이 **완결되지 않기** 때문이다. 아무리 먼
// 바다도 하늘과 똑같아지지는 않는다 — 물은 하늘을 반사하되 프레넬과 흡수 때문에 늘
// 조금 더 어둡다. 우리 씬에는 그 "조금"이 0 이다. `THREE.Fog` 는 `far` 에서 정확히
// 안개색이 되고, 그 안개색은 ⑨ 규칙상 하늘 지평선과 같은 색이다. 그래서 **정의상**
// 먼 바다는 하늘에 완전히 녹는다.
//
// 처방은 그 구간을 바다 쪽으로 조금 되돌리는 것이다. 안개가 덮은 만큼(=안개 계수)을
// 알파로 삼아 어두운 막을 겹치면, 안개가 100% 인 자리는 완전히 되돌아오고 안개가
// 0% 가 되는 자리에서 알파도 0 이 되어 **이음매가 원리적으로 없다.**
//
// ── 왜 안개 far 를 미는 쪽이 아닌가 ─────────────────────────────────────────
// 팀장 판정 B 가 지목한 것은 *"안개 far 76.8m 가 수평선을 덮는다"* 이고, 가장 곧은
// 처방은 far 를 밀어 더 멀리 보이게 하는 것이다. **안 한다.**
//   ① `FOG_FAR_CELLS` 는 `DEFAULT_BANDS.farExit`(LOD 가 그리기를 멈추는 거리)에서
//      유도된다. 안개만 밀면 그 사이가 텅 비어 **세계의 끝이 드러난다**(`decide/fog.ts`
//      가 그 이유를 이미 적고 있다).
//   ② `features/ocean.ts` 의 `SEA_PATCH_SEG` 주석이 *"정점 수가 강 이론 최악치를 넘는
//      far 에 도달하면 이 구현을 재판정한다(팀장 재상정)"* 로 **경계를 미리 그어 두었다.**
//      정점은 far 의 제곱으로 는다. 즉 far 를 미는 것은 팀장 상신 사안이지 디자이너가
//      혼자 고를 값이 아니다.
// 밴드는 far 를 건드리지 않으므로 두 조항 어디에도 닿지 않는다.

import { SEA_Y } from './water.js';
import { fogBand } from './fog.js';
import { DEFAULT_LAYOUT } from '../parts/types.js';

/** URL 노브 이름·범위. 소비자가 리터럴을 적지 않게 여기 한 곳에 둔다 */
export const HORIZON_KNOB = 'hz';
export const HORIZON_MIN = 0;
/**
 * 상한.
 *
 * 1 이면 밴드가 **검정**이 된다(색을 `fog × (1 − hz)` 로 만들기 때문이다). 검은 띠는
 * 수평선이 아니라 화면이 깨진 것으로 읽히므로 그 앞에서 끊는다. 0.9 는 "과한 지점을
 * 볼 수 있어야 감독이 어디까지가 좋은지 고른다"(`ocean.ts` 의 `SPARK_MAX` 와 같은
 * 논리)와 "명백히 고장난 값은 후보에 안 넣는다" 사이다.
 */
export const HORIZON_MAX = 0.9;

/**
 * 기본 세기 — **감독 판정 전의 잠정값이다.**
 *
 * 헤드리스 실측(밤 맑음, `?at=sea`, 900×560, pitch 0, 시선 yaw π, 화면 가운데 열 10%
 * 평균 휘도 Rec.709)으로 고른 값이고 **실기기 육안 판정을 받지 않았다.**
 * 고정 기준점: 하늘 87(y=260) · 물 86(y=320).
 *
 *   hz     밴드 상단(y=280)   밴드 하단부(y=300)
 *   ─────┼──────────────────┼──────────────────
 *   0      98 + **139.5**     119     ← y=285 에 흰 띠 피크. 하늘·물 **둘 다보다 밝다**
 *   0.15   89                 113
 *   **0.30**│ **80**          **112**  ← 채택
 *   0.50   66                 110
 *   0.70   48                 108
 *
 * 판정 기준은 부등식 하나다 — **하늘 > 먼 바다 ≥ 가까운 바다.** 대기원근이 그 순서일
 * 때만 "멀어서 흐려진 것" 으로 읽힌다. `hz=0` 에서는 먼 바다(139.5)가 셋 중 가장
 * 밝아 순서가 뒤집혀 있고, 그래서 띠가 원근이 아니라 **독립된 물체**로 보인다 —
 * 감독이 *"경계가 없다"* 고 한 화면이 이것이다.
 *
 * 0.15 는 물(86)과 거의 같아 선이 안 서고, 0.5 이상은 하늘보다 한참 어두워져 수평선이
 * 아니라 **검은 띠**가 된다. 0.30 이 부등식을 만족하는 구간의 가운데다.
 *
 * ── 경계 — 이 노브로 못 고치는 것이 남아 있다 ──────────────────────────────
 * 표의 `y=300` 열이 hz 를 아무리 올려도 108 아래로 안 내려간다. 그 자리는 알파가 작은
 * 구간이라 **배경(밝아진 밤 안개)이 그만큼 새어 나온다.** 원인은 이 파일 머리말의
 * 색공간 건이고 처방은 `?nfog=` 축이다 — **hz 를 더 올려서 덮으려 하지 마라.**
 * 덮으려면 알파를 1 로 눌러야 하고, 그러면 밴드 아래 끝에 계단이 생겨 지금 없앤
 * 이음매가 되살아난다. 여기서 멈춘다.
 *
 * ⚠ **헤드리스는 SwiftShader(WebGL)이고 감독 실기기는 WebGPU 다.** 구현은 두 백엔드에서
 * 같은 수단(캔버스 텍스처 + `MeshBasicMaterial`)만 쓰므로 렌더 경로가 갈리지 않지만,
 * **톤매핑을 거친 최종 휘도가 같다는 보장은 없다.** 위 표는 값을 고른 근거이지 실기기에서
 * 그 숫자가 나온다는 뜻이 아니다. 확정은 감독 판정이다.
 */
export const HORIZON_DEFAULT = 0.3;

/**
 * 수면 위 눈높이(m). 밴드 기하가 전부 이 값에서 나온다.
 *
 * `SEA_Y` 가 음수라 빼면 더해진다 — 물을 내리면 수평선까지의 각도가 커지고 밴드도
 * 함께 넓어진다. 리터럴을 적지 않는 이유가 그것이다.
 */
export function eyeAboveSea(eyeHeight: number): number {
  return eyeHeight - SEA_Y;
}

/**
 * 밴드가 덮는 각도(rad). 수평선(0)에서 **안개가 0% 가 되는 시선각**까지다.
 *
 * ── 유도 ────────────────────────────────────────────────────────────────────
 * 시선을 수평선 아래로 θ 만큼 내리면 수면과 만나는 거리는 `d = h / tan θ` 다.
 * 안개가 0% 인 곳은 `d = near` 이므로 `θ = atan(h / near)`.
 *
 * 그 밖(θ 가 더 큰 곳)은 안개가 아예 안 걸린 물이라 되돌릴 것이 없다. 즉 이 각도는
 * "적당히 고른 폭"이 아니라 **되돌릴 것이 남아 있는 마지막 지점**이고, 그래서 안개
 * 밴드를 옮기면 저절로 따라온다.
 *
 * 실측 대조(눈높이 1.7 · `SEA_Y` −1.0 · near 51.2m): 유도 3.02°, 화면에서 잰 밝은 띠의
 * 세로 폭 27px ÷ (560px / 세로 FOV 70°) = 3.4°. 한 픽셀 단위로 재는 값이 아니라
 * 자릿수 대조이고, 그 자릿수가 맞는다.
 */
export function horizonBandAngle(eyeH: number, near: number): number {
  const h = eyeAboveSea(eyeH);
  if (h <= 0 || near <= 0) return 0;
  return Math.atan(h / near);
}

/**
 * 시선각 θ(수평선 아래 rad)에서 **안개가 덮은 비율**. 그대로 밴드의 알파가 된다.
 *
 * `THREE.Fog`(선형)와 **같은 식**이다: `(depth − near) / (far − near)` 를 0..1 로 자른다.
 * 같은 식을 쓰는 것이 요점이다 — 밴드는 "안개가 가져간 만큼"만 되돌리므로, 안개가
 * 0 인 자리에서 알파도 정확히 0 이 되어 **이음매가 생길 수 없다.** 폭을 손으로 고르면
 * 그 자리에 계단이 남는다.
 *
 * θ=0(수평선)에서는 `d = ∞` 라 1 이다. 그 극한을 분기로 적는 이유는 `tan 0 = 0` 이
 * `Infinity` 를 만들고, `(Infinity − near) / (far − near)` 가 `Infinity` 라 clamp 로는
 * 살아나지만 `near = far` 같은 퇴화 입력에서 `NaN` 이 되기 때문이다.
 */
export function horizonFogAt(theta: number, eyeH: number, near: number, far: number): number {
  if (theta <= 0) return 1;
  if (far <= near) return 0;
  const h = eyeAboveSea(eyeH);
  const d = h / Math.tan(theta);
  if (!Number.isFinite(d)) return 1;
  return Math.min(1, Math.max(0, (d - near) / (far - near)));
}

/**
 * 밴드 텍스처의 알파 프로파일. `[0]` 이 수평선, `[n−1]` 이 밴드 아래 끝.
 *
 * 텍스처로 굽는 이유: 정점 색으로 하면 밴드를 세로로 잘게 쪼개야 하고, 그 세분 수가
 * 곧 프로파일 해상도가 된다. 텍스처는 지오를 2행으로 두고도 부드럽다.
 */
export function horizonAlphaProfile(
  n: number, eyeH: number, near: number, far: number,
): number[] {
  const band = horizonBandAngle(eyeH, near);
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    out.push(horizonFogAt(band * (i / Math.max(1, n - 1)), eyeH, near, far));
  }
  return out;
}

/**
 * 밴드 구면의 반경(m) = **안개 near**.
 *
 * ── 이 값이 자유롭지 않다 (설계의 핵) ───────────────────────────────────────
 * 밴드는 반투명이라 불투명 물 판보다 **나중에** 그려지고, `depthTest` 때문에 물이 앞에
 * 있는 픽셀에서는 아예 안 그려진다. 반경 R 인 밴드가 시선각 θ 에서 보이려면
 * `R < h / tan θ` 여야 한다 — 즉 밴드가 실제로 보이는 최대 각도는 `atan(h / R)` 이다.
 *
 *   R = 500m(돔 근처) → 0.31° 까지만 보인다. 덮어야 할 3° 의 10분의 1이다.
 *   R = near(51.2m)   → 3.02°. **밴드가 덮는 각도와 정확히 같다.**
 *
 * 우연이 아니다. 밴드 폭도 `atan(h / near)` 이고 가시 한계도 `atan(h / R)` 이라, `R` 을
 * near 로 두면 두 식이 같은 식이 된다. **밴드 전체가 항상 수면보다 앞에 놓인다.**
 *
 * 육지에서도 같은 성질이 지켜 준다 — 51.2m 안의 지형·건물은 밴드보다 앞이라 밴드를
 * 가린다. 밴드가 덮는 것은 그 밖, 즉 **안개가 이미 일하고 있는 거리**뿐이다.
 *
 * ⚠ **`depthTest` 를 끄면 이 유도가 전부 무의미해진다.** 끄는 순간 밴드가 건물·나무를
 * 뚫고 그려진다. 여기서 멈춘다 — 밴드를 더 크게 만들고 싶어지면 그 전에 이 문단을 읽어라.
 */
export function horizonRadius(near: number): number {
  return near;
}

/** 이 세계의 안개 밴드. 소비자가 셀 크기를 다시 적지 않게 여기서 한 번 유도한다 */
export function horizonFog(): { near: number; far: number } {
  return fogBand(DEFAULT_LAYOUT.cellX);
}

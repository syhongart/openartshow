// world2/decide/wave.ts — 수면 정점 파동의 **판정**. 집행(버퍼에 꽂기)은 `features/ocean.ts`.
//
// ── 왜 이 파일이 생겼나 (2026-08-20) ────────────────────────────────────────
// 이 계산은 오래 `features/ocean.ts` 안에 있었고, **정점에 값을 꽂는 한 줄은 갱신 루프에
// 인라인**으로 적혀 있었다. 그 한 줄이 `PATCH_SEP + LIFT_AMP + surfaceLift(…)` 여서
// 진폭이 평균 수면을 함께 밀어 올렸는데, `surfaceLift` 자체는 순수 함수라 단위 테스트가
// 촘촘히 보고 있었음에도 **어느 테스트도 그 한 줄에 닿지 못했다.** 이 저장소가 이름 붙인
// «판정/집행 분리의 구멍» 이 정확히 그 형태다. 판정을 여기로 옮겨 테스트가 보게 한다.
//
// **노브(`?wamp`·`?wstd`)는 여기 없다.** URL 을 읽는 것은 집행 쪽 일이고, 그 값은 인자로
// 들어온다. 예전에는 기본 인자가 노브 상수(`LIFT_AMP`)여서 **인자를 생략한 호출이 노브를
// 조용히 먹고 있었다** — 순수 함수인 척하면서 전역을 읽는 형태다. 여기서는 기본값이
// 상수이고, 노브를 쓰려면 호출부가 **명시적으로 넘겨야 한다.**

import { PHI } from './golden.js';

/** `?wamp` 미지정 시의 파고(m, 마루~골의 절반). 노브 상한은 `WAVE_PEAK_MAX`(water.ts). */
export const WAVE_AMP_DEFAULT = 0.2;

/**
 * `?wstd` 미지정 시의 진행파:정재파 배분. `0` 이면 전부 흘러가고 `1` 이면 전부 제자리
 * 오르내림이다. 어느 배분이 "일렁임" 으로 읽히는지는 감독 실기기 육안 판정이라
 * 노브로 뺐다(팀장 조건 3) — 감독 지적이 *"한 방향으로 흐르는데"* 였으므로 병진 쪽이
 * 이미 과했고, 그래서 기본값을 정재 쪽에 둔다.
 */
export const WAVE_STANDING_DEFAULT = 0.65;

/**
 * 변위가 담당할 **최단 파장**(m). 이보다 잔 물결은 노말맵이 계속 담당한다 —
 * 두 축의 분담 정의이고, 세분 수는 여기서 **유도된다**(손으로 정하지 않는다).
 *
 * 팀장이 확정한 값은 8m 였는데 유도해 보니 예산을 넘었다:
 *   λ=8m  → 세분 16×16 → 쿼드당 512 삼각형 → 최악 60칸 × 512 = 30,720 (씬 대비 **+30%**)
 *   λ=16m → 세분  8×8  → 쿼드당 128 삼각형 → 최악 60칸 × 128 =  7,680 (씬 대비 **+7.5%**)
 * 감독이 무게를 물었고("에이는 무겁지 않아?") 그 답의 전제가 +7% 였으므로 예산 초과로
 * 판정해 16m 로 올렸다 — 팀장 조건 1 이 그 경우를 명시적으로 허용한다.
 * 강 폭이 48m(`RIVER_HALF × 2`)라 파장 16m 면 강을 가로질러 파형이 3개 들어간다.
 */
export const LIFT_LAMBDA_M = 16;

/** `RIVER_SEG`·`SEGS_PER_TILE` 이 이 파장에서 유도된다(`features/ocean.ts`) */
export const LIFT_LAMBDA = LIFT_LAMBDA_M;
/**
 * 겹치는 파들. 감독 요청이 *"물은 복합적인 사인파들로 구성되어있잖아"* 였다.
 * 방향과 주파수 비를 정수비에서 멀리 둔다 — 정수비면 짧은 주기로 패턴이 되풀이된다.
 * `dir` 은 단위벡터, `rel` 은 기본 파수 대비 배율, `amp` 는 상대 진폭(합이 1).
 */
const LIFT_WAVES = [
  { dx: 1, dz: 0, rel: 1, amp: 0.5 },
  { dx: 0.5, dz: 0.866, rel: PHI, amp: 0.3 },              // 60°
  { dx: -0.309, dz: 0.951, rel: PHI * PHI, amp: 0.2 },     // 108°
];

/**
 * 수면 높이(m). **월드 좌표만의 함수다** — 이 성질이 파셀 경계의 이음새를 막는다.
 * 강 판은 파셀마다 독립된 정점을 쓰므로(같은 좌표에 정점이 둘) 위치 기반이 아니면
 * 두 값이 갈려 틈이 벌어진다.
 *
 * 진행파 `sin(k·x − ωt)` 와 정재파 `sin(k·x)·cos(ωt)` 를 섞는다. 정재파가 곧
 * "제자리 오르내림" 이다 — 공간 패턴이 고정된 채 진폭만 시간에 따라 오간다.
 *
 * ω 는 **깊은 물 분산관계 `ω = √(gk)`** 에서 유도한다(실측에 여유를 얹지 않는다).
 * λ=16m 면 주기 3.2초로, 사람이 물가에서 보는 잔잔한 강의 리듬과 맞는다.
 */
export function surfaceLift(
  x: number, z: number, t: number,
  amp: number = WAVE_AMP_DEFAULT, standing: number = WAVE_STANDING_DEFAULT,
): number {
  if (amp <= 0) return 0;
  const k0 = (2 * Math.PI) / LIFT_LAMBDA_M;
  let h = 0;
  for (const w of LIFT_WAVES) {
    const k = k0 * w.rel;
    const phase = k * (w.dx * x + w.dz * z);
    const omega = Math.sqrt(9.81 * k);
    h += w.amp * (
      (1 - standing) * Math.sin(phase - omega * t)
      + standing * Math.sin(phase) * Math.cos(omega * t)
    );
  }
  return h * amp;
}

/**
 * 층2 패치와 아래 층(평평한 `sea`)을 갈라 두는 몫(m). **진폭과 무관한 상수다** —
 * 물속에서 올려다볼 때 두 면이 겹쳐 보이지 않게 하는 것이 목적이고, 생성부·갱신
 * 루프 두 곳에 리터럴로 적혀 있던 것을 상수로 올렸다. 테스트도 이것을 기준으로 쓴다.
 */
export const PATCH_SEP = 0.01;

/**
 * 층2 패치 정점의 로컬 y. 원점이 `SEA_Y` 이므로 **이 값의 평균이 곧 평균 수면의
 * 오프셋**이고, 그것이 이 한 줄을 갱신 루프에서 함수로 끌어낸 이유다 — 인라인 자리에는
 * 테스트가 안 닿는다(이 저장소가 «판정/집행 분리의 구멍» 이라 부르는 형태).
 *
 * ── ⚠ `+ amp` 를 더하지 않는다 (감독 *"40센치인더. 너무 잔잔하다"* 2026-08-20) ──
 * 원래 `PATCH_SEP + LIFT_AMP + surfaceLift(…)` 였다. 골을 아래 층(평평한 `sea`) 위로
 * 들어올려 *"뚫지 않게"* 하려던 것인데 **진폭이 평균 수면을 함께 밀어 올렸다** —
 * `?wamp` 가 파도 세기 노브이면서 **수면 높이 노브를 겸했다.** `SEA_Y=-1.40` ·
 * `RIVER_Y=-0.90`(강이 바다보다 50cm 높다는 불변식) 위에서 리프트가 살아 있으면 패치
 * 월드 y 가 `wamp` 0.2 → -1.19~-0.99(강 아래, 여태 티가 안 났다) · 0.45 → -0.94~-0.04
 * (**강 위**) · 0.75 → -1.39~+0.11(**지면 위**). 즉 리프트를 안 걷으면 진폭 축을 열 수
 * 없다. 헤드리스 실측이 계산과 맞았다 — `?wamp=0.75` 에서 `seaPatch.peak = 1.396m`.
 *
 * 그리고 이 리프트는 **렌더와 판정도 어긋내고 있었다**: `waterSurfaceY`(수영 판정)는
 * 파동을 안 보고 `SEA_Y` 를 돌려주는데, 보이는 물은 그보다 `PATCH_SEP + amp` 만큼
 * 위에 있었다. 리프트를 걷으면 패치 평균이 `SEA_Y + PATCH_SEP` 이 되어 **판정과 맞는다.**
 *
 * ⚠ **그러면 골은 무엇이 받는가 — 아래 층을 내린다.** 처음에 *"두 층 다
 * `depthWrite:false` 라 순서만 문제이고 뚫려도 된다"* 고 판단해 아래 층을 그대로 뒀는데,
 * **`tests/world2-ocean.test.ts` 의 기존 단언이 그것을 반증했다**(«골이 아래 층을 뚫지
 * 않는다»). 그 테스트가 든 근거는 z-fighting 이 아니라 *"물이 두 겹으로 갈라져 보인다"*
 * — 반투명 두 판이 **교차**하면 그 교차선이 수면 위에 선으로 드러난다. 깊이 버퍼와
 * 무관하게 **위치**가 만드는 현상이라 내 논증은 축이 아예 달랐다. 그래서 집행 쪽에서
 * `sea.position.y` 를 `SEA_Y − LIFT_AMP` 로 내려 골 밑을 비운다(`features/ocean.ts`).
 * 아래 층은 패치 밖(안개 너머)에서만 보이는 판이므로 이 낙하는 근거리 화면에 안 나온다.
 */
export function patchVertexY(
  x: number, z: number, t: number,
  amp: number = WAVE_AMP_DEFAULT, standing: number = WAVE_STANDING_DEFAULT,
): number {
  return PATCH_SEP + surfaceLift(x, z, t, amp, standing);
}

// world2/decide/stylized.ts — 스타일라이즈드 룩을 켜는가. 순수 판정.
//
// ── 왜 마스터 노브가 따로 있는가 (감독 지시 2026-08-18) ─────────────────────
// 감독이 참조로 준 게임 화면은 잔디·물·지형이 **함께** 만드는 인상이다. 셋을 따로 켜야
// 하면 감독이 링크를 세 번 조립해야 하고, 그 조립이 곧 «확인이 안 일어나는» 자리다.
// 그래서 하나로 켜는 문을 두고, 종목별 노브는 **그 위에서 하나만 빼 볼 때** 쓴다.
//
// ── 항등원 ──────────────────────────────────────────────────────────────────
// `?styl=0` 이 완전한 no-op 이다 — 세 기능의 `create()` 가 `null` 을 돌려주고
// `mountFeatures` 가 목록에 넣지 않으므로 씬·재질·텍스처를 **한 번도 안 만진다.**
// `decide/ground-albedo.ts` 의 `?glift=1` 이 세운 규약과 같다: 되돌리는 방법이 하나여야
// 감독이 «원래 화면» 을 확실하게 볼 수 있다.

/** 마스터 노브 키. 소비처가 문자열을 다시 적지 않게 여기서 연다 */
export const STYLIZED_KNOB = 'styl';

/**
 * 이 종목을 켜는가.
 *
 * @param master `?styl` 값(0 또는 1)
 * @param own    종목별 노브(`?grass`·`?wstyle`·`?gtex`). **지정 안 됐으면 `null`** —
 *               `readNumOpt` 의 어휘를 그대로 받는다. 「지정 안 됨」과 「0 을 지정함」을
 *               구별해야 마스터를 켠 채 하나만 빼는 것이 가능하다.
 */
export function stylizedOn(master: number, own: number | null): boolean {
  return (own ?? master) >= 0.5;
}

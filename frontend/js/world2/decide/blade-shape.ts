// world2/decide/blade-shape.ts — 잎 **한 장**의 실루엣·자세·명암 판정. 순수, three 무의존.
//
// ── 왜 `decide/grass.ts` 에서 갈라 나왔나 ──────────────────────────────────
// 관심사가 다르다. `grass.ts` 는 «어디에 몇 포기를 심는가»(필드 배치)이고 여기는 «한
// 포기가 어떻게 생겼는가»(실루엣)다. 실제로 감독 판정이 이 둘을 따로 때렸다 — 밀도는
// 세 번, 모양은 네 번 각각 되돌았고 그때마다 서로 무관했다. 그리고 `grass.ts` 가 482줄로
// `check:filesize` 상한 근처라 새 축을 더 얹을 자리가 없다.
//
// ── 감독 판정 2026-08-18 (4차): *"이게 나뭇잎처럼 안보여. 레퍼런스봐."* ─────
// 참조 화면(Archery Clash)과 우리 화면을 나란히 놓고 갈린 곳이 **넷**이다. 값이 아니라
// 축이 넷이므로 넷 다 노브로 연다 — 어느 축이 «나뭇잎이 아니다» 의 원인인지는 화면으로만
// 갈린다.
//
//   ① **실루엣** — 참조의 잎은 밑동이 좁고 **아래 1/5 근처가 가장 넓은** 란셋형이다.
//      우리는 `(1-t)^1.6` 이라 밑동이 최대이고 끝까지 단조 감소한다 = **이등변삼각형**.
//      삼각형은 잎이 아니라 **가시**로 읽힌다. 감독이 1차에 *"끝이 뾰족하지 않고"*, 4차에
//      *"나뭇잎처럼 안보여"* 라고 한 것이 같은 곳을 두 방향에서 가리킨 것이다 — 끝을
//      뾰족하게 했더니(2차) 이번엔 전체가 가시가 됐다. 고칠 곳은 **끝이 아니라 배**다.
//   ② **자세** — 참조의 잎은 **정지 상태에서 이미 휘어 있다**. 우리는 굽힘이 바람
//      셰이더에만 있어서, 돌풍이 약한 구역의 잎은 자로 그은 듯 곧게 선다(`WIND_GUST_BASE`
//      가 0.35 라 전체의 상당수가 그 상태다). 자연에도 게임에도 곧게 선 풀은 없다.
//   ③ **명암** — 참조는 밑동이 어둡고 끝이 밝아 잔디밭이 하나의 **볼륨**으로 읽힌다.
//      우리는 법선을 전부 위로 세우고 잎당 단색이라 세로 명암이 **정확히 0**이다. 그래서
//      개별 잎이 또렷하게 분리돼 보이고 «덩어리» 가 안 생긴다.
//   ④ **단면** — 참조의 잎은 원통처럼 부풀어 보인다. 우리는 평면 한 장에 법선이 전부
//      (0,1,0) 이라 잎 안쪽이 완전 균일하다.
//
// ⚠ ③④ 를 고치면서도 **법선을 실제 면 법선으로 되돌리지는 않는다.** 위로 세우는 것은
// 잔디 렌더링의 표준이고 그 이유(지면과 같은 빛을 받아 한 장으로 읽힘)는 지금도 유효하다.
// 대신 세로 명암은 **정점 컬러**로, 가로 명암은 **법선을 좌우로 벌려서** 낸다 — 둘 다
// 잎 «안» 의 그라데이션이지 잎 «간» 얼룩이 아니다.

/** 잎을 몇 마디로 쪼개는가 — 아크 길이 기준. 위로 갈수록 촘촘한 것은 그대로다. */
export const BLADE_NODES = [0, 0.30, 0.56, 0.80, 1.0] as const;

/**
 * 란셋형 혼합. `0` = 이등변삼각형(4차 이전) · `1` = 배가 있는 잎.
 *
 * **항등원이 0 이다** — 이 저장소의 노브는 «1 이 현재값» 이 규약인데(`?glift=1` 이 완전
 * no-op), 여기서는 감독이 **현재값을 반려**했으므로 기본을 새 쪽에 둔다. `?gbelly=0` 이
 * 반려된 화면을 정확히 재현한다. 판정 축을 되돌릴 수 있게 남기는 것이 규약의 목적이고,
 * 어느 값이 항등원인지는 그 다음 문제다.
 */
export const BLADE_BELLY = 1;

/**
 * 정지 상태의 굽힘 — **라디안**. 잎 전체가 그리는 원호의 중심각이다.
 *
 * 0.8rad ≈ 46°. 이 값에서 끝이 옆으로 눕는 거리는 잎 길이의 0.379배이고 실제 높이는
 * 0.897배로 준다(아래 `bladeArc` 의 산술). 28cm 잎이면 25cm 서고 끝이 10.6cm 눕는다.
 *
 * **왜 아크 길이를 보존하는가** — 잎을 휘게 하는 흔한 방법은 `z += k·t²` 로 앞으로 미는
 * 것인데, 그러면 휠수록 잎이 **길어진다**(원호가 아니라 늘어난 곡선이다). 굽힘 노브를
 * 돌리면 밀도까지 달라 보이고, 그러면 감독이 두 축을 한 화면에서 못 가른다. 원호로 두면
 * 굽힘은 자세만 바꾼다.
 */
export const BLADE_CURVE = 0.8;

/** 밑동 AO 세기. `0` 이 항등원(= 4차 이전의 균일 명암). */
export const BLADE_AO = 1;

/**
 * AO 를 최대로 걸었을 때의 밑동/끝 밝기 배수.
 *
 * 밑동 0.45 는 «명암은 크게» 라는 감독 명세를 따른 것이다. 사실적 AO 는 이만큼 안
 * 어둡지만, 게임풍에서 잔디밭이 덩어리로 읽히는 것은 **대비**가 만든다.
 * 끝을 1 이 아니라 1.16 으로 넘긴 것은 참조 화면의 잔디 끝이 지면보다 밝기 때문이다 —
 * 빛이 잎 사이를 통과하는 것(투과광)의 값싼 흉내다.
 */
export const AO_ROOT = 0.45;
export const AO_TIP = 1.16;

/**
 * 법선을 좌우로 벌리는 각 — **라디안**. `0` 이 항등원(= 전부 위, 4차 이전).
 *
 * 잎 왼쪽 정점의 법선을 −x 로, 오른쪽을 +x 로 기울이면 램버트 셰이딩이 잎 안에 가로
 * 그라데이션을 만들어 **평면이 원통처럼 읽힌다.** 정점도 삼각형도 안 늘어난다 — 실제로
 * 접으려면(중앙맥 V자) 정점 열이 3개가 돼 삼각형이 8→12 로 1.5배, 15만 포기에서 60만
 * 삼각형이 더 붙는다. 같은 인상을 공짜로 얻는 쪽을 고른다.
 *
 * 0.45rad ≈ 26°. 크게 벌리면 잎마다 Y 회전이 랜덤이라(`bladeBase.rot`) 밝기가 갈려
 * 필드가 얼룩덜룩해진다 — 법선을 위로 세운 원래 이유가 그것이라 절반만 간다.
 */
export const BLADE_NORMAL_SPREAD = 0.45;

/**
 * 반폭 프로파일 — `t`(밑동 0 → 끝 1)에서 잎 반폭이 최대 반폭의 몇 배인가.
 *
 * `belly=0` 은 `(1-t)^1.6` 그대로(밑동 최대·단조 감소). `belly=1` 은 란셋형이고, 밑동
 * 0.847 → **t≈0.22 에서 1.0** → 끝 0 을 지난다. 배의 위치가 아래 1/5 인 것은 참조
 * 화면에서 잰 인상을 그대로 옮긴 것이다.
 *
 * `sin(π·s^0.62)^0.75` 에서 `s = 0.14 + 0.86t` 인 이유: `s=t` 면 밑동이 0 이 돼 잎이
 * 줄기에서 실처럼 시작한다. 0.14 를 깔아 밑동에 실체를 남긴다.
 *
 * `tip` 은 끝 반폭의 하한이라 프로파일과 **독립**이다 — 끝을 뭉툭하게 하는 축과 배를
 * 만드는 축이 섞이면 감독이 둘을 한 화면에서 못 가른다.
 *
 * **실측**(`tip=0.14`, 반폭을 최대폭 `W` 로 나눈 값):
 * ```
 *   t      0     0.15   0.22   0.30   0.50   0.80   1.00
 *   삼각형 0.500  0.402  0.361  0.313  0.212  0.103  0.070
 *   란셋   0.434  0.495  0.500  0.493  0.433  0.261  0.070
 * ```
 * 최대는 **t=0.217 에서 0.500** 이고, 같은 지점의 삼각형은 0.361 이다 — 잎의 배가
 * **1.39배** 넓어지고 밑동은 반대로 0.868배로 좁아진다. 끝(0.070 = `tip/2`)은 두 쪽이
 * 같다: 이 축은 **끝을 안 건드린다.**
 */
export function halfWidthProfile(t: number, tip: number, belly: number): number {
  const tri = Math.pow(1 - t, 1.6);
  const leaf = Math.pow(Math.sin(Math.PI * Math.pow(0.14 + 0.86 * t, 0.62)), 0.75);
  const mix = tri + (leaf - tri) * belly;
  return 0.5 * (tip + (1 - tip) * mix);
}

/**
 * 아크 길이 `t` 지점의 잎 좌표 — 일정 곡률 원호. 길이 1 기준이라 호출부가 높이를 곱한다.
 *
 * θ(s) = curve·s 로 두고 적분한 것이다: y = ∫cos, z = ∫sin. `curve→0` 극한이 정확히
 * `{y: t, z: 0}` 이라 굽힘 0 이 4차 이전의 직립 평면과 **바이트 단위로 같다.**
 */
export function bladeArc(t: number, curve: number): { y: number; z: number } {
  if (curve < 1e-4) return { y: t, z: 0 };
  return { y: Math.sin(curve * t) / curve, z: (1 - Math.cos(curve * t)) / curve };
}

/**
 * 아크 길이 `t` 지점의 정점 밝기 배수. `ao=0` 이면 언제나 정확히 1(항등원).
 *
 * `t^0.8` 은 거의 선형이되 밑동 쪽 어둠을 조금 넓게 깐다. 지수 감쇠(`1-e^-kt`)가 물리에
 * 더 가깝지만 밑동만 좁게 어두워져 «덩어리» 가 아니라 «그림자 띠» 로 읽혔다.
 */
export function bladeShade(t: number, ao: number): number {
  const g = AO_ROOT + (AO_TIP - AO_ROOT) * Math.pow(t, 0.8);
  return 1 + (g - 1) * ao;
}

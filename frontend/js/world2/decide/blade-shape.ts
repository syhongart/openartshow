//
// ── 왜 `decide/grass.ts` 에서 갈라 나왔나 ──────────────────────────────────
// 관심사가 다르다. `grass.ts` 는 «어디에 몇 포기를 심는가»(필드 배치)이고 여기는 «한
// 포기가 어떻게 생겼는가»(실루엣)다. 실제로 감독 판정이 이 둘을 따로 때렸다 — 밀도는
// 세 번, 모양은 네 번 각각 되돌았고 그때마다 서로 무관했다. 그리고 `grass.ts` 가 482줄로
// `check:filesize` 상한 근처라 새 축을 더 얹을 자리가 없다.
//
// ── 감독 판정 2026-08-18 (4차): *"이게 나뭇잎처럼 안보여. 레퍼런스봐."* ─────
// 참조 화면(Archery Clash)과 우리 화면을 나란히 놓고 갈린 곳이 **넷**이다. 값이 아니라
// 축이 넷이므로 넷 다 노브로 연다 — 어느 축이 «나뭇잎이 아니다» 의 원인인지는 화면으로만
// 갈린다.
//
//   ① **실루엣** — 참조의 잎은 밑동이 좁고 **아래 1/5 근처가 가장 넓은** 란셋형이다.
//      우리는 `(1-t)^1.6` 이라 밑동이 최대이고 끝까지 단조 감소한다 = **이등변삼각형**.
//      삼각형은 잎이 아니라 **가시**로 읽힌다. 감독이 1차에 *"끝이 뾰족하지 않고"*, 4차에
//      *"나뭇잎처럼 안보여"* 라고 한 것이 같은 곳을 두 방향에서 가리킨 것이다 — 끝을
//      뾰족하게 했더니(2차) 이번엔 전체가 가시가 됐다. 고칠 곳은 **끝이 아니라 배**다.
//   ② **자세** — 참조의 잎은 **정지 상태에서 이미 휘어 있다**. 우리는 굽힘이 바람
//      셰이더에만 있어서, 돌풍이 약한 구역의 잎은 자로 그은 듯 곧게 선다(`WIND_GUST_BASE`

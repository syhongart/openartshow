// frontend/js/world2/parts/surface.ts
//
// **파셀 안 어느 지점에서 실제로 밟는 바닥 높이**의 SSOT. 순수 함수 — three 무의존.
//
// ── 왜 생겼나 (감독 발견 2026-08-12) ────────────────────────────────────────
// 감독: *"초록바닥은 왜 그림자가 안 생기지?"* (스크린샷 2장 — 잔디 위 그림자 0,
// 광장 갈색 바닥에서는 정상)
//
// 원인은 그림자가 아니라 **높이의 모델**이었다. world2 의 바닥은 한 겹이 아니다:
//
//     도로(`road`)   0.14   ← 길이 지나는 자리에만
//     잔디(`garden`) 0.07   ← 파셀을 꽉 채운다. 단 광장에는 안 깐다
//     지면(`ground`) 0      ← 맨 밑. 광장에서는 이것이 드러난다
//
// 그런데 실물 파츠는 전부 `y: 0` 으로 놓였다. 그래서 잔디 파셀에서는 물건이 **7cm 잠기고**
// 그림자 데칼(0.02)이 잔디 판 **5cm 아래**로 묻혀 아예 안 보였다. 광장에는 잔디가 없어
// 지면이 드러나므로 거기서만 그림자가 정상으로 보였던 것이다 — 감독 스크린샷 두 장의 차이가
// 정확히 이 한 줄이다.
//
// ── 왜 파츠가 신고하지 않는가 (팀장 판정 2026-08-12) ────────────────────────
// 직전 처방은 `PartSpec.standsOn`(파츠가 자기 지면 높이를 상수로 신고)이었고 **축이 틀린
// 모델**이었다. 높이는 파츠 종류가 아니라 **자리**의 속성이다 — 같은 벤치가 광장에서는 0,
// 잔디 파셀에서는 0.07 이다. 상수 신고로는 그 갈림을 표현할 수 없다. 그래서 신고를 걷고
// **자리를 묻는 함수**로 옮겼다.
//
// ── 이 함수가 못 보는 것 ────────────────────────────────────────────────────
// · 지형 기복이 생기면(지금은 전부 평면) 여기서 그 높이도 함께 봐야 한다.
// · GLB 건물 바닥·다리(`bridge`) 같은 **파츠 위에 서는** 경우는 대상이 아니다. 그것은
//   "바닥이 무엇인가" 가 아니라 "무엇 위에 쌓았는가" 이고 다른 축이다.

import { isPlaza } from './plaza.js';
import { roadDirs, onRoad } from './road-topology.js';
import { GARDEN_SURFACE_Y } from './garden.js';
import { ROAD_SURFACE_Y } from './road.js';

/**
 * 파셀 `(px,pz)` 의 로컬 좌표 `(x,z)` 에서 밟는 바닥 높이(m).
 *
 * 위에서부터 덮은 순서로 본다 — 도로가 있으면 도로, 없으면 잔디, 광장이면 지면.
 * 이 순서가 곧 각 판의 y 순서(0.14 > 0.07 > 0)와 같아야 한다. 어긋나면 위에 깔린 판을
 * 무시하고 아래 높이를 돌려주게 되고, 그것이 이번 결함의 형태다.
 */
export function surfaceY(px: number, pz: number, x: number, z: number): number {
  if (onRoad(x, z, roadDirs(px, pz))) return ROAD_SURFACE_Y;
  // 광장은 잔디를 걷어 지면이 드러난 자리다(`garden.ts` 의 `isPlaza` 가드와 짝).
  // ⚠ **두 곳이 같은 조건을 보고 있다.** 한쪽만 고치면 잔디는 깔렸는데 표면은 0 이라고
  // 답하는(=다시 잠기는) 상태가 된다. 그 짝을 `tests/world2-surface.test.ts` 가 잡는다.
  if (isPlaza(px, pz)) return 0;
  return GARDEN_SURFACE_Y;
}

//
// ── 감독 지시 (2026-08-17) ────────────────────────────────────────────────
// *"조준 화면 그것도 해줘"* — 사진을 고르면 패널을 접고 조준 화면을 띄워, 벽에 맞았는지를
// **보면서** 확정한다(팀장 판정 (B)). W8-5 의 「두 번에 한 번 걸린다」를 해소하는 회차다.
//
// ── 🔴 이 파일이 존재하는 이유 — `pickFace()` 는 싸지 않다 ─────────────────
// 조준 화면은 「지금 벽에 맞았는가」를 **실시간으로** 보여줘야 하고, 그 판정은 확정 경로와
// **같은 함수**여야 한다(다른 걸 쓰면 «초록인데 안 걸린다» 가 난다). 그런데 그 함수가 비싸다:
//
//   `systems/instancing.ts` 의 `refreshBounds()` 가 **풀 용량 전체**에 `computeBoundingSphere()`
//   를 돈다. 이 저장소는 `mesh.count` 를 한 번도 낮추지 않으므로(풀을 `spec.max` 로 만들고
//   `count` 를 안 줄인다) 비용이 「쓰는 슬롯」이 아니라 **「용량」**(≈1000 슬롯, 그림자 풀
//   복제 포함)이다. 게다가 미사용 슬롯이 `ZERO` 행렬이라 경계구가 원점까지 감싸고, 그래서
//   three 의 경계구 사전 필터가 **거의 항상 통과**한다 — 인스턴스 루프가 용량만큼 다 돈다.
//
// `instancing.ts` 주석이 *"클릭당 한 번이라 무시할 만하다"* 라고 적고 있는데 **이 회차가
// 그 전제를 깬다.** 지금까지 `pickFace()` 호출자는 하나였고 조작 1회당 1회였다.
//
// ── ⚠⚠ 그리고 그 비용을 **로컬에서 잴 방법이 없다** ────────────────────────
// 이 저장소는 프레임 시간을 일부러 안 잰다(swiftshader 는 실기기와 무관 — `CLAUDE.md`).
// `scripts/smoke/` 에 시간 측정은 0건이다. **스모크가 전부 초록이어도 CPU 비용을 한 글자도
// 보증하지 않는다.**
//
// 그래서 시간을 재는 대신 **「몇 번 쏘는가」를 이산 게이트로** 만든다 — 이 저장소가 개수
// 불변식으로 이미 쓰는 형태다. 그 게이트가 읽는 값이 `stats().overlay.aim.casts` 이고,
// 그것을 **참으로 만드는 판정이 이 파일**이다.
//
// ⚠ **대리 축이지 시간이 아니다.** 호출 횟수가 상한 안이어도 한 번이 느리면 화면은 버벅인다.
// 그것은 **감독 실기기가 유일한 판정**이다 — 여기서 통과했다고 성능을 통과로 적지 않는다.

/** 카메라 자세 — 위치와 **바라보는 방향**(단위벡터). 조준은 이 둘로만 정해진다 */
export interface AimPose {
  readonly x: number; readonly y: number; readonly z: number;
  readonly dx: number; readonly dy: number; readonly dz: number;
}

/**
 * 연속 재판정 사이 **최소 간격(ms)**. 12.5Hz 상한이다.
 *
 * ── 왜 80 인가 ────────────────────────────────────────────────────────────
 * 조준 피드백은 **사람이 조준을 고치는 속도**만 따라가면 된다. 고개를 돌리다 «맞았다» 를
 * 보고 멈추는 반응이 대략 0.2초이므로 그 안에 두세 번 갱신되면 «즉시» 로 읽힌다. 60Hz 로
 * 돌 이유가 없고, 그 차이가 곧 위 헤더의 비용이다.
 *
 * ⚠ **이 값은 유도한 것이 아니라 고른 것이다.** 실기기에서 몇 Hz 가 필요한지는 못 쟀다
 * (그럴 수단이 없다 — 헤더 참조). 감독이 «반응이 굼뜨다» 고 하면 낮추고, «버벅인다» 고
 * 하면 올린다. **둘 다 화면으로만 판정된다.**
 */
export const AIM_MIN_MS = 80;

/**
 * 다시 쏠 만큼 움직였는가 — 위치(m)와 방향의 문턱.
 *
 * **정지 상태에서 0회를 만드는 것이 요점이다.** 가만히 서 있으면 결과가 같으므로 쏠 이유가
 * 없고, 그것이 이 판정으로 얻는 가장 큰 절약이다(조준 화면은 사용자가 **멈춰서 고민하는**
 * 시간이 길다 — 걸 자리를 정하는 중이다).
 *
 * `MOVE` 2cm 는 걷기 한 프레임이면 즉시 넘고, 서 있을 때의 부동소수 흔들림은 안 넘는다.
 * `TURN` 은 방향 단위벡터의 맨해튼 거리라 대략 0.1° 에 해당한다 — 손떨림은 넘고 정지는 안 넘는다.
 *
 * ⚠ 두 값 다 **화면에서 판정되는 값**이다. 너무 크면 «돌렸는데 표시가 안 바뀐다» 가 되고,
 * 너무 작으면 정지 상태에서도 계속 쏜다. 후자는 게이트가 잡는다(`casts` 불변식).
 */
export const AIM_MOVE_EPS = 0.02;
export const AIM_TURN_EPS = 0.002;

/**
 * 지금 다시 쏠 것인가. **순수** — 시간과 자세만 본다.
 *
 * @param prev 마지막으로 쏜 시점의 자세. 아직 안 쐈으면 `null`
 * @param cur  지금 자세
 * @param sinceMs 마지막으로 쏜 뒤 흐른 시간(ms)
 *
 * ⚠ **간격을 먼저 본다.** 자세 비교를 먼저 하면 빠르게 도는 프레임에서 문턱을 넘는 순간마다
 * 쏘게 되고 상한이 성립하지 않는다 — 상한은 **모든 경로 위에** 있어야 한다.
 */
export function shouldRecast(prev: AimPose | null, cur: AimPose, sinceMs: number): boolean {
  if (!(sinceMs >= AIM_MIN_MS)) return false;
  // 첫 회는 무조건 쏜다 — 조준 화면이 뜬 순간 「지금 뭘 보고 있나」를 말해야 한다.
  if (!prev) return true;
  const dp = Math.abs(cur.x - prev.x) + Math.abs(cur.y - prev.y) + Math.abs(cur.z - prev.z);
  if (dp > AIM_MOVE_EPS) return true;
  const dd = Math.abs(cur.dx - prev.dx) + Math.abs(cur.dy - prev.dy) + Math.abs(cur.dz - prev.dz);
  return dd > AIM_TURN_EPS;
}

/** 조준 화면이 화면에 말하는 것. **문구를 소비자가 짓지 않는다**(`artNameHelp` 와 같은 규약) */
export function aimHint(hit: boolean): string {
  return hit
    ? '이 벽에 걸립니다 — 「여기 걸기」를 누르세요.'
    : '벽을 찾는 중 — 고개를 돌려 벽을 조준선에 두세요.';
}

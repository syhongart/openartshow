//
// ── 왜 파일 하나를 따로 만들었나 (W8-4) ───────────────────────────────────
// 작품(`decide/artwork.ts`)에 `ry` 를 넣으면서 접기 함수를 **복제했고**, 그 순간 계약
// (`decide/overlay.ts` 의 `foldRy`)과 **규약이 갈렸다** — 내 것은 `[-π, π)` 로 좁혔고
// 계약은 `[-2π, 2π)` 였다. 테스트가 바로 빨간불을 냈다.
//
// 같은 값을 두 곳에 적으면 한쪽만 고쳐도 아무도 모른다는 것이 이 저장소가 세 번 덴
// 형태이고, 여기서는 **두 곳이 애초에 다른 값을 내고 있었다.** 증상은 «편집 화면에서
// GLB 와 액자의 회전 숫자가 다르게 보인다» 로만 났을 것이다.
//
// 합칠 자리가 마땅치 않았던 것이 원인이다: 계약에서 `export` 하면 `artwork.ts` →
// `overlay.ts` → `artwork.ts` **순환**이 되고(`check:cycles` 가 막는다), `artwork.ts` 가
// 소유하면 «작품 파일에 각도 유틸이 산다» 로 이름이 거짓이 된다. **leaf 를 하나 두는
// 것이 둘 다 피하는 유일한 길이다.**

/**
 * 회전(라디안)을 한 바퀴 안으로 접는다.
 *
 * ⚠ **범위는 `(-2π, 2π)` 다** — `[-π, π)` 가 아니다. 계약(`decide/overlay.ts`)이 v1 부터
 * 이 규약으로 저장해 왔고, 좁히면 **이미 배포된 문서의 값이 바뀐다**(내보내기 관문이
 * `folded` 사유를 새로 내기 시작한다 — 손실이 없는데 손실로 보고하는 것이다).
 *
 * 그래서 «더 나은 범위» 를 고르지 않고 **이미 있는 규약을 SSOT 로 승격**했다.
 * 재론 조건: 계약 버전을 올리는 회차. 그때는 마이그레이션이 값을 함께 옮긴다.
 *
 * 수가 아니면 `0`. 던지지 않는다 — 손으로 편집하는 JSON 이 입력이다.
 */
export function foldAngle(v: unknown): number {
  const n = typeof v === 'number' && Number.isFinite(v) ? v : 0;
  const m = n % (Math.PI * 2);
  // `-0` 을 없앤다. 남기면 `JSON.stringify` 가 `0` 으로 쓰는데 `Object.is` 비교는 다르다고
  // 해서, 관문이 「바뀐 것이 없는데 바뀌었다」고 보고한다.
  return Object.is(m, -0) ? 0 : m;
}

// ── ① 두 밴드 실측 ─────────────────────────────────────────────────────────
//   예산: draw ≤ 150 · tri ≤ 200,000 · 초기 전송 ≤ 10MiB (지시서 §7, 팀장 조건 4)
//
//   (ㄱ) PR #298 (검수관 독립 재현) — 정지·주행 위주 세션
//     밴드 | draw    | tri               | 초기 전송 | 판정
//     ─────┼─────────┼───────────────────┼──────────┼────────────────────────
//      1.0 | 116~210 | 279,908 ~ 348,700 | 7.72MiB  | draw·tri **둘 다 초과**
//      0.5 | 116~125 | 115,498 ~ 125,322 | 7.72MiB  | 셋 다 예산 안
//
//   (ㄴ) 2026-09-11 집행 실측 — **회전 360° 구간을 넣어 다시 잰 것**
//        (헤드리스 1280×720 · webgl-software · 세션 ①정지 ②회전 ③주행 ④재방문)
//     밴드 | draw 최대 | tri 최대  | 전송    | 떠 있는 셀 | 파이프라인 | 콘솔에러
//     ─────┼───────────┼──────────┼────────┼───────────┼───────────┼─────────
//      1.0 |  199      | 335,472  | 3.59MiB | 15~16     | 273 → 291 | 0
//      0.5 |  216      | 167,262  | 3.60MiB |  2~4      |  58 →  92 | 0
//
//   🔴 **(ㄱ) 의 draw 열을 「0.5 면 draw 도 예산 안」으로 읽으면 안 된다.** 회전을
//   넣으면 0.5 의 draw 피크가 **216 으로 1.0(199)보다 오히려 높다** — 밴드는 draw 를
//   줄이는 레버가 아니다. 원인은 이미 이 저장소가 적어 둔 것이다: 기본 세션의 draw 는
//   **컬링으로 정당하게 변하므로 판정에 쓸 수 없고**, 그래서 드로우콜 축은 사람·GLB 를
//   끈 대조군 세계에서만 판정한다(`scripts/smoke/run.mjs` `[7.6]`, 태스크 #208).
//   즉 (ㄱ)·(ㄴ)은 서로 틀린 것이 아니라 **draw 라는 축이 이 세션 방식으로 판정
//   불가**인 것이고, 두 실측이 어긋난 자리가 정확히 그 사실을 가리킨다.
//
//   그래서 (a) 채택을 떠받치는 축은 **tri 하나다** — 그 축에서는 1.0 이 예산을 1.7배
//   넘고 0.5 가 예산 안이며, 두 실측이 서로 일치한다. 곁가지로 파이프라인 절대값이
//   291 → 92 로 내려간다(world1 프리즈의 직접 원인이 파이프라인 단조증가였다).
//
//   격자 자체의 draw 는 셀 수와 무관한 **46 상수**다(슬롯 풀이 셀 종류마다 하나라
//   인스턴스가 늘어도 드로우콜이 안 는다). 그래서 초과분은 격자가 아니라 파셀 파츠·
//   액자에서 나온다. **draw 를 예산 안으로 넣는 일은 이 판정의 범위 밖이고 미해결이다.**
//
// ── ② 왜 팀장이 정했는가 ────────────────────────────────────────────────────
//   2026-09-07 에 감독께 상신했고 **다음 발화가 이 질문에 답하지 않았다**. 그 시점이
//   「감독에게 물었는데 답이 없는 결정 → 팀장이 결정하고 보고한다」(감독 지시
//   2026-07-31)의 발동 시점이다 — 시간 기준이 아니라 발화 기준이고, 묻고 멈춰 서
//   있지 않는 것이 그 조항의 목적이다. 감독이 나중에 다르게 판단하면 그것이 최종이다.
//
// ── ③ 재론 조건 — 감독이 화면을 보고 «더 멀리» 라고 하면 ────────────────────
//   **이 상수를 만지지 마라.** 열 것은 **감독 원문 수치(draw 150 · tri 20만) 개정
//   카드**다. 밴드를 올려 예산을 넘기는 것은 C3 위반이고, 그때 일어나는 일은 「예산을
//   조용히 넘긴 채 화면만 맞은 상태」다 — 이 저장소가 `MAX_PARCELS=20` 에서 이미
//   겪은 형태(두 값이 각각 틀린 채 서로를 가려주던 상태)와 같다. 예산이 근거를
//   잃었으면 예산을 고치는 것이 순서이지, 예산을 안 보고 값을 미는 것이 아니다.
//
// ── ④ 경계 — 여기서 멈춘다 ─────────────────────────────────────────────────
//   **0.5 와 1.0 사이 중간값(0.6·0.75·0.8 …) 탐색은 감독의 «더 멀리» 가 나오기
//   전에는 열지 않는다.** 지금 화면을 문제라고 한 사람이 없고, 「수치가 이상한 것과
//   화면이 잘못된 것은 다른 일」이다. 축을 먼저 여는 것이 이 저장소에서 가장 비쌌던
//   실수(형광 잔디 회차)의 형태다.
//
// ── ⑤ ⚠ 동반 결함 — 안개·비행천장·그림자는 이 배율을 **안 따라온다**(미해결) ──
//   `scaleBands`(`world10/decide/lod.ts`)는 **tier 밴드만** 곱한다. 아래 셋은 원본
//   `DEFAULT_BANDS` 에서 유도하므로 `?band=` 와 무관하게 2.40셀 = 153.6m 에 남는다:
//     · 안개     `decide/fog.ts`  `FOG_FAR_CELLS = DEFAULT_BANDS.farExit`
//     · 비행천장 `decide/fly.ts`  `FLY_CEIL_CELLS = DEFAULT_BANDS.farExit`
//     · 그림자   `world10/main.ts` `SHADOW_BAND` 의 fallback
//   결과(유도): 렌더는 76.8m 에서 끊기는데 안개는 `FOG_NEAR_CELLS` 1.6셀 = **102.4m**
//   에서야 시작한다 — 세계가 끊기는 지점의 안개 진행률이 **0%** 다. `fog.ts` 가
//   *"안개가 더 멀면 그 사이가 텅 비어 보인다"* 고, `scaleBands` 가 *"진단 전용이고,
//   상시 값으로 쓰려면 안개·그림자 밴드와 함께 설계해야 한다"* 고 **미리 적어 둔** 그
//   상태다. 같은 이유로 `residualAtSpawn` 이 0.375 → **1.0**(파셀이 자기 색 100% 로
//   등장), `crossingCells` 가 0.5 → **0**(페이드가 끝날 구간이 없다)이 된다.
//   **여기서 고치지 않는다** — 안개·그림자 밴드를 배율에 연동할 것인가는 되돌리기
//   비싼 설계 분기라 팀장 몫이고, (a) 채택의 근거였던 draw·tri 예산과는 다른 축이다.
//   이 사실을 적어 두는 이유: 다음 사람이 화면의 «끊김» 을 보고 밴드를 되돌리면
//   예산이 다시 깨진다. 축이 둘이라는 것을 모르면 한쪽만 고치게 된다.
//   ⚠ 이 다섯 수치는 `tests/world10-band-default.test.ts` 가 **유도로** 다시 계산해
//   못 박는다 — 여기 적힌 것은 기록이고, 값의 출처는 언제나 밴드다.
const DEFAULTS: Readonly<Record<string, string>> = { glb: '0', grass: '0', hemig: '8a857c', band: '0.5' };
const url = new URL(location.href);
let touched = false;
for (const [k, v] of Object.entries(DEFAULTS)) {
  if (!url.searchParams.has(k)) { url.searchParams.set(k, v); touched = true; }
}
if (touched) history.replaceState(history.state, '', url);

const canvas = document.getElementById('wg-canvas');
if (canvas instanceof HTMLCanvasElement) {
  const cam = parseCam(location.search);
  startGlbWorld(canvas, {
    tag: 'world10',
    source: async () => {
      const rel = document.body?.dataset?.glb ?? '';
      if (!rel) throw new Error('data-glb 가 비어 있다 — 열 세계가 없다');
      const res = await fetch(assetUrl(rel));
      if (!res.ok) throw new Error(`GLB 를 못 받았다: HTTP ${res.status}`);
      return res.arrayBuffer();
    },
    // `?cam=` 이 없으면 아트 기준 V1(거리 시작: 입구 중앙, 눈높이는 트리 기본 1.7m)에서 시작한다 —
    // 트리 기본 스폰(-3.5, 10)은 world2 광장 좌표라 거리 밖(남쪽 보도 뒤)이다.
    start: cam ?? V1_START,
  }).catch((err: unknown) => {
    console.error('[world10] 진입 실패', err);
  });
} else {
  console.error('[world10] 캔버스(#wg-canvas)를 찾지 못했습니다');
}

// world-glb/decide/village-pick.ts — **인스턴스 하나 → 그것이 배치의 몇 번째인가.** 순수 함수만.
//
// ── 왜 이 환원이 필요한가 ───────────────────────────────────────────────────
// 마을 파츠는 `InstancedMesh` 의 슬롯이다. 레이캐스트가 주는 것은 (메시, 인스턴스 번호)
// 이고, 그것을 쥔 핸들(`InstancePools.ownerAt`)이 아는 것은 **종류뿐**이다 — 어느 파셀의
// 몇 번째 건물인지는 아무도 모른다. 슬롯 풀은 «어디에 무엇이 있는가» 를 일부러 안 들고
// 있다(그것이 개수 불변식의 대가다).
//
// 그래서 **위치로 되짚는다.** 인스턴스 행렬의 이동 성분이 곧 `(ox + p.x, p.y, oz + p.z)`
// 이므로, 파셀을 구하고 그 파셀의 배치에서 같은 자리를 찾으면 인덱스가 나온다.
//
// ⚠ **이 경로가 성립하는 것은 위치가 변형되지 않기 때문이다**(실측 2026-08-13):
//   · `parcel-grow` 의 `apply` 는 `t.x, t.y, t.z` 를 그대로 쓰고 **스케일에만** 배수를 곱한다
//   · `shadow-decal` 의 `warp` 는 `shadow:` 접두 슬롯만 변형하고 나머지는 그대로 통과시킨다
// 둘 중 하나라도 위치를 만지게 되면 이 환원이 조용히 어긋난다 — 증상은 «가끔 엉뚱한
// 건물이 집힌다» 이고, 그때 고칠 곳은 여기가 아니라 그 변형 쪽이다.
//
// ── 왜 «슬롯 → 인덱스» 역인덱스를 빌더에 만들지 않았나 ──────────────────────
// 그러면 빌더가 슬롯마다 맵 항목을 하나씩 들어야 하고, 그 비용은 **라이브에서도** 난다.
// 편집은 `?edit=1` 세션에만 있는데 그 대가를 전 세션이 치르는 형태다. 위치 환원은
// 클릭할 때만 돌고 라이브에 아무것도 안 남긴다.
//
// ── 그리고 좌표 매칭이 인덱스 보관보다 견고하다 ─────────────────────────────
// 빌더는 tier 로 거른 배열을 놓는다(`forTier`). 지금은 항등이라 인덱스가 우연히
// 일치하지만, tier 가 실제로 갈리는 날 «near 배열의 12번» 과 «화면에 놓인 12번» 은
// 다른 것이 된다. 좌표는 그 날에도 같다.

import type { PlacedPart } from '../parts/types.js';

/**
 * 같은 자리로 볼 허용 오차(m).
 *
 * 왜 0 이 아닌가: 인스턴스 행렬은 `Float32Array` 에 담긴다. 좌표가 수백 미터면 float32
 * 상대 정밀도(~1e-7)가 절대 오차 1e-4 m 안팎으로 나타나므로 **정확히 같을 수 없다.**
 *
 * 왜 이 크기인가: 파츠 간 최소 간격보다 훨씬 작아야 «옆 건물이 집히는» 일이 없다.
 * 마을 배치는 충돌 검사를 거쳐 놓이므로 같은 종류가 1cm 안에 겹치지 않는다.
 */
export const PICK_EPS = 0.02;

export interface PartMatch {
  /** `parts` 배열에서의 인덱스. 이것이 편집이 가리킬 «이름» 이다 */
  readonly index: number;
  readonly part: PlacedPart;
}

/**
 * 파셀 로컬 좌표 `(lx, lz)` 에 있는 `kind` 파츠를 배열에서 찾는다. 없으면 `null`.
 *
 * **가장 가까운 것을 고르되 `PICK_EPS` 를 넘으면 실패다.** 「가장 가까운 것」만 쓰면
 * 파셀을 잘못 구했을 때도 **언제나 무언가를 집게 되고**, 그러면 감독이 클릭한 건물과
 * 다른 것이 선택된 채로 편집이 진행된다. 실패가 조용한 오답보다 낫다.
 */
export function matchPart(
  parts: readonly PlacedPart[],
  kind: string,
  lx: number,
  lz: number,
  eps: number = PICK_EPS,
): PartMatch | null {
  let best: PartMatch | null = null;
  let bestD = Infinity;
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i];
    if (p.kind !== kind) continue;
    // 제곱거리로 비교한다 — 루트는 판정에 필요 없고, 임계값도 제곱해서 견준다.
    const d = (p.x - lx) * (p.x - lx) + (p.z - lz) * (p.z - lz);
    if (d < bestD) { bestD = d; best = { index: i, part: p }; }
  }
  if (!best || !(bestD <= eps * eps)) return null;
  return best;
}

// ── ⚠ 그림자 데칼 슬롯을 거르는 판정은 **여기 만들지 않았다** ────────────────
// 데칼은 캐스터와 같은 자리에 깔린 별개 슬롯이라(`shadow-decal.ts` 의 `poseOf`), 거르지
// 않으면 광선이 지면 근처에서 **데칼을 먼저 맞힌다** — «바닥을 클릭했는데 아무것도 안
// 집힌다» 로 보이지만 실제로는 집을 수 없는 것을 집은 것이다.
//
// 그런데 그 판정은 **이미 있다**: `systems/shadow-decal.ts` 의 `isShadowKey`. 여기에
// 같은 접두를 다시 적으면 값 미러링이고, 접두가 바뀌는 날 한쪽만 고쳐도 아무도 모른다
// (증상은 데칼이 다시 집히는 것뿐이라 게이트가 안 잡는다). 소비자가 그쪽을 쓴다.

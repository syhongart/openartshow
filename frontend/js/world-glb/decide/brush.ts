// ── 감독 판정 2026-08-22 (카드) ─────────────────────────────────────────────
// *"워크래프트3 편집기 보니깐 … 우리 편집기 보고 개선해봐"* → 실행취소를 먼저 넣은 뒤
// 다음 축을 카드로 물었고 **「브러시로 여러 개 뿌리기」**가 뽑혔다.
//
// 그 편집기의 도장(doodad) 브러시가 하는 일은 셋이다: ① 붓 반경 안에 흩뿌리고
// ② **회전을 무작위로** 주고 ③ **크기를 조금씩 다르게** 준다. ②③이 없으면 같은 나무가
// 같은 방향으로 격자처럼 서고, 그것은 숲이 아니라 **가로수**로 보인다.
//
// ── 왜 여기가 지점만 뽑고 「놓을 수 있는가」는 안 보는가 ────────────────────
// 놓을 수 있는지는 물·격자 경계·파셀 상한·이미 놓인 것과의 겹침이 함께 정하고, 그
// 판정들은 각각 `decide/water.ts`·`decide/grid.ts`·`decide/asset-library.ts`·
// `parts/index.ts` 가 이미 소유한다. 여기서 다시 물으면 **네 곳을 미러링**하게 된다.
// 그래서 이 파일은 «어디에 찍을까» 만 답하고, 거르는 것은 집행부(`edit/actions.ts`)다.
//
// 예외가 하나 있다 — **점끼리의 최소 간격**은 여기서 본다. 그것은 붓 자신의 성질이고
// (한 붓질 안에서 겹치지 않게), 밖에서 걸러 내면 «요청한 만큼 안 나온다» 를 붓이 모른 채
// 화면에 잘못된 개수를 말하게 된다.
//
// ── 결정적이다 — `Math.random()` 을 안 쓴다 ────────────────────────────────
// 시드를 받는다. ① 이 저장소의 규율(생성은 좌표 해시 기반)과 같은 형태이고 ② 무엇보다
// **검사가 같은 붓질을 재현할 수 있어야** 분포·간격·변주를 잴 수 있다. 시드는 부르는
// 쪽이 준다(붓질마다 달라야 하므로 클릭 좌표에서 만든다).

import { rngFrom } from './parcel-layout.js';

/** 붓이 찍은 자리 하나. 좌표는 **월드**다 — 파셀 환산은 집행부가 한다 */
export interface BrushDot {
  readonly x: number;
  readonly z: number;
  /** 무작위 회전(라디안). 이것이 없으면 숲이 가로수가 된다 */
  readonly ry: number;
  /** 크기 배수. 1 근처에서만 흔든다 — 아래 `S_JITTER` */
  readonly s: number;
}

/**
 * 붓 반경(m)의 하한·상한. 감독이 슬라이더로 고른다.
 *
 * ── 왜 이 범위인가 (유도값이다) ────────────────────────────────────────────
 * 파셀 한 칸이 **32m**(`decide/grid.ts` 의 셀 크기)이다. 상한을 그 절반인 16m 로 두면
 * 붓 하나가 **최대 네 파셀**에 걸친다(중심이 모서리에 있을 때). 그보다 넓히면 한 붓질이
 * 아홉 파셀을 동결시켜 「어디를 손댔는지」가 화면에서 안 읽히고, 되돌리기 한 항목이
 * 지나치게 큰 덩어리가 된다.
 *
 * 하한 2m 는 **파츠 하나의 크기 정도**다. 그보다 좁으면 점들이 서로 겹쳐 간격 검사에
 * 전부 걸리고, 그러면 「개수를 올려도 안 늘어나는」 붓이 된다.
 */
export const R_MIN = 2;
export const R_MAX = 16;

/**
 * 한 붓질의 개수 하한·상한.
 *
 * 상한 24 는 **파셀당 상한에서 왔다** — `maxPartsPerParcel('tree')` 가 기본 레이아웃에서
 * 가장 큰 값이고(파츠 종류 중 나무가 가장 많이 들어간다), 붓 하나가 네 파셀에 걸칠 수
 * 있으므로 그보다 크게 두면 **언제나 상한에 잘리는** 개수가 된다. 잘리는 것 자체는
 * 화면이 말하지만(아래 `asked`/`placed`), 슬라이더가 도달할 수 없는 값을 보여 주는 것은
 * 거짓 UI 다.
 *
 * ⚠ **이 값은 파츠 상한을 미러링하지 않는다** — 「가장 큰 값 근처」라는 근거만 여기 있고
 * 실제 상한은 `parts/index.ts` 가 소유하며 집행부가 그것으로 자른다. 파츠가 상한을
 * 바꾸면 이 슬라이더가 조금 헐거워질 뿐 **틀린 배치가 나지는 않는다.**
 */
export const N_MIN = 1;
export const N_MAX = 24;

/**
 * 크기 변주 폭. ±15% 면 «같은 종인데 개체가 다르다» 로 읽히고, 그 이상은 종이 달라 보인다.
 *
 * ⚠ **`export` 인 것은 간격 때문이다**(검수관 권고 P4, 2026-08-22). 집행부가 최소 간격을
 * 파츠 반경에서 만드는데, 그 반경은 `s=1` 기준이고 붓은 여기 적힌 만큼 키운다 — 반영하지
 * 않으면 큰 쪽 둘이 만났을 때 이만큼 파고든다. 값을 저쪽에 다시 적지 않으려고 연다.
 */
export const S_JITTER = 0.15;

export interface BrushOpts {
  /** 붓 중심(월드) */
  readonly cx: number;
  readonly cz: number;
  readonly radius: number;
  readonly count: number;
  readonly seed: number;
  /**
   * 점 사이 최소 간격(m). 0 이면 안 본다.
   *
   * 집행부가 파츠 반경에서 준다 — 나무끼리는 넓게, 화분끼리는 좁게.
   */
  readonly minGap: number;
}

/**
 * 붓 반경 안에 `count` 개를 흩뿌린다. **간격에 걸린 것은 버린다** — 그래서 결과가
 * `count` 보다 적을 수 있고, 그 사실을 부르는 쪽이 화면에 말해야 한다.
 *
 * ── 분포: `sqrt(u)` 인 것이 요점이다 ───────────────────────────────────────
 * `r = R·u` 로 뽑으면 **가운데가 빽빽해진다** — 반지름 `r` 인 고리의 넓이가 `r` 에
 * 비례하므로, `r` 을 균등하게 뽑으면 안쪽 고리에 같은 수가 몰린다. `r = R·√u` 가
 * 원판 위 균등이다. 이것을 틀리면 붓 자국이 도넛이 아니라 **점 하나에 뭉친다.**
 *
 * ── 왜 「재시도」가 아니라 「버리기」인가 ────────────────────────────────────
 * 간격에 걸릴 때마다 다시 뽑으면 좁은 반경에서 **루프가 길어진다**(빈자리가 없으면
 * 영원히 못 찾는다). 상한을 걸어 재시도하는 방법도 있지만, 그러면 「몇 번 시도했나」가
 * 결과에 섞여 같은 시드로도 재현이 흔들린다. 버리면 결과가 시드의 함수로 남고,
 * 감독에게는 **「붓을 한 번 더 문지르면 된다」** 는 자연스러운 조작이 답이다.
 */
export function brushDots(opts: BrushOpts): BrushDot[] {
  const rnd = rngFrom(opts.seed);
  const radius = Math.max(0, opts.radius);
  const gap2 = Math.max(0, opts.minGap) ** 2;
  const out: BrushDot[] = [];
  for (let i = 0; i < Math.max(0, Math.floor(opts.count)); i += 1) {
    // ⚠ **난수 넷을 `continue` 보다 앞에서, 루프마다 같은 개수로 뽑는다.**
    //
    // 🔴 이 자리에 처음 *"안 그러면 개수를 하나 올리는 것만으로 이미 찍힌 것들이 통째로
    // 자리를 옮긴다"* 라고 적었고 **거짓이었다**(뮤테이션 실측 2026-08-22: 회전·크기를
    // `push` 시점으로 옮겨 봐도 검사가 하나도 안 깨졌다). 위치(`u`·`v`)는 어차피 걸러
    // 내기 **전에** 뽑히므로 그 진술은 성립하지 않는다.
    //
    // **실제로 지키는 것은 이것이다** — 간격(`minGap`)을 바꿔도 **살아남은 점들의 회전과
    // 크기가 그대로**다. 걸러진 점도 자기 몫의 난수를 소비하므로 i번째 점의 회전·크기가
    // 「몇 개가 걸러졌나」와 무관해진다. 감독이 간격을 조금 조였을 때 이미 마음에 든
    // 숲의 방향이 통째로 바뀌면, 그것은 조절이 아니라 다시 뽑기다.
    // 게이트 유효성에 대한 거짓 진술은 다음 사람이 확인을 생략하게 만든다 — 문장을
    // 고치는 데서 멈추지 않고 그 성질을 보는 축을 만들었다(`tests/world2-brush.test.ts`).
    const u = rnd();
    const v = rnd();
    const rRy = rnd();
    const rS = rnd();
    const r = radius * Math.sqrt(u);
    const th = v * Math.PI * 2;
    const x = opts.cx + Math.cos(th) * r;
    const z = opts.cz + Math.sin(th) * r;
    if (gap2 > 0 && out.some((d) => (d.x - x) ** 2 + (d.z - z) ** 2 < gap2)) continue;
    out.push({
      x,
      z,
      ry: rRy * Math.PI * 2,
      // `1 - J` … `1 + J` 균등. 곱셈 변주라 큰 파츠와 작은 파츠가 같은 비율로 흔들린다.
      s: 1 + (rS * 2 - 1) * S_JITTER,
    });
  }
  return out;
}

/** 슬라이더가 낸 값을 범위 안으로. **범위 밖은 자른다** — 여기는 UI 값이라 거절이 없다 */
export function clampRadius(v: number): number {
  return Number.isFinite(v) ? Math.min(R_MAX, Math.max(R_MIN, v)) : R_MIN;
}

export function clampCount(v: number): number {
  return Number.isFinite(v) ? Math.min(N_MAX, Math.max(N_MIN, Math.round(v))) : N_MIN;
}

/**
 * 붓질 하나의 **시드**. 같은 자리를 두 번 문지르면 다른 결과가 나와야 한다.
 *
 * ⚠ 좌표만으로 만들면 **같은 자리를 아무리 문질러도 같은 점이 나온다** — 간격 검사에
 * 전부 걸려 두 번째 붓질부터 아무것도 안 놓인다. 그래서 붓질 **횟수**를 함께 섞는다.
 * (시간을 쓰지 않는 것은 이 저장소의 규율이다 — 검사가 재현할 수 없게 된다.)
 */
export function strokeSeed(x: number, z: number, nth: number): number {
  // 좌표를 cm 단위 정수로 접어 넣는다. 실수 그대로면 비트 연산에서 하위가 날아간다.
  const a = Math.round(x * 100) | 0;
  const b = Math.round(z * 100) | 0;
  let h = 0x811c9dc5;
  h = Math.imul(h ^ a, 0x01000193);
  h = Math.imul(h ^ b, 0x01000193);
  h = Math.imul(h ^ (nth | 0), 0x01000193);
  return (h ^ (h >>> 16)) >>> 0;
}

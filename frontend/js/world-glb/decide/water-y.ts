// world-glb/decide/water-y.ts — **`?watery=` 수면 높이 오프셋.** 순수 상수·함수만.
//
// ── 왜 생겼나 (감독 신고 2026-09-17 → 감독 판정) ───────────────────────────
// 감독이 아이폰에서 월드11 을 열고 «유실» 을 신고했고, 받은 스크린샷의 실제 화면은
// **바닥 전체가 수면**이었다 — 횡단보도 흰 줄과 간판 글자가 그 위에 거꾸로 비쳤다.
// 첫 처방은 「물을 끈다」였는데 감독이 ***"노노. 우리 강이 더 멋있지나"*** 로 뒤집었다.
// **그래서 끄는 것이 아니라 높이를 맞춘다.**
//
// ── 실측 (여기 «값» 을 적지 않는다 — 전부 유도값이고 출처가 둘이다) ────────
//   우리 물   `decide/water.ts` 의 `RIVER_Y = −(WAVE_PEAK_MAX + WAVE_CLEARANCE)` ·
//             `SEA_Y = RIVER_Y − RIVER_ABOVE_SEA` — **world2 섬**을 두고 정한 값이다
//   자산      맨해튼 GLB: 아스팔트 윗면 ≈ +0.02 · 자산 자체의 강 윗면 ≈ −0.61 ·
//             bbox min y = −2.0 (측정 주체는 팀장, 2026-09-17)
//
// ⚠ **산술로는 우리 수면이 이미 도로보다 낮다**(강 −0.90 · 바다 패치 상한
// `SEA_Y + PATCH_SEP + amp`). 그런데 감독 화면에서는 도로가 잠겼다. **둘 중 하나가
// 틀렸고 나는 어느 쪽인지 못 쟀다** — 이 환경에는 WebGPU 가 없고(swiftshader=WebGL)
// 게임풍 수면은 **WebGPU 에서만** 그려진다(`features/water-style.ts` 의 폴백 경고).
// 그러므로 이 파일은 **원인을 단정하지 않는다.** 화면으로만 판정되는 축이니 감독이
// 링크로 고른다 — 이 저장소의 결정 사이클 그대로다(*"설명하지 말고 만들어서 배포한다"*).
//
// ── 무엇을 움직이는가 / 무엇을 안 움직이는가 (한계를 먼저 적는다) ──────────
// **움직이는 것**: `features/ocean.ts` 가 씬에 넣는 물 메시 전부(바다·강·두 물결 층·
// 해저). 게임풍 수면(`water-style`)은 그 메시들의 자세를 따라가므로 함께 따라온다.
//
// 🔴 **안 움직이는 것 — `decide/water.ts` 의 판정**(`waterSurfaceY`·`isWater`). 그 함수는
// 수영·부력·물가 판정의 SSOT 이고 **URL 을 모른다**(그래야 순수하다). 그래서 오프셋을
// 크게 주면 **화면의 물과 「물에 빠졌다」 판정이 어긋난다** — 눈에는 마른 땅인데 헤엄을
// 치거나 그 반대가 된다.
//
// 이것은 결함이 아니라 **이 노브의 정의**다: **비교용**이지 배포값이 아니다. 감독이 값을
// 고르면 그 값을 `decide/water.ts` 의 `RIVER_Y` **유도식 자체**로 옮기고(그러면 판정도
// 함께 따라온다) 이 노브는 0 으로 돌아간다. 그 시점을 안 적으면 노브가 장식으로 남는다
// — 이 저장소가 `?shlen` 에서 이미 겪은 형태다.
//
// ⚠⚠ **`SEA_Y`·`RIVER_Y` 를 여기 다시 적지 않는다.** 이 파일이 아는 것은 «얼마나
// 옮기는가» 뿐이고 «어디가 기준인가» 는 `decide/water.ts` 한 곳이다. 그 분업이 곧
// `features/water-style.ts` 가 이미 못 박아 둔 규율이다(*"값을 여기 적는 것이 아니라
// `SEA_Y` 를 `decide/water.ts` 에서 직접 받는다"*).

import { STYLED_WATER_NAMES, LAYER2_NAMES } from './water-style.js';

/**
 * 옮길 물 메시의 씬 이름. **두 목록을 import 해 합성한다 — 다시 적지 않는다.**
 * 그 둘은 `decide/water-style.ts` 가 소유하고(게임풍 수면이 덮을 대상), 이 파일은
 * 거기에 **해저**만 더한다 — 수면만 내리고 바닥을 두면 물이 얕아지는 것이 아니라
 * **바닥이 수면 위로 올라온다.**
 *
 * ⚠ `'seabed'` 는 `features/ocean.ts` 가 `bed.name` 에 직접 적는 문자열이고 상수가 없다.
 * 여기가 그 이름을 두 번째로 적는 자리라 **미러링이 하나 생겼다** —
 * `tests/world-glb-water-knob.test.ts` 가 두 파일을 읽어 대조해 그것을 막는다
 * (「해저 이름이 `ocean.ts` 와 같다」). 상수로 올리는 것은 그 파일이 `check:filesize`
 * 동결이라 이번 회차에 못 했다(줄이 는다). 동결이 풀리는 회차에 올린다.
 */
export const WATER_MESH_NAMES: readonly string[] = [
  ...STYLED_WATER_NAMES, ...LAYER2_NAMES, 'seabed',
];

/** 기본 오프셋. **0 = 현재 동작** — world7·world8 은 노브를 안 밀면 한 글자도 안 바뀐다 */
export const WATER_Y_OFFSET_DEFAULT = 0;

/**
 * 하한(m). 자산 bbox 의 바닥(−2.0)보다 더 내려도 의미가 있어야 한다 — 물을 «보이지 않는
 * 데까지» 내려 보는 것이 「물이 원인인가」를 가르는 대조군이기 때문이다. 그래서 자산
 * 높이 규모(≈2m)의 몇 배를 잡는다.
 */
export const WATER_Y_OFFSET_MIN = -8;
/**
 * 상한(m). **올리는 쪽도 연다** — 「물이 도로를 덮는다」가 맞는지 확인하려면 **일부러
 * 덮어 보는 것**이 가장 값싼 검증이다. 감독 화면과 같은 증상이 재현되면 원인이 확정된다.
 */
export const WATER_Y_OFFSET_MAX = 3;

/**
 * `?watery=` 값을 범위 안으로 접는다. **클램프는 노브를 안전하게 만든다** —
 * `?watery=999` 가 그대로 들어가면 물이 하늘로 올라가고, 그 상태를 「고장」으로 오해한다.
 */
export function waterYOffset(v: number): number {
  if (!Number.isFinite(v)) return WATER_Y_OFFSET_DEFAULT;
  return Math.max(WATER_Y_OFFSET_MIN, Math.min(WATER_Y_OFFSET_MAX, v));
}

// ════════════════════════════════════════════════════════════════════════════
// 「`?srcwater=` — 자산 안의 물을 숨긴다」
// ════════════════════════════════════════════════════════════════════════════
//
// 맨해튼 자산에는 **자기 강이 이미 들어 있다** — 노드 `Expanded_East_River_water`
// 하나(단위 큐브 × scale `[116, 0.08, 61]`, translation `[0, −0.65, −59.5]` → 월드
// `x ∈ [−58, 58] · y ∈ [−0.69, −0.61] · z ∈ [−90, −29]`). 우리 물이 같은 자리를
// 채우면 **두 겹**이 되고, 두 면이 0.3m 안에서 겹치면 어느 쪽이 이길지 픽셀마다 갈린다
// (이 저장소가 접촉그림자 데칼에서 이미 겪은 형태 — `systems/glb-source.ts` 의 「AO
// 데칼을 지면에서 띄운다」 절).
//
// ── 🔴 왜 «이름» 이 아니라 «재질» 로 찾는가 ────────────────────────────────
// `Expanded_East_River_water` 는 **맨해튼 고유 이름**이다. 그것을 `world-glb` 트리에
// 박으면 트리가 특정 자산을 알게 되고, 그 순간 world7(사용자가 고른 임의 GLB)·world8
// (world2 산 GLB)과의 계약이 깨진다 — `options.ts` 의 경계 조항이 금지하는 형태다.
//
// 재질 이름 `water` 는 **일반 어휘**다. 그리고 이 트리에는 이미 같은 형태의 선례가
// 있다 — `glb-instance.js` 의 `isShadowMaterial` 이 `shadow:` 접두로 판정한다. 우리
// 자산군의 재질 이름 규약을 쓰는 것이지 특정 파일을 아는 것이 아니다.
//
// ⚠ **오탐 가능성을 안고 쓴다**: 임의 GLB 에 `water` 라는 재질이 있으면 그것도 숨는다.
// 그래서 **기본값은 「안 숨김」**(현재 동작)이고, 켜는 것은 노브다 — world7·world8 은
// 노브를 안 밀면 한 글자도 안 바뀐다.

/** 자산 물 재질의 이름 규약. 대소문자를 안 가리고 **단어로** 본다(`underwater` 오탐 방지) */
const ASSET_WATER_NAME = /(^|[^a-z])water([^a-z]|$)/i;

/**
 * 이 재질이 **자산이 스스로 들고 온 물**인가.
 *
 * @param name 재질 이름(없으면 `undefined`)
 */
export function isAssetWaterMaterial(name: string | undefined | null): boolean {
  return typeof name === 'string' && ASSET_WATER_NAME.test(name);
}

// world-glb/decide/backend-knob.ts — **`?webgl=1` — 렌더 백엔드를 URL 로 강제한다.**
// 순수 함수·상수만. three 무의존, DOM 무의존.
//
// ── 왜 생겼나 (감독 신고 2026-09-17, 진단 우선순위 1) ──────────────────────
// 감독이 **핸드폰**에서 라이브 월드11 을 열어 «유실» 을 신고했다 — *"바닥도 안보였어.
// 바닥에 물가로 보였어."* · *"벽이나 없어진게 많았어."* · ***"도로 풀도 안보였어."***
// **로딩이 끝난 뒤**의 화면이다.
//
// 그런데 같은 자산을 헤드리스에서 열면 **건물·도로·횡단보도·간판·다리가 전부 렌더된다.**
// 두 화면이 다르고, 두 화면의 **백엔드가 다르다**:
//
//   헤드리스(내가 보는 것)  swiftshader **WebGL**  ← 콘솔에 「WebGPU 컨텍스트 생성 실패」
//   감독 핸드폰             **WebGPU**
//
// CLAUDE.md 가 *"헤드리스는 WebGL(swiftshader)이고 감독 실기기는 WebGPU다. 두 백엔드는
// **렌더 경로가 다르다** … **이 사각은 아직 열려 있다** — 헤드리스로 WebGPU를 검증할
// 방법이 없으므로 감독 실기기 확인이 유일한 판정이다"* 라고 못 박은 자리가 정확히 여기다.
//
// ── 이 노브가 사는 이유: **한 번의 탭으로 축이 갈린다** ────────────────────
// `adapters/renderer.ts` 는 이미 `forceWebGL` 을 인자로 받는데 **URL 로 그 문을 여는
// 곳이 없었다**(실측: 트리 전체 grep 0건). 그래서 감독은 자기 기기에서 WebGL 경로를
// 볼 방법이 없었고, 우리는 「WebGPU 경로 문제」와 「기기 메모리 문제」를 가를 수단이
// 없었다. 노브가 생기면 감독이 폰에서 한 번 탭해 답이 나온다:
//
//   `?webgl=1` 로 **보이면**       → WebGPU 렌더 경로 문제로 **확정**
//   `?webgl=1` 로도 **안 보이면**  → 백엔드와 무관 — 메모리·스케일·컬링 쪽
//
// 지금 이 저장소가 살 수 있는 **가장 값싼 정보**다. 그래서 다른 축(조명·가시거리)보다
// 먼저 나간다.
//
// ── 🔴 경계 — 자동 판정을 **바꾸지 않는다** ────────────────────────────────
// 노브가 없을 때(`null`)의 동작은 지금 그대로여야 한다. 이 함수가 `false` 를 내면
// `createRendererAdapter` 의 기존 분기가 한 글자도 안 바뀐 채 돈다 — world7·world8 의
// 불변이 그 성질로 보장된다(「기본값이 같다」가 아니라 **「경로가 없다」**).
//
// ── 왜 `readNum` 이 아니라 원문 판정인가 ───────────────────────────────────
// `?webgl` (값 없음) 도 켜진 것으로 읽어야 한다 — 감독이 주소창에서 손으로 지울 때
// `=1` 이 먼저 지워진다. `readNum` 은 빈 값을 `Number('')` = 0 으로 읽어 **꺼진 것**이
// 되고, 그 오독은 화면으로 구별되지 않는다(`url-knob.ts` 의 `readNumOpt` 가 같은 사고를
// 적어 두었다). 그래서 **원문**(`readRawOpt`)을 받아 여기서 판정한다 — 유효값이 무엇인가는
// 판정 계층이 통째로 갖는다(`url-knob.ts` 의 `readRawOpt` 독블록).

/** 「꺼짐」으로 읽는 원문. 그 밖의 값(빈 문자열 포함)은 전부 켜짐이다 */
const OFF = new Set(['0', 'false', 'no', 'off']);

/**
 * `?webgl=` 원문에서 「WebGL 을 강제하는가」를 판정한다.
 *
 * @param raw `readRawOpt('webgl')` 의 반환값. **`null` 은 「지정 안 됨」**이고 그때만 `false` 다
 *
 * ⚠ `null` 과 `'0'` 이 둘 다 `false` 를 내지만 **뜻이 다르다** — 전자는 「자동 판정에
 * 맡긴다」, 후자는 「명시적으로 WebGPU 를 쓰겠다」다. 지금은 결과가 같아서 갈라 두지
 * 않았다. **WebGPU 를 강제하는 축이 생기는 날 여기서 갈린다** — 그때 이 주석을 보라.
 */
export function forceWebGLFrom(raw: string | null): boolean {
  if (raw === null) return false;
  return !OFF.has(raw.trim().toLowerCase());
}

// decide/glb-normal.ts — GLB 재질의 노말맵 **강도 노브** 판정. 순수 함수, three 무의존.
//
// 감독 지시 2026-09-06 *"전체적으로 노말맵을 넣어줘"* → 팀장 조건 6: 재배포 없이 on/off 와 강도 3후보를
// 링크로 비교한다. 산출 GLB(`scripts/asset/nyc/textures.mjs`)에 구운 `normalTexture.scale` 위에 이 배율을
// 곱한다 — 0 이면 노말맵을 뗀다(대조군), 1 이면 산출 그대로.
//
//   ?nrm=0    노말맵 없음(텍스처 알베도는 유지)      ?nrm=0.6  **기본**(감독 판정, 아래)
//   ?nrm=1    산출 그대로                             ?nrm=1.5  강하게
//
// 판정 결과와 감독 실측은 `NORMAL_KNOB_DEFAULT` 주석 옆에 이어 적는다(팀장 조건 6).

/**
 * 기본 배율 — **0.6**.
 *
 * ── 판정 (감독 카드, 2026-09-06) ─────────────────────────────────────────────
 * 카드 답: **«더 약하게(0.6)»**. 비교한 것은 링크 5개다 —
 *
 * | 링크 | `?nrm=` | 무엇을 보여줬나 |
 * |------|---------|-----------------|
 * | 1 | (없음) = 1.0 | 산출 그대로 — 그때까지의 기본값 |
 * | 2 | `0`   | 노말맵을 뗀 대조군(알베도만) |
 * | 3 | `0.6` | 약하게 — **채택** |
 * | 4 | `1.5` | 강하게 |
 * | 5 | (외관 근접 시점) | 같은 값을 벽 가까이서 |
 *
 * **갈린 축은 「요철의 과함」 하나다.** 0(뗀 것)이 아니라 0.6 이 뽑혔다는 것은 감독이 요철
 * 자체를 원한다는 뜻이고, 1.0·1.5 가 밀린 것은 그 요철이 벽돌·스투코에서 **과하게** 도드라진다는
 * 뜻이다. 즉 판정은 「끌 것인가」가 아니라 「얼마나 얕게 할 것인가」였다.
 *
 * ⚠ **0 은 여전히 유효한 노브 값이다** — 기본을 0.6 으로 굽는 것과 «뗄 수 있어야 한다» 는
 * 별개다. 대조군을 지우면 다음에 요철을 의심할 때 비교할 것이 없어진다.
 *
 * **왜 상수를 바꾸는가(노브 기본값을 안 두고)**: 노브는 기본값을 무엇으로 정할지 찾는
 * 수단이고 «값이 확정되면 기본값으로 옮긴다»(`url-knob.ts` 머리말). 확정됐으므로 옮긴다.
 *
 * **경계**: 다음에 이 값을 만지는 계기는 감독이 **화면을 보고** 요철을 다시 발화하는
 * 회차다. 헤드리스 수치(입면 픽셀 분산 등)로 되돌리지 마라 — 이 축은 3m 거리에서 요철
 * 변화가 0 으로 측정된 적이 있고(디자이너 2026-09-06 «V3 좌우 입면 완전 균일»), 그
 * 측정값과 감독이 실기기에서 본 화면은 서로 다른 것을 말하고 있었다.
 */
export const NORMAL_KNOB_DEFAULT = 0.6;
export const NORMAL_KNOB_MAX = 3;

export interface NormalKnob {
  /** `normalScale` 에 곱할 배율 */
  scale: number;
  /** 노말맵을 뗀다(`?nrm=0`) */
  strip: boolean;
}

export function normalKnob(raw: number | null | undefined): NormalKnob {
  const k = raw == null || !Number.isFinite(raw) ? NORMAL_KNOB_DEFAULT : Math.max(0, Math.min(NORMAL_KNOB_MAX, raw));
  return { scale: k, strip: k === 0 };
}

/**
 * 🔴 **사람이 플레이어에게서 얼마나 떨어져 서는가** — 스폰 밴드의 **거리 배율**.
 *
 * 감독 신고 2026-09-19 *"치비 하나만 보여꼬"* 의 처방 후보 ⓒ 다(팀장 판정 A (나) —
 * ⓐ 와 **한 회차**에 나간다). 실측이 말한 것은 이것이다: 모바일 세로에서 치비가
 * **36방향 중 32방향에서 0체**이고 6체 중 5체가 벽에 가린다. 막는 것은 화각이 아니라
 * **거리와 벽**이다 — 가로·데스크로 화각을 넓혀도 34~36/36 로 거의 안 바뀐다.
 *
 * ── 왜 배율이고 왜 여기 있는가 ─────────────────────────────────────────────
 * 밴드 상수(`SPAWN_RING`·`SPAWN_REACH`)는 `FOG_NEAR_CELLS` 에서 유도된다 — 「안개 시작
 * 안쪽」이 근거다. 그 유도를 건드리면 안개와의 관계가 끊어지므로 **유도는 그대로 두고
 * 배율만 곱한다.** 근거가 갈라지지 않고, 되돌리기가 값 하나다.
 *
 * ── ⚠ 파셀 세계(world2·7·8·10)는 **산술적으로 불변**이다 ────────────────────
 * 배율은 **파셀 셀 단위**에 곱하고, 그 결과를 `npc-grid.ts` 의 `bandCells` 가 공급자 칸
 * 으로 환산한다: `max(1, round(parcelCells × cellX / src.cell))`. 파셀 공급자에서는
 * `src.cell === cellX` 이므로 배율 0.25~1 이 전부 `max(1, round(0.25~1))` = **1** 로
 * 접힌다. 곧 파셀 세계에서는 **어떤 후보를 골라도 지금과 같은 링**이다.
 * 구운 격자(0.34m)에서만 32m → 8~32m 로 갈린다. 이 불변은 `tests/world-glb-spawn-band
 * .test.ts` 가 `pickNearbyIn` 을 **실제로 불러** 지킨다(아래 B1 참조).
 *
 * ── ⚠⚠ B1 의 자리다 — 여기서 **라이브 회귀**가 한 번 났다 (2026-08-02) ──────
 * 요지 셋(팀장 재상신 조건으로 읽었다):
 * ① `SPAWN_REACH = FOG_NEAR_CELLS`(비정수) · `SPAWN_RING = REACH / 2` 로 썼는데 소비자
 *    `pickNearby` 의 계약이 **정수 셀 인덱스**라 후보 12개 중 정수 좌표가 **0개**가 됐다.
 * ② 그 비정수가 `floorMod(px, 2) !== 0` 을 **항상 참**으로 만들어 `roadDirs` 가 늘
 *    4방향을 반환했고, NPC 가 도로 위상을 무시하고 건물 안쪽을 가로질렀다.
 * ③ **테스트는 전부 통과했다** — 검사가 소스 문자열만 봤기 때문이다("`FOG_NEAR_CELLS`
 *    를 포함하는가"는 봤고 "그 값이 소비자 계약을 만족하는가"는 안 봤다).
 *
 * 그래서 이 파일은 **배율만** 내고 정수화는 하지 않는다 — 정수 계약을 지키는 자리는
 * `bandCells` 한 곳이고, 거기 `Math.round` + `Math.max(1, …)` 가 이미 있다. 배율을
 * 여기서 정수로 만들면 같은 계약이 두 곳에 생긴다(값 미러링).
 */
import { readNumOpt } from '../url-knob.js';

/**
 * `?spawnband=` 후보. **기본값에서 내려가는 쪽으로만** 낸다 — 늘리면 안개 시작을 넘어
 * 「보이지도 않으면서 비용만 내는」 체가 생기고, 그것은 밴드 유도가 막으려던 것이다.
 *
 * 값이 배수/약수가 아니라 0.25 간격인 이유: 구운 격자에서 실거리가 32m → 24·16·8m 로
 * 갈리고 그 간격이 **건물 한 채(맨해튼 블록 180m)보다 훨씬 작다.** 더 촘촘하게 내면
 * 후보끼리 화면에서 구별이 안 된다 — `?walkcell=` 이 정확히 그 함정에 빠졌다
 * (네 후보의 스폰 좌표가 최대 0.77m 차이였다, 실측 2026-09-22).
 */
export const SPAWN_BAND_CANDIDATES = [1, 0.75, 0.5, 0.25] as const;

/**
 * 🔴 **기본 배율 — 0.5** (실측 2026-09-22, 팀장 조건 B-1).
 *
 * 조건: 기본값은 **두 축 모두 스폰 수정 전 이상**이어야 한다 — 절두체 「≤1체 방향」이
 * 36/36 을 유지하고, 걷기격자 차폐 후 「0체 방향」이 28/36 이하일 것.
 *
 * 맨해튼 · 모바일 세로 390×844 · yaw 36방향 × 시드 8회 · `?walkcell=` 네 후보 전량
 * (`npm run measure:walk-candidates -- --repeat=8`). ⚠ 「≤1체」 결론은 **세로 한정**이다
 * (팀장 조건 C-2) — 가로·데스크는 차폐가 만든 결과라 일반화하지 않는다.
 *
 * | 배율 | 실거리(칸×1) | 0체 방향 | ≤1체 방향 | 가려진 체 | 판정 |
 * |---|---|---|---|---|---|
 * | 1 (수정 후 현행) | 32m | 32/36 | 36/36 | 5/6 | 기준선 |
 * | 0.75 | 24m | 24/36 | 36/36 | 3/6 | 칸×0.5 에서 ≤1체가 **33/36** 으로 떨어진다 |
 * | **0.5** | **16m** | **24/36** | **36/36** | **3/6** | ✅ 네 칸 후보 전부에서 두 축 유지 |
 * | 0.25 | 8m | 26/36 | **27~34/36** | 0~3/6 | ≤1체 조건 미달 |
 *
 * 0.5 를 고른 이유는 세로 수치가 0.75 보다 나아서가 아니다 — **칸×1 에서는 둘이 같다.**
 * 갈린 것은 `?walkcell=` 을 함께 흔들었을 때다: 0.75 는 칸×0.5 에서 ≤1체가 무너지고,
 * 0.5 는 네 칸 전부에서 36/36 을 지킨다. **노브 하나가 다른 노브의 후보 전반에서
 * 성립해야 기본값이다** — 한 조합에서만 좋은 값은 그 조합을 벗어나면 회귀가 된다.
 *
 * ⚠ **기록해 둘 초과 한 건**: 0.5 · 칸×2 에서 0체 방향이 **29/36** 으로 조건(≤28)을
 * 하나 넘는다. 기본 칸이 ×1(유도 상한)이라 판정 행은 24/36 이지만, 넘는다는 사실을
 * 지우지 않는다.
 *
 * ⚠⚠ **이 표를 지키는 게이트가 없다.** 수치는 하네스(`npm run measure:walk-candidates`)
 * 가 재고 그것은 CI 에서 안 돈다(맨해튼 자산 45MB). 값을 만지는 사람이 하네스를 다시
 * 돌려야 하고, 안 돌리면 표가 조용히 낡는다 — 그 한계를 안고 쓴다.
 *
 * ⚠⚠⚠ **이것이 감독 신고의 처방이라고 단정하지 않는다.** 수치가 나아지는 것과 화면이
 * 나아지는 것은 다른 일이다(이 저장소가 같은 회차에 두 번 확인했다). 네 후보를 노브로
 * 열어 두는 이유가 그것이고, **판정은 감독 화면이다.**
 */
export const SPAWN_BAND_DEFAULT = 0.5;

/**
 * `?spawnband=` 원문을 배율로 바꾼다. 지정이 없거나 후보 밖이면 **기본값**이다.
 *
 * ⚠ 후보 밖을 클램프하지 않고 **기본값으로 접는다**. 클램프하면 `?spawnband=0.4` 가
 * 0.25 로 조용히 바뀌어 감독이 「0.4 를 봤다」고 믿게 된다 — `walkCellFromKnob` 이 같은
 * 이유로 같은 형태다.
 */
export function spawnBandFromKnob(raw: number | null): number {
  if (raw === null) return SPAWN_BAND_DEFAULT;
  const hit = SPAWN_BAND_CANDIDATES.find((c) => Math.abs(c - raw) < 1e-9);
  return hit ?? SPAWN_BAND_DEFAULT;
}

/** 지금 주소의 `?spawnband=`. 범위는 후보의 최소~최대다 */
export function readSpawnBand(): number {
  return spawnBandFromKnob(readNumOpt('spawnband', 0.25, 1));
}

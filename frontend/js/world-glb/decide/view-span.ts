// world-glb/decide/view-span.ts — **가시 거리를 「셀」이 아니라 「자산」에서 유도한다.**
// 순수 함수·상수만. three 무의존, URL 무의존.
//
// ── 왜 생겼나 (감독 신고 2026-09-17) ────────────────────────────────────────
// 감독이 라이브 월드11 에서 *"보니깐 유실이 많이 되서 그랬어."* · *"바닥도 안보였어.
// 바닥에 물가로 보였어."* · *"바닥뿐 아니라... 벽이나 없어진게 많았어."* 라고 신고했다.
// **시작 지점은 멀쩡하다**(헤드리스 캡처로 확인 — 건물·도로·횡단보도·간판·다리가 전부
// 렌더된다). 그러므로 그것은 **이동한 뒤의 화면**이다.
//
// ── 원인: 컬링 거리가 「섬 스케일」이다 ─────────────────────────────────────
// `systems/glb-stream.ts` 는 **안개 far 너머의 격자 셀을 끈다.** 그 안개 far 는
// `decide/fog.ts` 의 `fogBand(cell)` 이 내고, 인자는 world2 **파셀 한 변**이다. 즉 이
// 세계의 가시 거리는 *"world2 섬의 파셀이 몇 개 보이는가"* 에서 나온 값이고 **월드11
// 자산의 크기를 한 번도 안 봤다.**
//
//   셀 유도 far   = cellX × FOG_FAR_CELLS            ← world2 섬 전제
//   맨해튼 자산   = bbox 로 실측한다(아래 `spanOf`)  ← 이 세계의 사실
//
// 자산이 셀 유도 거리보다 크면 **한가운데 서는 순간 절반 이상이 꺼진다.** 감독이 본
// 「벽이 없어짐」·「바닥이 물가로 보임」이 그 화면이다(바닥 격자 셀이 꺼지면 그 자리에
// 안개색 배경이 남는다).
//
// ── 그래서 배수를 적지 않고 **유도**한다 (world10 `decide/nyc-bands.ts` 선례) ──
// 그 파일은 `NYC_BAND_SCALE = BAND_REF_CELL_M / NYC_CELL` 로 «리터럴 0.5 를 적지 않고
// 유도» 한다. 이유 둘을 그대로 따른다: ① 식이 뜻을 말한다 ② **자산이 바뀌면 저절로
// 따라온다.** 여기서 유도하는 것은 배수가 아니라 **기준 거리 자체**다 —
// `viewBand` 는 `spanM`(자산이 낸 거리)을 받아 밴드를 다시 짓고, near/far **비율**은
// 원래 밴드에서 가져온다(`FOG_NEAR_CELLS`·`FOG_FAR_CELLS` 를 여기 다시 적지 않는다 —
// 그 둘의 SSOT 는 `decide/fog.ts` 한 곳이다).
//
// ── 🔴 경계 — **`spanM` 이 없으면 아무것도 안 한다** ────────────────────────
// world7·world8 은 이 축을 안 쓴다(`options.ts` 의 `viewSpan` 을 안 넘긴다). 그러면
// `viewBand` 는 **`?far=` 값과 무관하게 원래 밴드를 그대로 돌려준다.** 노브가 두 페이지의
// 동작을 건드릴 수 없다는 것이 구조로 보장돼야 하고(팀장 조건 «world7·8 diff 0»),
// 「기본값이 같다」보다 「경로가 없다」가 강한 보장이다.
// `tests/world-glb-view-span.test.ts` 가 그 성질을 못 박는다.
//
// ── ⚠ 이 노브는 성능과 맞바꾸는 축이다 ─────────────────────────────────────
// `glb-stream.ts` 헤더가 적어 둔 사고가 그대로 되돌아온다 — 컬링을 붙인 이유가
// **삼각형 2,110,989 = 예산(`decide/adapt.ts` `TRI_BUDGET`)의 35배**였다. 거리를 넓히면
// 켜지는 셀이 늘고 그 수치도 같이 오른다. 교환비는 **면적비**다: 반경을 k 배 하면 켜지는
// 셀 수는 대략 k² 배(평면 분포). `?far=2` 면 그릴 것이 4배가 된다는 뜻이다.
// **그래서 값을 고르는 것은 감독이고**(화면으로만 판정되는 축이다), 이 파일은 고를 수
// 있게 열어 둘 뿐이다. 확정되면 그 값을 기본값으로 옮기고 판정을 여기 적는다.

/**
 * 자산의 **치수**(m). `systems/glb-source.ts` 의 `GlbSourceResult.box` 에서 집행 쪽이
 * 빼서 넘긴다 — 이 파일은 `min`/`max` 를 모른다. **원점이 어디인지는 이 판정의 축이
 * 아니기 때문**이다(감독이 보는 것은 «가장자리까지의 거리» 이지 좌표가 아니다).
 */
export interface AssetSize { x: number; z: number }

/** 밴드 — `decide/fog.ts` 의 `FogBand` 와 같은 모양이다(import 하지 않는다: 이 파일은 의존 0) */
export interface ViewBand { near: number; far: number }

/** `?far=` 기본값. **1 = 「자산이 낸 거리를 그대로」** — 배수를 안 쓴다는 뜻이다 */
export const VIEW_FAR_MUL_DEFAULT = 1;
/**
 * 하한. 0 을 허용하지 않는 이유: 0 이면 안개 far 가 0 이 되어 **세계가 통째로 사라진다.**
 * 「안개를 끄는 것」은 이미 `?fogd=0` 이 가진 어휘이고, 두 노브가 같은 일을 하면 다음
 * 사람이 어느 쪽을 봐야 할지 모른다. 0.1 은 「가장 좁게」의 자리다.
 */
export const VIEW_FAR_MUL_MIN = 0.1;
/**
 * 상한. 자산 반대각선(`spanOf`)의 8배까지 연다 — 180m 급 자산에서 1km 가 넘고 그것은
 * 카메라 far(하늘 돔 유도, ≈1,375m)에 닿는 수준이라 그 위는 의미가 없다.
 */
export const VIEW_FAR_MUL_MAX = 8;

/**
 * 자산 bbox 에서 **가시 거리의 기준(m)** 을 낸다 — 평면 대각선의 **절반**.
 *
 * ── 왜 「반대각선」인가 ─────────────────────────────────────────────────────
 * 감독이 판정하는 축은 «한가운데 서서 가장자리까지 보이는가» 다. 축 정렬 사각형의
 * 중심에서 가장 먼 점은 모서리이고 그 거리가 대각선의 절반이다. 즉 이 값은
 * **「세계의 한가운데에 섰을 때 최악의 경우에도 전부 보이는 거리」** 로 유도된다.
 * (가장자리에 서면 대각선 전체가 필요하다 — 그때는 `?far=2` 가 그 자리다. 배수의
 *  의미가 산술로 읽히는 것이 리터럴을 적지 않는 이득이다.)
 *
 * **y 는 안 본다** — 컬링도 안개도 수평 거리 판정이다(`glb-stream.ts` 는 `Math.hypot(dx,dz)`).
 */
export function spanOf(size: AssetSize): number {
  return Math.hypot(size.x, size.z) / 2;
}

/**
 * 밴드를 자산 기준으로 다시 짓는다.
 *
 * @param base   셀에서 유도한 원래 밴드(`fogBand(cellX)`)
 * @param spanM  자산이 낸 기준 거리(m). **`null` 이면 `base` 를 그대로 돌려준다**
 * @param mul    `?far=` 배수
 *
 * near/far **비율**은 `base` 에서 가져온다 — 안개가 「어디서 시작해 어디서 닫히는가」의
 * 모양은 이 회차의 축이 아니고, 그 두 배수의 SSOT 는 `decide/fog.ts` 다.
 */
export function viewBand(base: ViewBand, spanM: number | null, mul: number): ViewBand {
  // ⚠ 이 줄이 world7·world8 의 불변을 만든다. **경로가 없으면 노브도 없다.**
  if (spanM === null || !Number.isFinite(spanM) || spanM <= 0) return base;
  const far = spanM * mul;
  // `base.far` 가 0 이면(이론상 cell=0) 비율을 못 구한다 — 그때는 원래 밴드를 존중한다.
  if (!(base.far > 0)) return base;
  return { near: far * (base.near / base.far), far };
}

// world-glb/parts/plaza.ts — 광장 판정. 순수 함수만.
//
// ── 왜 광장인가 ──────────────────────────────────────────────────────────────
// 감독 지적 *"건물이 빽빽하다"* 의 셋째 원인이 **숨 쉴 곳이 없다** 였다. 채수 하한이 2라
// "아무것도 없는 구획" 이 구조적으로 존재할 수 없었고, 하한을 1로 내린 뒤에도 어느 파셀에나
// 최소 한 채는 선다.
//
// 광장은 그 예외다. 건물이 0인 파셀을 의도적으로 섞어, 걷다 보면 트인 곳이 나오게 한다.
//
// ── 길이 닿는 곳에만 둔다 ────────────────────────────────────────────────────
// 도로가 하나도 없는 파셀은 광장이 될 수 없다. 갈 수 없는 광장은 광장이 아니라 그냥
// 빈 땅이고, 오픈월드에서 그건 "아직 안 만든 곳" 으로 읽힌다.
//
// 실제 도시의 광장도 길이 모이는 자리에 있다. 이 조건 하나로 그 성질이 따라온다.
//
// ── 배치가 아니라 판정이다 ───────────────────────────────────────────────────
// 광장이라는 사실을 여러 파츠가 소비한다 — 건물은 서지 않고, 나무·벤치는 오히려 모인다.
// 그래서 파츠마다 따로 정하지 않고 여기서 한 번 정한다. 도로가 `road-topology.ts` 를,
// 물이 `decide/water.ts` 를 SSOT 로 두는 것과 같은 배치다.

import { roadDirs } from './road-topology.js';
import { isCentralPlaza, centralPlazaCell } from '../decide/grid.js';

/**
 * 광장 확률(길이 닿는 파셀 기준). 전체에서는 `0.974 × 0.02 ≈ 1.9%` — 쉰두 파셀에 하나다.
 *
 * ── 이 값의 근거는 안개다 ──────────────────────────────────────────────────
 * 디자이너가 601×601(36만 파셀) 격자에 실제 도로 해시를 돌리고, 임의 400지점에서
 * **최근접 광장까지의 실측 거리**를 쟀다:
 *
 *   확률   전체비율      최근접(중앙값)
 *   6%    5.8% (1/17)      64m
 *   2%    1.9% (1/52)     115m
 *   1%    0.95% (1/105)   160m
 *
 * 기준선은 **안개 완전가시거리 `CELL × 1.9 = 60.8m`** 다. 6% 면 평균 최근접이 66m 로 그
 * 경계와 거의 같다 — 다음 광장이 늘 시야에 걸려 있다는 뜻이고, 랜드마크가 "가끔 만나는
 * 특별한 것" 이 아니라 "다음 블록에도 있는 것" 이 된다. 도보(9m/s)로 7초마다면 리듬이
 * 아니라 소음이다.
 *
 * 2% 는 중앙값 115m 로 안개 거리의 두 배다. 평상시엔 안 보이다가 다가가야 드러나고,
 * 걸어서 13초 — "어, 저기 뭔가 있네" 하고 방향을 트는 간격이다.
 *
 * 1% 아래로 내리면 최근접이 160m 를 넘어 로드 반경(~77m)의 두 배를 훌쩍 넘는다. 그때는
 * 리듬이 아니라 우연히 마주치는 희귀 이벤트가 된다.
 */
export const PLAZA_P = 0.02;

const SALT_PLAZA = 0x3b9aca07;

/**
 * 파셀 좌표 → 균등 해시. **소비자가 둘 이상이라 export 한다**(용도 판정 `zoning.ts`).
 *
 * 난수 스트림이 아니라 좌표 해시인 것이 핵심이다 — 파셀은 서로를 모르는 채로 로드되고
 * tier 마다 다시 계산되므로, 순서에 의존하는 난수를 쓰면 같은 파셀이 매번 다른 답을
 * 낸다. 해시는 좌표만 보므로 언제 어디서 물어도 같다.
 */
export function h2(a: number, b: number, salt: number): number {
  let h = salt >>> 0;
  h = Math.imul(h ^ (a | 0), 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h ^ (b | 0), 0xc2b2ae35);
  h ^= h >>> 16;
  h = Math.imul(h, 0x27d4eb2d);
  return (h ^ (h >>> 15)) >>> 0;
}

/**
 * 이 파셀이 광장인가. 길이 하나도 없으면 아니다 — 갈 수 없는 광장은 빈 땅이다.
 *
 * **중앙 광장은 무조건 광장이다.** 감독이 위치를 지정한 곳이라 확률이 끼어들 자리가
 * 없고, 길 조건도 묻지 않는다 — 세계의 중심이자 스폰 지점이므로 길이 어떻든 광장이다.
 */
export function isPlaza(px: number, pz: number, p: number = PLAZA_P): boolean {
  if (isCentralPlaza(px, pz)) return true;
  if (roadDirs(px, pz).length === 0) return false;
  return h2(px, pz, SALT_PLAZA) / 4294967296 < p;
}

/**
 * 광장 한가운데 무엇이 서는가. 없으면 `null`.
 *
 * 감독 지시: *"중앙은 중앙광장으로 하고 분수대 시계탑."*
 *
 * ── 흩어져 있던 것을 중앙으로 모았다 ────────────────────────────────────────
 * 예전에는 분수대·시계탑이 **동네 광장마다** 확률 반반으로 섰다. 그러면 중앙 광장이
 * 특별할 이유가 없다 — 두 블록만 걸으면 또 분수대가 있는데 굳이 중앙까지 갈 까닭이
 * 없고, 그건 랜드마크가 아니라 가로수와 같은 반복 요소다.
 *
 * 이제 둘 다 **중앙 광장에만** 선다. 자리는 `decide/grid.ts` 가 칸으로 고정한다.
 * 동네 광장은 랜드마크 없이 트인 채로 남는다 — 그것이 원래 목적("숨 쉴 곳")이다.
 */
export type PlazaLandmark = 'fountain' | 'clock';

/**
 * 이 광장 칸이 **큰 것에 통째로 점유돼** 소품을 놓을 수 없는가.
 *
 * ── 왜 생겼나 ───────────────────────────────────────────────────────────────
 * 미술관 GLB 가 실험에서 기본 노출로 올라오면서 광장 서쪽 칸에 선다(`features/glb-city.ts`).
 * 그 자산은 바닥이 **17.2 × 24.6m** 라 32m 파셀을 거의 채운다 — 사분면에 뽑는 소품과
 * 같은 칸에 두면 나무가 지붕을 뚫고 벤치가 벽 안에 박힌다.
 *
 * ── 분수대·시계탑 칸은 왜 여기 없나 ────────────────────────────────────────
 * 그 둘도 광장 칸을 쓰지만 **밑동이 작아**(분수 반경 2.4m·시계탑 한 변 2m 남짓) 소품이
 * 곁에 서도 겹치지 않고, 지금 실제로 그렇게 서 있다. 넣으면 보이는 것이 바뀌는데 그것은
 * 이번 작업이 요청받은 범위가 아니다. **"큰 것" 을 크기로 판정하지 않고 칸으로 열거하는
 * 것이 이 함수의 한계다** — 셋 다 파츠가 아니라 자리 이름으로 걸려 있어서, 미술관을
 * 옮기면 여기도 함께 고쳐야 한다.
 */
export function plazaOccupied(px: number, pz: number): boolean {
  return centralPlazaCell(px, pz) === 'west';
}

export function plazaLandmark(px: number, pz: number, _p: number = PLAZA_P): PlazaLandmark | null {
  // 격자는 "가운데 칸인가 북쪽 칸인가" 만 답한다. 무엇이 서는지는 파츠의 몫이다.
  switch (centralPlazaCell(px, pz)) {
    case 'center': return 'fountain';
    case 'north': return 'clock';
    default: return null;   // 나머지 칸은 트인 바닥 — 광장은 비어 있어야 광장이다
  }
}

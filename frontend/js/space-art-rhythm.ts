// space-art-rhythm.ts — **작품을 얼마나 크게 걸 것인가.** 순수 판정만.
// -----------------------------------------------------------------------------
// 감독 판정 2026-08-24: *"큰것도 있고 작은 것도 있고 복합적으로 배치. 일괄은 없어."*
//
// ── 왜 별도 파일인가 ────────────────────────────────────────────────────────
// 「어디에 거는가」(`space-generate` 의 벽·슬롯 배치)와 「얼마나 크게 거는가」는 다른
// 판정이다. 한 파일에 있으면 크기 규칙을 고칠 때마다 배치 로직까지 함께 읽어야 하고,
// 실제로 `space-generate.ts` 가 파일 크기 상한(512줄)을 넘긴 것이 이 둘을 붙여 둔
// 탓이었다. 여기 있으면 크기 규칙만 통째로 바꿔도 배치는 그대로다.
//
// three 를 안 쓴다(순수 leaf) — 노드에서 그대로 테스트된다.
//
// ⚠ `space-generate` 의 타입을 **import 하지 않는다.** `import type` 이라 런타임 순환은
// 없지만 `check:cycles` 는 정적 그래프로 잡고, 그 판정이 맞다 — 타입 하나 때문에 두
// 파일이 서로를 가리키면 「어느 쪽이 먼저인가」가 흐려진다. 이 함수가 실제로 보는 것은
// `featured` 하나뿐이므로 **구조적 타입**으로 받는다(`space-parts.ts` 동형).

/**
 * 자동생성 전시장의 **방 기준** 액자 배율. 작품별 배율(`GEN_SCALE_RHYTHM`)이 여기에 곱해진다.
 *
 * ⚠ **1.4 였다가 1.0 으로 되돌렸다 — 감독 판정으로 축이 바뀌었다.**
 * 2026-08-24: *"큰것도 있고 작은 것도 있고 복합적으로 배치. 일괄은 없어."*
 *
 * 내가 «작품을 크게 걸고» 를 **하나의 배율** 문제로 읽은 것이 틀렸다. 방 전체를 같은
 * 비율로 키우면 크기 **관계**는 그대로라, 화면에서는 「방이 작아진 것」과 구별되지
 * 않는다. 큰 작품이 크게 보이는 것은 **옆에 작은 것이 있을 때**뿐이다.
 *
 * 그래서 방 기준은 중립(1.0)으로 두고 **작품마다** 벌린다. 「크게」는 없어지지 않았다 —
 * 리듬 평균이 1 보다 크고 featured 는 훨씬 크므로 전체도 함께 올라간다.
 */
export const GEN_ART_SCALE = 1.0;

/**
 * 작품별 크기 리듬. 인덱스로 **순환**한다.
 *
 * 무작위가 아니라 고정 배열인 이유가 둘이다. ① 같은 갤러리는 항상 같은 전시장이어야
 * 한다(무저장 원칙에서 재현성은 곧 신뢰다 — 새로고침마다 배치가 바뀌면 「내 전시」가
 * 아니다) ② 무작위는 큰 것 셋이 연달아 나오는 구간을 만든다. 갤러리 걸이의 리듬은
 * **큰 것 다음에 작은 것**이고, 그건 순열로 보장하는 편이 낫다.
 *
 * 값은 큰/작은이 번갈아 오도록 짰고 평균이 1 보다 약간 크다(≈1.09) — 감독 지시
 * «작품을 크게 걸고» 가 리듬 안에서도 유지된다.
 *
 * ⚠ 배분은 「가장 덜 찬 벽 우선」이라 인덱스가 벽마다 흩어진다. 그래서 이 배열이
 * 순환하면 **한 벽 안에서도** 큰 것과 작은 것이 섞인다 — 그것이 목적이다.
 */
export const GEN_SCALE_RHYTHM: readonly number[] = [1.45, 0.82, 1.12, 0.9, 1.3, 0.78, 1.05, 0.95];

/**
 * 대표작 배율. `featured` 가 붙은 작품은 리듬을 무시하고 이 값을 쓴다.
 * 「이 작품이 이 방의 중심이다」를 크기로 말하는 자리다.
 */
export const GEN_FEATURED_SCALE = 1.7;

/** 작품 하나의 배율. featured 면 대표작 값, 아니면 리듬을 인덱스로 순환한다. */
export function artScaleOf(art: unknown, index: number): number {
  // `unknown` 으로 받아 안에서 좁힌다 — 좁은 구조적 타입(`{featured?: boolean}`)은
  // 다른 속성을 가진 실제 작품 객체를 «공통 속성 없음» 으로 거부한다(실측 정정).
  if (art && typeof art === 'object' && (art as { featured?: unknown }).featured) return GEN_FEATURED_SCALE;
  const n = GEN_SCALE_RHYTHM.length;
  return GEN_SCALE_RHYTHM[((index % n) + n) % n];
}

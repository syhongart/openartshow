// 다리 — 강을 건너는 현수교. **파셀 하나 = 다리 한 구간이다.**
//
// ── 감독 지시 ────────────────────────────────────────────────────────────────
// 2026-08-08: *"맨해탄 다리도 있고."* / *"진짜 뉴욕처럼 하고. … 진짜 3d로 꼼꼼히 하고."*
// 카드 선택: 중앙 호수 3영역 · 끝은 바다 · 밤 · **맨해튼 다리**.
//
// ── 양식이지 특정 다리가 아니다 (IP — 팀장 직권 판정 2026-08-08) ────────────
// 감독의 *"법무팀 검토 중지"* 는 이번 회차의 **검토 프로세스 중지**이지 IP 규율의
// 폐지가 아니다. `palette.ts` 가 다리 색을 정의하면서 같은 선을 이미 적어 두었다 —
// *"현수교라는 **구조 유형**은 장르 관용구이고, 특정 다리의 고유 비례·장식·명칭은
// 쓰지 않는다."* 여기서 만드는 것은 주탑·주케이블·행어·거더라는 현수교의 **작동 원리
// 그 자체**이고, 아래 비례(주탑 26m / 상판 9m / 스팬 32m)는 전부 이 파일에서 새로
// 정한 값이다. 명칭은 어디에도 없다.
//
// ══════════════════════════════════════════════════════════════════════════
// 왜 "한 파셀 = 한 구간" 인가 — **선택이 아니라 강제였다**
// ══════════════════════════════════════════════════════════════════════════
//
// 위임 프롬프트는 *"여러 파셀을 걸치는 구조가 기존에 없다면 한 파셀 안에 들어가는
// 다리 한 구간 형태로 만들라"* 고 물었다. 조사해 보니 **없는 정도가 아니라 원리적으로
// 불가능**하다:
//
//   `decide/stream.ts` 의 `blockedByWater` 가 `parcelWater(...) === 'water'` 인 파셀을
//   **아예 만들지 않는다.** 물 파셀은 지면조차 없고, 그 구멍으로 아래 수면이 비치는
//   것이 이 세계가 강을 그리는 방식이다(`decide/water.ts` 주석).
//
// 즉 **강 위에는 파츠를 놓을 자리가 없다.** 다리를 물 파셀에 얹는 설계는 첫 줄부터
// 성립하지 않는다. 놓을 수 있는 것은 강 **양쪽 뭍**뿐이고, 강 폭이 32~64m 이므로
// 다리는 반드시 자기 파셀 밖으로 뻗어야 한다.
//
// 그래서 구조가 이렇게 정해졌다:
//
//   ① 다리를 **길이 SPAN(=셀 한 변) 짜리 구간**으로 만든다. 구간 중앙에 주탑이 서고,
//      케이블은 주탑에서 가장 높고 구간 양 끝에서 가장 낮다.
//   ② 구간을 z 축으로 나열하면 케이블이 **끝에서 기울기까지 이어져** 연속된 현수
//      곡선이 된다(양 끝이 최저점이므로 이웃 구간과 대칭으로 만난다).
//   ③ 한 파셀이 강 폭만큼 구간을 **여러 개** 낸다. 그것들은 자기 파셀을 넘어 물 위로
//      뻗는다 — 파셀 밖으로 나가는 유일한 파츠이고, 그래야 강을 건넌다.
//
// ── 왜 강 **북쪽 물가만** 다리를 소유하는가 ──────────────────────────────────
// 양쪽 물가가 각자 다리를 놓으면 같은 자리에 두 벌이 겹친다. 파셀은 서로를 모르므로
// 이런 경우 **한쪽만 소유하는 규칙**을 둔다 — `lamp.ts` 가 경계 가로등에서 `+`방향
// (east·south)만 자기 것으로 삼는 것과 정확히 같은 처방이고, 그 파일이 실제로 겪은
// 겹침에서 나온 규율이다.
//
// ── 감수한 것 ────────────────────────────────────────────────────────────────
// 다리 구간은 **자기 파셀에 실린 채 물 위로 뻗는다.** 그래서 북쪽 물가 파셀이
// 언로드되면 다리 전체가 함께 사라진다(반대편 물가에서 다가가면 마지막 순간에
// 나타난다). tier 를 far 까지 열어 그 거리를 76.8m 로 밀어 놨지만 **없앤 것은 아니다.**
// 근본 해법은 물 파셀을 "지면 없이 파츠만" 로드하는 것인데, 그것은 스트리밍 계층의
// 변경이라 파츠가 결정할 일이 아니다 — 조립부에 보고했다.


// ── 지오메트리 ──────────────────────────────────────────────────────────────
//
// **구간 하나: 중심 z=0, 길이 `SPAN`, 주탑이 정중앙.**
//
// 주탑을 구간 **중앙**에 둔 것이 이 설계의 핵심이다. 구간 끝에 두면 이어 붙였을 때
// 주탑이 파셀 경계마다 서고 케이블 최저점이 파셀 한가운데 오는데, 그러면 **구간의
// 시작과 끝이 비대칭**이라 마지막 구간에서 주탑이 하나 모자라거나 남는다. 중앙에 두면
// 어느 구간을 몇 개 이어 붙여도 항상 완결된다.

function buildSpan(T: ThreeNS): InstanceType<ThreeNS['BufferGeometry']> {
  const pieces: Piece[] = [];
  const add = (geo: Piece['geo'], color: number, u: number) => {
    pieces.push({ geo, color: rgb(color), u: texel(u) });
  };

  const half = SPAN / 2;

  // ── 상판 ────────────────────────────────────────────────────────────────
  // 노면. 위에서 보는 면이라 `bridgeDeck` 색이 그대로 보인다.
  add(new T.BoxGeometry(DECK_W, 0.45, SPAN).translate(0, DECK_Y - 0.225, 0), V.bridgeDeck, M.off);
  // 밑 거더(주형). 다리를 아래에서 보면 이것이 전부다 — 없으면 상판이 종잇장이 된다.
  add(new T.BoxGeometry(DECK_W * 0.82, 1.1, SPAN).translate(0, DECK_Y - 1.0, 0), V.bridgeSteel, M.off);
  // 난간 겸 가장자리 조명. **다리가 어디로 이어지는지를 밤에 알려 주는 선**이라
  // 이 두 줄이 발광한다.
  for (const s of [-1, 1]) {
    add(
      new T.BoxGeometry(0.22, 1.0, SPAN).translate(s * (DECK_HALF - 0.11), DECK_Y + 0.5, 0),
      V.bridgeSteel, M.deck,
    );
  }

  // ── 주탑 ────────────────────────────────────────────────────────────────
  // 기둥 둘 + 가로보 둘. 상판을 사이에 끼고 서므로 **차가 그 사이로 지나간다** —
  // 기둥을 상판 밖에 세우면 문틀이 아니라 두 개의 기둥이 되어 현수교로 안 읽힌다.
  const COL = 1.7;
  const colX = DECK_HALF - COL * 0.55;
  const colH = TOWER_TOP + PIER_DEPTH;
  for (const s of [-1, 1]) {
    add(
      new T.BoxGeometry(COL, colH, COL).translate(s * colX, TOWER_TOP - colH / 2, 0),
      V.bridgeSteel, M.off,
    );
  }
  // 가로보 둘. 상판 바로 위와 꼭대기 근처 — 아르데코 시대 다리의 관용적인 배치이고,
  // 하나만 두면 주탑이 사다리처럼 보인다.
  add(new T.BoxGeometry(DECK_W + COL, 0.9, COL * 0.8).translate(0, DECK_Y + 2.6, 0), V.bridgeSteel, M.off);
  add(new T.BoxGeometry(DECK_W + COL, 1.1, COL * 0.8).translate(0, TOWER_TOP - 2.2, 0), V.bridgeSteel, M.off);
  // 꼭대기 항공장애등. 기둥 위에 얹는 작은 갓 둘.
  for (const s of [-1, 1]) {
    add(
      new T.BoxGeometry(COL * 0.7, 0.5, COL * 0.7).translate(s * colX, TOWER_TOP + 0.25, 0),
      V.bridgeCable, M.beacon,
    );
  }

  // ── 주케이블 ────────────────────────────────────────────────────────────
  //
  // 주탑 안장(`CABLE_TOP`)에서 구간 끝(`CABLE_LOW`)까지 포물선으로 내린다.
  //
  //   y(z) = CABLE_TOP − (CABLE_TOP − CABLE_LOW) · (z / half)²
  //
  // 현수선(catenary)이 아니라 포물선인 것은 **상판을 매단 케이블의 실제 형태가
  // 포물선이기 때문**이다(자중만 받는 줄이 현수선이고, 균등 하중을 매달면 포물선이
  // 된다). 이 규모에서 두 곡선의 차이는 화면에 안 나타나지만, 식이 간단한 쪽이
  // 세그먼트 끝점을 정확히 맞추기 쉽다.
  //
  // **양 끝이 최저점**이므로 이웃 구간과 높이도 기울기도 대칭으로 만난다 — 이어 붙였을 때
  // 꺾임이 안 보이는 이유가 그것이다.
  const cableY = (z: number) => CABLE_TOP - (CABLE_TOP - CABLE_LOW) * (z / half) ** 2;
  const CABLE_TH = 0.30;
  for (const s of [-1, 1]) {              // 좌우 두 줄
    for (const dir of [-1, 1]) {          // 구간 중앙에서 양쪽으로
      for (let i = 0; i < CABLE_SEG; i++) {
        const z0 = dir * half * (i / CABLE_SEG);
        const z1 = dir * half * ((i + 1) / CABLE_SEG);
        const y0 = cableY(z0);
        const y1 = cableY(z1);
        const dz = z1 - z0;
        const dy = y1 - y0;
        const len = Math.hypot(dz, dy);
        // 세그먼트는 y 축으로 선 막대를 만들어 **x 축 둘레로 눕힌다.** `atan2(dz, dy)`
        // 가 y 축에서 z 축 쪽으로 기운 각이고, `rotateX` 의 부호가 그 방향과 반대라
        // 음수를 쓴다(오른손 좌표계에서 +x 회전은 +y 를 +z 로 보낸다).
        const angle = -Math.atan2(dz, dy);
        add(
          new T.BoxGeometry(CABLE_TH, len, CABLE_TH)
            .rotateX(angle)
            .translate(s * colX, (y0 + y1) / 2, (z0 + z1) / 2),
          V.bridgeCable, M.cable,
        );
      }
    }
  }

  // ── 행어 ────────────────────────────────────────────────────────────────
  //
  // 케이블에서 상판까지 내려오는 수직 줄. **다리가 매달려 있다는 사실이 이것으로만
  // 보인다** — 없으면 케이블이 상판과 무관하게 공중에 떠 있는 장식이 된다.
  //
  // 반쪽당 2 개뿐인 것은 예산이다(위 `CABLE_SEG` 주석 — 깎아야 하면 여기부터).
  // 실제 다리는 훨씬 촘촘하지만, 32m 구간에 두 줄이면 near(36.8m)에서 매달림이
  // 읽히고 그 이상은 far 에서 어차피 안 보인다.
  const HANG_TH = 0.14;
  for (const s of [-1, 1]) {
    for (const dir of [-1, 1]) {
      for (let i = 1; i <= HANGERS; i++) {
        const z = dir * half * (i / (HANGERS + 1));
        const yTop = cableY(z);
        const yBot = DECK_Y + 0.6;
        add(
          new T.BoxGeometry(HANG_TH, yTop - yBot, HANG_TH)
            .translate(s * colX, (yTop + yBot) / 2, z),
          V.bridgeCable, M.cable,
        );
      }
    }
  }

  return bakePieces(T, pieces);
}

/**
 * 발광 마스크 — **4×1 픽셀 컬러.** 기법은 `tower.ts`·`clocktower.ts` 와 같다
 * (검은 바탕 + `globalAlpha` 로 세기, 색은 팔레트 그대로).
 *
 * 세기가 광고 타워(0.9 대)보다 낮고 마천루 창(0.4~0.5)보다 높은 자리에 있다. 다리는
 * **광고가 아니라 시설물**이라 밝으면 안 되지만, 강 위에 홀로 서 있어서 배경이 통째로
 * 어둡다 — 건물 창과 같은 세기로는 안 보인다.
 */
function bridgeMask(T: ThreeNS) {
  const cv = document.createElement('canvas');
  cv.width = MASK_TEXELS;
  cv.height = 1;
  const g = cv.getContext('2d')!;
  // 검은 바탕 — 칠하지 않은 텍셀은 발광 0 이다(색이 아니라 강도. `color.ts` 참고)
  g.fillStyle = greyCss(MASK_BLOCK);
  g.fillRect(0, 0, MASK_TEXELS, 1);

  // **명세를 소비한다 — 값을 여기 다시 적지 않는다**(경위는 `types.ts` 의 `NeonSpec`).
  TEXELS.forEach((t, i) => {
    if (t.a <= 0) return;
    g.globalAlpha = t.a;
    g.fillStyle = hexCss(t.hex);
    g.fillRect(i, 0, 1, 1);
    g.globalAlpha = 1;
  });

  const tex = new T.CanvasTexture(cv);
  tex.magFilter = T.NearestFilter;
  tex.minFilter = T.NearestFilter;
  tex.generateMipmaps = false;
  return tex;
}

/**
 * 텍셀 명세. **인덱스가 곧 `M.*` 값**이다.
 *
 * 상대비만 고정한다 — 절대 밝기는 `emissiveIntensity` 와 톤매핑이 정하고 그 둘은
 * 헤드리스(WebGL)와 감독 기기(WebGPU)에서 다르다. 순서: **케이블 > 항공등 > 상판.**
 * 케이블이 상판보다 밝은 것이 요점이다. 현수교의 야경은 **곡선**이 만들고, 상판 조명이
 * 더 밝으면 그냥 빛나는 직선 두 줄이 된다.
 *
 * ── 케이블 색을 `V.lampGlow` 에서 `V.neonWhite` 로 바꿨다 (2026-08-09) ──────
 * 이유가 둘이다.
 * ① **가로등과 색이 같았다.** 다리 케이블 조명이 가로등 불빛과 같은 색이면, 강 건너
 *    불빛 줄이 "가로등이 물 위로 이어진 것" 으로 읽힌다. 다리가 다리로 보이려면 색이
 *    갈려야 한다.
 * ② **문턱을 넘을 수 없는 색이었다.** `lampGlow` 의 상대휘도는 0.805 라, 위계가
 *    허락하는 세기(1.15)에서 문턱을 넘으려면 알파가 0.97 이 필요했다 — 그러면 케이블이
 *    거의 순백으로 타서 전구가 아니라 형광관이 된다. 흰빛(0.961)으로 바꾸면 알파
 *    0.85 로 여유를 두고 넘는다.
 *
 * ⚠️ 순서 서술이 *"항공등 > 케이블"* 이라고 적혀 있었고 **알파와는 맞았지만 화면과는
 * 달랐다** — 항공등의 색(`aviationRed`)은 휘도가 0.437 이라 알파 1.0 에서도 실제
 * 밝기는 케이블보다 낮았다. `emissiveIntensity` 만 보면 못 보이고 색까지 넣어야
 * 보이는 어긋남이고, 이번에 그 축을 게이트로 만든 이유가 이것이다.
 */
const TEXELS: readonly NeonTexel[] = [
  { hex: V.bridgeSteel, a: 0 },      // M.off
  { hex: V.neonWhite, a: 0.85 },     // M.cable — 이 파츠에서 블룸 문턱을 넘는 부위
  { hex: V.windowWarm, a: 0.46 },    // M.deck
  { hex: V.aviationRed, a: 1.0 },    // M.beacon
];

/** 감마를 무시한 상대 명도. 대비 판정에는 이 근사로 충분하다 */
export function luma(hex: number): number {
  const r = (hex >> 16) & 0xff;
  const g = (hex >> 8) & 0xff;
  const b = hex & 0xff;
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}

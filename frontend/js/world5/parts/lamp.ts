/**
 * 등불색. 나트륨등의 따뜻한 노랑을 조금 눅인 값이다.
 *
 * 순백으로 하면 밤에 형광등처럼 차갑고, 채도를 더 올리면 주황 점으로만 보여 등의
 * 형태가 사라진다. 이 값이 **켜졌다고 읽히면서 갓 모양도 남는** 선이다.
 */
const LAMP_LIGHT = V.lampGlow;

/** 기둥 — 어두운 금속. 갓과 대비돼야 실루엣이 산다 */
const POST = rgb(V.lampPost);
/** 갓 — 유백. 자체발광과 함께 밤에 불빛으로 읽힌다 */
const HEAD = rgb(V.lampShade);

/**
 * world1 `SG.lampPost` + `SG.lampHead` 의 치수 그대로.
 *
 *   기둥  CylinderGeometry(0.06, 0.09, 3.0, 8)  → y=1.5 로 올려 밑동을 바닥에
 *   갓    SphereGeometry(0.22, 10, 8) 을 세로 0.8배로 눌러 y=3.06
 *
 * 세그먼트를 8·10 그대로 둔 것은 가로등이 파셀당 최대 4개뿐이라 삼각형 예산에
 * 여유가 있어서다. 나무처럼 128그루가 서는 것과 다르다.
 */
function buildLamp(T: ThreeNS) {
  const pieces: Piece[] = [
    // `u` 가 발광 마스크에서 읽을 텍셀을 고른다 — 기둥은 왼쪽(검정), 갓은 오른쪽(흰색).
    { geo: new T.CylinderGeometry(0.06, 0.09, 3.0, 8).translate(0, 1.5, 0), color: POST, u: MASK_U_OFF },
    { geo: new T.SphereGeometry(0.22, 10, 8).scale(1, 0.8, 1).translate(0, 3.06, 0), color: HEAD, u: MASK_U_ON },
  ];
  return bakePieces(T, pieces);
}

/** 왼쪽 텍셀의 중앙 — 발광 0 */
const MASK_U_OFF = 0.25;
/** 오른쪽 텍셀의 중앙 — 발광 1 */
const MASK_U_ON = 0.75;

/**
 * 발광 마스크 — **2×1 픽셀.** 왼쪽 검정, 오른쪽 흰색.
 *
 * 이보다 작을 수 없는 크기다. 조각을 둘로만 가르면 되므로 텍셀도 둘이면 충분하고,
 * UV 를 텍셀 중앙 한 점에 고정하므로 필터링이 경계를 흐려도 값이 섞이지 않는다.
 * 그래도 `NearestFilter` 와 밉맵 끄기를 함께 걸어 둔다 — 나중에 조각이 늘어 텍셀이
 * 촘촘해질 때를 대비한 안전장치다.
 */
function lampMask(T: ThreeNS) {
  const cv = document.createElement('canvas');
  cv.width = 2; cv.height = 1;
  const ctx = cv.getContext('2d')!;
  ctx.fillStyle = greyCss(MASK_BLOCK); ctx.fillRect(0, 0, 1, 1);
  ctx.fillStyle = greyCss(MASK_PASS); ctx.fillRect(1, 0, 1, 1);
  const tex = new T.CanvasTexture(cv);
  tex.magFilter = T.NearestFilter;
  tex.minFilter = T.NearestFilter;
  tex.generateMipmaps = false;
  return tex;
}

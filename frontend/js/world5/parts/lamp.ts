  salt: 0x94d049bb,
  // 정점색이 색을 주므로 **흰색 근처**여야 한다 — 곱셈기다.
  tones: [TINTS.plain],

  // 방향당 하나이므로 최댓값은 방향 수다. **유도한다** — 4 를 적어 두면 방향이 늘 때

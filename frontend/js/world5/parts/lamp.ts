const OWNED_EDGES = 2;

/**
 * 인도 한가운데까지의 거리(미터). 차도 끝(`ROAD_HALF`)과 건물 셋백(`SETBACK`) 사이가
 * 인도이므로 그 **중점**이다. 두 값에서 유도한다 — 실측치를 직접 적으면 도로 폭이나
 * 인도 폭을 조정할 때 가로등만 옛 자리에 남는다(값 미러링). 실제로 도로 폭을 줄인
 * 2026-07-31 에 이 주석이 적어 둔 값이 거짓이 됐고, 유도였던 상수 쪽은 멀쩡했다.
 */
// 자리와 여유 반경의 정의는 `road-topology.ts` 에 있다. 슬롯 배치가 같은 값을 봐야
// 하기 때문이다(가로등이 안 그려지는 tier 에서도 그 자리는 비워 둔다).

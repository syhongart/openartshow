/**
 * ── 밉맵이 감당할 크기 (감독 판정 *"울지 않는 방법 찾아보자"*) ──────────────
 *
 * 밉맵은 텍스처를 절반씩 줄여 저장한다. 그러니 **디테일이 1픽셀이면 첫 단계에서
 * 절반이 사라지고 두 번째에서 없어진다.** 카메라가 미세하게 움직이면 밉 레벨이
 * 오가면서 그 디테일이 나타났다 사라졌다 하고, 그게 **밝기의 출렁임** 으로 보인다.
 * 감독이 "밑을 보고 미세하게 움직이면 텍스처가 운다" 고 한 것의 정체다.
 *
 * 살아남으려면 디테일이 최소 2~3픽셀이어야 한다. 아래 값들은 그 기준에서 나왔다:
 *
 *   해상도 128 → 256   밉 체인이 한 단계 길어져 먼 거리에서 더 곱게 평균된다
 *   선 굵기 1 → 2.5    첫 밉에서 1.25px 로 살아남는다
 *   선 개수 900 → 500  굵어진 만큼 줄여 밀도를 유지한다
 *   불투명도 0.6 → 0.32  출렁임의 **진폭**을 낮춘다. 대비가 낮으면 밉이 바뀌어도 덜 튄다
 *   반복 12 → 8        결이 1.5배 커져 화면에서 텍셀 밀도가 낮아진다
 */
/**
 * ── 산책로를 담으려면 반복이 성겨야 한다 (2026-08-08 공원 개조) ─────────────
 *
 * 값이 `256 / repeat 8` 에서 `512 / repeat 2` 로 바뀌었다. **바꾼 이유는 밀도가
 * 아니라 산책로다.**
 *
 * 반복 8 은 한 타일이 실제 4m 다. 거기에 산책로를 그리면 파셀 하나에 **8×8 = 64개의
 * 산책로 조각**이 격자로 찍혀 공원이 아니라 바둑판이 된다. 산책로가 길로 읽히려면
 * 타일이 사람 걸음 규모여야 하고, 반복 2 = 타일 16m 가 그 크기다(파셀당 2×2).
 *
 * 반복을 4배 줄이면 텍셀 밀도가 4배 성겨지므로 해상도를 4배(면적 기준)로 올려 절반만
 * 되찾는다. 최종 밀도는 **64 → 32 텍셀/m** 이다:
 *
 *   before  256 × 8 / 32m = 64 텍셀/m
 *   after   512 × 2 / 32m = 32 텍셀/m
 *
 * ⚠️ **성겨진 것은 손실이다.** 밀도를 지키려면 1024 가 필요한데(VRAM 4배), 잔디는
 * 세계에서 가장 넓은 면적을 덮는 텍스처라 그 비용을 이 효과에 쓰지 않기로 했다.
 * 대신 밑에서 밉맵 기준을 다시 잡는다 — 성겨질수록 1픽셀 디테일이 위험하다.
 *
 * ── 밉맵이 감당할 크기 (감독 판정 *"울지 않는 방법 찾아보자"*) ──────────────
 *
 * 밉맵은 텍스처를 절반씩 줄여 저장한다. 그러니 **디테일이 1픽셀이면 첫 단계에서
 * 절반이 사라지고 두 번째에서 없어진다.** 카메라가 미세하게 움직이면 밉 레벨이
 * 오가면서 그 디테일이 나타났다 사라졌다 하고, 그게 **밝기의 출렁임** 으로 보인다.
 * 감독이 "밑을 보고 미세하게 움직이면 텍스처가 운다" 고 한 것의 정체다.
 *
 * 살아남으려면 디테일이 최소 2~3픽셀이어야 한다. 아래 값들은 그 기준에서 나왔다:
 *
 *   해상도 256 → 512   밉 체인이 한 단계 길어져 먼 거리에서 더 곱게 평균된다
 *   선 굵기 2.5 → 3.0  화면 텍셀 밀도가 절반이 됐으므로 그만큼 굵혀 되돌린다
 *   선 개수 500 → 1600 캔버스 면적이 4배라 밀도를 유지하려면 비례해 늘려야 한다
 *   불투명도 0.32      출렁임의 **진폭**. 대비가 낮으면 밉이 바뀌어도 덜 튄다(유지)
 *
 * 풀 한 포기의 실제 크기는 `길이 / 512 × 16m` 이므로 0.16~0.44m 다 — 반복을 줄이기
 * 전(0.08~0.22m)의 두 배이고, 도시 공원 잔디로는 오히려 이쪽이 맞는 규모다.
 */

// 파츠 색의 표현 — 캔버스가 문자열을 받고 판정은 숫자를 읽는다.
//
// 텍스처 바탕색은 원래 `'hsl(102, 34%, 52%)'`·`'#2a2d33'` 처럼 CSS 문자열로 박혀 있었다.
// 그런데 밤 알베도 배수를 **그 색의 휘도에서 유도**하게 되면서(`decide/ground-albedo.ts`)
// 판정 쪽이 같은 색을 숫자로 알아야 했다. 두 곳에 적으면 한쪽만 고쳐도 아무도 모른다 —
// 이 저장소가 색·수치·임계값에서 세 번 겪은 사고다.
//
// 그래서 **원천은 hex 숫자 하나**로 두고, 캔버스에 칠할 때만 문자열로 되돌린다.

/** hex → `#rrggbb`. 앞자리 0 을 채우지 않으면 색이 통째로 어긋난다 */
export function hexCss(hex: number): string {
  return `#${(hex & 0xffffff).toString(16).padStart(6, '0')}`;
}

// ── 색이 아닌 것 — 강도 ──────────────────────────────────────────────────────
//
// 캔버스에 `'#000'`·`'#fff'` 로 적히던 것 중 **상당수가 색이 아니다.** 발광 마스크의
// 텍셀은 *"이 조각이 빛나는가"* 라는 스위치이고, 수피 텍스처의 흰 바탕은 *"여기는
// 그늘이 없다"* 는 곱셈 항등원이다. 둘 다 팔레트를 경유하면 안 된다 — 팔레트는
// *"이 도시가 무슨 색인가"* 를 담는 곳이라, `V.something` 을 끌어다 쓰면 도시 톤을
// 손볼 때 누군가 이 값을 함께 만지고 그 순간 기둥이 어중간하게 빛난다.
//
// hex 로 적어 두면 읽는 사람에게도 색 리터럴 검사에게도 **색으로 보인다.** 회색조
// 수치로 적으면 강도인 것이 코드에 드러나고, 조각이 늘어 중간값이 필요해질 때도
// 같은 축으로 이어진다. world3 가 `lamp.ts` 에서 같은 판단을 했고(2026-08-08),
// world5 는 소비자가 **넷**이라(가로등·타워·시계탑·다리) 지역 상수로 두면 그대로
// 미러링이 된다 — 그래서 여기로 올렸다.

/** 회색조 0~255 를 캔버스가 받는 형태로. 세 채널이 같다 */
export function greyCss(v: number): string {
  return `rgb(${v}, ${v}, ${v})`;
}

/** 발광 마스크 — 차단. 이 텍셀을 읽는 조각은 발광 0 이다 */
export const MASK_BLOCK = 0;

/** 발광 마스크 — 통과. 이 텍셀을 읽는 조각은 발광이 그대로 산다 */
export const MASK_PASS = 255;

// 밤의 밝기와 가로등 점등 — **순수 판정.** 씬도 재질도 모른다.
//
// ── 감독 지시 ────────────────────────────────────────────────────────────────
// *"밤에는 가로등이 켜져야 하고… 지금 밤이 너무 어두워."*
//
// ── 왜 어두웠나 ─────────────────────────────────────────────────────────────
// `sky.js` 의 `LIGHT.night.clear` 를 열어 보면 원인이 **밝기가 아니라 색**이다:
//
//   sunI 0.24 · hemiI 0.55   ← 낮(0.95 / 1.0) 대비 그리 낮지 않다
//   hemiS 0x39445c (명도 27%)
//   hemiG 0x232a24 (명도 **15%**)  ← 지면을 비추는 색이 거의 검정이다
//
// ── ⚠ 위 진단의 전제가 틀렸다 (실측 2026-08-04) ────────────────────────────
// 이 자리에는 원래 *"`groundColor` 는 아래에서 올라오는 빛이고, 그것이 검정이면 **위를
// 향한 면**(바닥·도로·정원)에 닿는 빛이 없다"* 고 적혀 있었다. **three 의 실제 식은 그
// 반대다:**
//
//   irradiance = mix(groundColor, skyColor, 0.5·dot(N, lightDir) + 0.5)
//   (`three/src/renderers/shaders/ShaderChunk/lights_pars_begin.glsl.js`)
//
// 법선이 위(N=+y, lightDir=+y)면 계수가 1 → **`skyColor` 를 받는다.** `groundColor` 는
// 법선이 아래를 향한 면에 들어간다. 즉 바닥·도로·정원의 **윗면은 `hemiG` 와 거의 무관**
// 하고, `NIGHT_GROUND`(아래 상수)와 `?nground=` 노브는 그것들을 거의 못 움직인다.
//
// 아래 "왜 하한(max)인가" 절 뒤의 스윕 기록이 *"하단(지면)이 가장 안 움직였다 — 재지
// 못한 축"* 이라 적은 관측이 **이것으로 설명된다.** 값이 아니라 재는 축이 틀렸다.
//
// 지면이 밤에 어두워지지 않는 진짜 원인은 따로 있다(실측): 지면 3파츠(`ground`·`garden`·
// `road`)의 재질이 **시간대를 전혀 받지 않고**, 밤 처방이 전부 조명·노출이라 알베도에
// 곱해진다. 잔디 알베도 휘도 0.348 대 도로 0.026 — **13.4배** 차라 같은 조명 한 벌이
// 한쪽은 형광으로, 한쪽은 검정으로 만든다. 두 증상은 한 축의 양끝이다.
//
// ── 왜 `sky.js` 를 안 고치는가 ──────────────────────────────────────────────
// 라이브 world1 이 같은 파일을 쓴다. 밤 팔레트를 거기서 바꾸면 미술관 오픈월드의 룩이
// 함께 바뀐다. world2 쪽 어댑터에서만 **하한**을 얹는다 — 그것이 어댑터가 있는 이유다.
//
// ── 왜 하한(max)인가 ────────────────────────────────────────────────────────
// 보정을 곱셈으로 하면 매 프레임 곱해져 발산한다. 하한은 **몇 번 적용해도 결과가 같다**
// (멱등). `sky.js` 가 값을 덮어쓰든 안 쓰든, 크로스페이드 중이든 아니든 안전하다.
// 이 성질이 없으면 "언제 적용되는가" 를 정확히 알아야 하고, 그 지식은 곧 어긋난다.


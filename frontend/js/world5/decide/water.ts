// ── 깊이를 파고에서 유도한다 (감독 지시 2026-08-04 *"강 더 깊게 파고 파고 올려봐"*) ──
//
// 처음 값은 감독 지시로 `강 −0.5 · 바다 −1.0` 이었다. 그때는 수면이 평면이라 그 깊이가
// **바닥이 비치는 정도**만 정했다. 이제 수면이 실제로 오르내리므로(`surfaceLift`) 깊이가
// **파고의 천장**이 된다 — 마루가 지면(y=0) 위로 솟으면 물이 둔치에 뜬 것처럼 보인다.
//
// 그래서 순서를 뒤집는다: 원하는 파고를 먼저 정하고 깊이를 거기서 유도한다.
// 반대로 하면(깊이를 정하고 파고를 맞추면) 파고를 키울 때마다 깊이를 손으로 따라
// 고쳐야 하고, 그 둘이 어긋나는 날 물이 땅 위로 넘친다.

/**
 * 태풍급 파고(m, 마루~골의 **절반**). 감독이 *"엄청 크게 태풍온것 처럼"* 을 요구했고
 * 이 값이 그 상한이다. `ocean.ts` 의 `?wamp=` 가 여기까지 열린다.
 */
export const WAVE_PEAK_MAX = 0.75;

/**
 * 마루와 지면 사이에 남길 여유(m). 0 이면 최대 파고에서 마루가 지면과 정확히 같아져
 * 물가에서 **딱 붙어 보인다** — 부동소수 오차 한 번이면 넘친다.
 */
export const WAVE_CLEARANCE = 0.15;

/**
 * 강(내수면) 수면 높이(미터). **최대 파고에서 유도한다** — 마루가 지면 아래 남는다.
 * (감독 최초 지시는 −0.5 였고, 파고를 올리라는 후속 지시로 이 유도가 그것을 대체한다.)
 */
export const RIVER_Y = -(WAVE_PEAK_MAX + WAVE_CLEARANCE);

/**
 * 바다(외해) 수면 높이(미터). **강보다 낮다** — 강물이 바다로 흘러나가는 지형이므로
 * 그 방향이 맞다(아래 주석과 `tests` 가 이 관계를 지킨다). 낙차는 감독이 처음 준
 * 50cm 를 유지한다 — 깊이가 바뀌어도 두 물의 **관계**는 그대로다.
 */
export const RIVER_ABOVE_SEA = 0.5;
export const SEA_Y = RIVER_Y - RIVER_ABOVE_SEA;

/**
 * 물의 깊이(미터) — 수면에서 해저까지.
 *
 * 감독 지시(Voxels 참조)로 수면을 반투명으로 만들면서 필요해졌다 — 물이 반투명인데
 * 아래에 아무것도 없으면 하늘이 비쳐 **물이 아니라 유리 구멍**으로 보인다. 비칠 바닥이
 * 있어야 반투명이 물로 읽힌다.
 *
 * 얕을수록 바닥이 또렷해 물빛이 밝고, 깊을수록 물색에 묻힌다. 2.4m 는 물가에서 바닥이
 * 어렴풋이 비치고 조금만 나가도 물색이 이기는 깊이다. 더 깊게 잡으면 반투명으로 만든
 * 의미가 사라지고, 더 얕으면 바닥이 너무 또렷해 물웅덩이처럼 보인다.
 */
export const WATER_DEPTH = 2.4;

/**
 * 해저 높이(미터). **바다 수면에서 유도한다.**
 *
 * 예전에는 `-2.9` 를 직접 적고 주석에 "수면보다 2.4m 아래" 라고 썼다. 그 유도는 수면이
 * `-0.5` 일 때만 참이었고, 감독이 바다를 `-1.0` 으로 내리자 **주석과 값이 어긋났다**
 * (실제로는 1.9m). 이 저장소가 "실측치를 적어두고 유도를 주석에만 남기는" 형태로 이미
 * 사고를 냈으므로(팀장 조건 3: 유도 없는 실측치 잔류 금지) 산술로 바꾼다 — 수면을
 * 옮기면 해저가 따라오고, 깊이의 의미는 그대로 유지된다.
 *
 * 기준은 **바다**다(더 낮은 쪽). 강은 바다보다 50cm 높으므로 강에서 본 깊이는 그만큼
 * 깊어진다 — 하나의 해저 판을 공유하면서 강이 조금 더 깊게 읽히는 것은 자연스럽다.
 */
export const SEABED_Y = SEA_Y - WATER_DEPTH;

/**
 * 세계의 바깥 가장자리(미터). 이 밖은 전부 바다다. **world2 는 유한 세계다**(감독 확정).
 *
 * ── 원에서 격자로 ───────────────────────────────────────────────────────────
 * 예전에는 반경 240m 의 **원형 섬**(`ISLAND_R`)이었다. 감독이 격자를 확정하면서
 * (`decide/grid.ts`) 그 원이 **세계를 잘라 버렸다** — 격자는 960m 사방인데 반경 240m
 * 밖이 전부 바다라, 지시대로 넓혀도 걸을 수 있는 땅은 예전 그대로였다.
 *
 * ⚠️ 사라진 그 `ISLAND_R` 이 **다른 파일의 근거로는 살아남아 있었다** — `features/
 * minimap.ts` 의 지도 반경이 *"섬 반경이 240m 이므로"* 를 근거로 `8` 이라는 리터럴을
 * 들고 있었고, world5(반경 320m)에서 지도에 바다가 안 나오는 상태였다(2026-08-09
 * 전수 점검). **개념을 없앨 때는 그것을 근거로 삼은 값들도 함께 찾아야 한다.**
 *
 * **지형 판정 둘이 서로 다른 세계 크기를 들고 있으면 넓은 쪽이 조용히 무시된다.** 어느
 * 쪽 단위 테스트에도 안 걸린다 — 격자는 "30×30 이다"를 통과하고, 물은 "반경 밖은
 * 바다다"를 통과한다. 그래서 크기를 격자에서 **유도한다.** 격자를 40×40 으로 바꾸면
 * 바다도 저절로 물러난다.
 *
 * 파셀 `px` 가 덮는 범위는 `[px·cell − cell/2, px·cell + cell/2]` 이므로, 바깥 가장자리는
 * 가장 먼 파셀 중심에서 **반 칸 더 나간 곳**이다. 좌표가 -15…14 로 비대칭이라(짝수
 * 격자) 양쪽 절댓값 중 큰 쪽을 쓴다 — 작은 쪽을 쓰면 한쪽 끝 파셀이 바다에 잠긴다.
 */
export function worldHalfExtent(cell: number): number {
  return Math.max(-GRID_MIN_X, GRID_MAX_X + 1, -GRID_MIN_Z, GRID_MAX_Z + 1) * cell;
}

/**
 * 강의 굽이를 만드는 파동들. **계수의 유일한 자리다.**
 *
 * ── 왜 배열인가 (감독 지시 2026-07-31 *"하드코딩하지말고. 코드지저분하게하지말고"*) ──
 * 예전에는 `riverCenterZ` 와 `riverFlowAt`(도함수)에 계수가 **각각 적혀** 있었다. 같은
 * 값이 두 곳에 사는 전형적인 미러링이라, 한쪽만 고치면 물이 제 방향으로 안 흐른다.
 * 그것을 `tests/world2-river-flow.test.ts` 가 수치미분으로 **감시**하고 있었다.
 *
 * 감시는 어긋난 뒤에야 알려준다. 배열 하나로 합치면 **어긋날 자리가 없어진다** — 두
 * 함수가 같은 배열을 순회하므로 계수를 고치면 도함수가 저절로 따라온다. 테스트는 남기되
 * 이제 그것은 감시가 아니라 유도가 옳다는 확인이다.
 *
 * 주기가 서로 다른 둘을 겹친다. 하나면 규칙적인 물결이라 인공물처럼 보이고, 둘이면
 * 되풀이 주기가 최소공배수로 밀려나 눈에 안 띈다(도로의 "바둑판 말고" 와 같은 해법).
 *
 * ══════════════════════════════════════════════════════════════════════════
 * world5 — **미터를 비율로 바꿨다.** 축소를 안 따라오는 값을 없애기 위해서다
 * ══════════════════════════════════════════════════════════════════════════
 * world2 에서 이 배열은 `{ amp: 70, len: 150 }` · `{ amp: 30, len: 61 }` 이라는
 * **미터 리터럴**이었고, 주석은 그것을 *"주 파동 주기 2π×150 ≈ 942m 로 세계 폭(960m)과
 * 비슷해 한 번 크게 굽이친다"* 로 정당화하고 있었다. 유도가 아니라 **설명**이었다.
 *
 * world5 가 격자를 20×20(640m)으로 줄이자 그 설명이 조용히 거짓이 됐다 — 진폭 합 200m 는
 * 640m 세계의 31%, 주 파동 주기 942m 는 세계 폭의 1.47배라 "가로지르며 한 번 굽이" 가
 * 아니라 **완만하게 한쪽으로 쏠린 사선**이 됐다. 아무 테스트도 안 깨졌고, 화면에서는
 * 강이 도시 북쪽 절반을 통째로 먹은 것으로 나타났다(검수관 블로커 B1).
 *
 * 그래서 진폭도 파장도 **세계 크기에 대한 비율**로 적는다. 격자를 다시 바꾸면 강의
 * 성격(세계를 한 번 가로지르는 굽이)이 저절로 보존된다.
 *
 * ⚠️ **단 셀 크기에는 정의역이 있다** — `cell < 2 × RIVER_HALF`(48). 그 밖에서는
 * 파셀이 강을 표현할 수 없어 굽이가 사라지거나 강이 끊긴다. 위 문장을 "어떤 격자에서도
 * 저절로 따라온다" 로 읽으면 안 된다(검수관 C2, 2026-08-09 — 그 일반 보증이 실측으로
 * 반증됐다). 유도와 그 근거는 `swingBySlope` 에 있고, 정의역을 벗어나면 그 함수가
 * **던진다.** `tests/world5-water.test.ts` 가 양쪽을 다 검사한다.
 */
const RIVER_WAVE_SHAPE = [
  /**
   * 주 파동 — 세계를 가로지르며 **정확히 한 주기**. `cycleShare: 1` 이 그 뜻이고,
   * world2 의 "942m ≈ 세계 폭 960m" 가 우연히 만족하던 조건을 이름으로 만든 것이다.
   */
  { ampShare: 0.7, cycleShare: 1.0, phase: -Math.PI / 2 },
  /**
   * 부 파동 — 주 파동 위에 얹는 잔물결. 주기가 세계 폭의 0.4배라 되풀이가 최소공배수로
   * 밀려난다(world2 의 383m / 960m = 0.399 를 그대로 옮긴 비율이다).
   */
  { ampShare: 0.3, cycleShare: 0.4, phase: -Math.PI / 2 },
] as const;

/**
 * 강과 **뭍 사이에 두는 최소 여유**(미터). 광장 쪽·남쪽 둔치 쪽 **양쪽에 같이 쓴다**.
 *
 * 0 이면 강이 그 파셀 **중심**에 딱 걸린다. 경계에 딱 붙으면 부동소수 다툼으로 어느
 * 쪽이 될지도 정해지지 않는다. 한 칸의 1/4 을 띄운다.
 *
 * ⚠️ 이름이 `PLAZA` 인 것은 world2 시절 소비처가 광장 하나뿐이었기 때문이다. world5 에서
 * 남쪽 둔치 유도(`riverSwing`)가 같은 여유를 쓰므로 **두 곳이 같은 값을 공유한다** —
 * 여유를 광장 쪽만 넓히고 싶어지면 그때 둘로 가른다. 지금 나누면 같은 뜻의 값이 두 개가
 * 되고, 그것이 이 저장소가 값 미러링으로 세 번 데인 형태다.
 */
const RIVER_BANK_GAP = 8;

/**
 * 강 **남쪽**에 반드시 남기는 뭍의 줄 수(파셀). `riverSwing` 의 상한 **둘 중 하나**다.
 *
 * ⚠️ **기본 레이아웃에서 이 제약은 지지 않는다** — 기울기 제약(`swingBySlope`, 35.1)이
 * 이쪽(64)보다 작아 `min` 이 그쪽을 고르고, 결과적으로 남쪽 뭍은 2줄이 아니라 **4줄**이
 * 남는다(실측). 그래도 이 제약을 지우지 않는 것은, 셀이나 격자를 바꾸면 두 상한의
 * 크기 관계가 뒤집혀 이쪽이 이기는 날이 오기 때문이다. 지금 지우면 그날 남쪽 뭍이
 * 조용히 0줄이 된다.
 *
 * ── 왜 2 인가 ───────────────────────────────────────────────────────────────
 * 1 이면 강 건너가 **세계 끝 한 줄**이라, 다리를 건넌 사람이 도착하자마자 바다를 본다.
 * 다리는 "건너면 저기로 갈 수 있다" 를 만드는 물건인데 건너편에 갈 곳이 없으면 다리가
 * 전망대가 된다(`parts/bridge.ts` 의 `BRIDGE_EVERY` 주석이 "길잡이" 라고 부른 것).
 *
 * 3 이면 남쪽 뭍이 96m 라 그 자체로 한 동네가 되고, 그만큼 강이 북상해 도심을 먹는다.
 * 2 줄(64m)은 **강변 한 블록** — 물가를 따라 걷다 뒤돌면 강 너머로 도시가 보이는 폭이다.
 *
 * ⚠️ 화면에서 확인되지 않았다. 위 유도는 "건너편에 갈 곳이 있는가" 라는 구조 판정이고,
 * 강변 블록이 실제로 그렇게 읽히는지는 감독 화면이 판정 수단이다.
 */
export const RIVER_SOUTH_BANK = 2;

/**
 * 그 셀 크기에서 강 중심선이 넘으면 **강이 끊기는** 기울기(칸/칸). 유도는
 * `swingBySlope` 에 있다 — 여기는 테스트가 실측 기울기와 비교할 수 있게 낸 창구다.
 *
 * 값을 테스트에 다시 적으면 유도와 검사가 각자 틀릴 수 있다. 이 함수를 공유하면 검사는
 * **"실제 곡선이 이 상한 아래인가"** 하나만 보고, 상한 자체가 틀렸는지는 결과 축
 * (강이 한 덩어리로 이어지는가)이 따로 잡는다. 원인과 결과를 각각 재는 배치다.
 */
export function riverSlopeLimit(cell: number): number {
  return (2 * RIVER_HALF) / cell - 1;
}

/**
 * 강이 광장 쪽으로 **가장 가까이 올라온 지점**의 중심선 z(미터).
 *
 * ── 기준점은 광장 **가장자리**가 아니다 (world2 에서 그렇게 적었다가 실패했다) ──────
 * 처음 유도는 `(PLAZA_R + 0.5) × cell`(광장의 기하학적 가장자리)이었다. 통과할 것 같지만
 * **광장 전체가 뭍이다** 검사가 `'shore'` 로 깨졌다. `parcelWater` 는 파셀을 **중심
 * 좌표**로 판정하므로, 강이 광장 바로 바깥 링의 파셀 중심까지 오면 그 칸이 `'water'` 가
 * 되고 광장 칸은 그 이웃이라 `'shore'` 가 된다.
 *
 * 그러니 기준은 **광장 밖 첫 링 파셀의 중심**이다. 기하학적 가장자리와 반 칸(16m)
 * 차이인데, 그 반 칸이 검사 하나를 가르는 크기였다.
 */
function riverNearestZ(cell: number): number {
  const firstRingCenter = (PLAZA_R + 1) * cell;
  return firstRingCenter + RIVER_BANK_GAP + RIVER_HALF;
}

/**
 * 굽이의 진폭 합(미터). 중심선이 기준선에서 벗어날 수 있는 최대 거리다.
 * **유도한다 — 이 값을 손으로 적지 않는다.**
 *
 * 강은 광장 쪽 한계(`riverNearestZ`)와 남쪽 둔치 한계 **둘 사이에 갇혀** 있고, 굽이는
 * 그 사이를 오간다. 그러니 진폭은 남는 폭의 절반이다:
 *
 *   최북단 = 기준선 − 진폭합 = riverNearestZ            ← 광장에 가장 가까울 때
 *   최남단 = 기준선 + 진폭합 ≤ southLimit               ← 남쪽 뭍을 남길 때
 *   ⇒ riverNearestZ + 2·진폭합 ≤ southLimit
 *
 * `southLimit` 은 **뭍으로 남길 가장 북쪽 파셀의 중심**에서 강 폭과 여유를 뺀 자리다.
 * 파셀 중심으로 재는 이유는 위 `riverNearestZ` 와 같다 — `parcelWater` 가 중심 한 점으로
 * 판정하므로 파셀 중심이 젖지 않아야 그 칸이 뭍이다.
 *
 * 기본 레이아웃(cell 32, 격자 20×20)에서 **64** 다. 세계 세로 640m 의 10% 를 굽이가
 * 쓰고 강 폭 48m 를 더해 강 띠 전체가 176m(27.5%)인데, 그중 대부분이 **남쪽 가장자리**에
 * 몰려 도심을 안 건드린다.
 */
function riverSwing(cell: number): number {
  // 뭍으로 남길 줄 중 가장 북쪽 파셀. 남쪽 끝에서 `RIVER_SOUTH_BANK` 줄을 센 자리다.
  const bankNorthmost = (GRID_MAX_Z - RIVER_SOUTH_BANK + 1) * cell;
  const southLimit = bankNorthmost - RIVER_HALF - RIVER_BANK_GAP;
  const byBank = (southLimit - riverNearestZ(cell)) / 2;
  // 제약이 둘이고 **작은 쪽을 따른다.** 하나만 보면 다른 하나가 조용히 깨진다 —
  // 실제로 둔치 제약만으로 잡은 첫 값(64)이 아래 기울기 제약(35.1)을 크게 넘어
  // 강이 세 토막으로 끊겼다.
  return Math.min(byBank, swingBySlope(cell));
}

/**
 * 강이 **끊기지 않는** 진폭 상한(미터). 기울기에서 유도한다.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 이 제약은 world2 에도 필요했는데 **없었다** — 실측으로 드러났다 (2026-08-08)
 * ══════════════════════════════════════════════════════════════════════════
 * `parcelWater` 는 x 열마다 중심선을 한 번 평가해 물 칸을 고른다. 열 하나의 물 칸은
 * `|pz·cell − c| < RIVER_HALF` 를 만족하는 정수 `pz` 이므로, 길이 `2·RIVER_HALF/cell`
 * (기본 1.5칸)짜리 열린구간 안의 정수 — **1개 또는 2개**다.
 *
 * 이웃 열과 **공통 파셀이 없으면 강은 대각으로만 닿는다.** 지면은 파셀 단위 판이므로
 * 그 자리에서 강을 걸어서 건널 수 있고, 화면에서는 강이 토막 난 웅덩이로 보인다.
 *
 *   열 px 의 구간 I₁ = (a, a + 2h),  열 px+1 의 구간 I₂ = (a + Δ, a + Δ + 2h)
 *   (h = RIVER_HALF/cell 칸, Δ = 중심선이 한 칸 사이에 움직인 칸 수 = 기울기)
 *
 *   교집합 = (a + Δ, a + 2h) 이고 **길이가 1 을 넘으면 정수를 반드시 품는다.**
 *   ⇒ 2h − Δ > 1  ⇒  **Δ < 2·RIVER_HALF/cell − 1**   (기본값에서 0.5)
 *
 * 중심선의 최대 기울기는 각 파동 기울기의 합이다(`Σ ampᵢ/lenᵢ` — 도함수의 진폭 합).
 * 비율 명세로 풀어 쓰면:
 *
 *   Σ ampᵢ/lenᵢ = swing · (2π / 세계폭) · Σ (ampShareᵢ / cycleShareᵢ)
 *
 * 이것을 위 상한 아래로 누르는 `swing` 이 여기서 나온다.
 *
 * ── world2 는 왜 안 걸렸나 (우연이다) ───────────────────────────────────────
 * world2 의 이론 최대 기울기는 `70/150 + 30/61 = 0.959` 로 **상한 0.5 의 두 배**였다.
 * 그런데 두 파동의 파장이 서로 소에 가까워 두 코사인이 동시에 최대가 되는 x 가 세계
 * 안에 없었고, 실측 최대는 0.4455 로 상한 아래였다. `RIVER_HALF` 주석에 적힌 그
 * "0.4455" 는 **실측이지 보장이 아니다** — 계수를 조금만 건드리면 넘어간다.
 *
 * world5 가 정확히 그랬다. 비율 유도로 바꾸자 이론 최대가 0.911, 실측 최대가 0.62 로
 * 올라 상한을 넘었고, `px = −2`(중심선 pz 3.87 → 물칸 4)와 `px = −1`(3.24 → 물칸 3)
 * 사이에서 **공통 칸이 사라져** 강이 끊겼다. 그래서 실측이 아니라 **상한**으로 적는다.
 */
function swingBySlope(cell: number): number {
  const limit = riverSlopeLimit(cell);
  // ── ★ 정의역 밖에서 **조용히 퇴화한다** — 그래서 시끄럽게 터뜨린다 (검수관 C2) ──
  //
  // `riverSlopeLimit = 2·RIVER_HALF/cell − 1` 은 `cell ≥ 2·RIVER_HALF`(48)에서 0 이하가
  // 된다. 그러면 이 함수가 **음수**를 돌려주고 `Math.min` 이 그것을 그대로 고른다 —
  // 하한이 없기 때문이다. 검수관 실측:
  //
  //   cell=32  limit= 0.500  중심선  96.0~155.7  강 덩어리 1  ← 정상
  //   cell=48  limit= 0.000  중심선 128.0~128.0  강 덩어리 1  ← 굽이 0. 직선이 됐다
  //   cell=64  limit=−0.250  중심선 100.3~160.0  강 덩어리 2  ← **끊겼다**
  //
  // **이 함수가 존재하는 이유가 정확히 그 지점에서 뒤집힌다.** 강이 끊기는 것을 막으려고
  // 만든 상한이 강을 끊는다.
  //
  // 그리고 이 파일 머리말은 *"격자를 다시 바꾸면 강의 성격이 저절로 보존된다"* 라고
  // **일반 보증**으로 적고 있었다. 정의역 밖에서 거짓인 문장이고, 이 저장소는 그 형태로
  // 이미 세 번 값을 치렀다(behind-flag 괄호 · hookify 검출력 · `main` unprotected).
  // 다음 사람은 "저절로 따라온다" 를 읽고 셀을 바꾼다.
  //
  // **하한을 두지 않고 던지는 이유**: 하한은 또 하나의 조용한 퇴화다(굽이가 0 에 붙어도
  // 아무도 모른다). 정의역 밖은 값을 고를 문제가 아니라 **파셀이 강을 표현할 수 없는
  // 영역**이므로, 그때는 강 폭이나 지면 해상도를 다시 정해야 한다.
  //
  // 정상 경로 비용은 비교 하나다. 이 함수는 `riverFlowAt` 을 통해 정점마다 불리지만
  // 이미 배열을 할당하고 있어 비교 하나는 묻힌다.
  if (limit <= 0) {
    throw new RangeError(
      `[world5/water] 이 유도의 정의역은 cell < ${2 * RIVER_HALF} 다(강 폭 2×RIVER_HALF). `
      + `cell=${cell} 에서 기울기 상한이 ${limit} 이라 굽이가 사라지거나 강이 끊긴다. `
      + `셀을 그만큼 키우려면 RIVER_HALF 나 지면 해상도를 함께 다시 정해야 한다.`,
    );
  }
  const worldW = worldHalfExtent(cell) * 2;
  const shapeSum = RIVER_WAVE_SHAPE.reduce((a, w) => a + w.ampShare / w.cycleShare, 0);
  return (limit * worldW) / (2 * Math.PI * shapeSum);
}

/** 그 셀 크기에서 실제로 쓰이는 굽이 파동(진폭·파장은 미터). 비율 명세에서 유도한다 */
function riverWaves(cell: number): { amp: number; len: number; phase: number }[] {
  const swing = riverSwing(cell);
  const worldW = worldHalfExtent(cell) * 2;
  return RIVER_WAVE_SHAPE.map((w) => ({
    amp: swing * w.ampShare,
    // `len` 은 사인의 **각속도 역수**이므로 주기는 `2π·len` 이다. 주기를 세계 폭의
    // `cycleShare` 배로 두려면 `len = 세계폭 · cycleShare / 2π`.
    len: (worldW * w.cycleShare) / (2 * Math.PI),
    phase: w.phase,
  }));
}

/**
 * 강 중심선의 기준선(미터). **유도한다 — 이 값을 손으로 적지 않는다.**
 *
 * ── 예전에는 +180 이라는 상수였다 ───────────────────────────────────────────
 * 그 자리에 "왜 180 인가" 를 설명하는 긴 주석이 붙어 있었다. 광장을 비켜 가려는 값이라는
 * 설명이었는데, **설명할 수 있다는 것은 유도할 수 있다는 뜻이다.** 그리고 그 주석은
 * 광장 가장자리를 **32** 로 적고 있었다 — `PLAZA_R = 1` 에 셀 32 면 3×3 이라 실제
 * 가장자리는 **48** 이다. 손으로 적은 값이 손으로 적은 설명과도 어긋나 있었다.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * world5 — **부호를 되돌렸다. 강은 남쪽(+z) 가장자리를 흐른다**
 * (팀장 재판정 (C), 2026-08-08)
 * ══════════════════════════════════════════════════════════════════════════
 *
 * world2 에서는 이 값이 **음수**였고, 그 근거는 감독 지시 *"스폰 앞 주변에 흐르는 강이
 * 있으면"* 이었다(시선 기본값 `yaw = 0` 이 −z 를 보므로 +z 는 등 뒤다). world5 는
 * 그 지시를 물려받은 포크지만 **감독 지시가 달라졌다** — *"진짜 뉴욕처럼"* · *"맨해튼
 * 다리도 있고"* 이고, 맨해튼의 강은 도시를 관통하지 않고 **섬을 두르고 흐른다.**
 *
 * ── 뒤집힌 판정: (A) 를 채택했다가 실측으로 반증했다 ─────────────────────────
 * 처음 팀장 판정은 **(A) 공원을 강 북쪽으로 옮긴다** 였다. 강은 그대로 두고 공원만
 * 비키게 하는, 가장 싼 처방으로 보였다.
 *
 * **실측이 그 판정을 무너뜨렸다.** 강이 덮는 z 는 파셀 −7.63…−2.25 였고, 격자가
 * 20×20 이라 북쪽 끝은 −10 이다. 즉 강 북쪽에 남는 뭍은 **한 줄(pz = −9)뿐**이라
 * 공원이 들어갈 자리가 없었다. (A) 는 값이 틀린 것이 아니라 **애초에 실행 불가능**했다.
 *
 * 왜 아무도 못 봤나 — *"격자 20×20 축소 시 강이 상대 비율로 커진 것을 아무도 안 봤다"*
 * (팀장 재판정 원문). 진폭 합 200m 는 960m 세계에서 21% 였지만 640m 에서 31% 다.
 * 값은 그대로인데 **세계가 줄어서** 강이 커졌고, 그것을 재는 축이 아무 데도 없었다.
 * 같은 원인이 `DOWNTOWN_R`(도심 18.8% → 42.3%)과 공원 배치에서도 났다 — 세 번째다.
 *
 * 그래서 처방은 두 겹이다: ① 부호를 뒤집어 강을 남쪽 가장자리로(이 함수) ② 진폭·파장을
 * **비율로 유도**해 다음 축소 때 저절로 따라오게(`RIVER_WAVE_SHAPE`·`riverSwing`).
 * ①만 하면 네 번째가 온다.
 *
 * ── 그러면 스폰에서 강이 안 보이는가 — 아니다 ──────────────────────────────
 * 위상이 `-π/2` 이므로 `wx = 0`(스폰의 x)에서 두 파동이 동시에 **최소**가 되고, 강이
 * 그 자리에서 광장 쪽으로 가장 가까이 올라온다(`riverNearestZ`). 스폰은 등 뒤로
 * 돌아서면 강과 다리를 보고, 정면(−z)으로는 분수대 → 시계탑 → 센트럴파크를 본다.
 * **첫 화면에 도시가 오고 강은 한 번 돌아보면 나온다** — 실측표는 재검수 브리프에 있다.
 * 이 위상을 `+π/2` 로 되돌리면 `wx = 0` 에서 강이 가장 **멀어져** 스폰에서 다리가
 * 사라진다(far 반경 76.8m 밖으로 나간다).
 */
function riverBase(cell: number): number {
  return riverNearestZ(cell) + riverSwing(cell);
}

/**
 * 강 중심선. x 를 따라 흐르고 z 가 굽이친다.
 *
 * @param wx 월드 x 좌표
 * @param cell 파셀 한 변(미터). 기준선이 광장 크기에서 유도되므로 필요하다.
 *   **기본값을 두지 않는다** — `decide/` 가 셀 크기를 알면 그것이 곧 값 미러링이고
 *   (`worldHalfExtent`·`parcelWater` 가 같은 규약이다), 기본값을 주려면 `parts/` 를
 *   import 해야 해서 계층까지 뒤집힌다.
 */
export function riverCenterZ(wx: number, cell: number): number {
  let z = riverBase(cell);
  for (const w of riverWaves(cell)) z += w.amp * Math.sin(wx / w.len + w.phase);
  return z;
}

/** 이 월드 좌표가 **강** 위인가. 바다와 나눠 둔다 — 강은 세계 안에만 있다 */
export function isRiver(wx: number, wz: number, cell: number): boolean {
  return Math.abs(wz - riverCenterZ(wx, cell)) < RIVER_HALF;
}

/**
 * 강 반폭(미터). **셀 크기에서 유도한 값이다.**
 *
 * 지면은 파셀 한 칸을 통째로 덮는 판이므로 **파셀이 물의 최소 해상도**다. 강이 보이려면
 * 강이 지나는 x 열마다 물로 분류된 파셀이 최소 하나 있어야 한다.
 *
 * `parcelWater` 가 파셀 **중심 한 점**으로 판정하므로(아래 참고), 필요한 부등식은:
 *
 *     파셀 중심 간격 32m → 강 중심선에서 최근접 파셀 중심까지 거리 ≤ 16m
 *     그 중심이 강(±반폭) 안에 들려면   반폭 > 16
 *
 * 24 는 그 하한의 1.5배다. 여유를 준 이유는 안전마진이 아니라 **강 폭에 변화를 주려는
 * 것**이다 — 24 면 대부분 한 줄(32m), 굽이가 완만한 구간에서 두 줄(64m)이 되어 강이
 * 넓어졌다 좁아졌다 한다. 20 이면 거의 항상 한 줄로 균일하고, 32 면 거의 항상 두 줄이라
 * 강이 far 렌더 반경(76.8m)을 거의 채워 건너편이 안 보이는 벽이 된다.
 *
 * ── 앞선 유도가 왜 틀렸나 ───────────────────────────────────────────────────
 * 처음에는 파셀 **다섯 점**(중심 + 네 귀퉁이)이 전부 잠겨야 물로 쳤고, 거기서
 * `반폭 − 16 ≥ 16 → 반폭 ≥ 32` 를 유도했다. **그 유도는 강 중심선이 수평일 때만 참이다.**
 * `riverCenterZ` 의 최대 기울기는 0.4455 라 파셀 한 칸(32m)을 지나는 동안 중심선이 14.3m
 * 움직인다. 그것까지 넣으면 `16 + 16 + 16×0.4455 = 39.1` — 반폭 32 는 부등식을 어긴 값이고,
 * 실제로 두 개의 x 열에서 강이 지면에 덮여 끊겼다.
 *
 * 그때 고를 수 있던 길은 둘이었다. 반폭을 40 으로 키우거나(폭 80m — 섬 지름의 1/6),
 * 판정을 지면 해상도에 맞추거나. **뒤쪽이 맞다** — 5점 표본은 지면이 표현할 수 없는
 * 정밀도를 가진 척했고, 그 척함의 대가가 "강 폭을 두 배로 키워라" 였다.
 */
export const RIVER_HALF = 24;

/**
 * 이 월드 좌표의 **수면 높이**(m). 물이 아니면 `null`.
 *
 * ── 왜 `isWater` 보다 이 함수가 아래쪽인가 (감독 지시 *"강에 사람이 빠지게해줘"*) ──
 * 플레이어를 물에 잠기게 하려면 "물인가" 만으로는 모자라다 — **어느 물인가**를 알아야
 * 한다. 강과 바다는 수면 높이가 50cm 다르고(`RIVER_Y` vs `SEA_Y`), 그 차이는 감독이
 * 직접 지시한 것이라 뭉개면 안 된다.
 *
 * 소비자가 `isRiver` 를 다시 불러 높이를 고르게 두면 **"어느 물인가" 판정이 두 곳에
 * 생긴다.** 그래서 여기서 한 번에 답하고, `isWater` 를 이 함수 위에 다시 세웠다 —
 * 둘이 갈라질 자리가 원리적으로 없어진다.
 *
 * `null` 을 쓰는 이유는 `0` 이 유효한 높이이기 때문이다. "물이 아니다" 를 숫자로 표현할
 * 방법이 없다.
 *
 * ── ★ 파셀 단위로 답한다 — `isRiver` 를 직접 쓰지 않는다 (감독 발견 2026-08-01) ──
 * 감독: *"강 가기 전에 빠져."*
 *
 * 처음에는 `isRiver(wx, wz, cell)` 로 **연속 좌표** 판정을 했다. 그런데 **지면은 파셀
 * 단위로 그려진다** — `parcelWater` 가 `'water'` 로 분류한 칸만 지면을 안 그리고, 그
 * 구멍으로 수면이 드러난다(`stream.ts` 가 물 파셀을 아예 안 만든다).
 *
 * 두 해상도가 다르면 **땅을 밟고 서서 물로 판정되는 띠**가 생긴다. 파셀 중심이 강
 * 중심선에서 `RIVER_HALF` 보다 멀면 그 칸은 뭍이라 지면이 깔리는데, 칸은 중심 ±`cell/2`
 * 를 덮으므로 그 가장자리는 여전히 강 띠 안이다. 최악의 경우 **반 칸(16m)을 먼저**
 * 빠진다 — 감독이 본 것이 이것이다.
 *
 * *"물에 빠진다"* 는 것은 **발밑에 땅이 없다**는 뜻이고, 땅의 유무는 파셀이 정한다.
 * 그러니 판정도 파셀이어야 한다. 화면에 구멍이 보이는 자리와 정확히 일치한다.
 *
 * 이것은 값이 틀린 것이 아니라 **재는 축의 해상도가 달랐던 것**이다 — 이 저장소가
 * `parcelWater` 주석에 *"파셀보다 정밀한 판정은 그릴 방법이 없다"* 고 적어 두고도,
 * 물빠짐을 붙이면서 그보다 정밀한 판정을 새로 만들었다.
 */
export function waterSurfaceY(wx: number, wz: number, cell: number): number | null {
  const half = worldHalfExtent(cell);
  if (Math.abs(wx) > half || Math.abs(wz) > half) return SEA_Y;   // 세계 밖 = 바다
  // 이 좌표가 **속한 파셀**을 묻는다. 파셀 `p` 의 중심이 `p·cell` 이므로 반올림이다.
  const px = Math.round(wx / cell);
  const pz = Math.round(wz / cell);
  return parcelWater(px, pz, cell, cell) === 'water' ? RIVER_Y : null;
}

/**
 * 월드 좌표가 물인가. **이 함수가 유일한 답이다.**
 *
 * `cell` 을 받는 이유는 세계 경계가 격자에서 유도되기 때문이다 — 격자는 파셀 단위로
 * 세어지고 여기는 미터로 묻는다. 셀 크기를 이 파일이 알면 그것이 곧 값 미러링이다.
 *
 * **판정 자체는 `waterSurfaceY` 가 한다.** 예전에는 여기에 세계 경계 검사와 강 검사가
 * 직접 적혀 있었는데, 수면 높이를 묻는 함수가 생기면서 같은 판정이 두 벌이 될 뻔했다.
 */
export function isWater(wx: number, wz: number, cell: number): boolean {
  return waterSurfaceY(wx, wz, cell) !== null;
}

/**
 * 파셀이 물과 어떤 관계인가.
 *
 *   'dry'   — 뭍이다. 평소대로 짓는다
 *   'shore' — 물에 닿은 뭍이다. **지금은 미니맵 색으로만 쓴다**(부품 셋백은 미구현)
 *   'water' — 물이다. 스트리밍이 아예 만들지 않는다 — 지면도 부품도 없다
 *
 * ── 왜 중심 한 점인가 ───────────────────────────────────────────────────────
 * 지면은 파셀 한 칸을 통째로 덮는 판이다. 그러니 물의 최소 단위도 파셀이고, **파셀보다
 * 정밀한 판정은 그릴 방법이 없다.** 중심이 강 안이면 그 칸은 물이다 — 그게 전부다.
 *
 * 처음에는 중심 + 네 귀퉁이 다섯 점을 보고 "전부 물이면 water" 로 했는데, 그러면 강이
 * 파셀 대각선을 비스듬히 지나는 구간에서 다섯 점이 다 잠기지 않아 **강이 지면에 덮여
 * 끊겼다.** 그것을 막으려면 강 폭을 80m 까지 키워야 했다 — 판정의 허구적 정밀도를 맞추려
 * 세계 지형을 바꾸는 꼴이다. 판정을 지면 해상도로 내리는 쪽이 맞다.
 *
 * 'shore' 는 자기는 뭍인데 **네 이웃 중 하나가 물인** 칸이다. 강 양옆으로 정확히 한 줄씩
 * 생기고, 바다에 닿는 섬 가장자리에도 한 줄 두른다.
 *
 * **현재 소비처는 미니맵 하나다**(`features/minimap.ts` 가 물가를 다른 색으로 칠한다).
 * 원래 의도는 "부품이 물가를 피하게" 하는 것이었고 주석도 그렇게 적혀 있었으나, 그 셋백은
 * 구현된 적이 없다. 물가에 건물이 물에 닿아 서는 것이 눈에 걸리면 그때 붙인다 — 그전까지
 * 이 값이 배치를 바꾼다고 적어두면 다음 사람이 "이미 처리됐다"고 믿고 지나간다.
 *
 * `cellX`/`cellZ` 를 인자로 받는 것은 셀 크기를 이 파일이 알지 않기 위해서다 — 셀은
 * 레이아웃의 소유이고 여기는 좌표만 안다.
 */
export type WaterClass = 'dry' | 'shore' | 'water';

export function parcelWater(px: number, pz: number, cellX: number, cellZ: number): WaterClass {
  // 세계 밖은 파셀 좌표로 바로 답한다 — 미터로 환산해 경계와 비교하면 반 칸 어긋나
  // 가장자리 한 줄이 바다에 잠기거나 바다가 한 줄 육지가 된다.
  if (!inGrid(px, pz)) return 'water';
  // 여기 "광장은 무조건 dry" 를 한 줄 넣었다가 **뮤테이션이 죽은 코드임을 드러내** 뺐다.
  // 강이 광장에서 24m 떨어져 있어 그 분기는 한 번도 실행되지 않는다 — 지워도 테스트가
  // 전부 통과했다. 방어선인 척하면서 아무것도 안 막고 있었고, 있으면 오히려 "여기서
  // 막고 있으니 강 위치는 신경 안 써도 된다"는 잘못된 안심을 준다.
  //
  // 광장을 지키는 것은 `tests/world2-water.test.ts` 의 "강 중심선이 광장에 닿지 않는다"
  // 다. 누가 진폭을 키우면 그 테스트가 깨진다(실제로 강을 옛 위치로 되돌리는 뮤테이션을
  // 잡았다).
  // 강 기준선은 광장 가장자리를 **z 방향으로** 재서 유도하므로 `cellZ` 를 넘긴다
  // (`riverBase`). `cellX` 를 넘기면 두 셀이 달라지는 날 강이 조용히 밀린다.
  if (isRiver(px * cellX, pz * cellZ, cellZ)) return 'water';
  // 센트럴파크 안의 호수 셋 (감독 지시 *"중앙에 호수도 넣어줘. 호수 3개 영역"*).
  //
  // **강과 같은 'water' 로 둔다** — 스트리밍이 그 칸을 아예 만들지 않아 지면에 구멍이
  // 뚫리고 그리로 수면이 비친다. 호수를 위해 새 물 종류를 만들면 그 경로를 스트리밍·
  // 미니맵·수영·다리가 각자 알아야 하고, 그 넷 중 하나만 모르면 **지도에는 있는데
  // 걸어가면 없는 물**이 된다(이 파일 머리말이 경고하는 형태다).
  //
  // 자리는 격자가 정한다(`decide/grid.ts` 의 `isParkLake`). 좌표를 여기 적으면 공원을
  // 옮기는 날 호수만 옛 자리에 남는다.
  if (isParkLake(px, pz)) return 'water';
  // 물가 — 자기는 뭍인데 네 이웃 중 하나가 물인 칸
  if (
    parcelIsWater(px + 1, pz, cellX, cellZ) ||
    parcelIsWater(px - 1, pz, cellX, cellZ) ||
    parcelIsWater(px, pz + 1, cellX, cellZ) ||
    parcelIsWater(px, pz - 1, cellX, cellZ)
  ) return 'shore';
  return 'dry';
}

/** 이웃 판정용 — `parcelWater` 를 재귀 호출하면 물가의 물가까지 번진다 */
function parcelIsWater(px: number, pz: number, cellX: number, cellZ: number): boolean {
  if (!inGrid(px, pz)) return true;
  // 호수도 함께 본다 — 안 보면 호숫가가 'shore' 로 안 잡혀 미니맵에서 물가 색이
  // 안 나오고, 나중에 물가 셋백을 붙일 때 호수만 빠진다.
  return isRiver(px * cellX, pz * cellZ, cellZ) || isParkLake(px, pz);
}

// ── 수면 광택 — 시간대별 (감독 지시 2026-07-31 "반짝임부터 살려봐") ────────────
//
// ── 왜 시간대로 나누는가 ────────────────────────────────────────────────────
// 예전에 감독이 *"밤 강에서 반사가 어색하네. 밤인데 빛이 이렇게 많지 않잖아"* 라고
// 해서 `normalScale` 을 0.85→0.35, `roughness` 를 0.28→0.62 로 올렸다. **전역으로.**
// `ocean.ts` 주석은 그 선택을 이렇게 정당화했다:
//
//   "시간대로 분기하지 않는다. 낮에도 이 정도가 과하지 않고, 분기를 넣으면 바다가
//    하늘의 상태를 알아야 해서 기능 사이에 결합이 생긴다."
//
// 두 문장 다 지금은 성립하지 않는다:
//
//   ① *"낮에도 과하지 않다"* — 검증 없이 들어간 판단이었고, 감독이 낮 화면을 보고
//      *"진짜 리얼하게 빤짝빤작"* 을 요구했다. `normalScale 0.35` 는 기본값의 1/3 이라
//      물결 기울기가 거의 평평하다. 빛이 튈 각도 자체가 없으니 반짝일 수가 없다.
//   ② *"결합이 생긴다"* — **이미 계약에 있다.** `FeatureEnv.time()` 이 그것이다.
//      후보정이 똑같은 문제를 겪었고(반구광으로 낮/밤을 추측하다 밤이 낮으로 읽혔다)
//      팀장 판정 A-2 로 공식 경로가 열렸다. 그 뒤로 이 주석만 낡은 채 남아 있었다.
//
// 밤을 고치려고 전역을 낮춘 것이 낮을 죽였다. **한 축으로 두 시간대를 맞추려던 것이
// 애초에 무리였다** — 밤 물은 광원이 달·가로등뿐이라 좁고 약해야 하고, 낮 물은 태양이
// 하나뿐이라 좁고 강해야 한다. 같은 값일 이유가 없다.
//
// ── 왜 순수 함수인가 ────────────────────────────────────────────────────────
// 판정(어떤 시간대에 어떤 광택인가)과 집행(재질에 넣기)을 가른다. 이 저장소가 "경계를
// 건너는 지점은 아무도 안 본다" 로 데였으므로, **집행 쪽 통합 테스트를 함께** 붙인다
// (`tests/world2-water-gloss.test.ts`).

/** 수면 광택 파라미터. `MeshStandardMaterial` 의 두 필드에 그대로 들어간다. */
export interface WaterGloss {
  /**
   * 물결 기울기 배수. **반짝임의 1차 원인이다** — 이 값이 낮으면 법선이 평평해져
   * 빛이 튈 각도가 사라진다. 0.35(구 전역값)에서는 사실상 반짝임이 없다.
   */
  readonly normalScale: number;
  /**
   * 거칠기. 낮을수록 하이라이트가 **좁고 밝다**(반짝이는 점), 높을수록 넓고 흐리다(은은한 띠).
   * 밤에 이 값을 올린 것은 옳았다 — 달빛은 넓게 번진다. 낮에까지 적용한 것이 문제였다.
   */
  readonly roughness: number;
  /**
   * 흰 윤슬의 발광 세기(감독 지시 2026-07-31 *"흰 반짝임효과 해줘"*).
   *
   * ── 이 값이 팀장 조건 4 를 대신한다 ──────────────────────────────────────
   * 2026-07-30 팀장 판정은 *"`emissive` 로 내지 않는다 — 스스로 빛나는 물은 광원과
   * 무관해져 밤 지적과 정면 충돌한다"* 였다. 그 판정이 **지키려던 것**은 감독의 예전
   * 지적(*"밤인데 빛이 이렇게 많지 않잖아"*)이지 `emissive` 금지 자체가 아니었다 —
   * 그것은 목적이 아니라 수단이었다.
   *
   * 수단을 바꾸고 목적은 여기서 지킨다. 밤 값이 낮의 1/4 이하라 물 전체가 밝아지지
   * 않는다 — 달빛에 잔물결 몇 개가 튀는 정도다.
   *
   * 광원 방향 의존을 잃은 것이 이 교체의 대가다. 그 대신 **실제로 보인다** — 광원에
   * 의존하던 예전 수단(거칠기 변조)은 반사할 환경맵이 없어 실기기에서 반짝임이 0 이었고,
   * 같은 구조가 검은 줄기까지 만들고 있었다(`features/ocean.ts` 의 슬롯 주석).
   */
  readonly sparkle: number;
}

/**
 * 시간대별 수면 광택.
 *
 * @param time 지금 시간대. `FeatureEnv.time()` 이 준다 — 추측하지 않는다.
 */
export function waterGloss(time: SkyTime): WaterGloss {
  switch (time) {
    // 태양 하나가 강하게 내리쬔다. 물결이 서면 그 각도마다 점이 박힌다 —
    // **좁고(roughness↓) 강하게(normalScale↑)** 가 한낮 물의 문법이다.
    case 'day': return { normalScale: 0.9, roughness: 0.18, sparkle: 0.85 };
    // 노을은 광원이 낮고 크다. 물 위로 **길게 끌리는 띠**가 생긴다 —
    // 기울기는 살리되 거칠기를 중간에 둬 띠가 끊기지 않게 한다.
    case 'sunset': return { normalScale: 0.7, roughness: 0.3, sparkle: 0.55 };
    // 밤은 달·가로등뿐이다. 감독이 지적한 그 화면 — 여기서는 예전 값을 지킨다.
    // **이 줄이 예전 지시를 보존하는 자리다.** 낮을 살리려다 밤을 되돌리면 안 된다.
    case 'night': return { normalScale: 0.35, roughness: 0.62, sparkle: 0.18 };
  }
}

// ── 강의 흐름 방향 (감독 지시 2026-07-31 "물살로 보이고") ────────────────────
//
// ── 왜 정점마다 방향이 달라야 하나 ──────────────────────────────────────────
// 지금 물결은 텍스처 `offset` 을 등속으로 흘려서 낸다(`ocean.ts` 의 `FLOW_A/B`).
// 그것은 **씬 전체에 하나뿐인 방향**이라, 강줄기가 굽으면 물이 강을 가로질러 흐른다.
// 바다는 방향이 없으니 상관없지만 강은 **흐르는 방향이 곧 강의 정체성**이다.
//
// 강 중심선이 사인파 둘의 합이므로(`riverCenterZ`) 접선을 **해석적으로 유도**할 수 있다.
// 실측하거나 근사할 필요가 없다 — 미분 한 번이면 정확하다. 그리고 유도해 두면
// `riverCenterZ` 의 계수를 바꿔도 흐름이 저절로 따라온다(값 미러링이 안 생긴다).
//
// 계수를 여기 다시 적지 않는다 — 그것이 `RIVER_WAVES` 를 만든 이유다. 일반형만 적는다:
//
//   z(x)  = base + Σ ampᵢ·sin(x/lenᵢ + phaseᵢ)
//   z'(x) =        Σ (ampᵢ/lenᵢ)·cos(x/lenᵢ + phaseᵢ)      ← base 는 상수라 사라진다
//
// ── 왜 단위벡터인가 (중요) ──────────────────────────────────────────────────
// 방향만 정점마다 다르고 **속력은 모두 같아야 한다.** 속력이 다르면 정점마다 UV 가
// 다른 속도로 밀리고, 주기적으로 UV 를 되감을 때(무한히 커지면 float 정밀도가 깨진다)
// 정점마다 되감기는 시점이 어긋나 **쿼드가 순간 뒤틀린다.** 크기를 1 로 고정하면
// 모두 같은 주기로 되감기므로 되감기가 눈에 보이지 않는다.

/** 강이 흐르는 방향(월드 xz 평면, 단위벡터). `+x` 를 하류로 본다. */
export interface RiverFlow {
  readonly x: number;
  readonly z: number;
}

/**
 * 그 x 에서 강이 흐르는 방향.
 *
 * @param wx 월드 x 좌표
 * @param cell 파셀 한 변(미터).
 * @returns 단위벡터. 크기는 항상 1 이다(위 주석의 "속력은 같아야 한다").
 *
 * ── ★ world5 에서 `cell` 을 받게 됐다 — 시그니처가 걸던 약속이 깨졌다 ──────────
 * world2 에서 이 함수는 `cell` 을 **안 받았고**, 그것이 주장이었다:
 * *"기준선(`riverBase`)은 상수라 미분하면 사라지므로 `cell` 을 받을 필요가 없다."*
 * `tests/world2-river-flow.test.ts` 에 그 약속을 지키는 검사까지 있다.
 *
 * 그 주장은 **진폭과 파장이 미터 리터럴일 때만** 참이었다. world5 는 둘 다 세계
 * 크기에서 유도하므로(`riverWaves`) 도함수의 계수도 `cell` 에 의존한다 — 강이 완만해지면
 * 흐름 방향도 완만해지는 것이 물리적으로도 맞다.
 *
 * **약속을 조용히 깨지 않고 시그니처를 바꾼 이유가 이것이다.** 인자를 안 받은 채 안에서
 * `riverWaves(DEFAULT)` 를 부르면 컴파일은 통과하고 흐름만 어긋난다 — 그 어긋남은 물이
 * 강을 비스듬히 가로질러 흐르는 모습으로만 나타나고, 어떤 테스트도 안 본다.
 */
export function riverFlowAt(wx: number, cell: number): RiverFlow {
  // `riverCenterZ` 의 도함수 — **같은 명세에서 유도한다.** 예전에는 계수를 여기 다시
  // 적었고 테스트가 수치미분으로 감시했는데, 이제 어긋날 자리 자체가 없다.
  // 기준선(`riverBase`)은 x 에 무관한 상수라 미분하면 사라진다.
  let dzdx = 0;
  for (const w of riverWaves(cell)) dzdx += (w.amp / w.len) * Math.cos(wx / w.len + w.phase);
  const len = Math.hypot(1, dzdx);
  return { x: 1 / len, z: dzdx / len };
}

// ── 어느 수면 구현을 쓸 것인가 (감독 지시 2026-08-01, 팀장 판정 B) ────────────
//
// `?water=tsl` 은 **요청이지 채택이 아니다.** 노드 재질(`MeshBasicNodeMaterial`)은
// WebGPU 백엔드에서만 컴파일된다 — 레거시 `WebGLRenderer` 에는 노드를 GLSL 로 낮출
// 경로가 아예 없어서, 재질에 `vertexShader` 문자열이 없는 채로 첫 렌더에 들어가
// 이렇게 죽는다(실측 스택, 2026-08-01 헤드리스):
//
//   resolveIncludes (WebGLProgram.js:261) ← new WebGLProgram ← acquireProgram
//     ← getProgram ← setProgram ← WebGLRenderer.renderBufferDirect
//
// CLAUDE.md 가 적어둔 사각의 **반대 방향**이다(거기서는 GLSL `ShaderMaterial` 이
// `three.webgpu` 빌드에 렌더 경로가 없다고 적었다). 두 재질계는 서로의 렌더러에서
// 각각 죽는다 — 한쪽만 알고 있으면 반드시 다른 쪽에서 밟는다.
//
// **왜 여기(순수 판정)에 두는가.** 이 한 줄이 `ocean.create` 안에 묻혀 있으면 어떤
// 테스트도 못 닿는다. 헤드리스는 항상 WebGL 이라 스모크가 밟는 것은 폴백 가지 하나뿐
// 이고, `WebGPU → tsl` 가지는 감독 실기기에서만 실행된다. 그러면 그 가지가 뒤집혀도
// (예: 조건을 `!==` 로 잘못 적어도) 배포 전에는 아무도 모른다. 순수 함수로 빼면
// 두 가지 다 테스트에서 돈다.

/** 수면 구현 후보. `std` = 기존 PBR 물, `tsl` = TSL 노드 물(`ocean-tsl.ts`) */
export const WATER_MODES = ['std', 'tsl'] as const;
export type WaterMode = (typeof WATER_MODES)[number];

/**
 * 요청과 백엔드를 받아 **실제로 걸 수면 구현**을 고른다.
 *
 * @param requested URL 노브가 요청한 것
 * @param backend   렌더러 어댑터가 확정한 백엔드(`adapter.backend`)
 * @returns 채택된 구현. 요청이 `tsl` 이어도 WebGPU 가 아니면 `std` 다.
 */
export function pickWaterMode(requested: WaterMode, backend: string): WaterMode {
  // 화이트리스트다 — "WebGL 이 아니면 통과" 로 적으면 앞으로 백엔드가 하나 더
  // 늘었을 때 검증되지 않은 경로가 **저절로** 열린다.
  return requested === 'tsl' && backend === 'WebGPU' ? 'tsl' : 'std';
}


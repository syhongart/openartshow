// 프로필 저장의 **키 규약과 일괄 삭제** — leaf.
//
// ── 왜 `store.ts` 에서 갈라 나왔나 (검수관 P1, 2026-08-08 실측) ──────────────
// `auth.js` 가 로그아웃 정리를 위해 `mypage/store.js` 를 import 하자, 번들러가 그
// 모듈 그래프를 통째로 auth 청크에 끌어왔다:
//
//   ae0344b  auth 청크 1,186 B (gzip 725 B)
//   fa45ebc  auth 청크 12,586 B (gzip 5,254 B)  ← 프로필 스키마·링크 플랫폼 표가 들어옴
//
// 그 청크를 싣는 페이지는 마이페이지만이 아니다 — **랜딩(`index.html`)과 3D 미술관
// (`app/index.html`)** 이 함께 싣는다. 즉 미술관을 여는 사람이 `instagram`·`bioShort`
// 같은 문자열을 내려받고 있었다.
//
// 크기보다 **결합**이 문제다. `store.ts` 의 모듈 최상위가 언젠가 던지면 랜딩과 미술관이
// 함께 죽는다 — 2026-08-08 사고(장식이 실패해 내비게이션이 통째로 안 열림)와 같은 계열이고,
// 그 사고 때문에 랜딩은 지금 햄버거를 **가장 먼저** 배선한다.
//
// 그래서 `auth.js` 가 필요한 것만 여기 둔다: **키 규약과 삭제.** 스키마·검증·어댑터는
// 알 필요가 없다. 값을 양쪽에 적지 않으므로 SSOT 도 그대로다 — `store.ts` 가 여기서
// 가져다 쓴다(반대 방향이 아니다).

/** 프로필 한 벌의 키 접두사. 실제 키는 `PROFILE_PREFIX + uid`. */
export const PROFILE_PREFIX = 'lu-profile::';

/** 이 기기가 아는 별명 예약. `{ [nicknameKey]: uid }` */
export const NICKNAME_INDEX_KEY = 'lu-profile-nicknames-v1';

/**
 * 로그아웃할 때 이 기기에 남은 프로필을 **전부** 지운다.
 *
 * ── 왜 필요한가 (검수관 P5 · 라이브 승격 선결 조건) ──────────────────────
 * `auth.logout()` 은 로그인 정보(`lu-auth-profile-v1`)만 지우고 `lu-profile::` 는
 * 그대로 뒀다. behind-flag(무링크)인 동안에는 문제가 아니었다 — 아무도 그 화면에
 * 도달하지 못했다. **홈에서 링크로 접근 가능해지는 순간 성질이 달라진다.**
 *
 * 신원이 아직 mock 이라(`auth.js` 의 OAuth 키가 전부 빈 문자열) 사용자 식별자는
 * `"google:아트러버"` 같은 **자칭 문자열**이다. 공용 PC 에서 뒷사람이 같은 이름을
 * 자칭하면 앞사람의 **프로필 사진·활동 지역·전시 이력**을 그대로 본다.
 * 아바타에도 같은 성질이 있지만 담기는 것이 다르다 — **mock 신원 위에 개인식별정보를
 * 얹은 것은 마이페이지가 처음이다.**
 *
 * ── ⚠ 파급: 이 기기의 **다른 계정 프로필까지** 지운다 (검수관 P2) ──────────
 * 위 위협은 "현재 uid 의 프로필" 하나만 지워도 막힌다. 그런데 이 구현은 접두사가 붙은
 * **모든** 키와 별명 인덱스를 지운다 — **그것이 의도다.** 근거는 신원이 mock 이라는
 * 바로 그 사실이다: uid 가 자칭 문자열이므로 "다른 계정" 이라는 구분 자체가 이 기기에서
 * 신뢰할 수 없고, 남겨 둔 프로필은 다음 사람이 같은 이름을 자칭하면 그대로 열린다.
 *
 * **대가는 실재한다.** 한 기기를 여러 사람이 번갈아 쓰면(가족 PC) 로그아웃 한 번에
 * 다른 사람의 프로필이 사라지고, **서버 백업이 없어 복구가 불가능하다.** 사생활 쪽으로
 * 안전한 방향을 골랐지만 데이터 손실 쪽으로는 거친 선택이다 — 실제 OAuth 가 붙어 uid 가
 * 신뢰 가능해지면 **현재 uid 만 지우도록 좁혀야 한다**(백로그 `G-MP1`).
 *
 * 아바타(`lu-chibi-*`)는 **건드리지 않는다.** 그것은 이 변경 이전부터 있던 성질이고,
 * 지우면 로그아웃한 사람이 꾸며 둔 캐릭터를 잃는다 — 이 함수가 고치려는 문제가 아니다.
 */
export function clearProfilesOnLogout(): void {
  try {
    const keys: string[] = [];
    for (let i = 0; i < localStorage.length; i += 1) {
      const key = localStorage.key(i);
      if (key && key.startsWith(PROFILE_PREFIX)) keys.push(key);
    }
    for (const key of keys) localStorage.removeItem(key);
    localStorage.removeItem(NICKNAME_INDEX_KEY);
  } catch {
    /* 저장소가 막혀 있으면 할 수 있는 일이 없다 — 로그아웃 자체를 막지는 않는다 */
  }
}

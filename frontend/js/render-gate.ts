// render-gate.ts — "지금 3D 씬을 그릴 필요가 있는가"의 SSOT.
//
//   전체화면 오버레이가 씬을 덮고 있는 동안 렌더를 건너뛰기 위한 게이트다. 아무것도
//   import 하지 않는 순수 모듈이라 어느 방향에서 참조해도 순환이 생기지 않는다
//   (게임루프 ← 게이트 → UI 양쪽에서 쓰인다).
//
// ── 왜 만들었나 (2026-08-07, 감독 신고) ─────────────────────────────────────
//   감독: "캐릭터 디자인페이지에서 밑에 종족·얼굴·헤어 등 버튼을 누르면 바로 안 바뀌고
//   한 템포 느리게 반응해."
//
//   진단해보니 **버튼 처리 자체는 느리지 않았다.** 탭 클릭 핸들러의 동기 실행 시간은
//   실측 최대 9.1ms(종족 탭 — 프리셋 56장 + 칩 28개, DOM 노드 218개를 전부 재생성하는
//   가장 무거운 탭)로 60fps 프레임 예산 16.6ms 안쪽이었다. 다른 탭은 2.6~8.3ms.
//   "매 렌더마다 DOM 을 통째로 다시 만드는 게 병목"이라는 첫 가설은 **기각됐다.**
//
//   실제 병목은 처리가 끝난 뒤 **다음 페인트까지**였다. 편집기가 열려 있는 동안 프레임당:
//       메인 미술관 씬   115 draw   ← 오버레이가 덮고 있는데도 계속 그렸다
//       캐릭터 프리뷰      98 draw
//       합계             213 draw
//   편집기를 여는 것만으로 헤드리스 fps 가 6.85 → 3.23 (-53%) 로 떨어졌다.
//   (절대값은 swiftshader 라 실기기와 무관하다. 유효한 것은 "여는 것만으로 절반"이라는
//    상대 사실과, 메인 씬이 안 보이는데도 그려진다는 구조적 사실이다.)
//
//   메인 씬이 안 멈춘 이유: 렌더 루프(main-gameloop.ts)가 보던 정지 조건은
//   `document.hidden`(브라우저 탭 전환)뿐이었다. **오버레이가 화면을 덮은 상태는 그것과
//   다른 사건인데 같은 축으로 취급되고 있었다** — 정확히는, 취급된 적이 없었다.
//
//   덤으로 오버레이는 `backdrop-filter: blur(10px)`(gallery.css:261)을 쓴다. 뒤가 매
//   프레임 갱신되면 그 블러 합성도 매 프레임 다시 계산된다. 뒤를 멈추면 draw 115 만
//   아끼는 게 아니라 전체화면 블러 재합성도 함께 멈춘다.
//
// ── 왜 boolean 하나가 아니라 출처별 Set 인가 ────────────────────────────────
//   오버레이는 겹칠 수 있다(편집기 위에 라이트박스, 그 위에 공유 시트…). 단일 boolean
//   이면 **나중에 닫힌 쪽이 아직 열려 있는 오버레이의 게이트까지 풀어버린다** — 아직
//   덮여 있는데 렌더가 되살아나므로 이 최적화가 조용히 무효가 된다. Set 은 "덮은 것이
//   하나라도 남아 있으면 가려진 상태"를 정확히 표현하고, 같은 출처가 두 번 덮어도
//   (open 이 중복 호출돼도) 한 번만 세므로 해제가 어긋나지 않는다.
//
// ── 경계 — 여기서 멈춘다 ────────────────────────────────────────────────────
//   이 게이트는 **렌더만** 막는다. 시뮬레이션(이동·NPC·멀티플레이어 상태 전송)은 계속
//   돌린다. 시뮬까지 멈추면 ① 다른 접속자에게 내가 얼어붙은 것으로 보이고 ② 오버레이를
//   닫는 순간 누적된 delta 가 한 번에 튄다. draw call 이 병목이었으므로 렌더만 막아도
//   목적은 달성된다 — 시뮬 CPU 까지 아끼려는 확장은 그 두 문제를 먼저 풀고 나서 한다.

/** 씬을 덮고 있다고 선언한 출처들. 비어 있으면 씬이 보이는 상태다. */
const covers = new Set<string>();

/**
 * 오버레이가 3D 씬을 덮는지 선언한다.
 *
 * @param source 출처 식별자(예: 'chibi-maker'). 같은 값으로 덮고 같은 값으로 걷어야
 *               한다 — 오타는 "영원히 덮인 상태"로 남아 화면이 멈춘 것처럼 보인다.
 * @param covered true=덮음, false=걷음.
 */
export function setSceneCover(source: string, covered: boolean): void {
  if (covered) covers.add(source);
  else covers.delete(source);
}

/** 지금 씬이 오버레이에 가려져 있는가 — 렌더 루프가 프레임마다 묻는다(불린 1회, 할당 0). */
export function isSceneCovered(): boolean {
  return covers.size > 0;
}

/** 덮고 있는 출처 목록(디버그·검증용 순수 가산). 렌더 경로에서는 쓰지 않는다. */
export function getSceneCovers(): string[] {
  return [...covers];
}

/** 전부 걷는다. 테스트 격리용 — 런타임 복구 수단으로 쓰지 마라(출처를 잃는다). */
export function resetSceneCover(): void {
  covers.clear();
}

// 가로등 — 밤의 거리감을 만드는 것.
//
// ── world1 실물을 가져왔다 (감독 지시) ──────────────────────────────────────
// 감독: *"임시 아셋들 삭제하고 월드1에 있던 의자 가로등 가지고 오자."*
//
// 예전 이 파일은 원기둥 하나짜리 **플레이스홀더**였고, 주석이 스스로 그렇게 적고
// 있었다 — "빛나는 헤드가 없다. world2 는 야간이 기본이라 가로등이 룩에 미치는 영향이
// 큰데, 지금은 어두운 막대기다."
//
// world1(`world.js` 의 `SG`)은 기둥(CylinderGeometry 0.06→0.09, 높이 3.0)과
// 갓(Sphere 0.22를 세로로 눌러 y=3.06)이었다. 그 치수를 그대로 쓴다 — 라이브에서
// 사람 옆에 서 있던 값이라 스케일이 검증돼 있다.
//
// 조각이 둘이지만 재질은 하나여야 하므로(개수 불변식) `bakePieces` 로 한 지오에 굽고
// 정점색으로 기둥(어두운 금속)과 갓(밝은 유백)을 나눈다.
//
// 크기 편차를 두지 않는다. 가로등이 제각각이면 자연물이 아니라 인공물이라 눈에 띈다.
//
// ── 도시 가로등 → 마을 초롱등 (2026-08-08 포근마을 개조) ────────────────────
// 바뀐 것은 **지오메트리·색·높이 셋뿐**이다. `place`·`footprint`·`tiers`·`salt` 은
// 한 줄도 안 건드렸다 — 가로등 자리는 도로 축이 정하고(`lampAnchors`), 그려지지 않는
// tier 에서도 `decide/parcel-slots.ts` 가 그 자리를 예약한다. 룩을 바꾸자고 배치를
// 흔들면 나무·벤치·화분의 자리가 전부 함께 어긋난다.
//
// **밤 발광 배선은 구조를 그대로 승계했다** — `emissiveMap` 마스크 + 조각별 UV 한 점
// 고정 + `emissiveIntensity` 0 에서 시작. 조각이 2개에서 6개로 늘었으므로 여기서
// 새로 생긴 함정이 하나 있다: `Piece.u` 를 **빠뜨린 조각은 원본 UV 를 그대로 쓴다**
// (`bake.ts`). 2×1 마스크 위에서 원본 UV 는 0~1 을 훑으므로 그 조각이 절반쯤 빛난다 —
// 감독이 *"가로등은 조명만 불이 켜져야지"* 라고 한 그 증상이 뚜껑·받침에서 재현된다.
// 그래서 **조각마다 `u` 를 반드시 적는다**(아래 `buildLamp` 참고).


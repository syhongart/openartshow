/**
 * 등불색. 나트륨등의 따뜻한 노랑을 조금 눅인 값이다.
 *
 * 순백으로 하면 밤에 형광등처럼 차갑고, 채도를 더 올리면 주황 점으로만 보여 등의
 * 형태가 사라진다. 이 값이 **켜졌다고 읽히면서 갓 모양도 남는** 선이다.
 *
 * ── 마을 개조에서 이 값을 **일부러 안 바꿨다** (2026-08-08) ─────────────────
 * 개조 지시는 *"등불 색만 따뜻하게"* 였고 이 값은 이미 따뜻한 쪽이다. 그런데 더
 * 중요한 이유가 있다 — **이 값은 `decide/night.ts` 에 미러링돼 있다.**
 *
 *   `LAMP_LUMINANCE = 0.2126*(0xff/255) + 0.7152*(0xc8/255) + 0.0722*(0x6e/255)`
 *
 * 저쪽이 여기 채널값 셋을 **손으로 베껴 적고** 있고, 그 휘도가 블룸 문턱
 * (`BLOOM_THRESHOLD`)을 넘는지로 밤 가로등이 번질지가 갈린다. 이 저장소는 바로 그
 * 축에서 이미 한 번 터졌다 — 문턱 0.85 에 휘도 0.805 라 블룸이 정상 동작하면서
 * 걸리는 픽셀이 0 이었고, 감독 화면은 *"가로등 똑같은데"* 였다.
 *
 * `decide/night.ts` 주석은 *"등불색을 바꾸면 이 값도 함께 바꿔야 한다 — 그 정합은
 * 테스트가 지킨다"* 고 적어 두었는데, **world3 에서는 그 테스트가 없다.**
 * `tests/world2-night.test.ts` 는 world2 트리를 보고, world3 는 `world3-independence`
 * 하나뿐이다(2026-08-08 실측). 즉 지금 이 값을 바꾸면 **아무것도 빨개지지 않은 채**
 * 저 상수가 거짓이 되고, 밤 블룸은 화면을 봐야만 판정된다.
 *
 * 그래서 룩의 "따뜻함" 은 미러링이 없는 쪽 — **초롱의 정점색**(`V.lantern`) 과
 * 금속의 갈색화(`V.metal`) 로 만든다. 낮에는 정점색이 색의 전부이고, 밤에도 발광은
 * 정점색 **위에** 얹히므로 실제로 보이는 따뜻함의 대부분이 거기서 온다.
 *
 * ── 그래서 순서대로 했다 (부팀장, 같은 날) ────────────────────────────────
 * 위 문단이 *"팔레트로 옮기려면 `LAMP_LUMINANCE` 미러링을 **먼저** 없애야 한다.
 * 순서를 뒤집으면 미러링이 둘로 늘 뿐이다"* 라고 적었고, 그 순서를 따랐다:
 * `decide/night.ts` 가 이제 `luma(V.lanternGlow)` 로 **유도**하고, 여기는 그
 * 팔레트 항목을 가리킨다. 값은 한 톨도 안 바뀌었고 출처만 하나가 됐다.
 */
const LAMP_LIGHT = V.lanternGlow;

/**
 * 금속붙이 — 기둥·밑동·등 받침·꼭지.
 *
 * world2 는 `0x4a4636`(어두운 올리브 회색)이었다. 마을에서는 `V.metal` 로 간다 —
 * 팔레트가 그 색을 *"검정 대신 따뜻한 짙은 갈색. 순수 무채색은 파스텔 화면에서
 * 구멍처럼 보인다"* 는 근거로 이미 정해 두었고, 가로등이 그 규칙의 대표 소비자다.
 */
const METAL = rgb(V.metal);
/**
 * 초롱 유리 — 유백에서 **크림빛 노랑**으로.
 *
 * world2 의 갓은 `0xd8cfa8`(바랜 유백)이라 낮에는 회색 공으로 보였다. 밤에만 발광이
 * 얹혀 등처럼 보였다는 뜻이고, 마을은 낮이 기본이라 그대로 두면 낮 내내 회색이다.
 * `V.lantern` 은 팔레트가 *"등불 유리"* 로 이름 붙여 둔 색이라 역할이 정확히 맞는다.
 */
const GLASS = rgb(V.lantern);
/**
 * 초롱 뚜껑 — 목재 짙은 쪽.
 *
 * 금속으로 두면 뚜껑과 기둥이 같은 색이라 초롱이 공중에 뜬 것처럼 보인다. 목재를
 * 한 겹 끼우면 "등을 매단 것" 으로 읽히고, 마을 소품(벤치·다리·표지판)과 재료가
 * 이어져 한 세트로 보인다.
 */
const CAP = rgb(V.woodDeep);

/**
 * 기둥 높이(미터). **집 높이에서 유도한 값이다.**
 *
 * world2 는 world1 `SG.lampPost` 치수를 그대로 계승해 기둥 3.0m · 갓 꼭대기 3.06m
 * 였다. 그 값은 라이브에서 사람 옆에 서 있던 검증된 스케일이라 손대지 않는 것이
 * 원칙이었는데, **마을 개조가 그 전제를 바꿨다** — `building.ts` 의 집 높이가
 * 4~20m 에서 3.2~5.6m 로 내려왔다.
 *
 * 절대 높이가 아니라 **집과의 비율**을 보존한다:
 *
 *   world2   3.06 / 4.0(최저 집)  = 0.765
 *   world3   2.47 / 3.2(최저 집)  = 0.773   ← 꼭대기 높이는 실측(아래 주석)
 *
 * 3.06 을 그대로 두면 이 비가 0.956 이 되어 **가로등이 집과 키가 같아진다.** 그러면
 * 마을이 아니라 주차장으로 읽힌다 — 파스텔로 칠해도 마찬가지다.
 *
 * 아래로도 한계가 있다. 초롱 중심이 2.0m 근처라야 사람 눈높이(1.6~1.7m) 위에 확실히
 * 걸려 "등" 으로 읽힌다. 더 낮추면 정원 조명이 되고 길을 밝히는 물건이 아니게 된다.
 */
const POST_H = 1.7;

/** 등 받침(컵)의 높이. 기둥 끝과 초롱 사이를 끊어 주는 최소한의 두께 */
const CUP_H = 0.09;
/** 초롱 반지름. 세로로 0.92배만 눌러 **거의 정구(正球)** — 둥근 실루엣이 이 룩의 핵심 */
const GLOBE_R = 0.26;
/** 초롱 세로 눌림. world2 의 갓은 0.8 이라 접시에 가까웠다 — 초롱은 부풀어야 한다 */
const GLOBE_SQUASH = 0.92;

/** 기둥 꼭대기 = 컵 밑면 */
const CUP_Y0 = POST_H;
/** 컵 윗면 = 초롱 밑면 */
const GLOBE_Y0 = CUP_Y0 + CUP_H;
/** 초롱 중심. 밑면에서 눌린 반지름만큼 올린다 */
const GLOBE_CY = GLOBE_Y0 + GLOBE_R * GLOBE_SQUASH;

/** 뚜껑 밑면. 초롱 꼭대기보다 살짝 **내려** 겹쳐 접합부를 감춘다 */
const CAP_Y0 = GLOBE_CY + GLOBE_R * GLOBE_SQUASH - 0.03;
/** 뚜껑 높이 */
const CAP_H = 0.15;

/**
 * 마을 초롱등 — 조각 여섯.
 *
 *   밑동   Cylinder(0.15, 0.19, 0.12, 8)      땅에 앉은 굽. 없으면 기둥이 땅에서 자란다
 *   기둥   Cylinder(0.05, 0.07, POST_H, 8)    아래가 굵어 서 있는 것으로 보인다
 *   컵     Cylinder(0.10, 0.055, CUP_H, 6)    위가 넓은 받침 — 초롱을 얹은 자리
 *   초롱   Sphere(GLOBE_R, 10, 8) 을 0.92배   **여기만 빛난다**
 *   뚜껑   Cone(0.30, CAP_H, 8)               목재 삿갓. 초롱보다 넓어 처마가 된다
 *   꼭지   Octahedron(0.055)                  8삼각형짜리 장식. 로우폴리 룩에 맞다
 *
 * 실측 결과(2026-08-08): 삼각형 252 · 높이 0 ~ 2.473m · 실루엣 반경 0.300m.
 * 반경이 늘어난 것은 뚜껑(0.30)이 world2 의 갓(0.22)보다 넓어서인데, `footprint` 가
 * 보는 `LAMP_CLEARANCE`(0.9)의 3분의 1이라 배치에는 아무 영향이 없다.
 *
 * ── 삼각형 예산 (전부 실측, 2026-08-08) ────────────────────────────────────
 * **172 → 252 (+47%).** 조각이 2개에서 6개로 늘었는데 삼각형은 1.5배에 그친다 —
 * 무거운 둘을 그대로 물려받았기 때문이다:
 *
 *   초롱 Sphere(10,8) = 140   world2 갓과 **같은 값**(반지름만 0.22→0.26)
 *   기둥 Cylinder(8)  =  32   world2 기둥과 같은 값
 *   ─────────────────────────
 *   실질 증가 80 = 밑동 32 + 컵 24 + 뚜껑 16 + 꼭지 8
 *
 * 세그먼트를 8·6 으로 눌러 둔 것이 그래서다. 가로등은 `far` 까지 그려지고 파셀당
 * 4대라 인스턴스가 100 단위로 늘어난다 — 광장당 1개인 분수와 예산 감각이 정반대다.
 * 꼭지에 `OctahedronGeometry`(8삼각형)를 쓴 것도 같은 이유이고, 마침 그 각진 면이
 * 로우폴리 룩에 맞아서 예산과 룩이 같은 답을 냈다.
 *
 * ⚠️ 위 숫자를 **눈으로 세지 마라.** world2 주석 시절 이 자리를 176 으로 적었다가
 * 실측 172 로 정정했다(캡 삼각형을 잘못 셌다). 값을 고칠 때는 지오를 실제로 굽어
 * `position.count / 3` 을 본다.
 *
 * ⚠️ **조각마다 `u` 를 반드시 적는다.** 빠뜨리면 그 조각은 원본 UV 를 쓰고, 2×1
 * 마스크 위에서 원본 UV 는 검정 텍셀과 흰 텍셀을 함께 훑어 **절반쯤 빛난다.**
 * 감독이 *"가로등은 조명만 불이 켜져야지"* 로 잡았던 그 증상이다.
 */
function buildLamp(T: ThreeNS) {
  const pieces: Piece[] = [
    // `u` 가 발광 마스크에서 읽을 텍셀을 고른다 — 금속·목재는 왼쪽(검정), 초롱만 오른쪽(흰색).
    { geo: new T.CylinderGeometry(0.15, 0.19, 0.12, 8).translate(0, 0.06, 0), color: METAL, u: MASK_U_OFF },
    { geo: new T.CylinderGeometry(0.05, 0.07, POST_H, 8).translate(0, POST_H / 2, 0), color: METAL, u: MASK_U_OFF },
    { geo: new T.CylinderGeometry(0.10, 0.055, CUP_H, 6).translate(0, CUP_Y0 + CUP_H / 2, 0), color: METAL, u: MASK_U_OFF },
    {
      geo: new T.SphereGeometry(GLOBE_R, 10, 8).scale(1, GLOBE_SQUASH, 1).translate(0, GLOBE_CY, 0),
      color: GLASS,
      u: MASK_U_ON,
    },
    { geo: new T.ConeGeometry(0.30, CAP_H, 8).translate(0, CAP_Y0 + CAP_H / 2, 0), color: CAP, u: MASK_U_OFF },
    { geo: new T.OctahedronGeometry(0.055).translate(0, CAP_Y0 + CAP_H + 0.03, 0), color: METAL, u: MASK_U_OFF },
  ];
  return bakePieces(T, pieces);
}

/** 왼쪽 텍셀의 중앙 — 발광 0 */
const MASK_U_OFF = 0.25;
/** 오른쪽 텍셀의 중앙 — 발광 1 */
const MASK_U_ON = 0.75;

/**
 * 마스크 텍셀 — **색이 아니라 발광 강도의 0 과 1 이다.**
 *
 * 그래서 `palette.ts` 를 경유하지 않는다. 팔레트는 *"마을이 무슨 색인가"* 를 담는
 * 곳이고, 이 둘은 *"이 조각이 빛나는가"* 라는 **스위치**다. 여기에 `V.something` 을
 * 끌어다 쓰면 마을 톤을 손볼 때 누군가 이 값을 함께 만지게 되고, 그 순간 기둥이
 * 어중간하게 빛난다 — 이름이 곧 역할이라는 팔레트의 규약이 오히려 깨지는 쪽이다.
 *
 * `'#000'`·`'#fff'` 로 적던 것을 회색조 수치로 바꾼 것도 같은 이유다(2026-08-08).
 * CSS hex 로 적으면 읽는 사람에게도 검사(`tests/world3-parts-assets.test.ts` 의 색
 * 리터럴 검사)에게도 **색으로 보인다.** 0 과 255 로 적으면 마스크 값인 것이 코드에
 * 드러나고, 나중에 조각이 셋 이상으로 늘어 중간값이 필요해질 때도 같은 축으로 이어진다.
 */
const MASK_BLOCK = 0;
const MASK_PASS = 255;

/** 마스크 텍셀 값을 캔버스가 받는 형태로. 회색조라 세 채널이 같다 */
const maskFill = (v: number) => `rgb(${v}, ${v}, ${v})`;

/**
 * 발광 마스크 — **2×1 픽셀.** 왼쪽이 차단(0), 오른쪽이 통과(255).
 *
 * 이보다 작을 수 없는 크기다. 조각을 둘로만 가르면 되므로 텍셀도 둘이면 충분하고,
 * UV 를 텍셀 중앙 한 점에 고정하므로 필터링이 경계를 흐려도 값이 섞이지 않는다.
 * 그래도 `NearestFilter` 와 밉맵 끄기를 함께 걸어 둔다 — 나중에 조각이 늘어 텍셀이
 * 촘촘해질 때를 대비한 안전장치다.
 *
 * 마을 개조로 조각이 2개에서 6개가 됐지만 **텍셀은 여전히 둘이면 된다** — 빛나는
 * 조각이 초롱 하나뿐이라 마스크가 갈라야 하는 것은 지금도 "그것" 과 "나머지" 둘이다.
 */
function lampMask(T: ThreeNS) {
  const cv = document.createElement('canvas');
  cv.width = 2; cv.height = 1;
  const ctx = cv.getContext('2d')!;
  ctx.fillStyle = maskFill(MASK_BLOCK); ctx.fillRect(0, 0, 1, 1);
  ctx.fillStyle = maskFill(MASK_PASS); ctx.fillRect(1, 0, 1, 1);
  const tex = new T.CanvasTexture(cv);
  tex.magFilter = T.NearestFilter;
  tex.minFilter = T.NearestFilter;
  tex.generateMipmaps = false;
  return tex;
}

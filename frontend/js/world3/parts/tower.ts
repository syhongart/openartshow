// 등대 — 마을에서 가장 높은 것. **스카이라인을 만드는 파츠다.**
//
// ── 감독 지시 2026-08-02 (world2 시절) ──────────────────────────────────────
// 대도시의 스카이라인을 원한다. 지금 건물은 높이 4~20m 육면체 하나뿐이라 지평선이
// 평평하다.
//
// ── 왜 형태가 아니라 높이·희소성부터인가 (디자이너 진단 2026-08-02) ─────────
// *"스카이라인이 평평한 건 건물 형태가 아니라 높이 상한(20m)과 배치 확률(파셀당 최대
// 4채 균일 분포) 때문이다 — 셋백 실루엣을 붙이기 전에 '20m를 훌쩍 넘는 덩어리가 도심
// 쪽에 몰려서 드물게 선다' 는 사실만으로도 스카이라인이 바뀐다."*
//
// 그래서 **1단계는 단일 매스**였다. 계단식 셋백·첨탑·창문은 그것이 화면에서 확인된 뒤에
// 얹기로 했고, 포근마을 개조가 그 2단계에 해당한다 — 높이·희소성은 world2 에서 이미
// 확인됐으므로 이번에는 형태를 준다.
//
// ── 포근마을 개조 2026-08-08: 도시 타워 → 등대 ──────────────────────────────
// 집이 20m → 5.6m 로 낮아졌다(`building.ts`). world2 에서 이 파츠는 **도시의 골격**
// 이었지만 — 그 시절 주석이 그렇게 적고 있다 — 마을에는 골격이 필요 없다. 필요한 것은
// **멀리서 보이는 한 점**이고, 그것이 등대다.
//
// 바뀐 것 셋: 높이 범위(32~60m → 16~26m) · 지오메트리(육면체 → 기단+탑신+랜턴실) ·
// `tones`(회색 5종 → 곱셈 틴트). `place`·`footprint`·`maxPerParcel`·`tiers`·`salt` 은
// 한 글자도 안 건드렸다.
//
// ── 양식이지 특정 건물이 아니다 (법무 실사 2026-08-02 · 팀장 판정 A) ────────
// 실존 건물의 형상을 알아볼 수 있게 재현하는 것은 금지다 — 상표권자가 건물 외관 디자인
// 자체를 등록상표로 보유한 사례가 있고 엔터테인먼트 분야까지 지정돼 있다. 여기서 만드는
// 것은 **등대라는 건축 유형의 일반 문법**(원기둥 탑신, 상단 갤러리와 유리 랜턴실, 붉은
// 가로 띠)이고, 어느 등대를 연상시키는 것은 설계 목표가 아니다. 붉은/흰 배색은 항로표지
// 관용 도색이지 특정 소유자의 표지가 아니다.
//
// 이격은 값으로 기록한다(팀장 조건 ②) — 아래 상수 주석이 그 기록이다.

import type { PartSpec, PlacedPart, ThreeNS } from './types.js';
import { roadDirs, SETBACK, LAMP_CLEARANCE, EAVE } from './road-topology.js';
import { isTowerParcel } from './zoning.js';
import { bakePieces, rgb, type Piece } from './bake.js';
import { V, TINT_SET } from './palette.js';

// 처마 여유(`EAVE`)·도로 셋백·가로등 여유는 전부 `road-topology.ts` 가 소유한다.
// 여기 다시 적지 않는다 — 처음엔 적었고, 그것이 검수관 블로커였다(2026-08-02 B1).
// 위험을 주석으로 서술하면서 그 위험을 새로 만든 형태다.

/**
 * 바닥 한 변(m). **9~13m. 값을 안 바꿨다.**
 *
 * 상한의 근거는 배치 부등식이다. `pickInQuadrant` 가 아니라 파셀 중앙 고정이므로 더
 * 여유롭지만, 셋백이 바뀔 여지를 감안해 이론 최댓값에서 물러선 값을 쓴다:
 *
 *   파셀 반폭 16 − 도로 셋백 6.0 − 가로등 여유 0.9 − 처마 0.6 = 8.5m 까지 반폭 가능
 *   → 한 변 17m 까지 이론상 가능하지만, 도로 폭은 감독 지시로 이미 두 번 바뀌었다
 *     (`road-topology.ts` 의 `ROAD_SEG` 주석). 그 절반 수준에서 멈춘다.
 *
 * 하한 9m 인 것은 일반 건물 상한(6m)보다 확실히 커야 "다른 종류의 구조물" 로 읽히기
 * 때문이다. 겹치면 그냥 조금 큰 건물이 된다.
 *
 * ── 등대가 됐는데 왜 그대로인가 (2026-08-08) ───────────────────────────────
 * 등대 **탑신**은 이 폭을 다 쓰지 않는다 — 단위 지오에서 반경 0.165 라 실제 지름
 * 3.0~4.3m 다. 이 값이 정하는 것은 **기단**(등대가 올라선 돌 대)의 폭이다.
 *
 * 그러니 "탑신이 가늘어졌으니 `MIN_SIDE` 도 줄이자" 가 성립할 것 같지만, 줄이지 않은
 * 이유가 있다: 이 값은 `place` 안에서 `side` 를 뽑고 그 `side` 가 `footprint` 를
 * 유도한다. 배치·겹침 게이트의 근거이므로 룩 변경이 건드릴 자리가 아니다. 실루엣이
 * 작아지는 방향이라 겹침 위험도 줄어들 뿐이고, 남는 여백은 등대 발치의 **숨 쉴 틈**이
 * 된다(`types.ts` 의 *"반경은 넉넉한 쪽으로"*).
 */
const MIN_SIDE = 9;
const MAX_SIDE = 13;

/**
 * 높이(m). **16~26m.**
 *
 * ── world2 는 32~60m 였다. 왜 내렸나 (2026-08-08) ──────────────────────────
 * 그때의 근거는 이랬다: *"기준은 시계탑이다 — 12m 짜리가 스카이라인에 걸리는 랜드마크로
 * 실측된 전례다. 타워는 그 2.5~5배로 잡아야 랜드마크가 아니라 **도시의 골격**으로
 * 읽힌다."*
 *
 * 그 문장은 지금도 참이다. **바뀐 것은 목표다** — 마을에는 골격이 필요 없다. 그리고
 * 기준이 되는 다른 값이 통째로 내려앉았다: 집이 4~20m 에서 3.2~5.6m 가 됐다. 60m 는
 * 이제 집의 **10.7배**이고, 그 비율에서는 등대가 아니라 마천루로 읽힌다 — 크림색으로
 * 칠하고 붉은 띠를 둘러도 그렇다.
 *
 * 16~26m 는 집(최대 5.6m)의 **2.9~4.6배**다. 실제 연안 등대의 비례이기도 하고, 종탑
 * (12m, `clocktower.ts`)보다 확실히 높아 "마을에서 가장 높은 것" 자리가 유지된다.
 * 그 순서가 깨지면 광장 종탑과 등대가 서로 랜드마크 자리를 다툰다.
 *
 * 상한 26m 가 **보이는 범위를 낭비하지 않는가**: far tier 로드 반경이 76.8m 이고 안개
 * 완전가시거리가 60.8m 다. 60.8m 에서 26m 짜리는 올려본각 23°로, 화면 세로의 3분의 1을
 * 차지한다 — 못 보고 지나칠 크기가 아니다. world2 가 60m 에서 끊은 근거(*"더 높여도
 * 이미 보이는 것이 더 커질 뿐"*)는 여기서도 같은 방향으로 작동한다.
 *
 * 비례는 높이:바닥(기단) = 1.2:1 ~ 2.9:1 이지만, 눈에 읽히는 것은 **탑신** 비례다 —
 * 지름 3.0~4.3m 에 탑신 높이 10.2~16.5m 로 3.4:1 ~ 3.8:1 이다. 낮고 넓은 개체가
 * 뭉툭해 보이지 않도록 **높이와 바닥을 같은 난수로 상관시킨다**(아래 `place`).
 */
const MIN_H = 16;
/**
 * **export 한다** — 그림자 카메라가 "세계에서 가장 높은 것" 을 알아야 프러스텀 깊이를
 * 유도할 수 있다(`decide/shadow.ts`, `main.ts` 의 `shadowFrustum`). 26 을 그쪽에 다시
 * 적으면, 등대를 높이는 날 그림자만 옛 높이에 맞춰진 채 남고 꼭대기 그림자가 소리 없이
 * 잘린다.
 *
 * ⚠ **이 값을 60 → 26 으로 내렸다(2026-08-08).** 그림자 프러스텀이 그만큼 얕아지므로
 * 같은 `SHADOW_MAP` 해상도에 더 작은 볼륨이 들어가 **텍셀이 촘촘해진다** — 품질이 좋아
 * 지는 방향이라 새 아티팩트는 예상되지 않지만, 프러스텀 유도가 높이에만 의존하는지는
 * 이 파일이 판정할 수 없다. 부팀장 확인 대상으로 보고에 올렸다.
 */
export const MAX_H = 26;

/**
 * 색조. **곱셈기다 — 색이 아니다.**
 *
 * world2 는 여기에 석재·유리 회색 5종(`0xb8bcc4` 등)을 적었고 그것이 곧 타워의 색이었다.
 * 등대는 정점색을 굽으므로(`asset`) 그 값을 그대로 두면 **회색 × 크림**이 되어 등대가
 * 탁해진다 — world2 가 나무에서 겪은 형태다(초록 tones × 초록 정점색으로 나무가 새까맣게
 * 죽었다). 게다가 `0xb8` 은 `0xd0` 미만이라 파츠 자산 테스트가 곧바로 잡는다.
 *
 * `TINT_SET` 이 정확히 5종이라 `place` 의 `TONES.length` 를 손대지 않아도 된다. 이름을
 * `TONES` 로 남긴 것도 그래서다 — 배치 코드를 한 글자도 안 건드리는 쪽을 골랐다.
 */
const TONES = TINT_SET;

export const tower: PartSpec = {
  kind: 'tower',
  // far 까지 그린다. 등대의 의미는 **멀리서 보이는 것**이라, near 에만 두면 다가가야
  // 나타나는 유령이 된다 — 스카이라인이 성립하지 않는다.
  tiers: ['near', 'mid', 'far'],
  salt: 0x5bd1e995,
  tones: TONES,

  /** 바닥 사각형을 감싸는 원. 회전이 직각 배수라 긴 변의 절반 + 처마면 충분하다 */
  footprint: (p) => Math.max(p.sx, p.sz) * 0.5 + EAVE,

  maxPerParcel: () => 1,

  place: ({ px, pz, rnd, o }) => {
    if (!isTowerParcel(px, pz, o.cellX, o.cellZ)) return [];

    // ── 자리는 파셀 중앙 고정이다 ──────────────────────────────────────────
    // 사분면에 뽑지 않는다. 이유가 둘이다:
    //   · 중앙이 도로에서 가장 먼 지점이라 셋백이 저절로 지켜진다(아래 단언 참고)
    //   · 파셀당 한 채뿐이라 자리를 다툴 상대가 없다 — 흔들 이유가 없다
    // `fountain`·`clocktower` 가 같은 이유로 중앙 고정이다.
    //
    // **크기를 먼저 뽑는다.** 자리가 고정이므로 순서가 결과를 바꾸지는 않지만, 크기가
    // 셋백을 만족하는지 검사하려면 크기가 먼저 있어야 한다(`building.ts` 가 감독 지시로
    // 바꾼 순서와 같은 이유다).
    //
    // 높이와 바닥을 **같은 난수로 상관시킨다** — 독립으로 뽑으면 "낮고 뚱뚱한" 개체가
    // 나와 비례가 무너지고, 그러면 등대가 아니라 물탱크로 보인다.
    const bulk = rnd();
    const side = MIN_SIDE + bulk * (MAX_SIDE - MIN_SIDE);
    // 높이는 조금 더 흔든다 — 바닥이 같아도 높이가 다르면 스카이라인에 굴곡이 생긴다.
    const h = MIN_H + (bulk * 0.6 + rnd() * 0.4) * (MAX_H - MIN_H);
    const ry = Math.floor(rnd() * 4) * (Math.PI / 2);
    const tone = Math.floor(rnd() * TONES.length);

    // 도로가 있는 파셀에서 중앙 고정이 셋백을 지키는지 **유도로 확인한다.**
    // 중앙에서 파셀 변까지 `cellX/2`, 거기서 도로 셋백과 가로등 여유를 빼면 설 수 있는
    // 반폭이 나온다. 이 값보다 크면 도로를 덮으므로 그때는 세우지 않는다.
    //
    // ── ⚠️ 이 실패는 **아무 데도 안 나타난다** (검수관 블로커 2026-08-02 B2) ──
    // 처음 이 자리에 "`starved` 로 세어진다" 고 적었다. **거짓이다.** `starved` 는
    // 풀 슬롯 고갈(`pool.acquire()` 실패)에서만 오른다(`systems/parcel-builder.ts`).
    // 여기서 `[]` 를 돌려주면 조립부는 이 파셀에 타워를 **요청하지도 않으므로** 그
    // 카운터는 손도 안 탄다.
    //
    // 즉 지금은 "겹치지 않는다" 를 "안 세운다" 로 사서 **관측을 잃은** 상태다. 그
    // 거래 자체는 맞다고 본다 — 조용히 겹치는 편이 더 나쁘다. 다만 **잃은 것을
    // 잃었다고 적어 둔다.** 파셀 크기나 셋백을 줄이는 변경이 오면 등대가 소리 없이
    // 사라지고, 그때 이 주석이 유일한 단서다.
    //
    // 현재 `DEFAULT_LAYOUT`(cell 32)에서는 이 분기가 **도달 불가능**하다:
    //   16 − (SETBACK 6.0 + LAMP_CLEARANCE 0.9) − EAVE 0.6 = 8.5m  >  MAX_SIDE/2 = 6.5m
    // 그래서 `tests/world2-zoning.test.ts` 가 **좁은 셀 기준으로 타워 파셀을 다시 찾아**
    // 이 가지를 직접 돌린다. 그냥 좁은 셀만 넘기면 물 판정까지 바뀌어 배제 조건에
    // 걸리고, 이 가드에는 도달조차 안 한다 — 첫 판본이 실제로 그랬고 뮤테이션으로
    // 드러났다(검수관 R4).
    const clearance = roadDirs(px, pz).length === 0 ? 0 : SETBACK + LAMP_CLEARANCE;
    const maxHalf = Math.min(o.cellX, o.cellZ) / 2 - clearance - EAVE;
    if (side / 2 > maxHalf) return [];

    const out: PlacedPart[] = [{
      kind: 'tower', x: 0, z: 0, y: 0, ry, sx: side, sy: h, sz: side, tone,
    }];
    return out;
  },

  asset: (T) => ({
    geometry: buildLighthouseGeometry(T),
    // 정점색이 곧 색이다 — `tones` 는 거기 곱해지는 틴트다(위 `TONES` 주석).
    material: new T.MeshStandardMaterial({
      vertexColors: true,
      // 집(0.72)보다 살짝 거칠다. 등대는 바닷바람을 맞는 회반죽이라 윤기가 덜하고,
      // 무엇보다 **높아서 하늘을 배경으로 본다** — 매끈하면 하이라이트가 띠처럼 앉아
      // 실루엣이 흐려진다.
      roughness: 0.78,
      metalness: 0.0,
    }),
    // 높은 만큼 **그림자가 길게 떨어지는 것이 스카이라인의 절반**이다 — 그림자가 없으면
    // 등대가 배경 그림처럼 떠 보인다.
    castShadow: true,
    receiveShadow: true,
  }),
};

// ── 지오메트리 ──────────────────────────────────────────────────────────────
//
// **단위 등대: 밑면 1×1, 전체 높이 1.** 인스턴스가 `sx`·`sy`·`sz` 로 늘린다.
// 피벗은 바닥(y=0 이 땅) — 파츠 계약이다.
//
// ⚠️ **비균등 스케일이고, 그것이 의도다.** `sx=sz=side`(9~13m) 인데 `sy=h`(16~26m) 라
// **세로가 가로의 약 2배로 늘어난다.** 집(`building.ts`)은 이 왜곡을 피하려고 높이
// 범위를 1.75배 안으로 좁혀 뒀는데, 등대는 반대다 — 늘어나는 방향이 곧 등대의 형태다.
// 그래서 단위 지오의 창·문은 **가로로 뭉툭하게** 그려 뒀다. 스케일 후에 세로로 긴 창이
// 된다. 단위 지오만 보고 "창이 납작한데" 로 고치면 실제 화면에서 세로로 찢어진다.
//
// 조각이 여럿이라 `bakePieces` 로 하나로 굽는다(개수 불변식: 지오 1 · 재질 1).

/** 옆면 분할. 8각이면 로우폴리 실루엣이 남으면서 원기둥으로 읽힌다 */
const SEG = 8;
/**
 * 반 칸 회전. 8각 원통은 기본적으로 z+ 방향에 **정점(모서리)** 이 오는데, 문과 창을
 * 거기 붙이면 모서리에 걸쳐 접힌다. 반 칸 돌리면 z+·x± 가 전부 **면 중앙**이 된다.
 * `building.ts` 가 사각뿔 지붕을 45° 돌린 것과 같은 이유이고 같은 처방이다.
 */
const FACE = Math.PI / SEG;

/** 탑신 구간(단위 y). 기단 위에서 시작해 갤러리 밑에서 끝난다 */
const SHAFT_Y0 = 0.065;
const SHAFT_H = 0.635;
/** 탑신 아래·위 반지름. 위가 좁아야 곧게 선 것으로 보인다 — 평행하면 파이프가 된다 */
const SHAFT_R0 = 0.165;
const SHAFT_R1 = 0.105;

/**
 * 탑신의 그 높이에서의 반지름. **띠·문·창이 전부 이 함수를 읽는다.**
 *
 * 각 조각에 반지름을 손으로 적었다가 테이퍼를 한 번 바꾸면 띠만 공중에 뜨거나 벽에
 * 파고든다 — 같은 진실을 여러 곳에 적는 그 형태다. 유도해 두면 `SHAFT_R0`·`SHAFT_R1`
 * 한 쌍만 만져도 전부 따라온다.
 */
function shaftR(y: number): number {
  return SHAFT_R0 + (SHAFT_R1 - SHAFT_R0) * ((y - SHAFT_Y0) / SHAFT_H);
}

function buildLighthouseGeometry(T: ThreeNS) {
  const pieces: Piece[] = [];
  const add = (geo: Piece['geo'], color: number) => pieces.push({ geo, color: rgb(color) });

  /** 원통/원뿔대 한 단. `y` 는 **바닥** 높이다(피벗 규약과 같은 방향으로 읽히게) */
  const tube = (rTop: number, rBot: number, h: number, y: number, color: number) =>
    add(
      new T.CylinderGeometry(rTop, rBot, h, SEG).rotateY(FACE).translate(0, y + h / 2, 0),
      color,
    );

  // ── 기단 ────────────────────────────────────────────────────────────────
  // 두 단으로 끊는다. 한 단이면 탑신이 접시에 꽂힌 것처럼 보이고, 두 단이면 등대가
  // **돌 대 위에 올라선 것**으로 읽힌다. 집의 굽(`wallBase`)이 하는 일과 같다.
  tube(0.44, 0.48, 0.030, 0.000, V.stoneSeam);
  tube(0.30, 0.34, 0.035, 0.030, V.stone);

  // ── 탑신 ────────────────────────────────────────────────────────────────
  tube(SHAFT_R1, SHAFT_R0, SHAFT_H, SHAFT_Y0, V.wall);

  /**
   * 붉은 가로 띠. **등대를 등대로 만드는 것이 이 두 줄이다** — 크림색 원기둥만으로는
   * 굴뚝이나 사일로와 구별되지 않는다.
   *
   * 나선 도색이 더 등대답지만 로우폴리 8각에 나선을 감으려면 조각이 열 배가 된다.
   * 가로 띠는 실루엣이 아니라 색으로 읽히므로 멀리서도 같은 값을 한다.
   *
   * 탑신보다 `OUT` 만큼 튀어나오게 해 z-파이팅을 피한다. 반지름은 `shaftR` 에서 유도라
   * 테이퍼를 바꿔도 띠가 벽에 파고들지 않는다.
   */
  const band = (y0: number, h: number) => {
    const OUT = 0.006;
    tube(shaftR(y0 + h) + OUT, shaftR(y0) + OUT, h, y0, V.roof);
  };
  band(0.220, 0.08);
  band(0.450, 0.08);

  // 문. 앞면(z+)에 살짝 띄워 붙인다. 벽과 같은 평면이면 z-파이팅이 난다.
  // 스케일 후 실제 크기는 폭 0.65~0.94m · 높이 1.76~2.86m 다(비균등 스케일 주석 참고).
  add(new T.BoxGeometry(0.072, 0.110, 0.03).translate(0, 0.130, shaftR(0.130)), V.door);
  // 문 위 차양 — 작은 판 하나로 현관이 생긴다
  add(new T.BoxGeometry(0.100, 0.012, 0.045).translate(0, 0.192, shaftR(0.192) + 0.012), V.trim);

  /**
   * 창. 높이를 셋 다 다르게 두는 것은 **안에 나선 계단이 도는** 인상을 주기 위해서다 —
   * 같은 높이에 나란히 두면 층이 있는 건물로 읽힌다.
   *
   * 방위별로 두께 축이 달라 인자를 그대로 못 돌린다. `x` 면은 x 를 얇게, `z` 면은 z 를
   * 얇게 잡는다(회전으로 처리하면 조각마다 `rotateY` 가 붙어 읽기 어려워진다).
   */
  const winZ = (y: number, sign: number) => {
    const r = shaftR(y) * sign;
    add(new T.BoxGeometry(0.055, 0.055, 0.020).translate(0, y, r), V.trim);
    add(new T.BoxGeometry(0.040, 0.040, 0.028).translate(0, y, r), V.glass);
  };
  const winX = (y: number, sign: number) => {
    const r = shaftR(y) * sign;
    add(new T.BoxGeometry(0.020, 0.055, 0.055).translate(r, y, 0), V.trim);
    add(new T.BoxGeometry(0.028, 0.040, 0.040).translate(r, y, 0), V.glass);
  };
  winZ(0.330, 1);
  winX(0.550, 1);
  winX(0.420, -1);

  // ── 갤러리(전망대) ──────────────────────────────────────────────────────
  // 탑신보다 넓게 내밀어야 랜턴실이 **얹힌** 것으로 보인다. 등대 실루엣에서 가장 눈에
  // 띄는 꺾임이 여기라, 이 한 단이 없으면 위가 그냥 뾰족해진다.
  const GAL_Y = 0.700;
  tube(0.205, shaftR(GAL_Y) + 0.004, 0.035, GAL_Y, V.trim);
  // 난간. 실제 난간살은 로우폴리에서 밉맵에 지워지므로 **막힌 벽**으로 만든다 —
  // 정원 잔디·자갈이 겪은 것과 같은 이유다(가는 것은 멀어지면 사라진다).
  tube(0.195, 0.195, 0.050, 0.735, V.woodDeep);

  // ── 랜턴실 ──────────────────────────────────────────────────────────────
  // 유리를 난간보다 높게 세워 위쪽 절반이 드러나게 한다. 등대에서 실제로 빛나는 자리라
  // 팔레트에서 가장 밝은 축(`lantern`)을 쓴다.
  //
  // **발광(emissive)은 여기서 켜지 않는다.** 밤 점등은 조명·성능 축이고 이 저장소에는
  // 그 축에 팀장 조건과 실측 이력이 붙어 있다(물 반짝임 건). 색만 밝게 굽고 판단은
  // 넘긴다 — 룩 담당이 조명 예산을 혼자 정하지 않는다.
  tube(0.115, 0.115, 0.135, 0.735, V.lantern);
  // 랜턴실 지붕(원뿔). 띠와 같은 붉은색이라 위아래가 한 세트로 읽힌다.
  add(new T.ConeGeometry(0.175, 0.085, SEG).rotateY(FACE).translate(0, 0.870 + 0.0425, 0), V.roof);
  // 피뢰침과 꼭대기 구슬. 실루엣의 마지막 5%인데 이게 없으면 원뿔이 뭉툭하게 끝난다.
  tube(0.006, 0.010, 0.030, 0.955, V.metal);
  add(new T.OctahedronGeometry(0.015).translate(0, 0.985, 0), V.metal);

  return bakePieces(T, pieces);
}

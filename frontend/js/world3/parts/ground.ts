// 지면 — 파셀 한 칸을 통째로 덮는 판.
//
// 유일하게 개수가 고정(1)이고 위치도 고정이다. 그래서 난수를 색조 하나에만 쓴다.
// 여기에 틈이 생기면 아래 허공이 보이므로 셀 크기를 **정확히** 덮는다(여백 적용 안 함).
//
// ── 흙바닥에서 잔디 땅으로 (2026-08-08 포근마을 개조) ──────────────────────
// world2 는 이 판이 **어두운 회갈색 통짜**였다(`tones: [0x6b6659, …]`). 도시의 맨땅이고,
// 그 위에 정원(`garden.ts`)이 초록을 덧깔았다. 마을에서는 순서가 뒤집힌다 — 땅이 먼저
// 잔디이고 흙은 그 **단면**에서만 보인다.
//
// 바뀐 것은 색과 지오메트리 두 가지뿐이다. `place`·`footprint`·`maxPerParcel` 은 한 줄도
// 안 건드렸다. 여기는 파셀당 정확히 하나가 고정 좌표에 놓이는 파츠라 배치를 흔들 여지가
// 없는데도 그렇게 적어 두는 이유는, **다음 사람이 "룩만 바꿨다" 를 diff 로 확인할 수 있어야
// 하기 때문**이다.

import type { PartSpec, ThreeNS } from './types.js';
import { SEABED_Y } from '../decide/water.js';
import { bakePieces, rgb, type Piece } from './bake.js';
import { V, TINTS } from './palette.js';

/**
 * 지면 판이 **수면 아래로 더 내려가는 여유**(미터).
 *
 * 이 값이 0 이면 판 아랫면이 수면과 정확히 같은 높이가 되고, 물결·시야각·깊이 정밀도가
 * 조금만 흔들려도 그 경계에 실틈이 보인다. 30cm 면 어느 각도에서도 판이 수면보다 확실히
 * 아래에 있다.
 */
const SUBMERGE_MARGIN = 0.3;

/**
 * 지면 판의 두께(미터). **물가에서 보이는 흙벽의 높이**가 이 값이다.
 *
 * ── 감독 지적에서 정해졌다 ─────────────────────────────────────────────────
 * *"강과 바다 땅보다 더더 아래. 50센치 밑에있게해줘."*
 *
 * 그런데 물은 **이미** 아래에 있었다(`SEA_Y`, 당시 −1.2m). 화면에서 붙어 보인 이유는
 * 이 값이 **0.1m** 였기 때문이다. 물 파셀은 로드되지 않고 그 구멍으로 물판이 비치는
 * 구조라(`features/ocean.ts`), 물가에서 보이는 것은 육지 파셀의 **옆면**뿐이다. 그
 * 옆면이 10cm 면 원근상 없는 것과 같아서, 물이 아무리 깊어도 잔디와 수면이 한
 * 평면처럼 읽힌다.
 *
 * 그래서 고칠 것은 물 높이가 아니라 **여기**였다.
 *
 * ── 왜 상수를 적지 않고 유도하는가 (검수관 블로커) ─────────────────────────
 * 이 값은 `0.8` 이라는 상수였다. 물이 −0.5m 하나였을 때 "수면보다 30cm 더 깊다" 는
 * 뜻이었고 그때는 맞았다. 그런데 감독이 물을 강 −0.5m / 바다 −1.0m 로 가르면서
 * (`decide/water.ts`) **0.8 이 바다 수면보다 얕아졌다** — 바닷가에서 판 옆면이 수면
 * 위로 20cm 드러난다. 값은 그대로인데 뜻이 바뀌었다.
 *
 * 같은 커밋의 `SEABED_Y` 는 `SEA_Y` 에서 유도해 이 사고를 피했는데 여기만 안 따랐다.
 * 한 diff 안에서 유도 규율이 한쪽만 적용된 것이고, 검수관이 그것을 블로커로 잡았다.
 *
 * ── 기준을 수면에서 **해저**로 옮긴다 (감독 실기기 2026-08-02) ─────────────
 * 감독: *"물속에서 봤을때 이런 모양인데. 벽이 쳐있고 뚫고 못들어가게해야지."*
 *
 * 위 문단이 정한 기준은 **바다 수면**(−1.0)이었다. 물 밖에서 보는 한 그것으로 족했다 —
 * 물가에 틈이 없고 단차가 보인다는 목표를 실제로 달성했다. 그런데 감독이 **물에 빠지는
 * 기능**을 요구하면서(#178) 시점이 수면 아래로 내려갔고, 거기서 보니 이렇다:
 *
 *   판 아랫면  −1.3   ← 수면에서 유도한 값
 *   해저       −3.4   ← `SEABED_Y = SEA_Y − WATER_DEPTH`
 *              ─────
 *              2.1m 가 비어 있다
 *
 * 플레이어는 물에 빠지면 해저에 앉으므로 **눈높이가 정확히 그 틈 한가운데**다. 육지가
 * "떠 있는 얇은 판" 으로 보이고, 그 밑으로 헤엄쳐 들어갈 수 있다.
 *
 * **값이 틀린 것이 아니라 기준이 낮은 시점을 못 보고 있었다.** 이 저장소가 이름 붙인
 * 형태 그대로다 — *"참인 문장에서 성립하지 않는 결론을 뽑는 것: 값이 아니라 재는 축이
 * 틀린다."* "두 수면 아래로 내려간다" 는 내내 참이었고, 물 밖 시점에서만 충분했다.
 *
 * 그래서 **바닥(해저)에서 유도한다.** 해저는 물이 닿는 가장 낮은 자리이므로, 여기를
 * 덮으면 어느 시점에서도 육지 아래가 열리지 않는다.
 *
 *   지면 상면 0 → 강 수면 −0.5      : 감독이 말한 50cm 단차는 그대로 보이고
 *   지면 상면 0 → 바다 수면 −1.0    : 바다 단차도 그대로이며
 *   판 아랫면 −3.7                  : 해저(−3.4)보다 더 내려가 물속에서도 벽이다
 *
 * `WATER_DEPTH` 를 바꾸면 흙벽이 저절로 따라온다. 상수를 다시 적을 자리가 없다.
 *
 * **`SEA_Y` 는 이제 안 읽는다** — `SEABED_Y` 가 이미 그것에서 유도되므로(`water.ts`),
 * 여기서 둘 다 읽으면 같은 사실을 두 경로로 참조하는 셈이다.
 */
export const GROUND_DEPTH = Math.abs(SEABED_Y) + SUBMERGE_MARGIN;

export const ground: PartSpec = {
  kind: 'ground',
  tiers: ['near', 'mid', 'far'], // 지면이 없으면 파셀이 구멍으로 보인다
  salt: 0x9e3779b9,
  // ── `tones` 가 색이었다가 **틴트가 됐다** (포근마을 개조) ────────────────────
  // world2 값은 `[0x6b6659, 0x746f61, 0x625e52]` — 명도 40% 대의 회갈색이고, 그것이
  // 곧 이 파츠의 색이었다. 그 값이 나온 이력은 지우지 않고 옮겨 적는다:
  //
  //   그보다 더 앞선 값은 `0x2a3140` 계열의 짙은 남색이었다. **도로 텍스처 베이스가
  //   `#2a2d33` 이라 명도 차이가 3% 밖에 안 났고**, 그것이 감독이 말한 *"바닥 격자
  //   바닥이 잘 드러나지 않아"* 의 정확한 원인이었다. 정원을 넣은 것은 증상 완화였다 —
  //   초록 판이 검은 바닥에 스티커처럼 떠 있었다. 원인은 지면 자체가 **야간 팔레트**인데
  //   하늘은 낮이라는 것이었고, 그래서 땅을 밝혔다.
  //
  // 마을에서는 그 처방이 **한 걸음 더** 간다. 색을 정점에 굽고(윗면 잔디·옆면 흙)
  // 여기는 곱셈기로 돌린다. 두 가지가 동시에 해결된다:
  //   · 밝기 대비 — 잔디(명도 72%)는 아스팔트(17%)와 비교조차 안 된다
  //   · 물가 단면 — 잔디 땅인데 옆면까지 초록이면 3.7m 짜리 초록 벽이 선다
  //
  // ⚠️ 정점색이 있으므로 **각 채널이 0xd0 이상이어야 한다.** 여기에 잔디색을 적으면
  // 초록 × 초록으로 땅이 새까맣게 죽는다 — world2 가 나무에서 실제로 겪은 형태다.
  //
  // 하늘색(`sky`)·라일락(`lilac`)을 빼고 초록·따뜻한 쪽만 쓴다. 땅은 파셀 수십 칸이
  // 이어 붙는 면이라, 틴트가 색상환을 돌면 잔디가 알록달록해져 한 장의 땅으로 안 읽힌다.
  tones: [TINTS.plain, TINTS.mint, TINTS.butter],

  /**
   * 지면 평면 신고 + **알베도의 원천.**
   *
   * ⚠️ world2 는 여기가 `0xffffff` 였다. `map` 이 없으니 곱해질 것이 흰색이라는 뜻이고,
   * `tones` 가 곧 색이던 시절에는 그것이 맞았다. **지금은 정점색이 색을 준다** —
   * `map` 이든 정점색이든 `tones` 에 곱해지는 것은 마찬가지이므로(`bake.ts` 머리 참조),
   * 알베도의 원천은 흰색이 아니라 **윗면 잔디색**이다.
   *
   * `types.ts` 의 필드 주석은 *"`map` 이 없으면 `0xffffff`"* 라고 적고 있는데, 그 문장은
   * 정점색 파츠가 지면이 되는 경우를 상정하지 않은 것이다. 판정식
   * (`decide/ground-albedo.ts` 의 `groundBase × tones 평균`)은 두 경우를 이미 같은 식으로
   * 덮는다 — 고쳐야 할 것은 식이 아니라 그 산문이다.
   *
   * 옆면(흙)이 아니라 **윗면**을 적는 이유: 이 값이 정하는 것은 밤 조명 배수이고, 밤에
   * 화면을 채우는 것은 위에서 내려다보는 지면이다. 옆면은 물가에서만 보인다.
   *
   * ⚠️ **이 값을 밝히면 `MAX_LIFT` 가 내려간다.** `MAX_LIFT = 1 / max(DAY_ALBEDO)` 이고
   * (알베도가 1을 넘으면 지면이 자체발광처럼 뜬다), 잔디가 가장 밝은 지면 파츠이므로
   * 상한을 여기가 정한다. 실측은 아래 `garden.ts` 쪽 주석과 함께 보고에 적었다 —
   * world2 의 2.4(감독이 화면에서 고른 값)가 마을에서는 상한에 눌린다. **밤이 어두워지는
   * 것이 아니다**: 알베도 자체가 이미 두 배 가까이 밝아서 최종 밝기는 오히려 올라간다.
   * 배수가 작아진 것을 "밤 처방이 약해졌다" 로 읽지 말 것.
   */
  groundBase: V.grass,

  // 바닥에 깔리는 평면 — 그 위에 물건이 서는 것이 정상이라 겹침 개념이 없다.
  footprint: () => 0,

  maxPerParcel: () => 1,

  place: ({ rnd, o }) => [{
    kind: 'ground',
    x: 0, z: 0, y: 0, ry: 0,
    sx: o.cellX, sy: GROUND_DEPTH, sz: o.cellZ,
    tone: Math.floor(rnd() * 3),
  }],

  // 지면만 피벗이 위쪽이다 — 판이 y=0 **아래로** 깔려야 그 위를 걷는다.
  asset: (T) => ({
    geometry: buildGroundGeometry(T),
    material: new T.MeshStandardMaterial({
      // 정점색이 곧 색이다 — `tones` 는 거기 곱해지는 틴트다(위 `tones` 주석).
      vertexColors: true,
      roughness: 0.95,
      // world2 는 0.05 였다. 0 으로 내린다 — 금속성이 조금이라도 있으면 잔디가 얕은
      // 각도에서 젖은 것처럼 번들거리고, 그것이 파스텔 무광 톤에서 가장 먼저 튄다.
      metalness: 0,
    }),
    castShadow: false,
    receiveShadow: true,
  }),
};

// ── 지오메트리 ──────────────────────────────────────────────────────────────
//
// **단위 판: 밑면 1×1, 두께 1, 피벗은 위쪽**(y=0 이 지면 상면, 아래로 −1 까지).
// 인스턴스가 `sx`(셀 크기) · `sy`(`GROUND_DEPTH`) · `sz` 로 늘린다.

/**
 * 잔디층이 판 두께에서 차지하는 비율.
 *
 * 0.1 × `GROUND_DEPTH`(3.7m) = **37cm**. 물가에서 보이는 것이 이 띠이고, 아래로
 * 3.3m 의 흙이 이어진다. 눈높이 1.7m 에서 강 건너를 보면 잔디 띠가 손가락 한 마디쯤으로
 * 읽히는 두께다.
 *
 * 비율로 적는 이유는 늘 같다 — `WATER_DEPTH` 가 바뀌면 판 두께가 따라 움직이는데,
 * 잔디 띠를 절대값(예: 0.37m)으로 박아 두면 그날 비율이 조용히 어긋난다. 스케일이
 * 비균등이라 지오메트리는 비율만 알 수 있다.
 */
const GRASS_CAP = 0.1;

function buildGroundGeometry(T: ThreeNS) {
  const pieces: Piece[] = [];
  const add = (geo: Piece['geo'], color: number) => pieces.push({ geo, color: rgb(color) });

  // 잔디층. 윗면이 y=0 — 여기를 걷는다.
  add(new T.BoxGeometry(1, GRASS_CAP, 1).translate(0, -GRASS_CAP / 2, 0), V.grass);

  // 흙 몸통. 잔디층 바로 아래에 이어 붙인다.
  //
  // 두 박스가 y = −GRASS_CAP 에서 **면끼리 정확히 맞닿는다.** z-파이팅이 아니다 —
  // 맞닿은 두 면은 서로 반대 방향을 보고 있어(잔디 아랫면은 아래, 흙 윗면은 위) 어느
  // 시점에서도 둘 중 하나만 뒷면이라 깊이 경쟁이 일어나지 않는다. 사이를 띄우면 오히려
  // 그 틈으로 배경이 비친다.
  const bodyH = 1 - GRASS_CAP;
  add(
    new T.BoxGeometry(1, bodyH, 1).translate(0, -GRASS_CAP - bodyH / 2, 0),
    V.dirt,
  );

  return bakePieces(T, pieces);
}

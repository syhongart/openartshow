// 길 — 파셀을 잇는 흙·자갈길.
//
// ── 감독 판정: "도로는 저번 것 별로야" / "바둑판 말고" ──────────────────────
// world1 도로가 밋밋한 회색 슬래브로 보인 원인은 색이 아니라 **텍스처 종횡비 왜곡**이었다.
// `applyGroundTex(..., repeat 3, ...)` 가 양축에 같은 repeat 를 걸어 U축 8m/타일 vs
// V축 0.83m/타일 — **압축비 9.6배**다. 밉맵이 그 방향의 디테일을 지워서 무늬가 사라졌다.
//
// 여기서는 repeat 를 쓰지 않는다. 길을 **정사각형 조각**으로 깔고 조각마다 UV 0~1 을
// 그대로 매핑한다. 조각이 정사각형이므로 왜곡이 구조적으로 0이다.
//
// ── 왜 조각열인가 ────────────────────────────────────────────────────────────
// 길 전체를 파셀마다 다른 모양의 메시로 만들면 지오메트리가 파셀 수만큼 생긴다 —
// 개수 불변식이 깨진다. 대신 **똑같은 정사각형 조각 하나**를 인스턴싱해 늘어놓는다.
// 지오 1개 · 재질 1개 · 드로우콜 1개로 어떤 모양의 길이든 만들어진다.
//
// 파셀당 최대 9조각(네 방향 × 2 + 중심), 평균 5.8조각. 조각당 2삼각형이므로 파셀당
// 12삼각형 남짓이다.
//
// ── 포근마을 개조 2026-08-08: 아스팔트 → 흙·자갈길 ──────────────────────────
// 바뀐 것은 **텍스처와 그 바탕색뿐**이다. `place`·`footprint`·`maxPerParcel`·`tiers`·
// `salt` 는 한 줄도 안 건드렸다 — 길의 **모양**(조각열·팔 시작점·겹침 0)은 감독 판정으로
// 두 번 고쳐 얻은 것이고, 룩을 바꾸자고 그것을 흔들면 *"길이 예뻐졌는가"* 와 *"사거리가
// 지글거리지 않는가"* 가 한 diff 에서 갈리지 않는다. 아래 `place` 안의 사고 이력이
// 그대로 유효한 이유이기도 하다.

import type { PartSpec, PlacedPart } from './types.js';
import { roadDirs, ROAD_SEG } from './road-topology.js';
import { isPlaza } from './plaza.js';
import { hexCss } from './color.js';
import { V, TINTS, luma } from './palette.js';

export { GRAIN_R, PEBBLE_R, ROAD_TEX };

/**
 * 흙길 텍스처의 바탕색. hex 로 두는 이유는 밤 알베도 배수가 이 색의 **휘도**를 읽기
 * 때문이다(`decide/ground-albedo.ts`) — 캔버스와 판정에 따로 적으면 한쪽만 고쳐도
 * 아무도 모른다.
 *
 * ── ⚠️ 이 상수가 왜 따로 있나 — 팔레트가 두 번 틀렸다 (2026-08-08) ──────────
 * 처음 `V.dirt` 는 베이지(`0xd8b585`)였고 이름 옆에 *"잔디와 명도가 뚜렷이 갈려야
 * 길이 길로 보인다"* 라고 적혀 있었다. `luma()` 로 실제로 재보면 이랬다:
 *
 *   luma(V.grass)   = 0.7203
 *   luma(구 V.dirt) = 0.7254   ← 차 **0.0051**
 *
 * **선언과 값이 어긋나 있었다.** 이 파일이 그것을 실측으로 잡아 팔레트를 짙은 흙
 * (`0xb08055`)으로 되돌렸고, 베이지는 `V.dirtLight`(마른 결) 자리로 옮겼다.
 * 지금은 `DIRT_BASE = V.dirt` 로 이름과 역할이 맞는다.
 *
 * 초록은 G 가중치(0.7152)가 커서 sRGB 명도가 매우 높다. 채도 높은 잔디와 베이지 흙은
 * **색상만 다르고 밝기는 같다.** 그 조합은 이 저장소가 이미 값을 치른 형태다 — world2 는
 * 지면 19% vs 도로 17% 로 2%p 차라 화면이 통짜 바닥으로 보였고, 감독 판정이 *"바닥 격자
 * 바닥이 잘 드러나지 않아"* 였다. 명도가 같으면 길이 길로 안 읽힌다.
 *
 * 그래서 바탕을 **짙은 흙**으로 내리고, `V.dirt`·`V.dirtLight` 는 그 위에 뿌리는
 * **마른 결**로 돌린다. 바탕 기준 차가 0.2292 로 벌어진다(규약 0.15).
 *
 * ── 왜 반대 방향(밝은 모랫길)이 아닌가 ─────────────────────────────────────
 * 잔디보다 **밝은** 길도 후보였고, 파스텔 통일감에는 그쪽이 더 맞다. 두 이유로 접었다:
 *
 *   ① 팔레트에서 0.15 를 넘기는 밝은 색은 `V.sand`(0.8765, 차 0.1562) 하나뿐이고
 *      여유가 0.0062 다. 잔디를 한 톤만 밝혀도 규약이 깨진다.
 *   ② **밤 처방이 죽는다.** `decide/ground-albedo.ts` 의 `MAX_LIFT` 는 *가장 밝은* 지면
 *      파츠가 정한다 — 길이 잔디만큼 밝아지면 밤 알베도 배수 상한이 함께 내려앉고,
 *      감독이 화면에서 고른 2.4(`NIGHT_GROUND_LIFT`)가 상한에 눌린다. 짙은 흙길은 선형
 *      휘도 0.235 로 잔디(0.513)보다 낮아 그 축을 아예 건드리지 않는다.
 *
 * ── 한때 `V.trunk` 를 빌려 썼다 (해소됨) ──────────────────────────────────
 * 팔레트에 "짙은 흙" 역할이 없던 동안 나무 줄기 색을 전용했다. 화면으로는 맞지만
 * **역할 이름이 달라서** 나무 담당이 줄기를 붉게 바꾸면 길이 함께 바뀌는 상태였다.
 * `V.dirt` 를 짙은 흙으로 되돌리면서 그 빌림이 사라졌다 — 기록으로만 남긴다.
 */
export const DIRT_BASE = V.dirt;

export const road: PartSpec = {
  kind: 'road',
  // far 까지 그린다. 멀리서 길이 이어져 보이는 것이 "마을 안에 있다"는 인상의 대부분이고,
  // 조각당 2삼각형이라 far 까지 넣어도 삼각형 예산에 거의 영향이 없다.
  tiers: ['near', 'mid', 'far'],
  salt: 0x6c8e9cf5,

  // ⚠️ **텍스처가 있는 파츠의 `tones` 는 색이 아니라 곱셈기다.**
  //
  // `instanceColor` 는 프래그먼트에서 `diffuseColor *= instanceColor` 로 적용된다.
  // 텍스처가 없는 파츠는 곱해질 것이 흰색이라 `tones` 가 그대로 색이 되지만, 길은
  // 흙 텍스처와 **곱해진다.**
  //
  // world2 에서 다른 파츠와 같은 방식으로 어두운 회색 두 개(`0x23262b`/`0x25282d`)를
  // 골랐다. 그 값은 텍스처 베이스(`#2a2d33`)와 곱해져 최종 알베도가 선형 0.0003 대 —
  // 표시색으로 RGB(6,6,7) 안팎, 사실상 **완전한 검정**이 됐다. 디자이너가 fog 를 끄고
  // 그림자를 꺼도 암전이 그대로인 것으로 원인을 좁혀 잡아냈다. 텍스처는 멀쩡했고 곱셈이
  // 문제였다. **흙길로 바꿔도 이 위험은 그대로다** — 오히려 바탕이 아스팔트보다 밝아진
  // 만큼 어두운 톤을 곱하고 싶어지는 유혹이 커진다.
  //
  // 흰색 하나만 둔다. 텍스처가 이미 최종 밝기와 얼룩을 담고 있으므로 곱셈 항등원이 맞다.
  // 파셀별 색 변주도 넣지 않는다 — 길은 이어진 하나로 읽혀야 하고, 파셀마다 미세하게
  // 색이 다르면 그 경계가 이음매로 드러난다.
  tones: [TINTS.plain],

  // 지면 평면 신고 + 알베도 원천. 길은 잔디보다 알베도가 낮아 밤 압축의 **기준 아래**에
  // 있고, 그래서 상한(`MAX_LIFT`)을 정하는 쪽이 되지 않는다.
  groundBase: DIRT_BASE,

  // 네 방향 × 조각 2개 + 중심 1개. 중심은 방향이 하나라도 있을 때만 놓으므로 실제
  // 최댓값은 9다.
  // 네 방향 × 2 + 중심 1. 광장은 중심이 빠져 최대 8 이지만, 상한은 최악치로 잡는다.
  // 길은 평면이고, 길 위에 서면 안 되는 것은 `onRoad` 가 이미 막는다.
  footprint: () => 0,

  maxPerParcel: () => 9,

  // 난수를 쓰지 않는다. 길의 모양은 경계 해시가 정하고, 색은 텍스처가 정한다.
  place: ({ px, pz, o }) => {
    const dirs = roadDirs(px, pz);
    if (dirs.length === 0) return [];

    const tone = 0;
    const out: PlacedPart[] = [];
    // 지면(두께 0.1, 피벗 위쪽)보다 아주 살짝 위. 같은 높이면 z-fighting 으로 지글거린다.
    // 정원(0.07) 위. 예전 0.06 은 정원(0.03)과 3cm 차이라 먼 거리에서 깊이가
    // 뭉갤 수 있었다. 14cm 로 벌린다 — 계단으로 보이지 않으면서 확실히 앞이다.
    const y = 0.14;

    /** 폭 `ROAD_SEG` 고정, 길이만 다르다. 회전은 인스턴스가 하므로 로컬 축으로 적는다 */
    const seg = (x: number, z: number, ry: number, len: number) => {
      out.push({ kind: 'road', x, z, y, ry, sx: ROAD_SEG, sy: 1, sz: len, tone });
    };

    // 중심 — 막다른 길이어도 길머리는 있어야 한다. 다만 **광장에서는 비운다**:
    // 그 자리에 분수대나 종탑이 선다. 팔은 그대로 남으므로 길은 광장 둘레를 도는
    // 로터리처럼 읽힌다.
    if (!isPlaza(px, pz)) seg(0, 0, 0, ROAD_SEG);

    // ── 팔은 중심 조각 **밖에서** 시작한다 (감독 판정) ────────────────────────
    // 감독: *"길이 겹쳐지는 곳. 사거리? 시선을 밑을 보고 미세하게 움직이면 거기는 왜
    // 텍스처가 울어."*
    //
    // 예전 공식은 `t = i × SEG − SEG/2` 라 첫 조각이 z ∈ [−8, 0] 이었다. 중심 조각이
    // [−4, 4] 이므로 **[−4, 0] 4m 가 겹친다.** 네 방향이 다 그러니 사거리 한복판은
    // 판이 다섯 장 포개지고, 같은 높이(y=0.06)의 두 면이 겹치면 어느 쪽이 앞인지
    // 깊이값이 못 정해 **화면이 지글거린다**(z-fighting). 얕은 각도에서 특히 심하다 —
    // 감독이 "밑을 보고 미세하게 움직이면" 이라 한 조건이 정확히 그것이다.
    //
    // 중심 반폭(4m)부터 **파셀 변**까지를 조각 둘로 나눈다. 겹침이 0이 된다.
    //
    // `halfX`(배치용 반경)가 아니라 `o.cellX / 2` 인 것에 주의 — `halfX` 는 여백이
    // 적용된 값이라 부품이 이웃 파셀을 침범하지 않게 하는 용도다. 길은 반대로 **변까지
    // 정확히 닿아야** 옆 파셀의 길과 이어진다. 여백만큼 물러나면 파셀마다 길이 끊긴다.
    const armStart = ROAD_SEG / 2;
    const armLen = (o.cellX / 2 - armStart) / 2;
    for (const d of dirs) {
      for (let i = 1; i <= 2; i++) {
        // 조각 중심 = 시작 + (i − 0.5) × 길이. 피벗이 조각 한가운데다.
        const t = armStart + (i - 0.5) * armLen;
        if (d === 'north') seg(0, -t, 0, armLen);
        else if (d === 'south') seg(0, t, 0, armLen);
        else if (d === 'west') seg(-t, 0, Math.PI / 2, armLen);
        else seg(t, 0, Math.PI / 2, armLen);
      }
    }
    return out;
  },

  asset: (T) => {
    // 평면을 눕힌다. `rotateX(-90°)` 로 지오메트리 자체를 돌려두면 인스턴스 회전(ry)을
    // Y축 회전으로 그대로 쓸 수 있다 — 배치가 회전을 한 축으로만 다루게 하려는 것이다.
    const geometry = new T.PlaneGeometry(1, 1).rotateX(-Math.PI / 2);

    return {
      geometry,
      material: new T.MeshStandardMaterial({
        map: dirtRoadTexture(T),
        // 0.95 → 0.98. 아스팔트는 젖으면 반들거리지만 마른 흙은 거의 완전 무광이다.
        // 이 0.03 이 화면을 바꾸지는 않는다 — 흙길이 아스팔트의 반사 특성을 물려받은 채로
        // 남지 않게 **의미를 맞춰 두는** 쪽이다.
        roughness: 0.98,
        metalness: 0.0,
      }),
      castShadow: false,
      // 길이 그림자를 받아야 집이 땅에 붙어 보인다.
      receiveShadow: true,
    };
  },
};

/**
 * 흙길 텍스처. **자기완결 원칙**대로 외부 이미지를 쓰지 않고 캔버스로 굽는다.
 *
 * 방향성 있는 무늬(바퀴자국·차선 등)를 넣지 않는다. 조각이 네 방향으로 깔리는데 무늬에
 * 방향이 있으면 교차로에서 어긋나고, 그걸 맞추려면 조각 종류를 늘려야 한다(= 개수
 * 불변식과 부딪힌다). 무방향 거친 면이면 어느 방향으로 놓아도 이어져 보인다.
 *
 * 조각 경계가 드러나지 않게 **가장자리를 어둡게 하지 않는다** — 조각마다 테두리가 지면
 * 길이 타일 바닥처럼 보인다. 마을 흙길이라 "잔디와 맞닿는 가장자리를 흐리게" 하고 싶어
 * 지는데, 그것이 정확히 이 함정이다.
 *
 * ── 덧그림이 명도를 얼마나 올리는가 (해석 근사) ────────────────────────────
 * 바탕만 어둡게 잡아 놓고 그 위에 밝은 결을 잔뜩 뿌리면 **화면 평균은 바탕이 아니다.**
 * 대비 규약은 바탕색(`groundBase`)으로 판정되므로, 덧그림이 규약을 몰래 무효화할 수
 * 있다. 알파·면적으로 유효 커버율을 계산해 둔다:
 *
 *   마른 결      V.dirtLight(0.7254) 유효 5.1%  → +0.0112
 *   젖은흙 얼룩  V.metal(0.3469)     유효 3.0%  → −0.0048
 *   잔모래       V.sand(0.8765)      유효 6.9%  → +0.0256
 *   자갈         stone/seam(0.789)   유효 3.1%  → +0.0088
 *   ─────────────────────────────────────────────────────
 *   합계                                        → +0.0409
 *
 *   바탕 0.5055 → 화면 평균 ≈ 0.5463 · 잔디 0.7203 대비 **0.174** (규약 0.15)
 *
 * ⚠ 이 표는 팔레트가 `V.dirt` 를 짙은 흙으로 되돌린 뒤 **다시 계산한 값**이다. 처음
 * 표는 바탕이 `V.trunk`(0.4912)이고 결이 한 단계씩 어두운 색이라 합계가 +0.0381 이었다.
 * 색을 옮기면 이 표도 함께 옮겨야 한다 — 안 그러면 근거만 남고 값은 딴 것을 가리킨다.
 *
 * ⚠ **재지 않고 계산한 값이다.** jsdom 에 네이티브 캔버스가 없어 실제 텍셀 평균은 이
 * 환경에서 못 잰다(`decide/ground-albedo.ts` 가 같은 한계를 같은 이유로 적어 뒀다).
 * 어두운 얼룩을 일부러 섞어 둔 것이 이 계산의 결론이다 — 밝은 결만 뿌렸다면 상승이
 * +0.042 였고 여유가 그만큼 얇아진다.
 */

/**
 * 잔모래 알갱이의 최소 반경(픽셀). **밉맵에서 살아남을 크기다.**
 *
 * 0.7 이었다. 반경 0.7px 은 지름 1.4px 이라 첫 밉에서 0.7px 이 되고 두 번째에서
 * 사라진다 — 카메라가 조금만 움직여도 밉 레벨이 오가며 알갱이가 나타났다 사라졌다
 * 한다. 그게 감독이 말한 "우는" 것이다. 정원 잔디와 같은 원인이고 같은 처방이다.
 *
 * 이 파일의 주석은 예전에 "멀어지면 밉맵이 평균 내버려 다시 단색이 된다" 고 적고
 * 있었다. 평균으로 **수렴하는** 것은 맞는데, 수렴하기 전 몇 단계에서 출렁인다는 것을
 * 못 봤다.
 *
 * 흙길이 되면서도 이 값은 그대로다 — 근거가 재질이 아니라 **밉맵 체인**이라서다.
 */
const GRAIN_R = 1.6;
const GRAIN_COUNT = 1300;

/**
 * 자갈 반경(픽셀). **아스팔트에는 없던 층이다.**
 *
 * 마을 길을 흙길로 읽히게 하는 것은 바탕색이 아니라 이 알갱이다 — 색만 갈색으로 바꾼
 * 평면은 "갈색 아스팔트" 로 보인다. 잔모래(`GRAIN_R`)는 밉맵 생존이 목적이라 작고
 * 옅어서 자갈 노릇을 못 한다.
 *
 * 2.6px 인 것도 같은 밉맵 논리다: 첫 밉 1.3px · 둘째 0.65px 로 **두 단계**를 버틴다.
 * 잔모래(1.6)보다 한 단계 더 살아남아, 멀어질수록 잔모래가 먼저 뭉개지고 자갈만 남는
 * 자연스러운 감쇠가 된다. 더 키우면 256px 타일 안에서 반복이 눈에 띈다.
 */
const PEBBLE_R = 2.6;
const PEBBLE_COUNT = 160;

const ROAD_TEX = 256;

function dirtRoadTexture(T: typeof import('three/webgpu')): InstanceType<typeof import('three/webgpu')['CanvasTexture']> {
  const S = ROAD_TEX;
  const cv = document.createElement('canvas');
  cv.width = cv.height = S;
  const g = cv.getContext('2d')!;

  // 색은 위 `DIRT_BASE` 하나. 여기서는 CSS 로 되돌려 칠하기만 한다.
  g.fillStyle = hexCss(DIRT_BASE);
  g.fillRect(0, 0, S, S);

  /**
   * 부드러운 얼룩 하나. 알파는 `globalAlpha` 로 준다 — 팔레트 색을 rgba 문자열로 다시
   * 쓰면 그 자리가 곧 색 리터럴이 되고, 팔레트를 고쳐도 안 따라온다.
   */
  const blot = (color: number, alpha: number, rMin: number, rMax: number) => {
    const x = Math.random() * S;
    const y = Math.random() * S;
    const r = rMin + Math.random() * (rMax - rMin);
    const grad = g.createRadialGradient(x, y, 0, x, y, r);
    grad.addColorStop(0, hexCss(color));
    grad.addColorStop(1, 'rgba(0,0,0,0)');
    g.globalAlpha = alpha;
    g.fillStyle = grad;
    g.fillRect(x - r, y - r, r * 2, r * 2);
    g.globalAlpha = 1;
  };

  // 마른 흙이 뜬 자리 — 길에서 사람이 자주 밟아 색이 바랜 부분. 이게 없으면 알갱이만
  // 남아 균일한 갈색으로 읽힌다(아스팔트 때 "얼룩" 이 하던 일과 같은 역할이다).
  // ⚠️ `V.dirt` 를 쓰면 안 된다 — 그건 이제 **바탕색 자신**이다(`DIRT_BASE`).
  // 바탕과 같은 색으로 얼룩을 찍으면 아무것도 안 그린 것과 같고, 증상은 "길이 밋밋
  // 하다" 로만 나타나 원인을 짚기 어렵다. 밝은 결은 `dirtLight` 다.
  for (let i = 0; i < 10; i++) blot(V.dirtLight, 0.22, 16, 60);
  // 그늘지고 축축한 자리. **밝은 결만 뿌리면 평균이 올라 대비 규약이 몰래 무너진다** —
  // 위 표의 −0.0043 이 이 루프다.
  for (let i = 0; i < 8; i++) blot(V.metal, 0.16, 16, 60);

  // 잔모래. 크기와 밝기를 섞어 균일한 노이즈로 보이지 않게 한다 — 한 종류만 뿌리면
  // 사포처럼 보인다.
  // 마른 결(`dirtLight`)보다 한 단계 더 밝은 `sand` 다. 둘을 같은 색으로 두면
  // 얼룩과 알갱이가 한 층으로 뭉쳐 결의 깊이가 사라진다.
  g.fillStyle = hexCss(V.sand);
  for (let i = 0; i < GRAIN_COUNT; i++) {
    const x = Math.random() * S;
    const z = Math.random() * S;
    const r = Math.random() < 0.15 ? GRAIN_R * 2 : GRAIN_R;
    // 불투명도 상한을 낮춰 둔다(아스팔트 때 0.75 → 0.45 로 내린 그 판단이다).
    // 출렁임의 **진폭**을 줄이는 쪽이다 — 대비가 낮으면 밉 레벨이 바뀌어도 눈에 덜 띈다.
    g.globalAlpha = 0.18 + Math.random() * 0.24;
    g.beginPath();
    g.arc(x, z, r, 0, Math.PI * 2);
    g.fill();
  }
  g.globalAlpha = 1;

  // 자갈. 두 색을 섞어 뿌린다 — 한 색이면 흰 점이 규칙적으로 박힌 것처럼 보인다.
  for (let i = 0; i < PEBBLE_COUNT; i++) {
    const x = Math.random() * S;
    const z = Math.random() * S;
    const r = PEBBLE_R * (0.8 + Math.random() * 0.7);
    g.fillStyle = hexCss(Math.random() < 0.45 ? V.stone : V.stoneSeam);
    g.globalAlpha = 0.45 + Math.random() * 0.3;
    g.beginPath();
    g.arc(x, z, r, 0, Math.PI * 2);
    g.fill();
  }
  g.globalAlpha = 1;

  const tex = new T.CanvasTexture(cv);
  tex.colorSpace = T.SRGBColorSpace;
  // **16 으로 올렸다.** 4 였을 때 얕은 각도(바닥을 내려다보며 조금씩 움직일 때)에서
  // 텍스처가 지글거렸다 — 그 각도에서는 픽셀 하나가 텍셀 수십 개를 덮는데, 이방성이
  // 낮으면 그 중 몇 개만 골라 쓰므로 프레임마다 다른 텍셀이 뽑힌다.
  // 하드웨어 상한을 넘으면 three 가 알아서 클램프하므로 안전하다.
  tex.anisotropy = 16;
  return tex;
}

/**
 * 잔디와 길의 **명도차**. 규약(0.15)을 코드가 스스로 계산해 둔 자리다.
 *
 * 값을 주석에만 적으면 팔레트가 바뀔 때 주석이 낡는다. 여기서 계산해 두면 `luma` 가
 * 하나뿐인 출처를 읽으므로 저절로 따라온다. **아직 이것을 읽는 게이트는 없다** —
 * `tests/world3-parts-assets.test.ts` 가 생기면 이 값을 단언 대상으로 쓰면 된다.
 * 그전까지 이 상수는 보증이 아니라 **기록**이다(못 잰 것을 통과로 적지 않는다).
 */
export const GRASS_ROAD_CONTRAST = luma(V.grass) - luma(DIRT_BASE);

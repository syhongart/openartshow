// 분수대 — 광장 한가운데.
//
// 감독 지시: *"가운데. 분수대있고 시계탑있고."*
//
// ── 지오메트리 하나로 만든다 ─────────────────────────────────────────────────
// 수반과 중앙 기둥을 따로 만들어 합치는 게 자연스러운 접근인데, **병합을 못 쓴다.**
// `utils/BufferGeometryUtils.js` 가 `'three'`(WebGL 빌드)를 import 하는데 world2 는
// `'three/webgpu'` 라, 섞으면 두 빌드의 `BufferGeometry` 가 달라져 렌더러가 처리하지
// 못할 수 있다.
//
// 대신 `LatheGeometry` 를 쓴다. 분수대는 **회전체**라 옆면 프로파일 하나를 축 둘레로
// 돌리면 수반도 기둥도 한 번에 나온다. 병합이 필요 없고 파츠 계약도 그대로다.
//
// ── 광장 분수 → 낮고 둥근 마을 분수 (2026-08-08 포근마을 개조) ──────────────
// `place`·`footprint`·`maxPerParcel`·`tiers`·`salt` 은 한 줄도 안 건드렸다. 분수는
// 파셀 **중앙 고정**이라 자리를 양보할 수 없고(`parts/index.ts` 의 목록 순서), 최대
// 반경은 스폰 안전 거리의 근거다(`FOUNTAIN_R`).
//
// ── 왜 이제 `bakePieces` 를 함께 쓰는가 — **물이 보여야 해서다** ─────────────
// world2 는 `LatheGeometry` **하나**에 재질 하나였고, 그래서 `tones` 가 곧 색이었다
// (돌 회색 셋). 회전체 하나로는 수반 안쪽만 다른 색으로 칠할 방법이 없다 — 정점색은
// 조각 단위이고 `instanceColor` 는 인스턴스 단위라 한 물건 안에서 두 색을 못 쓴다.
// 그 제약 때문에 world2 분수에는 **물이 아예 없었다.** 파인 수반만 있고 담긴 것이
// 없으니 멀리서는 돌 화분으로 읽혔다.
//
// 회전체를 **버리지는 않았다.** 돌붙이는 여전히 Lathe 둘이고(수반·기둥), 거기에 물
// 조각 셋을 얹어 `bakePieces` 로 굽는다. 지오 1 · 재질 1 은 그대로다.
//
// ⚠️ **밤에 물이 밝아지지 않을 것** (팀장 조건). 이 재질에는 `emissive` 도
// `emissiveMap` 도 없고 `transparent` 도 없다 — 물은 정점색만으로 표현한다. 물이
// 밤에 뜨는 경로는 발광과 반사 둘인데, 발광은 안 쓰고 반사는 `roughness` 0.8 을
// 그대로 둬서 막는다(아래 `asset` 주석).

import type { PartSpec, PlacedPart, ThreeNS } from './types.js';
import { plazaLandmark } from './plaza.js';
import { bakePieces, rgb, type Piece } from './bake.js';
import { V, TINTS } from './palette.js';

/**
 * 밑동 반경(미터). **스폰 안전 거리의 근거다.**
 *
 * 아래 수반 프로파일의 최대 반지름과 같은 값이다. 스폰이 이 안에 들어오면 카메라가
 * 분수대 속에 갇히는데, 이 프로젝트에는 플레이어-메시 충돌이 없어 아무것도 밀어내지
 * 않는다. `tests/world2-grid.test.ts` 가 이 값과 `SPAWN` 의 거리를 비교해 지킨다.
 *
 * 마을 개조에서 수반은 **낮아졌을 뿐 넓어지지 않았다** — 이 값을 건드리면 스폰 판정이
 * 함께 움직이므로 반경은 손대지 않는 쪽으로 형태를 잡았다.
 */
export const FOUNTAIN_R = 2.4;

/**
 * 회전 세그먼트. world2 는 16 이었다.
 *
 * 20 으로 올린 것은 이 개조의 요구가 *"둥글게"* 이기 때문이다. 16 이면 반경 2.4m 짜리
 * 수반에서 한 변이 0.94m 라 가까이서 각이 읽힌다. 20 이면 0.75m 로 내려간다.
 *
 * **삼각형이 아깝지 않은 파츠라서 가능한 선택이다** — 분수는 광장당 하나뿐이고 광장은
 * 평균 115m 간격이라, `mid`(56m) 안에 들어오는 인스턴스가 0~1개다. 가로등(파셀당 4개
 * × `far` 까지)과는 예산 감각이 정반대다.
 */
const SEG = 20;

/**
 * 수반 프로파일. `(반지름, 높이)` 를 아래에서 위로.
 *
 * 축(반지름 0)에서 시작해 축으로 돌아오면 위아래가 막힌 입체가 된다. 중간에 축으로
 * 돌아오지 않으므로 수반 안쪽이 실제로 파여 물을 담은 모양이 나온다.
 *
 * ── world2 에서 무엇이 바뀌었나 ────────────────────────────────────────────
 * 외벽 높이 0.55 → 0.40, 테두리 0.62 → 0.52. **낮고 넓은 쪽으로 갔다.** world2 의
 * 비율(높이 0.62 : 반경 2.4)은 도시 광장 분수라 벽이 서 있는 인상이었는데, 마을에서는
 * 걸터앉을 수 있는 높이로 보이는 편이 맞다. 반경은 `FOUNTAIN_R` 이 스폰 판정을 물고
 * 있어 고정이므로, **낮추는 것만으로 가로세로비를 눕혔다.**
 *
 * 테두리를 2.15 에서 2.28→2.05 두 점으로 늘린 것은 윗면에 폭 0.23m 의 평평한 띠를
 * 만들기 위해서다. world2 는 테두리가 한 점이라 외벽에서 안쪽 벽으로 바로 꺾였고,
 * 그 각이 로우폴리에서 날카롭게 읽혔다.
 */
const BASIN_PROFILE: readonly (readonly [number, number])[] = [
  [0.00, 0.00], // 바닥 중심
  [2.40, 0.00], // 바닥 가장자리 — 이 반지름이 `FOUNTAIN_R`
  [2.40, 0.40], // 외벽
  [2.28, 0.52], // 테두리 바깥 위 — 살짝 안으로 꺾어 모서리를 죽인다
  [2.05, 0.50], // 테두리 안쪽
  [2.05, 0.16], // 수반 안쪽 벽 — 여기까지가 물이 담기는 깊이
  [0.00, 0.12], // 축으로 돌아와 바닥을 막는다
];

/**
 * 중앙 기둥 프로파일. **수반과 별개의 회전체다.**
 *
 * world2 는 수반과 기둥이 한 프로파일로 이어져 있었다. 나누면 둘을 다른 색으로 구울 수
 * 있고(정점색은 조각 단위), 무엇보다 **이음매 정합을 맞출 필요가 없다** — 각자 축에서
 * 시작해 축으로 끝나는 닫힌 입체라, 밑면이 수반 바닥에 파묻혀 보이지 않는다. 두 열린
 * 링을 맞대는 방식이었다면 한쪽 점을 고칠 때마다 다른 쪽을 함께 봐야 했다.
 *
 * 꼭대기는 접시를 **오목하게** 판다(1.38 테두리 → 1.31 바닥). world2 는 접시가 볼록해
 * 물이 얹힐 자리가 없었다. 오목해야 위에도 물 조각을 놓을 수 있다.
 */
const COLUMN_PROFILE: readonly (readonly [number, number])[] = [
  [0.00, 0.12], // 밑 중심 — 수반 바닥에 앉는다
  [0.48, 0.12], // 밑동 가장자리
  [0.44, 0.34], // 밑동에서 좁아진다
  [0.32, 1.02], // 기둥
  [0.40, 1.14], // 상단으로 다시 벌어진다
  [0.74, 1.28], // 접시 바깥 아래
  [0.72, 1.38], // 접시 테두리
  [0.58, 1.35], // 접시 안쪽 — 여기부터 오목
  [0.17, 1.31], // 접시 바닥
  [0.15, 1.45], // 물이 솟는 노즐
  [0.00, 1.47], // 축으로 돌아와 꼭대기를 막는다
];

/** 큰 수면의 반지름. 수반 안쪽 벽(2.05)보다 안쪽이어야 z-파이팅이 안 난다 */
const WATER_R = 2.02;
/** 큰 수면의 높이. 수반 안쪽 벽 구간(0.16~0.50) 안이라 물이 담긴 것으로 보인다 */
const WATER_Y = 0.36;

export const fountain: PartSpec = {
  kind: 'fountain',
  // mid 까지 그린다(56m).
  //
  // 처음에 near 전용(41.6m)으로 뒀다가 감독이 **"광장 안 보여"** 로 잡았다. 광장은 평균
  // 115m 간격인데 랜드마크 가시 반경이 41.6m 라, 서 있는 자리에서 보일 확률이 11.5% 였다 —
  // 열 번에 아홉 번은 없었다. 디자이너가 "안개(60.8m)의 두 배 거리면 다가가야 드러난다"
  // 는 근거로 간격을 정했는데, 내가 가시 반경을 그 절반 아래로 잡아 리듬 자체를 깼다.
  //
  // 분수대는 높이 1.7m 라 far(76.8m)에서는 어차피 몇 픽셀이다. 안개 경계에서 보이면 된다.
  //
  // 마을 개조로 1.7 → 1.82m 가 됐다(수반은 낮아졌지만 솟는 물방울이 위로 더 갔다).
  // **그래도 `tiers` 는 그대로다** — 12cm 는 위 판정을 뒤집는 크기가 아니고, 이 줄은
  // 슬롯 예산의 근거라 룩 때문에 건드리면 다른 파츠의 자리가 함께 움직인다.
  tiers: ['near', 'mid'],
  salt: 0x1f2e3d4c,
  /**
   * **곱셈기다 — 색이 아니다.** 돌과 물의 색은 정점에 굽혀 있고(`asset`), 여기 값은
   * 거기에 곱해지는 광장마다의 옅은 색조 편차다.
   *
   * world2 는 여기에 돌 회색 셋(`0x8d8577` 계열)을 적었고 그것이 곧 색이었다 —
   * 재질에 `map` 도 정점색도 없어 곱해질 것이 흰색이었기 때문이다. 정점색을 도입한
   * 지금 그 값을 그대로 두면 **회색 × 크림돌** 이 되어 분수만 탁하게 가라앉는다.
   * 나무가 초록 × 초록으로 새까맣게 죽은 것과 같은 형태이고,
   * `tests/world2-parts-assets.test.ts` 가 그 사고를 검사로 남겨 두었다.
   *
   * `place` 가 인덱스 0·1·2 를 쓰므로 **길이 3 을 유지해야 한다.**
   */
  tones: [TINTS.plain, TINTS.blush, TINTS.sky],

  // 광장당 하나. 광장이 아닌 파셀은 0개다.
  // `PROFILE` 최대 반경 2.4 에 물받이 테두리 여유를 얹는다.
  footprint: () => 2.7,

  maxPerParcel: () => 1,

  place: ({ px, pz }) => {
    if (plazaLandmark(px, pz) !== 'fountain') return [];
    const out: PlacedPart[] = [{
      kind: 'fountain',
      // 정확히 파셀 중심. 도로는 광장에서 중심 조각을 비워 자리를 내준다.
      x: 0, z: 0, y: 0, ry: 0,
      sx: 1, sy: 1, sz: 1,
      // 색만 파셀마다 다르다. 크기·회전을 흔들면 광장이 제각각으로 보인다 —
      // 랜드마크는 반복돼야 랜드마크다.
      tone: (px * 7 + pz * 13) & 3 ? ((px + pz) & 1) : 2,
    }];
    return out;
  },

  asset: (T) => ({
    geometry: buildFountain(T),
    // 정점색이 곧 색이다 — `tones` 는 거기 곱해지는 틴트다(위 `tones` 주석).
    //
    // **`roughness` 를 world2 값(0.8) 그대로 둔다.** 물을 매끈하게 보이려면 내리는 것이
    // 자연스러운 수순인데, 재질이 하나뿐이라 그 변경이 돌에도 함께 걸린다. 게다가
    // 거칠기를 내리면 반사가 세지고, 그것은 팀장 조건 *"밤에 물이 밝아지지 않을 것"* 이
    // 막으려는 바로 그 경로다. 헤드리스(swiftshader)로는 밤 반사를 판정할 수 없으므로
    // **못 재는 값을 건드리지 않는 쪽**을 골랐다. 물의 존재감은 거칠기가 아니라 색
    // 대비(`waterDeep` 대 `stone`)로 만든다.
    material: new T.MeshStandardMaterial({ vertexColors: true, roughness: 0.8, metalness: 0.05 }),
    castShadow: true,
    receiveShadow: true,
  }),
};

/** 수반 — 포장 돌 크림. 마을 광장 바닥과 같은 재료로 읽히게 한다 */
const STONE = rgb(V.stone);
/** 기둥·접시 — 줄눈색. 수반보다 한 단 짙어야 중앙 조형이 앞으로 나온다 */
const STONE_DEEP = rgb(V.stoneSeam);
/** 큰 수면 — 깊은 물. 수반이 깊으니 짙은 쪽을 쓴다 */
const WATER_DEEP = rgb(V.waterDeep);
/** 얕은 물 — 상단 접시와 솟는 물방울. 같은 물이라도 얕으면 밝다 */
const WATER = rgb(V.water);

/**
 * 마을 분수 — 조각 다섯.
 *
 *   수반    Lathe(BASIN_PROFILE, SEG)      낮고 넓은 돌 대야
 *   기둥    Lathe(COLUMN_PROFILE, SEG)     밑동·기둥·오목한 접시가 한 회전체
 *   큰 수면  Circle(WATER_R, SEG)           **world2 에 없던 것** — 물이 담겨 보인다
 *   윗 수면  Circle(0.55, SEG)              접시에 고인 얕은 물
 *   물방울   Sphere(0.20, 8, 6)             노즐에서 솟는 덩어리
 *
 * ── 물을 원기둥이 아니라 **원판**으로 놓는 이유 ────────────────────────────
 * 수면은 위에서만 보인다. 물통을 만들면 옆면이 수반 안쪽 벽과 겹쳐 z-파이팅이 나고,
 * 삼각형도 배로 든다. 원판 하나면 법선이 +Y 라 하늘빛을 그대로 받는다.
 *
 * ── 물방울에 `SphereGeometry` 를 쓰는 이유 ─────────────────────────────────
 * 물줄기를 원기둥으로 세우면 정지한 막대가 되어 오히려 물처럼 안 보인다. 이 세계에는
 * 분수 애니메이션이 없으므로(개수 불변식 때문에 파츠는 부팅 때 굳는다) **움직임을
 * 흉내 내지 않고 덩어리로 요약하는 편**이 낫다. 로우폴리 룩에서는 그것이 관용구이기도
 * 하다. 세그먼트를 8×6 으로 낮게 둔 것도 같은 이유 — 매끈한 구는 물방울로 안 읽힌다.
 *
 * ── 삼각형 예산 (실측, 2026-08-08) ─────────────────────────────────────────
 * **320 → 760(2.4배).** 배수는 크지만 인스턴스가 0~1개라 절대량이 무의미한 자리다
 * (위 `SEG` 주석). 같은 배수를 가로등에서 냈다면 받아들이지 않았다 — 거기는 인스턴스가
 * 100 단위다.
 *
 * 실측: 삼각형 760 · 높이 0 ~ 1.820m · 실루엣 반경 2.400m(= `FOUNTAIN_R`, 스폰
 * 안전거리 근거와 정확히 일치).
 */
function buildFountain(T: ThreeNS) {
  const lathe = (profile: readonly (readonly [number, number])[]) =>
    new T.LatheGeometry(profile.map(([r, y]) => new T.Vector2(r, y)), SEG);
  // `CircleGeometry` 는 XY 평면(법선 +Z)이라 눕혀야 수면이 된다.
  const disc = (r: number, y: number) =>
    new T.CircleGeometry(r, SEG).rotateX(-Math.PI / 2).translate(0, y, 0);

  const pieces: Piece[] = [
    { geo: lathe(BASIN_PROFILE), color: STONE },
    { geo: lathe(COLUMN_PROFILE), color: STONE_DEEP },
    { geo: disc(WATER_R, WATER_Y), color: WATER_DEEP },
    // 접시 안쪽(1.31~1.38) 사이. 테두리보다 낮아야 고인 것으로 보인다.
    { geo: disc(0.55, 1.345), color: WATER },
    // 노즐(1.45)을 물고 올라간다 — 띄우면 공중에 뜬 공이 된다.
    { geo: new T.SphereGeometry(0.20, 8, 6).translate(0, 1.62, 0), color: WATER },
  ];
  return bakePieces(T, pieces);
}

// world10/parts/road-topology.ts — 도로 위상. 순수 함수만.
//
// ── 풀어야 할 문제 ───────────────────────────────────────────────────────────
// 파셀은 **서로를 모른다.** 배치는 `(px,pz)` 만으로 계산되고, 이웃 파셀은 아직 로드되지
// 않았을 수도, 이미 언로드됐을 수도 있다("파라미터가 곧 공간" — 저장하지 않는다).
//
// 그런데 도로는 이어져야 한다. 내 파셀 동쪽 끝에서 길이 나가면 옆 파셀 서쪽 끝에서도
// 길이 들어와야 하고, 안 그러면 세상이 끊긴 길 조각으로 뒤덮인다.
//
// ── 해법: 경계를 파셀이 아니라 **경계 자신의 좌표**로 식별한다 ──────────────
// 두 파셀 사이의 경계를 유일한 좌표로 식별하면, 양쪽이 각자 계산해도 **같은 값**이 나온다.
// 이웃을 조회할 필요가 없다.
//
//   파셀 (px,pz) 의 동쪽 경계 = 파셀 (px+1,pz) 의 서쪽 경계 = `edgeX(px, pz)`
//   파셀 (px,pz) 의 남쪽 경계 = 파셀 (px,pz+1) 의 북쪽 경계 = `edgeZ(px, pz)`
//
// 각 경계가 "길이 지나는가"를 스스로 정하고, 파셀은 자기 네 경계를 물어보기만 한다.
//
// ── 격자로 바꿨다 (감독 지시) ────────────────────────────────────────────────
// *"길을 변경하자. 월드 1처럼 격자로 해주고."*
//
// 예전에는 각 경계가 **확률 0.6 으로 독립 추첨**이었다. 그러면 활성 경계 수가 B(4,0.6)
// 을 따라 막다른 길 15%·사거리 13% 가 섞이는데, 의도는 "바둑판 말고" 였지만 결과는
// 길이 곳곳에서 끊긴 도시였다. 감독이 world1 을 가리킨 것이 이 지점이다 — world1 은
// 파셀마다 남·동 가장자리에 도로 스트립을 그려 **전부 이어진 격자**가 된다.
//
// 이제 경계 판정은 `decide/grid.ts` 가 답한다. 기본은 전부 길이고, **2×2 슈퍼셀이
// 자기 내부 경계 하나를 끄면 두 칸이 한 블록**이 된다 — 감독이 말한 *"칸의 크기는 모두
// 같은 크기가 아니라 조금 달랐으면해. 2개 셀이 한개인것도 있고."* 가 이것이다.
//
// "import 0" 이 깨진 것처럼 보이지만 아니다. `decide/grid.ts` 도 import 0 의 순수 판정
// 파일이고, 격자의 SSOT 를 두 곳에 적지 않으려면 여기가 그것을 **참조해야** 한다.

import { gridEdgeX, gridEdgeZ } from '../decide/grid.js';

/** 파셀 (px,pz) 와 (px+1,pz) 사이 경계에 길이 지나는가 */
export function edgeX(px: number, pz: number): boolean {
  return gridEdgeX(px, pz);
}

/** 파셀 (px,pz) 와 (px,pz+1) 사이 경계에 길이 지나는가 */
export function edgeZ(px: number, pz: number): boolean {
  return gridEdgeZ(px, pz);
}

/** 파셀의 네 방향. 배열 순서가 곧 배치 순서다 */
export type Dir = 'north' | 'south' | 'west' | 'east';
export const DIRS: readonly Dir[] = ['north', 'south', 'west', 'east'];

/**
 * 이 파셀에서 길이 나가는 방향들.
 *
 * 북쪽은 `(px, pz-1)` 과의 경계이므로 `edgeZ(px, pz-1)` 을 본다 — **한 칸 뒤로 물러난
 * 좌표**다. 여기를 `edgeZ(px, pz)` 로 적으면 북쪽과 남쪽이 같은 값을 보게 되고, 길이
 * 항상 남북으로 관통하거나 아예 없는 세상이 된다.
 */
export function roadDirs(px: number, pz: number): Dir[] {
  const out: Dir[] = [];
  if (edgeZ(px, pz - 1)) out.push('north');
  if (edgeZ(px, pz)) out.push('south');
  if (edgeX(px - 1, pz)) out.push('west');
  if (edgeX(px, pz)) out.push('east');
  return out;
}

/**
 * 도로 판 한 조각의 한 변(미터). **눈에 보이는 도로 폭이 곧 이 값이다** — `road.ts` 가
 * 이것을 조각의 `sx` 로 그대로 쓴다.
 *
 * ── 8 에서 줄였다 (감독 지시 2026-07-31 *"길이 너무 넓은것같아"*) ─────────────
 * 8m 는 **차도** 폭이다. 왕복 2차선이 대략 그만큼이고, 그 값을 고를 때 머릿속에 있던
 * 것도 차가 다니는 길이었다. 그런데 **이 세계에는 차가 없다** — 아야모가 걸어 다닌다.
 * 차 없는 8m 는 길이 아니라 빈 광장으로 읽히고, 파셀(32m)의 1/4 을 먹어 사거리 파셀
 * 에서는 넓이의 절반 가까이가 길이 됐다.
 *
 * 5m 는 걷는 길의 폭이다. 아야모 어깨폭이 0.5m 남짓이라 열 명이 나란히 지나가고,
 * 양옆 건물이 그만큼 가까워져 **거리**로 읽힌다.
 */
export const ROAD_SEG = 5;

/**
 * 연석 여유(미터). 그려진 도로 가장자리보다 판정을 조금 넓게 잡는 몫이다.
 *
 * 판정과 그림이 정확히 같으면 도로 가장자리 픽셀에서 "여기가 길인가"가 부동소수 다툼이
 * 되고, 부품이 도로 끝선에 정확히 접해 설 수 있다.
 */
const CURB = 0.5;

/**
 * 도로가 차지하는 반폭(미터). 건물·나무가 이 안에 들어오면 길 위에 서게 된다.
 *
 * **그려진 폭에서 유도한다** — 도로를 넓히거나 좁히면 판정이 저절로 따라온다.
 */
export const ROAD_HALF = ROAD_SEG / 2 + CURB;

/**
 * 인도 폭(미터). 차도 끝과 건물 앞면 사이에 남기는 띠다.
 *
 * 가로등이 이 띠 한가운데 선다(`LAMP_OFFSET`). 그러니 이 값이 0 이면 가로등이 설 자리가
 * 없어지고, 너무 크면 건물이 물러나 거리가 다시 휑해진다.
 */
const SIDEWALK = 3;

/**
 * 건물·나무·가로등이 물러서는 안쪽 경계(미터). **도로 판정(`ROAD_HALF`)보다 넓다.**
 *
 * 둘을 같은 값으로 쓰다가 갈랐다. `ROAD_HALF` 는 "여기가 길인가"를 답하는 값이고,
 * 셋백은 "여기까지는 안 짓는다"는 값이라 역할이 다르다. 같게 두면 건물 벽이 차도 끝에
 * 딱 붙어 서고 인도가 없다 — 디자이너가 "숨 쉴 곳이 없다"고 지적한 지점의 일부다.
 *
 * ── 유도로 바꿨다 (감독 지시 *"하드코딩하지말고"*) ──────────────────────────
 * 예전에는 `7` 을 직접 적고 주석에 *"7.0 = 도로 반폭 4 + 인도 3"* 이라 적었다. 그 유도의
 * "도로 반폭 4" 는 `ROAD_SEG / 2` 였고, **실제 `ROAD_HALF` 는 5.5 였다.** 손으로 적은
 * 값이 손으로 적은 설명과 어긋난 채 오래 있었고, 어긋난 줄 아무도 몰랐다 — 유도를
 * 주석에만 남기면 그렇게 된다.
 */
export const SETBACK = ROAD_HALF + SIDEWALK;

/**
 * 가로등이 서는 자리 — **도로에서 옆으로 비킨 거리.**
 *
 * `lamp.ts` 가 이 값의 주인이었는데, 슬롯 배치가 "여기는 이미 예약됐다"를 알아야 해서
 * 공용 기하인 이 파일로 올렸다. 파츠끼리 직접 import 하면 파츠 하나를 빼는 순간 다른
 * 파츠가 깨지므로, 이 파일이 그 중개를 맡는 것이 원래 규약이다.
 */
export const LAMP_OFFSET = (ROAD_HALF + SETBACK) / 2;

/**
 * 가로등이 비워 둘 반경(미터). `lamp.ts` 의 `footprint` 와 슬롯 예약이 **같은 값**을
 * 써야 하므로 여기 하나만 둔다 — 두 곳에 적으면 한쪽만 고쳐도 아무도 모른다.
 */
export const LAMP_CLEARANCE = 0.9;

/**
 * 건물류가 벽면 밖으로 더 내미는 여유(미터) — 처마·간판 몫.
 *
 * ── 왜 여기로 왔나 (검수관 블로커 2026-08-02 B1) ───────────────────────────
 * 이 값은 `building.ts` 안의 module-private 상수였다. 타워를 만들며 **같은 값을
 * `tower.ts` 에 다시 적었고**, 그 옆 주석에는 "건물과 같은 값을 쓴다 — 배치 한계와
 * 겹침 반경이 같은 값을 봐야 한다" 고 위험까지 정확히 적어 두었다. 위험을 서술하면서
 * 그 위험을 새로 만든 셈이다. 같은 커밋에서 `h2` 해시는 `plaza.ts` 에서 export 해
 * 미러링을 없앴는데 여기만 반대로 갔다.
 *
 * ── 원래의 사고 (`building.ts` 에서 옮겨 온 기록) ──────────────────────────
 * 이 값이 `footprint` 에만 `+ 0.6` 으로 적혀 있고 배치 한계는 반폭만 당겼다. 그래서
 * 건물 중심이 `cellX/2 − half` 까지 갈 수 있는데 겹침 반경은 `half + 0.6` 이라,
 * 이웃 파셀 건물과 **0.6m 씩 마주 뻗어** 최대 0.74m 겹쳤다(13×13 파셀에서 11쌍).
 *
 * 값 미러링의 변종이다 — 같은 값을 두 곳에 적어 어긋난 게 아니라, **두 곳에서 필요한
 * 값을 한 곳에만 적어서** 다른 쪽이 몰랐다. 파셀 겹침 검사는 **파셀 안**만 보므로
 * (41×41 전수로 0) 경계를 넘는 겹침은 볼 지점이 없었다.
 *
 * `SETBACK`·`LAMP_CLEARANCE` 와 같은 자리에 두는 것이 맞다 — 셋 다 "무엇이 얼마나
 * 물러서야 하는가" 를 정하고, 파츠 여럿이 함께 봐야 하는 값이다.
 */
export const EAVE = 0.6;

/**
 * 이 파셀에서 **가로등이 점유하는 자리**. 실제로 가로등을 그리는지와 무관하다.
 *
 * ── 왜 "그리는지와 무관" 이 중요한가 ───────────────────────────────────────
 * 가로등은 `tiers: ['near']` 라 mid 에서는 그려지지 않는다. 다른 파츠가 "놓인 가로등"을
 * 보고 자리를 피하면, **mid 에서는 피할 것이 없어져 위치가 달라진다** — tier 가 바뀔 때
 * 물건이 순간이동한다는 뜻이고, 그건 이 파일이 지키기로 한 불변식 ②의 위반이다.
 *
 * 그래서 자리를 **예약**으로 다룬다. tier 와 무관하게 계산되므로 near 든 mid 든 같은
 * 자리가 비워지고, 가로등이 안 그려지는 거리에서는 그냥 빈 인도로 남는다.
 */
export function lampAnchors(
  o: { cellX: number; cellZ: number },
  dirs: readonly Dir[],
): { x: number; z: number }[] {
  const L = LAMP_OFFSET;
  const out: { x: number; z: number }[] = [];

  // ── 감독 지적 두 건을 **동시에** 만족해야 한다 ─────────────────────────────
  //
  // ① *"가로등은 길 양옆에 가지런히 있어야하는데. 무슨 나무처럼있냐"*
  // ② *"왜 가로등이 2개 한쌍처럼 보이지?"*
  //
  // 둘은 같은 자리에서 충돌한다. 자리를 도로 팔의 중간(`cellX/4`)에 두고 양옆에 세우면
  // ①은 되지만, 교차로 모서리에서 동서용 `(cellX/4, L)` 과 남북용 `(L, cellZ/4)` 이
  // 서로 코앞(`√2 × (cellX/4 − L)`)에 만나 ②가 된다.
  //
  // 그 `cellX/4` 는 못 움직인다 — 그것만이 이웃 파셀과 이어져 등간격이 되는 값이고,
  // `LAMP_OFFSET` 도 `ROAD_HALF` 와 `SETBACK` 사이 인도 폭 안에 갇혀 있다.
  //
  // **수치를 여기 적지 않는다.** 예전 주석은 `8`·`6.25`·`2.47` 을 직접 적고 있었는데
  // 도로 폭을 줄이자(감독 지시) 전부 거짓이 됐다 — 주석의 값 미러링도 값 미러링이다.
  //
  // ── 실패한 처방 둘 (같은 것을 두 번 놓쳤다) ───────────────────────────────
  // (a) 붙은 둘을 **중점으로 합치기** — 그 자리가 셋백을 넘어 인도 밖으로 나갔다.
  //     가로등이 건물 마당에 서는 것은 자리를 옮긴 게 아니라 잃은 것이다.
  // (b) 모서리마다 **주인**을 정해 한 대만 세우기 — 파셀 하나만 보면 그럴듯한데,
  //     이웃까지 이어 보면 x축 도로를 따라 `(−cellX/4, −L) · (cellX/4, +L) · …` 로
  //     **좌우 지그재그**가 된다. ②를 고치려다 ①을 도로 깼다.
  //
  // ── 자리를 옮긴다 — 교차로가 아니라 **블록 중간**으로 ───────────────────────
  // 붙는 원인은 두 도로의 가로등 줄이 교차로 근처에서 만나는 것이다. 그러면 교차로에서
  // 멀어지면 된다. 가장 먼 곳이 **파셀 경계**(`cellX/2`)이고, 거기는 두 도로선의 중간
  // 지점이라 상대 축의 가로등과 `9.75 × √2 = 13.8m` 떨어진다.
  //
  // 파셀은 서로를 모르므로 경계 자리를 양쪽이 만들면 **두 대가 겹친다.** 그래서
  // **+방향 경계만 자기 것**으로 삼는다 — `east` 와 `south` 만 세우고, `west`·`north`
  // 쪽 경계는 그 이웃이 자기 `east`·`south` 로 세운다. 격자 판정이 대칭이므로
  // (`edgeX(px,pz)` 를 양쪽이 같은 좌표로 조회한다) 빠지는 자리가 없다.
  //
  //   동서 도로선   x = 파셀 경계마다  각각 z = ±LAMP_OFFSET  ← 양옆 두 줄, 셀 등간격
  //   교차로 근처는 비어 있다                                 ← 실제 도시가 그렇다
  //
  // 간격이 셀의 절반에서 셀 하나로 늘었다. **줄어든 것이 맞다** — 실제 가로등 간격이
  // 25~40m 라 셀 절반(16m)은 오히려 촘촘했고, 파셀당 최대 4대로 슬롯 예산도 절반이 된다.
  //
  // ── 경계 위에 서도 되는 이유 ──────────────────────────────────────────────
  // 파츠는 반폭 `cellX/2 − margin` 안에서만 자리를 잡으므로, 그 반폭과 경계(`cellX/2`)
  // 사이 띠는 **어느 파셀의 파츠도 들어오지 않는 땅**이다. 가로등은 그 띠 한가운데를
  // `LAMP_CLEARANCE` 만큼 쓰고, 이웃 파셀 파츠는 띠 건너편에 있다. 겹칠 수가 없다.
  if (dirs.includes('east')) {
    out.push({ x: o.cellX / 2, z: L }, { x: o.cellX / 2, z: -L });
  }
  if (dirs.includes('south')) {
    out.push({ x: L, z: o.cellZ / 2 }, { x: -L, z: o.cellZ / 2 });
  }
  return out;
}

/**
 * 파셀 안 좌표 `(x,z)`(중심 기준 오프셋)가 도로 위인가.
 *
 * 도로는 **중심에서 각 활성 방향으로 뻗은 십자**이므로, 그 축들 중 하나에 걸치면 도로다.
 * 방향이 하나도 없으면 이 파셀에 길이 없고, 그때는 어디든 지을 수 있다.
 *
 * 건물·나무·가로등이 이 함수를 보고 자리를 피한다. **파츠끼리 직접 참조하지 않는다** —
 * 서로를 import 하기 시작하면 파츠 하나를 빼는 순간 다른 파츠가 깨진다. 공용 판정을
 * 여기 두고 양쪽이 이것만 본다.
 */
export function onRoad(x: number, z: number, dirs: readonly Dir[]): boolean {
  if (dirs.length === 0) return false;
  // 중심 교차 패치 — 방향이 하나뿐(막다른 길)이어도 중심에는 길이 있다
  if (Math.abs(x) <= ROAD_HALF && Math.abs(z) <= ROAD_HALF) return true;
  for (const d of dirs) {
    if (d === 'north' && z < 0 && Math.abs(x) <= ROAD_HALF) return true;
    if (d === 'south' && z > 0 && Math.abs(x) <= ROAD_HALF) return true;
    if (d === 'west' && x < 0 && Math.abs(z) <= ROAD_HALF) return true;
    if (d === 'east' && x > 0 && Math.abs(z) <= ROAD_HALF) return true;
  }
  return false;
}

/**
 * 도로를 피해 자리를 고른다. **언제나 성공한다.**
 *
 * ── 왜 재시도 방식을 버렸나 ────────────────────────────────────────────────
 * 처음에는 "아무 데나 뽑고 도로면 다시 뽑기"를 네 번까지 하고 실패하면 그 부품을 건너뛰게
 * 했다. 실측에서 **건물이 1채인 파셀이 나왔다** — 사거리 파셀은 십자 도로가 넓이의 57% 를
 * 먹어서 네 번으로 모자란다. 시도를 늘려도 확률만 줄지 0이 되지 않고, 늘린 만큼 난수
 * 소비도 늘어 배치가 통째로 바뀐다.
 *
 * 대신 **도로가 아닌 영역에서 바로 뽑는다.** 도로는 중심에서 뻗은 십자이므로 그 여집합은
 * 네 사분면이고, 사분면 하나를 골라 그 안에서 균등 표집하면 재시도가 필요 없다.
 * 난수 소비도 항상 3개로 고정이다(사분면 · x · z).
 *
 * 길이 없는 파셀(2.6%)은 사분면으로 자르지 않는다 — 그러면 멀쩡한 땅 한가운데가 늘 비어
 * 도넛처럼 보인다.
 */
export function pickOffRoad(
  rnd: () => number,
  halfX: number,
  halfZ: number,
  dirs: readonly Dir[],
): { x: number; z: number } {
  const q = Math.floor(rnd() * 4);
  return pickInQuadrant(rnd, halfX, halfZ, dirs, q);
}

/**
 * 사분면을 **지정해서** 자리를 고른다. 난수는 두 개만 쓴다(x·z).
 *
 * 건물이 이걸 쓴다. `pickOffRoad` 는 사분면을 무작위로 고르므로 두 채가 같은 사분면에
 * 배정될 수 있고, 사분면 폭이 6.5m 인데 건물 폭이 3~8m 라 **겹친다.** 디자이너가
 * "붙어 선다"의 실체로 지목한 지점이다.
 *
 * 채수를 4 이하로 제한하고 사분면을 1:1로 나눠 주면 겹침이 **구조적으로** 사라진다 —
 * 충돌 판정도, 재시도도 필요 없다.
 *
 * 길이 없는 파셀은 안쪽 경계를 두지 않는다(사분면으로 나누기만 한다). 비켜설 도로가
 * 없는데 가운데를 비우면 땅이 도넛처럼 보인다.
 */
export function pickInQuadrant(
  rnd: () => number,
  halfX: number,
  halfZ: number,
  dirs: readonly Dir[],
  quad: number,
  /**
   * 사분면 안쪽 경계의 **하한**. 호출자가 자기 부품의 최대 반폭을 넘긴다.
   *
   * 길 없는 파셀에는 비켜설 도로가 없어 안쪽 경계가 0인데, 그러면 인접 사분면의 두
   * 부품이 중심선 근처에서 만나 **겹친다**(1024 파셀 표본에서 실제로 4건 나왔다).
   * 중심 거리가 `2 × inset` 이므로 `inset ≥ 최대 반폭` 이면 겹침이 사라진다.
   */
  minInset = 0,
): { x: number; z: number } {
  const u = rnd();
  const v = rnd();
  // 파셀이 셋백보다 좁으면(설정을 크게 바꾼 경우) 폭이 음수가 되므로 눌러 준다.
  const inset = dirs.length === 0 ? minInset : Math.max(SETBACK, minInset);
  const x0 = Math.min(inset, halfX);
  const z0 = Math.min(inset, halfZ);
  const sx = quad & 1 ? 1 : -1;
  const sz = quad & 2 ? 1 : -1;
  return {
    x: sx * (x0 + u * (halfX - x0)),
    z: sz * (z0 + v * (halfZ - z0)),
  };
}

/**
 * 사분면 0~3 을 섞어 돌려준다. 난수 3개 고정(Fisher-Yates 4원소).
 *
 * 건물을 사분면에 1:1로 나눌 때 쓴다. 섞지 않으면 첫 건물이 늘 같은 사분면에 서서
 * 도시 전체가 한쪽으로 쏠린 규칙성을 띤다.
 */
export function shuffledQuadrants(rnd: () => number): number[] {
  const q = [0, 1, 2, 3];
  for (let i = 3; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    const t = q[i]; q[i] = q[j]; q[j] = t;
  }
  return q;
}

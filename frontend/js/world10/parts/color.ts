// 파츠 색의 표현 — 캔버스가 문자열을 받고 판정은 숫자를 읽는다.
//
// 텍스처 바탕색은 원래 `'hsl(102, 34%, 52%)'`·`'#2a2d33'` 처럼 CSS 문자열로 박혀 있었다.
// 그런데 밤 알베도 배수를 **그 색의 휘도에서 유도**하게 되면서(`decide/ground-albedo.ts`)
// 판정 쪽이 같은 색을 숫자로 알아야 했다. 두 곳에 적으면 한쪽만 고쳐도 아무도 모른다 —
// 이 저장소가 색·수치·임계값에서 세 번 겪은 사고다.
//
// 그래서 **원천은 hex 숫자 하나**로 두고, 캔버스에 칠할 때만 문자열로 되돌린다.

/** hex → `#rrggbb`. 앞자리 0 을 채우지 않으면 색이 통째로 어긋난다 */
export function hexCss(hex: number): string {
  return `#${(hex & 0xffffff).toString(16).padStart(6, '0')}`;
}

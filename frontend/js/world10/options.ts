// world10/options.ts — **두 페이지의 계약.** `world7-boot`·`world8-boot` 가 읽는다.
//
// 조립부(`main.ts`)가 아니라 여기 있는 이유: 이것은 **트리 안의 구현 사항이 아니라
// 트리와 페이지 사이의 경계**다. 부트 파일이 무엇을 넘겨야 하는지가 한 곳에 있어야
// 다음 사람이 「이 트리를 쓰려면 무엇이 필요한가」를 파일 하나로 읽는다.
//
/**
 * **두 페이지가 갈리는 유일한 자리다.**
 *
 * ── ⚠ 경계 (팀장 조건 3, 2026-08-26) ────────────────────────────────────────
 * `world7.html` 과 `world8.html` 은 **같은 트리를 쓴다.** 세계·기능·조작이 전부 같고
 * 다른 것은 「GLB 를 어디서 얻는가」 하나뿐이라 45,170줄을 복제하지 않기로 했다
 * (world3·world5 는 지오메트리·팔레트·규칙이 다른 세계라 포크가 맞았지만, 여기는
 * **같은 세계가 다른 파일을 여는 것**이다).
 *
 * **world7 만 다르게 할 요구가 생기면 그때 포크한다**(`cp -r frontend/js/world-glb
 * frontend/js/world7`). **이 트리 안에 페이지 분기를 늘리지 마라** — `if (tag === …)`
 * 가 두 곳을 넘는 순간 그것이 포크 시점이고, 그 전에 늘리면 두 페이지가 한 파일 안에서
 * 조용히 갈라진다. 경계도 판정이다.
 */
export interface GlbWorldOptions {
  /**
   * 페이지 정체성. **로그 접두**(`[world7] 부팅 실패`)와 **진단 훅의 `tag` 필드**,
   * 그리고 **성능 리포트 제목**에 쓴다.
   *
   * ⚠ 여기 *"씬 노드 이름(`world7:sky`)"* 이라고 적혀 있었고 **거짓이었다**(검수관 P1) —
   * 씬 노드는 전부 하드코딩 `glb-world:` 다(`systems/sky.ts`·`glb-source.ts`·
   * `instancing.ts`·`horizon.ts`·`artwork-scene.ts`). 팀장 조건 3 이 지정한 **경계 SSOT
   * 파일**에 있는 거짓 진술이라 다음 사람이 그 이름으로 씬을 찾다 못 찾는다.
   *
   * ⚠⚠ **`tag` 가 선택이 아니라 필수인 진짜 이유**: 진단 훅 이름을 `__glbWorld` 로
   * **합쳤다**(두 페이지가 같은 이름을 노출한다). 그 훅을 읽는 스모크·진단이 「어느
   * 페이지를 잡았는가」를 알 방법이 이 필드뿐이다. 콘솔 접두는 탭 단위라 약한 근거다.
   *
   * ⚠ **하나로 합치지 마라**(검수관 N2, 2026-08-26): 두 페이지를 함께 열었을 때 콘솔의
   * 「부팅 실패」가 어느 쪽인지 구별이 안 된다. 실제로 world8 이 world2 트리를 복사한
   * 직후 `[world2] 부팅 실패` 로 찍혔고 그것이 반려 사유였다.
   */
  tag: string;
  /**
   * 세계가 될 GLB 를 가져온다. **부팅의 `stream` 단계에서 불린다** — 그래야 로딩
   * 진행률이 이 시간을 포함한다.
   *
   * world8 은 고정 자산을 `fetch` 하고, world7 은 사용자가 이미 고른 파일을 즉시 낸다.
   */
  source(): Promise<ArrayBuffer>;

  /**
   * **불러오기 직후 자가진단 체크리스트를 띄운다.**
   *
   * 감독 지시 2026-08-28: *"처음에 불러올때 체크리스트를 만들어서. 정상적으로 동작하는지
   * 확인하는 과정이 있으면 좋겠다. **당분간.. 월드7에만..**"*
   *
   * ⚠ **`tag` 로 분기하지 않는다.** 위 경계 조항대로다 — 지금 이 트리의 `if (tag === …)`
   * 는 **0곳**이고(`opts.tag` 는 로그 접두·리포트 제목처럼 값으로만 쓰인다), 「world7 에만」을
   * `tag` 비교로 짜면 그 경계를 여기서 처음 깨는 것이 된다. 계약에 플래그를 두면 **부트
   * 파일이** 켜고 끄므로 트리는 두 페이지를 계속 같게 본다 — world8 에도 켜려면 한 줄이다.
   *
   * 판정은 `decide/glb-checklist.ts`(순수 함수), 화면은 `ui/glb-checklist-panel.ts`.
   */
  checklist?: boolean;

  /**
   * **부팅 시작 위치·시선.** 안 주면 트리 기본(`spawnFor('default')`)이다.
   *
   * ── 왜 생겼나 (뉴욕 갤러리 거리, 2026-09-06 팀장 판정 하위 3) ──────────────────
   * 지시서 §9 의 6 고정 시점 캡처는 «같은 좌표·방향» 을 재현해야 하는데 이 트리에는 좌표
   * 노브가 없고 `PlayerSystem.moveTo` 는 팀장이 일부러 닫은 문이다(`systems/player.ts`
   * 궤도 절: *"`moveTo(x, z)` 를 열면 임의 순간이동이 가능해지고, 그 문은 이번 용도보다
   * 언제나 넓다"*). **이 필드는 그 문을 열지 않는다** — 세션 중 위치 쓰기가 아니라
   * **부팅 인자**이고, `PlayerSystem` 생성자의 `start` 로 그대로 넘어간다(그 자리는 `?at=river`
   * 스폰 선택이 이미 쓰던 문이다). 순간이동이 아니므로 산술·충돌·복원 책임은 그대로
   * `PlayerSystem` 에 남는다. 봉인 목적(«편집·주행 경로에서 임의 위치 쓰기 금지»)은 보존된다.
   *
   * ⚠ 백로그 `G-W8J` 재건 조건 ⓐ(«진단 전용 순간이동 문») 과 다르다 — 이것은 «벽 코앞에서
   * 시작» 을 가능하게 하므로 ⓑ(«걸어서 벽에 닿는 스폰») 의 대체가 될 수 있다. 그 재건은 별도 회차.
   *
   * ⚠⚠ **`tag` 로 분기하지 않는다.** 캡처 페이지(`world10-boot`)만 `?cam=` 을 읽어 이 필드를
   * 채우고, world7·8 부트는 넘기지 않는다 — 트리는 두 페이지를 계속 같게 본다. 파서는
   * `decide/capture-entry.ts`(순수)이고 `tests/world-glb-capture-entry.test.ts` 가 호출처를 지킨다.
   */
  start?: { x: number; z: number; yaw?: number; pitch?: number };
}



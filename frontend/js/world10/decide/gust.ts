// world10/decide/gust.ts — **돌풍**. 잔디밭을 가로질러 지나가는 강한 바람의 판정.
//
// ── 감독 지시 2026-08-19: *"산들바람이 아니. 간간히 강한바람이 불게해줘"* ────
//
// 그전까지 바람 세기는 이렇게 만들어졌다(`decide/grass.ts` 의 폐기된 `WIND_GUST_*`):
//
//     gust = mx_noise_float(x·0.03, z·0.03, t·0.35)      // 대략 −1 … 1
//     세기  = gust · 0.75 + 0.35                          // 대략 −0.4 … 1.1
//
// 세 가지가 «산들바람» 을 만들고 있었다:
//   ① **평균이 0.35 로 높다** — 언제나 뭔가 불고 있어서 «지금 강하다» 가 성립할 여지가
//      없다. 강풍은 약할 때가 있어야 강한 것이다.
//   ② **최대가 1.1 뿐이다** — 평시 대비 겨우 3배고, 잎 굽힘으로는 3.4cm → 13cm 다.
//      실루엣이 별로 안 변한다.
//   ③ **파면이 없다** — 노이즈가 공간에서 뭉치기만 하고 **흐르지 않는다**(시간축이
//      독립 차원이라 무늬가 제자리에서 물결댄다). 그런데 실제 돌풍의 정체는 «강한
//      바람이 저쪽에서 이쪽으로 **훑고 지나가는 것**» 이다. 그것이 안 보이니 각자
//      알아서 흔들리는 필드가 됐다 — 감독이 3차에 *"혼자 살아있는 스스로 움직이는것
//      같은 느낌"* 이라고 한 것과 같은 뿌리다.
//
// ── 왜 노이즈를 세기 판정에서 뺐나 ──────────────────────────────────────────
// 노이즈로 «가끔 강하게» 를 만들려면 `pow(noise, k)` 나 `smoothstep(문턱, …)` 로 눌러야
// 하는데, **그러면 값이 노이즈의 분포에 의존한다.** MaterialX perlin 의 분위수를 우리는
// 모르고(헤드리스로 못 재고, 재도 three 버전에 묶인다), 그러면 «몇 초에 한 번 부는가» 를
// **추측으로** 적게 된다. 이 저장소가 *"실측에 여유를 얹은 값은 근거가 아니다 — 유도할
// 수 있으면 유도한다"* 라고 적어 둔 자리가 정확히 그것이다.
//
// 그래서 **파면은 결정적 주기 함수**로 만들고(간격·폭·속도가 산술로 나온다), 노이즈는
// **파면마다 세기를 다르게 하는 데만** 쓴다. 노이즈가 틀린 분포를 가져도 «간격» 은 안
// 흔들린다.

/** 돌풍이 땅을 훑고 지나가는 속도(m/s). 걷는 속도(5)보다 조금 빠르다. */
export const GUST_MPS = 6;

/** 돌풍 한 번의 간격(초). 파장은 여기서 유도된다 — `gustWave` 참조. */
export const GUST_PERIOD = 7;

/**
 * 파면의 뾰족함. `sin(πs)^SHARP` 의 지수다 — 클수록 좁은 띠가 된다.
 *
 * **실측**(임계 0.5 이상인 구간이 주기에서 차지하는 비율, 주기 7초 기준):
 * ```
 *   n      4      6      8     10     12
 *   비율  0.364  0.300  0.261  0.234  0.214
 *   초    2.55   2.10   1.83   1.64   1.50
 * ```
 * **8 을 고른 근거**: 7초 주기에서 강풍이 1.8초 — 「지나갔다」 가 읽히면서 「계속 분다」
 * 로는 안 읽히는 폭이다. 더 뾰족하게(12) 하면 1.5초라 훅 스치고 마는데, 파면이 42m
 * 폭이라 그 사이 시야를 다 못 건넌다.
 */
export const GUST_SHARP = 8;

/**
 * 파면마다 세기가 갈리는 정도. `0` = 모든 파면이 똑같이 강함(기계적) · `1` = 어떤
 * 파면은 0 까지 약해짐.
 *
 * 0.65 면 파면 세기가 **0.35 … 1.0** 사이다. 절반쯤은 약하게 지나가므로 «확실히 강한»
 * 돌풍의 체감 간격은 7초가 아니라 **10~15초**가 된다 — 감독이 말한 *"간간히"* 다.
 * 규칙적인 파면만 있으면 시계처럼 보인다.
 */
export const GUST_VARY = 0.65;

/** 평시 바람 세기. 옛 값 0.35 보다 낮다 — **낮춘 것이 이 변경의 절반**이다. */
export const BREEZE = 0.28;

/**
 * **정적 굽힘** — 바람이 없어도 잎이 바람 쪽으로 누워 있는 정도.
 *
 * ── 감독 판정 2026-08-19 (세 번째): *"한방향이 아닌데? 아직도 가위로 움직여."* ──
 *
 * 이 항이 생긴 이유는 값이 아니라 **구조**다. 잎의 굽힘은 원래 지오메트리에 구워져
 * 있었고(`decide/blade-shape.ts` 의 `BLADE_CURVE`), 그 방향은 인스턴스 Y 회전을 따라
 * **잎마다 랜덤**이었다. 그런데 잎 평면과 굽힘 축이 **같은 회전 하나에 묶여 있어**
 * (평면이 XY, 굽힘이 +Z = 평면 법선) 회전을 좁혀 굽힘만 정렬할 방법이 없었다.
 *
 * **실측 — 두 번의 오진이 여기서 갈렸다:**
 * 인스턴스 행렬은 `T · R_y · S(sw, sy, sw)` 이고 지오메트리의 굽힘은 z 축인데,
 * **z 에 곱해지는 것은 높이(0.28)가 아니라 폭(0.13)** 이다. 직전 회차는 높이를 곱해
 * 랜덤 굽힘을 10.6cm 로 적었으나 실제는 **4.9cm** 다.
 * ```
 *                        크기            방향
 *   랜덤 굽힘          4.9cm          잎마다 다름  ← 항상 있다
 *   평시 바람    −3.4 … +3.4cm        고정        ← 주기의 61%
 *   돌풍 바람   +12.8 … +28.0cm       고정        ← 주기의 39%
 * ```
 * **평시에는 랜덤 성분(4.9)이 바람(3.4)보다 1.47배 크다** — 방향을 정하는 것이 바람이
 * 아니라 각 잎이 원래 휜 방향이다. 감독이 보는 시간의 61% 가 그 구간이고, 돌풍 중에도
 * ±21° 가 남는다. 직전 커밋의 판정 기준(*"12.8 > 10.6"*)은 틀린 수치 위에 있었고,
 * **그래서 「고쳤다」 고 적었는데 안 고쳐졌다.**
 *
 * 굽힘을 셰이더의 정적 항으로 옮기면 방향이 인스턴스 회전과 **무관**해진다 — 월드 고정
 * 방향(= 바람 방향)으로 모두가 똑같이 휘고, 잎 평면 회전은 랜덤 그대로다.
 *
 * **0.41 의 근거**: `0.41 × WIND_AMP(0.12) = 4.9cm` — 지금 랜덤 굽힘과 **같은 크기**다.
 * 크기는 감독이 이미 승인한 것이라(밤 화면) 바꾸지 않는다. 바꾸는 것은 방향뿐이다.
 */
export const STATIC_LEAN = 0.41;

/**
 * 돌풍이 진동(살랑임)에 더하는 세기.
 *
 * ⚠ **1.3 → 0.35 (감독 판정 2026-08-19 *"돌풍이불면 잎이 한방향으로 가야하는데.
 * 엇갈리면서 가. 가위처럼."*).**
 *
 * 첫 판본은 편향(`GUST_LEAN` 0.8)보다 진동을 **2배 크게** 잡았다. 그런데 진동은
 * `sin(위상)` 이라 −1 … +1 이고, 위상에는 잎마다 다른 지터가 섞여 있다
 * (`WIND_JITTER_*` — 감독이 앞서 요구한 «각자 흔들림»). 그래서 진동이 편향보다 크면
 * **이웃한 두 잎의 굽힘 부호가 갈린다.** 그것이 가위다.
 *
 * **실측**(굽힘 거리, 잎 높이 0.28m):
 * ```
 *              평시(gust 0)      돌풍(gust 1)
 *   옛 값     −3.4 … +3.4cm    −9.4 … +28.6cm   ← 돌풍 중에도 9.4cm 뒤로 눕는 잎이 있다
 *   새 값     −3.4 … +3.4cm   **+12.8 … +28.0cm**  전부 양수 = 전부 한 방향
 * ```
 * **원인이 둘이었고 값 하나가 둘 다 덮고 있었다:**
 *   ① 진동 부호가 뒤집힌다(위 표의 음수).
 *   ② 편향(9.6cm)이 **정지 굽힘(10.6cm)보다 작았다** — 잎은 `?gcurve` 로 이미 휘어
 *      있고 그 방향은 인스턴스마다 랜덤이다(`bladeBase.rot`). 바람이 그보다 약하면
 *      실루엣의 방향을 정하는 것은 바람이 아니라 **각 잎이 원래 휜 방향**이 된다.
 *      새 값의 최솟값 12.8cm 가 10.6cm 를 넘는 것이 이 축의 판정 기준이다.
 *
 * **평시가 여전히 양방향인 것은 의도다.** 산들바람은 앞뒤로 살랑여야 한다 — 한 방향으로만
 * 밀리면 그건 약한 돌풍이지 산들바람이 아니다.
 */
export const GUST_OSC = 0.35;

/**
 * 돌풍이 잎을 **한쪽으로 눕히는** 정도(진동이 아닌 편향).
 *
 * 이 항이 없으면 돌풍은 «더 빨리 살랑임» 으로만 보인다. 실제 강풍에서 풀은 진폭이
 * 커지는 게 아니라 **누워 있다가 그 자세로 떤다.** 그 차이가 «강한 바람» 의 정체다.
 *
 * ⚠ **0.8 → 1.7** — 첫 판본은 이 항을 넣어 두고도 진동을 더 크게 잡아 **묻히게** 했다
 * (위 `GUST_OSC` 의 실측). 항을 만드는 것과 그 항이 이기게 하는 것은 다른 일이다.
 */
export const GUST_LEAN = 1.7;

/**
 * 파면 세기 노이즈의 좌표 배수. 파면 번호(정수)에 곱해 노이즈 격자를 훑는다.
 *
 * 정수 격자점에서 perlin 이 0 이 되는 성질을 피하려고 **정수비가 아닌 두 값**을 쓴다 —
 * 같은 값을 두 축에 쓰면 대각선만 훑어 주기가 짧아진다.
 */
export const GUST_VARY_KX = 0.37;
export const GUST_VARY_KZ = 0.13;

/**
 * 파면 좌표의 계수 — `u = (p·dir)·waveK − t·timeK` 로 쓴다. `u` 가 1 늘 때마다 파면 하나.
 *
 * 주기와 속도에서 **파장을 유도한다**(파장 = 속도 × 주기). 반대로 파장을 상수로 박고
 * 주기를 노브로 열면 간격을 늘릴 때 파면이 **느려져서** 돌풍이 슬로모션으로 지나간다 —
 * 실제로는 간격이 멀어져도 바람 자체의 속도는 그대로다.
 *
 * **실측**(`GUST_MPS=6`): 주기 5초 → 파장 30m · 7초 → **42m** · 10초 → 60m.
 * 42m 는 잔디 필드 지름(140m)의 0.3배라 화면에 늘 한 파면 정도가 들어온다.
 */
export function gustWave(periodSec: number): { waveK: number; timeK: number } {
  const period = Math.max(0.5, periodSec);
  return { waveK: 1 / (GUST_MPS * period), timeK: 1 / period };
}

/**
 * 주어진 돌풍 세기에서 굽힘이 가질 수 있는 **최솟값**.
 *
 * 굽힘 = `정적 + 편향 + 진동` 이고 진동은 ±(BREEZE + gust·OSC) 이므로
 * 최솟값은 `staticLean + gust·LEAN − (BREEZE + gust·OSC)` 다. **이것이 0 이상이면 모든
 * 잎이 같은 방향으로 눕는다** — 부호가 갈릴 여지가 없기 때문이다.
 */
export function bendFloor(
  gust: number, staticLean = STATIC_LEAN, breeze = BREEZE,
  osc = GUST_OSC, lean = GUST_LEAN,
): number {
  return staticLean + gust * lean - (breeze + gust * osc);
}

/**
 * 잎이 **전부 한 방향으로만** 눕기 시작하는 돌풍 세기. `0` 이면 세기와 무관하게 항상.
 *
 * ⚠ **이 함수의 전제가 `STATIC_LEAN` 도입으로 바뀌었다.** 예전에는 돌풍이 어느 세기를
 * 넘어야만 한 방향이었고(현재 값 이전 기준 0.207), 그래서 **주기의 61% 를 차지하는
 * 평시가 통째로 가위 구간**이었다. 정적 항이 `BREEZE` 이상이면 `gust=0` 에서도 최솟값이
 * 0 이상이라 **전 구간이 한 방향**이 된다.
 *
 * **실측**(현재 값 `STATIC_LEAN=0.41` ≥ `BREEZE=0.28`): **0** — 언제나 한 방향이다.
 *
 * ⚠⚠ `LEAN ≤ OSC` 이고 정적 항도 모자라면 어떤 세기로도 한 방향이 안 된다 — 그때
 * `Infinity` 를 돌려준다. 값을 만지다 그 상태에 빠지면 가위가 그대로 돌아온다.
 * **이 함수를 주석이 아니라 산술로 둔 이유가 그것이다** — 이 회차에서 실패한 지점이
 * 정확히 «두 항의 크기를 비교하지 않은 것» 이었다.
 */
export function gustUnidirectionalFrom(
  breeze = BREEZE, osc = GUST_OSC, lean = GUST_LEAN, staticLean = STATIC_LEAN,
): number {
  if (staticLean >= breeze) return 0;
  return lean > osc ? (breeze - staticLean) / (lean - osc) : Infinity;
}

/**
 * 돌풍이 임계 이상인 구간의 길이(초). 값을 고를 때 읽으라고 둔 것이지 런타임 경로가
 * 아니다 — 위 `GUST_SHARP` 표가 이 함수의 출력이다.
 */
export function gustPeakSeconds(sharp: number, periodSec: number, threshold = 0.5): number {
  const q = Math.pow(threshold, 1 / Math.max(0.001, sharp));
  return periodSec * (1 - (2 * Math.asin(Math.min(1, q))) / Math.PI);
}

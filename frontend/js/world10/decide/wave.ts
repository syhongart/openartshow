// world10/decide/wave.ts — 수면 정점 파동의 **판정**. 집행(버퍼에 꽂기)은 `features/ocean.ts`.
//
// ── 왜 이 파일이 생겼나 (2026-08-20) ────────────────────────────────────────
// 이 계산은 오래 `features/ocean.ts` 안에 있었고, **정점에 값을 꽂는 한 줄은 갱신 루프에
// 인라인**으로 적혀 있었다. 그 한 줄이 `PATCH_SEP + LIFT_AMP + surfaceLift(…)` 여서
// 진폭이 평균 수면을 함께 밀어 올렸는데, `surfaceLift` 자체는 순수 함수라 단위 테스트가
// 촘촘히 보고 있었음에도 **어느 테스트도 그 한 줄에 닿지 못했다.** 이 저장소가 이름 붙인
// «판정/집행 분리의 구멍» 이 정확히 그 형태다. 판정을 여기로 옮겨 테스트가 보게 한다.
//
// **노브(`?wamp`·`?wstd`)는 여기 없다.** URL 을 읽는 것은 집행 쪽 일이고, 그 값은 인자로
// 들어온다. 예전에는 기본 인자가 노브 상수(`LIFT_AMP`)여서 **인자를 생략한 호출이 노브를
// 조용히 먹고 있었다** — 순수 함수인 척하면서 전역을 읽는 형태다. 여기서는 기본값이
// 상수이고, 노브를 쓰려면 호출부가 **명시적으로 넘겨야 한다.**

import { PHI } from './golden.js';

/**
 * `?wamp` 미지정 시의 파고(m, 마루~골의 **절반**). 노브 상한은 `WAVE_PEAK_MAX`(water.ts).
 *
 * ── 0.2 → 0.45 → **0.30** (감독 판정 2회, 2026-08-20) ───────────────────────
 * **눈에 보이는 양은 진폭이 아니라 경사다.** 파장 16m 에서 최대 경사(수치미분 실측,
 * 0.5m 격자·64m 각형):
 *
 *   wamp 0.2 → 4.9°(거의 평면) · **0.3 → 7.3°** · 0.45 → 10.9° · 0.6 → 14.4° · 0.75 → 17.8°
 *
 * ① *"40센치인더. 너무 잔잔하다"* → 비교 링크 → *"출렁이는 것은 뭐든 링크 다 좋다"*
 *    셋(0.3·0.45·0.6)이 다 통과했으므로 가운데인 0.45 를 골랐다.
 * ② 그 화면을 다시 보고 *"파도가 너무 너울성이야"* → 카드 판정 **「줄여라」**.
 *    통과했던 셋 중 **가장 작은 것**으로 내린다 — 0.3 도 이미 감독이 좋다고 한 값이라
 *    새 값을 지어내지 않는다.
 *
 * ⚠ **①이 틀렸던 것이 아니다 — 물음이 바뀌었다.** ①의 판정은 잔물결이 하나도 없는
 * 화면에서 나왔다. 그 화면에서 «움직임» 을 만들 수 있는 축은 이 진폭뿐이었고, 그래서
 * 큰 파가 그 몫을 혼자 졌다. 잔물결(`RIPPLE_SPEED`, `features/ocean.ts`)이 생기면
 * 그 몫이 갈리므로 큰 파는 작아도 된다. **한 축의 적정값은 다른 축의 상태에 달렸다** —
 * 그래서 판정을 «0.45 는 과했다» 가 아니라 «전제가 바뀌었다» 로 적는다.
 *
 * ⚠ 파장을 줄여도 가팔라지지만 세분이 파장에서 유도되므로 정점이 제곱으로 는다
 * (λ 16→6m 이면 칸당 81→484). **진폭은 정점 예산에 안 걸린다** — 그래서 이 축이다.
 *
 * ⚠ **게임풍 물(`?styl=1`)에서 이 값이 바꾸는 것은 강뿐이다.** 바다는 파동을 담당하는
 * 층2(`ocean-wave2`)를 스타일 물이 숨기고, 남은 층1 지오는 `PlaneGeometry(…, 1, 1)` 이라
 * 정점이 네 귀퉁이뿐이다(`features/water-style.ts`). 감독께 그 사실을 함께 보고했다.
 *
 * ── ✅ 감독 승인 (2026-08-21) ───────────────────────────────────────────────
 * 바다 앞·낮(`?styl=1&at=sea&time=day`)에서 이 값과 옛 값(`?wamp=0.45`)을 나란히 보고
 * **"응 승인"**. 즉 0.30 은 이제 «내가 고른 값» 이 아니라 **감독이 화면으로 판정한 값**
 * 이다 — 다음에 이걸 만지려면 그 판정을 뒤집는 것이고, 그러려면 다시 화면으로 물어야 한다.
 * 값만 보고 «좀 작지 않나» 로 올리지 마라.
 */
export const WAVE_AMP_DEFAULT = 0.30;

/**
 * `?wstd` 미지정 시의 진행파:정재파 배분. `0` 이면 전부 흘러가고 `1` 이면 전부 제자리
 * 오르내림이다. 어느 배분이 "일렁임" 으로 읽히는지는 감독 실기기 육안 판정이라
 * 노브로 뺐다(팀장 조건 3) — 감독 지적이 *"한 방향으로 흐르는데"* 였으므로 병진 쪽이
 * 이미 과했고, 그래서 기본값을 정재 쪽에 둔다.
 */
export const WAVE_STANDING_DEFAULT = 0.65;

/**
 * 변위가 담당할 **최단 파장**(m). 이보다 잔 물결은 노말맵이 계속 담당한다 —
 * 두 축의 분담 정의이고, 세분 수는 여기서 **유도된다**(손으로 정하지 않는다).
 *
 * 팀장이 확정한 값은 8m 였는데 유도해 보니 예산을 넘었다:
 *   λ=8m  → 세분 16×16 → 쿼드당 512 삼각형 → 최악 60칸 × 512 = 30,720 (씬 대비 **+30%**)
 *   λ=16m → 세분  8×8  → 쿼드당 128 삼각형 → 최악 60칸 × 128 =  7,680 (씬 대비 **+7.5%**)
 * 감독이 무게를 물었고("에이는 무겁지 않아?") 그 답의 전제가 +7% 였으므로 예산 초과로
 * 판정해 16m 로 올렸다 — 팀장 조건 1 이 그 경우를 명시적으로 허용한다.
 * 강 폭이 48m(`RIVER_HALF × 2`)라 파장 16m 면 강을 가로질러 파형이 3개 들어간다.
 */
export const LIFT_LAMBDA_M = 16;

/** `RIVER_SEG`·`SEGS_PER_TILE` 이 이 파장에서 유도된다(`features/ocean.ts`) */
export const LIFT_LAMBDA = LIFT_LAMBDA_M;
/**
 * 겹치는 파들. 감독 요청이 *"물은 복합적인 사인파들로 구성되어있잖아"* 였다.
 * 방향과 주파수 비를 정수비에서 멀리 둔다 — 정수비면 짧은 주기로 패턴이 되풀이된다.
 * `dir` 은 단위벡터, `rel` 은 기본 파수 대비 배율, `amp` 는 상대 진폭(합이 1).
 */
// ── 방향 — 감독 판정 2026-08-20 *"같은 방향으로 가야지. 속도만 다를뿐"* ──────
//
// 감독: *"윗물은 자연스러워. 아래 물도 같은 방향으로 가야지. 속도만 다를뿐"*
// 윗물(강)은 `riverFlowAt(x)` 로 **강줄기를 따라** 흐르고 그것이 통과했다. 아래 물은
// 방향이 흩어져 있었다 — 실측(2026-08-20):
//
//   강 UV        ≈0°    (강줄기)          ← 감독이 «자연스럽다» 고 한 것
//   바다 노멀맵   31.0°  `FLOW_A`
//   색조 층      122.3°  `FLOW_B`
//   층2 무늬     168.5°  `FLOW_A` + 황금각
//   정점 파동      0° / 60° / 108°
//
// `features/ocean.ts` 주석이 *"서로 다르고 **방향도 어긋나야** 한다"* 고 그렇게 설계했고
// 근거는 *"같은 속도로 같은 방향이면 한 덩어리로 미끄러져 «흐르는 벽지»가 된다"* 였다.
// **그 걱정은 「같은 속도 + 같은 방향」에만 해당한다** — 감독 처방은 정확히 그 조건을
// 피한다. 같은 방향에 속도가 다르면 두 층이 서로 미끄러지며 간섭하고, 실제 파도도
// 바람 방향으로 정렬된 채 속도만 다르다. 직각 교차가 오히려 부자연스럽다.
//
// ⚠ **이 저장소가 방향을 어긋내다 반려당한 것이 두 번째다.** 물결 무늬가 「타일 장판」이
// 됐을 때(감독 *"이게 뭐여"*) PR 에 적힌 원인이 *"2층 방향 다름 → 격자"* 였다. 같은
// 실수가 축을 바꿔 재발했다.

/**
 * 물결이 흐르는 기준 방향(도). `0` = +x = 강이 흐르는 축.
 *
 * 노브 `?wdir`. `31` 을 주면 예전 `FLOW_A` 방향으로 정확히 되돌아간다.
 */
export const FLOW_DIR_DEG = 0;

/**
 * 정점 파동 방향의 **부채꼴 반각**(도). 주 방향(`FLOW_DIR_DEG`) 좌우로 이만큼 퍼진다.
 *
 * ⚠ **0 으로 두면 안 된다.** 세 파가 완전히 같은 방향이면 1차원 파형이 되어 마루가
 * 직선이 되고, 그것은 감독이 2026-07-31 에 *"ㅈ런. 일자형 말고"* 로 **이미 기각한**
 * 화면이다. 그러니 이 축은 «정렬» 이 아니라 **«수렴»** 이다.
 *
 * 28°: 실제 풍파 스펙트럼이 주 방향 주위 좁은 부채꼴에 몰리는 것을 따른다. 예전 값
 * (0/60/108°)은 셋째 성분이 주 방향과 거의 **직각**이라 방향감이 상쇄됐다.
 * 노브 `?wspread`. `108` 을 주면 예전 배치로 되돌아간다.
 */
export const WAVE_SPREAD_DEG = 28;

/**
 * 흐름 벡터. 속력과 방향을 **따로** 받는다 — 그것이 감독 처방(«방향 하나, 속도만
 * 다르게»)을 코드 형태로 못 박는 방법이다. 예전에는 `{x, z}` 리터럴이라 방향과 속력이
 * 한 덩어리로 섞여 있었고, 그래서 «속력만 다르게» 를 표현할 자리가 없었다.
 */
export function flowVec(speed: number, dirDeg: number = FLOW_DIR_DEG): { x: number; z: number } {
  const r = (dirDeg * Math.PI) / 180;
  return { x: Math.cos(r) * speed, z: Math.sin(r) * speed };
}

/**
 * 정점 파동 성분들의 방향. 주 방향을 중심으로 **부채꼴로 벌린다.**
 *
 * 셋을 `-spread · 0 · +spread` 로 두지 않고 `0 · +s · −s·0.75` 로 비대칭을 준다 —
 * 대칭이면 좌우 성분이 서로 상쇄해 다시 1차원처럼 읽힌다(주 파가 가장 크므로 그쪽으로
 * 무게가 실려야 한다).
 */
export function waveDirs(spreadDeg: number = WAVE_SPREAD_DEG): Array<{ dx: number; dz: number }> {
  return [0, spreadDeg, -spreadDeg * 0.75].map((d) => {
    const r = ((FLOW_DIR_DEG + d) * Math.PI) / 180;
    return { dx: Math.cos(r), dz: Math.sin(r) };
  });
}

/** 기본 파수 대비 배율. 정수비에서 멀어야 되풀이가 안 보인다 — 그래서 황금비 거듭제곱 */
const WAVE_REL = [1, PHI, PHI * PHI];
/** 상대 진폭. 합이 1 이라 `amp` 인자가 곧 마루~골의 절반이 된다 */
const WAVE_AMP = [0.5, 0.3, 0.2];

/** 겹치는 파들. 부채꼴 반각을 받아 **방향만** 다시 만든다 — 파장·진폭은 그대로다 */
export function liftWaves(spreadDeg: number = WAVE_SPREAD_DEG) {
  return waveDirs(spreadDeg).map((d, i) => ({ ...d, rel: WAVE_REL[i], amp: WAVE_AMP[i] }));
}

const LIFT_WAVES = liftWaves();

/**
 * 수면 높이(m). **월드 좌표만의 함수다** — 이 성질이 파셀 경계의 이음새를 막는다.
 * 강 판은 파셀마다 독립된 정점을 쓰므로(같은 좌표에 정점이 둘) 위치 기반이 아니면
 * 두 값이 갈려 틈이 벌어진다.
 *
 * 진행파 `sin(k·x − ωt)` 와 정재파 `sin(k·x)·cos(ωt)` 를 섞는다. 정재파가 곧
 * "제자리 오르내림" 이다 — 공간 패턴이 고정된 채 진폭만 시간에 따라 오간다.
 *
 * ω 는 **깊은 물 분산관계 `ω = √(gk)`** 에서 유도한다(실측에 여유를 얹지 않는다).
 * λ=16m 면 주기 3.2초로, 사람이 물가에서 보는 잔잔한 강의 리듬과 맞는다.
 */
export function surfaceLift(
  x: number, z: number, t: number,
  amp: number = WAVE_AMP_DEFAULT, standing: number = WAVE_STANDING_DEFAULT,
  waves: ReturnType<typeof liftWaves> = LIFT_WAVES,
): number {
  if (amp <= 0) return 0;
  const k0 = (2 * Math.PI) / LIFT_LAMBDA_M;
  let h = 0;
  for (const w of waves) {
    const k = k0 * w.rel;
    const phase = k * (w.dx * x + w.dz * z);
    const omega = Math.sqrt(9.81 * k);
    h += w.amp * (
      (1 - standing) * Math.sin(phase - omega * t)
      + standing * Math.sin(phase) * Math.cos(omega * t)
    );
  }
  return h * amp;
}

/**
 * 층2 패치와 아래 층(평평한 `sea`)을 갈라 두는 몫(m). **진폭과 무관한 상수다** —
 * 물속에서 올려다볼 때 두 면이 겹쳐 보이지 않게 하는 것이 목적이고, 생성부·갱신
 * 루프 두 곳에 리터럴로 적혀 있던 것을 상수로 올렸다. 테스트도 이것을 기준으로 쓴다.
 */
export const PATCH_SEP = 0.01;

/**
 * 층2 패치 정점의 로컬 y. 원점이 `SEA_Y` 이므로 **이 값의 평균이 곧 평균 수면의
 * 오프셋**이고, 그것이 이 한 줄을 갱신 루프에서 함수로 끌어낸 이유다 — 인라인 자리에는
 * 테스트가 안 닿는다(이 저장소가 «판정/집행 분리의 구멍» 이라 부르는 형태).
 *
 * ── ⚠ `+ amp` 를 더하지 않는다 (감독 *"40센치인더. 너무 잔잔하다"* 2026-08-20) ──
 * 원래 `PATCH_SEP + LIFT_AMP + surfaceLift(…)` 였다. 골을 아래 층(평평한 `sea`) 위로
 * 들어올려 *"뚫지 않게"* 하려던 것인데 **진폭이 평균 수면을 함께 밀어 올렸다** —
 * `?wamp` 가 파도 세기 노브이면서 **수면 높이 노브를 겸했다.** `SEA_Y=-1.40` ·
 * `RIVER_Y=-0.90`(강이 바다보다 50cm 높다는 불변식) 위에서 리프트가 살아 있으면 패치
 * 월드 y 는 `SEA_Y + PATCH_SEP + amp ± amp` 이므로 **하한은 진폭과 무관하게 -1.39** 이고
 * 상한만 오른다: `wamp` 0.2 → -0.99(강 아래, 여태 티가 안 났다) · 0.45 → **-0.49**(강
 * 수면 위) · 0.75 → **+0.11**(지면 위). 즉 리프트를 안 걷으면 진폭 축을 열 수 없다.
 * 헤드리스 실측이 계산과 맞았다 — `?wamp=0.75` 에서 `seaPatch.peak = 1.396m`.
 *   ⚠ 이 자리에 처음 적은 표는 하한을 `0.2 → -1.19`·`0.45 → -0.94` 로 적고 있었고
 *   **산술이 틀렸다**(검수관이 옛 공식을 직접 시뮬레이션해 잡았다). 상한만 움직인다는
 *   것이 요점이므로 결론은 그대로지만, 틀린 표를 남기면 다음 사람이 그 위에 판정을
 *   세운다 — 이 저장소가 `main` unprotected 오기로 7일을 잃은 그 형태다.
 *
 * 그리고 이 리프트는 **렌더와 판정도 어긋내고 있었다**: `waterSurfaceY`(수영 판정)는
 * 파동을 안 보고 `SEA_Y` 를 돌려주는데, 보이는 물은 그보다 `PATCH_SEP + amp` 만큼
 * 위에 있었다. 리프트를 걷으면 패치 평균이 `SEA_Y + PATCH_SEP` 이 되어 **판정과 맞는다.**
 *
 * ⚠ **그러면 골은 무엇이 받는가 — 아래 층을 내린다.** 처음에 *"두 층 다
 * `depthWrite:false` 라 순서만 문제이고 뚫려도 된다"* 고 판단해 아래 층을 그대로 뒀는데,
 * **`tests/world2-ocean.test.ts` 의 기존 단언이 그것을 반증했다**(«골이 아래 층을 뚫지
 * 않는다»). 그 테스트가 든 근거는 z-fighting 이 아니라 *"물이 두 겹으로 갈라져 보인다"*
 * — 반투명 두 판이 **교차**하면 그 교차선이 수면 위에 선으로 드러난다. 깊이 버퍼와
 * 무관하게 **위치**가 만드는 현상이라 내 논증은 축이 아예 달랐다. 그래서 집행 쪽에서
 * `sea.position.y` 를 `SEA_Y − LIFT_AMP` 로 내려 골 밑을 비운다(`features/ocean.ts`).
 * 아래 층은 패치 밖(안개 너머)에서만 보이는 판이므로 이 낙하는 근거리 화면에 안 나온다.
 */
export function patchVertexY(
  x: number, z: number, t: number,
  amp: number = WAVE_AMP_DEFAULT, standing: number = WAVE_STANDING_DEFAULT,
  waves: ReturnType<typeof liftWaves> = LIFT_WAVES,
): number {
  return PATCH_SEP + surfaceLift(x, z, t, amp, standing, waves);
}

// world-glb/decide/glb-nodes.ts — GLB 노드 이름 규약. 순수.
//
// ── 문자열 재기입 방지 ────────────────────────────────────────────────────────
// 생성기와 런타임 로더가 같은 이름을 쓰게 둔다. 한 곳에서 정의하고 양쪽이 참조한다.
//
// `tests/nyc-gen.test.ts` 가 「두 값이 갈리면 여기서 깨진다」를 단언한다
// (팀장 조건 ②).
//
// ── ⚠ 구분자는 `_` 다. `.` 로 되돌리지 마라 ──────────────────────────────────
// **three 의 `GLTFLoader` 가 로드 중에 노드 이름을 고쳐 쓴다.** `createUniqueName`
// (`GLTFLoader.js:3655`) → `PropertyBinding.sanitizeNodeName`(`three.core.js:31930`) 이
// `[ ] . : /` 를 **삭제**한다. 노드(`:4207`)·메시(`:3844`)·씬(`:4345`) 이름 전부에 걸린다.
//
// 실측(three 0.171, `node -e "import('three').then(t=>…sanitizeNodeName(x))"`, 2026-09-06):
//
// | 생성기가 쓴 이름          | 로더가 붙인 이름   | 불변? |
// |---------------------------|--------------------|-------|
// | `bld.2.room.1.light`      | `bld2room1light`   | ✗     |
// | `bld.2.door`              | `bld2door`         | ✗     |
// | `bld.2.room.1.slot.3`     | `bld2room1slot3`   | ✗     |
// | `ground.walk.n`           | `groundwalkn`      | ✗     |
// | `gate.1`                  | `gate1`            | ✗     |
// | `bld_2_room_1_light`      | `bld_2_room_1_light` | ✓   |
// | `bld_2_door`              | `bld_2_door`       | ✓     |
// | `gate_1`                  | `gate_1`           | ✓     |
//
// **대가**: 이 규약이 `.` 이던 동안 `isRoomLightNode` 는 런타임에서 **한 번도 참이 아니었고**
// `systems/glb-source.ts` 의 `PointLight` 가 **0개**였다. 강도 스윕 4장이 md5 동일로 나와서야
// 드러났다(BOARD 2026-09-06). `tests/world-glb-lights.test.ts` 14개는 그동안 전부 초록이었다 —
// 검사가 GLB json 의 **원** 이름만 봤고 로더를 통과한 **뒤**는 아무도 안 봤다(CLAUDE.md
// «판정/집행 분리의 구멍 — 경계를 건너는 지점은 아무도 안 본다»).
//
// **`_` 를 고른 이유**: sanitize 가 보존하는 문자 중 `\w` 에 속해 정규식이 단순하다(`-` 는
// 음수와 헷갈린다). 대안 B(런타임 정규식만 sanitize 후 형태로 맞추기)는 규약 문자열이 두
// 형태로 갈려 미러링 함정이 되므로 버렸다(부팀장 판정 2026-09-06).
//
// **이 규약이 지켜지는 것을 검사하는 자리**: `tests/world-glb-lights.test.ts` 의
// `it('생성기의 모든 노드·메시 이름이 sanitizeNodeName 에 불변이다 — `.` 을 쓰면 로더가 지운다')`
// 와 `it('로더를 통과한 뒤에도 라이트 노드가 isRoomLightNode 를 만족한다(경계 축)')`.
// 그 둘이 three 의 실물 `PropertyBinding` 을 통과시켜 단언한다.
//
// ── 규약 전체 ────────────────────────────────────────────────────────────────
//   `street`                            루트(거리 전체, `--street-yaw` 가 도는 유일한 노드)
//   `ground_{road|walk|curb|yard}[_n|_s]`  지면 7장
//   `bld_<n>`                           건물 <n>
//   `bld_<n>_<mat>`                     건물 <n> 의 재질 <mat> 메시 묶음
//   `bld_<n>_door`                      문 빈 노드(extras: w·h)
//   `bld_<n>_room_<r>`                  실내(extras: inner)
//   `bld_<n>_room_<r>_wall_<w>`         실내 벽 <w> ∈ {back,left,right,front}
//   `bld_<n>_room_<r>_slot_<s>`         작품 슬롯(extras: w·h·wall)
//   `bld_<n>_room_<r>_light`            방 조명 빈 노드 → 런타임 `PointLight`
//   `gate_1`                            거리 끝 구조물
// 생성처는 `scripts/asset/nyc/generate.mjs` 한 곳이다.

/**
 * 실내 조명 노드의 이름 접미사.
 *
 * 전체 패턴: `bld_<n>_room_<r>_light` (예: `bld_2_room_1_light`)
 */
export const ROOM_LIGHT_SUFFIX = '_light';

/**
 * 노드 이름이 실내 조명 노드인지 확인한다.
 *
 * 패턴: `bld_<n>_room_<r>_light` (n·r은 정수)
 *
 * ⚠ 이 정규식은 **three 로더를 통과한 뒤의 이름**을 받는다 — 구분자를 `.` 로 되돌리면
 * 로더가 그 문자를 지우므로 영원히 거짓이 된다(헤더의 실측 표).
 */
export function isRoomLightNode(name: string): boolean {
  return /^bld_\d+_room_\d+_light$/.test(name);
}

/**
 * 실내 조명 색(16진). **값 출처: `docs/nyc/art-direction.md` §2 「전시 조명 `#FFF6EA` (≈3800K)」.**
 *
 * 흰색(`0xffffff`)이 아닌 이유가 그 표에 적혀 있다 — 전시 조명은 중성 온백색이고,
 * 흰색 광원은 벽면 아이보리를 푸르게 민다. 값을 바꾸려면 그 표를 먼저 고친다(미러링 금지).
 */
export const ROOM_LIGHT_COLOR = 0xfff6ea;

/**
 * 실내 조명 강도(three `PointLight.intensity`) — **단위는 candela** 다. three 0.171 은
 * physically-correct 단위이고 `PointLight.decay` 기본값이 2 라 조도가 `I / r²` 로 떨어진다.
 *
 * ⏳ **임시 기본값이다 — 감독 판정 전.** 후보는 `?pli=` 노브로 열려 있다(아래 `roomLightIntensity`).
 * 판정을 받으면 그 값을 여기에 굽고 이 문단을 「왜 그 값인가 + 실측 표」로 바꾼다.
 * 감독께 드릴 3안은 **12 / 24 / 48**(현재 기본 · 2배 · 4배)이다 — 인접 쌍의 화면 차이가
 * |ΔL| 평균 13.4 · 17.5 로 갈리는 것을 실측했다(6↔12 는 9.3 으로 가장 약해 하한 쪽에서 뺐다).
 *
 * ── ✅ **점광이 화면에 실제로 선다**(2026-09-06 실측, 검수관 «후속 필수» 해소) ──────────
 * 노드 규약을 `_` 로 고친 회차(#295)는 **정적 검증만** 이었다 — 「`isRoomLightNode` 가 참이
 * 된다」까지만 보고 「그래서 `PointLight` 가 서고 화면이 달라지는가」는 아무도 안 쟀다.
 * 이번에 같은 커밋을 클론에서 이 상수만 `0` 으로 바꿔 빌드해 대조했다(`?cam=13.2,-16.6,180,0`):
 * **|ΔL| 평균 26.4 · 최대 190.7 · Δ>5 인 화소 89.2%**, 천장 평균 L **64.4 → 134.1**(위 표와 같은
 * 영역 정의). 점광이 0개이던 동안 강도 스윕 4장이 md5 동일이던 그 사고(BOARD 2026-09-06)의
 * 반대 결과다.
 *
 * ── ⚠ 이 문단은 원래 «이 값을 URL 노브로 열지 않는다» 였다(2026-09-06 갱신) ────────────
 * 금지의 **이유**는 *"노브는 `world-glb/main.ts` 를 키운다"* 였다 — 앞선 회차에 `?pli=` 를 그
 * 동결 파일에 넣어 baseline(1250줄)을 올리고 게이트를 우회한 사고가 났다(BOARD 2026-09-06
 * «🔴 조명 executor 사고»). 그 이유는 **경로에 달린 것이지 노브 자체에 달린 것이 아니다.**
 *
 * 지금 노브는 `systems/glb-source.ts` 가 직접 읽어 `main.ts` **+0** 이다(그 파일 md5 불변으로
 * 확인한다) — 그래서 금지 근거가 성립하지 않고, 남는 것은 반대 방향의 감독 사이클 원칙
 * («후보를 여럿 동시에 · 노브로 열어 재배포 없이 비교», CLAUDE.md) 뿐이다.
 *
 * **`main.ts` 경로로는 여전히 열지 않는다 — 그 파일은 동결이다.** 이유 없는 금지를 남기지
 * 않기 위해 문장을 지우는 대신 «어느 경로가 왜 막혔는가» 로 좁혔다.
 */
export const ROOM_LIGHT_INTENSITY = 12;

/**
 * `?pli=` 의 상한(candela).
 *
 * **왜 상한이 필요한가**: 클램프의 목적은 «값을 제한» 이 아니라 «판정할 수 없는 구간으로 못
 * 나가게» 하는 것이다(`url-knob.ts` 머리말 — `?nexp=999` 로 화면이 하얗게 날아가면 그 상태를
 * "고장" 으로 오해하게 된다).
 *
 * **왜 100 인가 — 두 축이 같은 자리를 가리킨다**:
 *
 * ① **물리**(주 근거): 전방위 점광원의 광속은 `4π × I` 다. 100 cd ≈ **1,257 lm** 으로, 실제
 *    갤러리 트랙 조명(할로겐 50W ≈ 900 lm)보다 밝다. 그 위는 «전시 조명» 이라는 대상 자체를
 *    벗어난다 — 상한은 «세기 제한» 이 아니라 «이 노브가 무엇을 고르는 노브인가» 의 경계다.
 * ② **화면**(보조, 실측 2026-09-06 — 900×560 헤드리스 WebGL·swiftshader, `?cam=13.2,-16.6,180,0`,
 *    노말맵 기본 0.6, 증거 `docs/nyc/evidence/iteration-02-light/`):
 *
 *    | `?pli=` | 전역 L | 천장 L (포화%) | 정면벽 L | 바닥 L |
 *    |---------|--------|----------------|----------|--------|
 *    | 0       | 116.3  |  64.4 ( 0.0)   | 138.6    | 150.7  |
 *    | 12      | 142.7  | 134.3 ( 4.2)   | 150.2    | 170.3  |
 *    | 48      | 173.6  | 176.9 (13.3)   | 171.7    | 202.2  |
 *    | 100     | 194.2  | 200.2 (20.4)   | 187.6    | 221.6  |
 *
 *    100 에서 측벽·바닥이 211~222 로 올라 **실내가 흰 상자가 된다**(육안: 좌우 측벽과 바닥의
 *    경계가 거의 사라진다). 그 위로 더 밀 이유가 화면에 없다.
 *
 * ⚠ **여기서 «포화» 는 천장 핫스팟에서만 일어난다** — 벽·바닥은 100 에서도 포화 0.0% 다.
 * 그래서 «모든 표면이 255 로 날아가는 지점» 을 상한 근거로 쓰지 않았다(그 지점은 이 방
 * 기하에서 훨씬 위이고, 그때는 이미 ①이 말하는 대상 밖이다). **실측에 여유를 얹은 값이
 * 아니라 대상의 정의에서 온 값이다.**
 */
export const ROOM_LIGHT_INTENSITY_MAX = 100;

/**
 * `?pli=` 원문을 실내 조명 강도로 판정한다. **순수 함수** — URL 읽기는 `url-knob.ts` 소관이다.
 *
 * - 없음 · 빈 값 · 숫자 아님 · 음수 → `ROOM_LIGHT_INTENSITY`(기본값)
 * - `0` 은 **유효한 지정**이다 — 「점광을 끈 대조군」이고, `?nrm=0`(노말맵 떼기)과 같은 어휘다.
 *   이 축은 실물 사고에서 왔다: 점광이 0개이던 동안 스윕 4장이 md5 동일이었고, 그것을 가른
 *   것이 바로 «켠 화면 ↔ 끈 화면» 대조였다(BOARD 2026-09-06).
 * - 상한은 `ROOM_LIGHT_INTENSITY_MAX` 로 클램프한다.
 *
 * ⚠ **음수를 0 으로 클램프하지 않고 기본값으로 되돌린다.** 음수 intensity 는 three 에서
 * 「빛을 빼는」 광원이 되어 실내가 검게 파이고, 그 화면은 «노브를 잘못 밀었다» 가 아니라
 * «세계가 깨졌다» 로 읽힌다. 0 으로 클램프하면 «끈 것» 과 «잘못 적은 것» 이 같은 화면이 되어
 * 구별이 사라진다 — 그래서 기본값 복귀다.
 *
 * @param raw URL 파라미터 원문(`url-knob.readRawOpt('pli')`). 지정 안 됐으면 `null`.
 */
export function roomLightIntensity(raw: string | null | undefined): number {
  if (raw == null) return ROOM_LIGHT_INTENSITY;
  const t = raw.trim();
  if (t === '') return ROOM_LIGHT_INTENSITY;
  const n = Number(t);
  if (!Number.isFinite(n) || n < 0) return ROOM_LIGHT_INTENSITY;
  return Math.min(n, ROOM_LIGHT_INTENSITY_MAX);
}

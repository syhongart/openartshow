// world10/decide/daylight.ts — 낮의 빛 대비를 얼마로 할 것인가. 순수 함수만.
//
// ── 감독 지시 2026-08-02 ─────────────────────────────────────────────────────
// *"주간에 하드라이트 느낌이 없어."*
//
// ── 원인 (2×2 실측) ─────────────────────────────────────────────────────────
// 처음엔 그림자 카메라 프러스텀(±5m)을 원인으로 짚었고 **틀렸다.** 같은 좌표에서 네
// 조건을 재니 화면 대비(밝기 표준편차)가 이렇게 갈렸다:
//
//                        프러스텀 ±5   프러스텀 41.6
//   광비율 기존              52.51        52.76      ← 프러스텀 효과 +0.25
//   광비율 조정              56.25        56.82      ← 프러스텀 효과 +0.56
//                          ↑ 광비율 효과 +3.74 / +4.06
//
// **광비율이 프러스텀의 7~15배다.** 낮 팔레트가 태양 0.95 · 반구 1.0 이라 하늘에서 오는
// 반사광이 태양보다 세고, 그래서 그림자 영역을 도로 채운다. 그림자를 아무리 정확히
// 그려도 반사광이 메우면 대비가 안 생긴다.
//
// ── 왜 `sky.js` 를 안 고치고 여기서 덮는가 ──────────────────────────────────
// 낮 팔레트(`sky.js` 의 `LIGHT.day.clear`)는 **라이브 오픈월드(`world.html`)와 공유하는
// 파일**이다. 거기를 고치면 감독이 지시하지 않은 라이브 화면까지 함께 바뀐다.
// 감독 지시는 *"월드2"* 였다.
//
// 그래서 world2 쪽에서 얹는다. `applyNightFloor` 가 밤에 하한을 얹는 것과 같은 자리이고,
// 그 함수는 낮이면 손대지 않고 빠져나간다 — 그 빈자리를 쓴다.
//
// ── 값은 **절대값**이다 (아래 `dayLightMix` 주석에 이유) ─────────────────────
// 매 프레임 도는 자리라 배수는 발산한다 — `night-lights.ts` 가 같은 함정을 이미 적어
// 두었고, 그 경고를 그대로 따른다.
//
// ⚠ **위 회차의 결론 절반은 2026-08-28 에 뒤집혔다.** 「광비율이 대비를 만든다」는 실측은
// 그대로 참이지만, 그때 고른 반구광 0.55 는 감독 판정으로 **1.20** 이 됐다. 경위와 내
// 규정이 왜 틀렸는지는 `DAY_HEMI_I` 주석에 있다 — 헤더만 읽고 0.55 를 복원하지 마라.

/** 낮에 쓸 조명 세기. **배수가 아니라 절대값이다**(아래 이유) */
export interface DayLightMix {
  /** `DirectionalLight.intensity` 로 대입한다 */
  sun: number;
  /** `HemisphereLight.intensity` 로 대입한다 */
  hemi: number;
}

/**
 * 낮 태양 세기. **1.30** (팔레트 0.95)
 *
 * 디자이너 판정 2026-08-02. 후보 넷을 재서 정했고, 근거는 **더 밀어도 안 는다**는 것이다
 * — 비율 2.36:1 에서 대비 56.00, 8.67:1 로 밀어도 56.63 으로 +0.63 뿐이었다. ACES
 * 톤매핑이 밝은 면을 이미 압축하고 있어서, 태양을 더 세게 밀면 늘어나는 것은 "더 밝은
 * 하이라이트" 가 아니라 **"더 많이 클리핑된 하이라이트"** 다(실측 평균이 115 까지 튀어
 * 지붕·잎이 뭉갰다).
 */
export const DAY_SUN_I = 1.3;

/**
 * 낮 반구광(천공광) 세기. **1.20** (팔레트 1.0)
 *
 * ── 이 값은 **뒤집힌 값이다** (감독 판정 2026-08-28) ────────────────────────
 * 원래 **0.55** 였고 「총량 보존」 논리로 길게 정당화돼 있었다. 감독 진단이 그 논리를
 * 통째로 겨눴다:
 *
 *   *"태양의 주광원은 동작하는데.. 주변 반사광. 실제 세상으로 보면 청공광이라고
 *   할수있겠지? 그런 역활을 하는 필라이트가 없어서. 콘트라스트가 쎄게 느겼던 것 같아."*
 *
 * 후보 셋(`?dhemi=1.1`·`1.65`·`2.2`)을 world8 라이브에 걸어 드렸고, 감독은 **링크에 없는
 * 넷째 값**을 냈다 — *"dhemi 링크들 봤어. 1.2 제일 자연스러운데"*. 1.1 과 1.65 사이를
 * 손으로 잡은 값이라 후보 선택이 아니라 **감독이 직접 정한 값**이다.
 *
 * ── 내 규정이 왜 틀렸나 ───────────────────────────────────────────────────
 * 옛 주석은 *"총량은 일부러 보존했다 — 팔레트 0.95+1.0 = 1.95, 적용 후 1.30+0.55 =
 * 1.85"* 였다. 두 군데가 틀렸다:
 *
 * ① **총량 보존은 애초에 목표가 아니었다.** 지금은 1.30+1.20 = **2.50** 으로 팔레트보다
 *    28% 밝고, 그것이 감독이 고른 화면이다. 밝아진 것은 부작용이 아니라 **그늘이 열린
 *    것**이고 눈이 보는 것은 절대 밝기가 아니라 그늘의 정보량이다 — `NIGHT_GROUND_LIFT`
 *    가 *"사람 눈은 밝기에 적응하잖아"* 로 끊긴 것과 같은 축이다.
 * ② **비(比)를 뒤집는 방향은 맞았고 「얼마나」가 틀렸다.** 팔레트 0.95:1 → 옛값
 *    **2.36:1** → 지금 **1.08:1**. 태양이 여전히 근소 우위라 방향광 대비는 남는다.
 *    2.36:1 은 대비가 센 세계가 아니라 **필라이트가 아예 없는 세계**였다. 옥외에서
 *    그림자를 채우는 것은 태양이 아니라 천공광인데, 나는 그 축을 「대비를 죽이는 것」
 *    으로만 놓고 깎았다. 대비를 만드는 방법이 **채움을 없애는 것**뿐이라고 본 것이 오진이다.
 *
 * ── 딸려 무너지는 서술 ────────────────────────────────────────────────────
 * 옛 주석의 *"반구광을 낮추면 그림자 쪽이 상대적으로 차가워지고 … 볕/그늘 색 대비가
 * 부수 효과로 따라온다"* 도 이 값에서는 성립하지 않는다. `hemiS`(하늘색) 기여가 도로
 * 커져 그늘이 **다시 푸르게 식는다** — 그런데 그것이야말로 감독이 말한 「청공광」이다.
 * 색을 따로 조율하지 않는다는 결론만 같고 **이유는 반대**다.
 *
 * ── 여기서 멈춘다 ─────────────────────────────────────────────────────────
 * `DAY_SUN_I`(1.30)는 **안 건드린다.** `?dsun=` 도 쓸 수 있다고 함께 안내했는데 감독은
 * `dhemi` 만 답했고, 진단에서 태양은 정상으로 지목됐다(*"태양의 주광원은 동작하는데"*).
 * 화면이 밝다고 느껴지면 다음 축은 톤매핑 노출이지 이 두 값이 아니다.
 *
 * ⚠ **처음에는 world2/3/5 를 안 바꿨고, world2 는 다음 회차에 따라왔다.** 그때 근거는
 * 감독이 본 것이 world8 화면이고 함께 고치면 지시받지 않은 라이브(`world.html` =
 * world2)가 같이 변한다는 것이었다 — 이 파일 헤더가 `sky.js` 를 안 고친 이유로 적어 둔
 * 바로 그 경계다. 배포 후 카드로 확대를 물었고 감독이 **「월드2도 1.2 로」** 를 골랐다.
 * **world3/world5 는 여전히 0.55 다**(behind-flag 라 감독이 본 화면이 아니다).
 */
export const DAY_HEMI_I = 1.2;

/**
 * 낮에 쓸 조명 세기. **낮이 아니면 `null`** — 그때는 아무것도 손대지 않는다.
 *
 * ── 배수가 아니라 절대값인 이유 ─────────────────────────────────────────────
 * 이 값을 소비하는 자리는 **매 프레임** 돈다. `night-lights.ts` 의 `liftNightLights` 가
 * 같은 함정을 이미 주석으로 적어 두었다 — *"배수를 곱하면 프레임마다 곱해져 발산한다.
 * 하한은 몇 번 적용해도 결과가 같아서(멱등) `sky.js` 가 값을 덮어쓰든 크로스페이드
 * 중이든 안전하다. **언제 덮어쓰는가를 알아야 하는 처방은 그 지식이 어긋나는 순간
 * 깨진다.**"*
 *
 * 배수는 그 경고에 정확히 걸린다. 절대값 대입은 하한과 마찬가지로 멱등이라 몇 번
 * 적용해도 같고, `sky.js` 의 갱신 시점을 알 필요가 없다.
 *
 * ── 낮에만 손대는 이유 ──────────────────────────────────────────────────────
 * 밤 밝기는 `applyNightFloor` 가 자기 규칙으로 이미 잡고 있다. 두 축이 같은 값을 서로
 * 다른 방향으로 당기면 **어느 쪽이 이겼는지 아무도 모르게 된다.** 노을도 제외한다 —
 * 태양이 낮게 깔릴 때 그림자가 부드러워지는 것은 물리적으로 맞는 모습이라 고칠 것이
 * 아니다(디자이너 판정).
 *
 * @param nightAmount `decide/night.ts` 의 `nightness(time)` — 낮 0 · 노을 0.4 · 밤 1
 * @param tune URL 노브로 덮어쓴 값(없으면 상수)
 */
export function dayLightMix(
  nightAmount: number, tune?: Partial<DayLightMix>,
): DayLightMix | null {
  if (nightAmount > 0) return null;
  return { sun: tune?.sun ?? DAY_SUN_I, hemi: tune?.hemi ?? DAY_HEMI_I };
}

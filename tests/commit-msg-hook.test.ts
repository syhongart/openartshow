// @vitest-environment node
//
// `scripts/githooks/commit-msg` 의 **검출력**.
//
// ── 왜 이 검사가 있나 (검수관 블로커, 3회차 재발) ───────────────────────────
// 커밋 메시지의 「테스트 N건 / M파일」이 실측과 다른 일이 세 번 났고, 두 번은 자기 신고
// **뒤에** 났다. 검수관 판정: *"권고의 효과가 실측으로 0이었다."* 그래서 훅으로 옮겼다.
//
// ⚠ **훅도 검사를 받아야 한다.** 이 저장소는 그것을 이미 값비싸게 배웠다 —
// `tests/hookify-guard.test.ts` 헤더가 적은 그 사고다: 마크다운 규칙이 아무 검사도 안
// 받아서 정규식 한 글자가 깨지자 보호가 **조용히 사라졌고**, 뮤테이션으로 재 보니
// 규칙 파일을 통째로 지워도 0 failed 였다. 그래서 여기서는 훅을 **실제로 돌린다**.
//
// ── 무엇을 재는가 ───────────────────────────────────────────────────────────
//   ① 막아야 할 것을 막는가 — 실제로 세 번 쓴 형태를 그대로 넣는다
//   ② **통과시켜야 할 것을 통과시키는가** — 오탐이 나면 커밋이 막혀 작업이 선다
//   ③ 우회로가 살아 있는가 — 탈출로 없는 차단은 오탐 한 번에 세션을 잠근다
//
// **여기서 못 재는 것**: `--no-verify`(git 이 훅을 아예 안 부른다) · 다른 표기 ·
// 보고서·PR 본문의 같은 수치. 훅은 커밋 메시지 파일 하나만 본다.

import { describe, it, expect } from 'vitest';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const HOOK = 'scripts/githooks/commit-msg';

/** 훅을 실제로 돌린다. 종료코드와 stderr 를 함께 낸다 */
function run(msg: string, env: Record<string, string> = {}): { code: number; err: string } {
  const dir = mkdtempSync(join(tmpdir(), 'cmsg-'));
  const file = join(dir, 'COMMIT_EDITMSG');
  writeFileSync(file, msg, 'utf8');
  try {
    execFileSync(HOOK, [file], { env: { ...process.env, ...env }, encoding: 'utf8', stdio: 'pipe' });
    return { code: 0, err: '' };
  } catch (e) {
    const x = e as { status?: number; stderr?: string };
    return { code: x.status ?? -1, err: x.stderr ?? '' };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe('🔴 막아야 할 것 — **실제로 세 번 쓴 표기 그대로**', () => {
  // ⚠ **첫 판본은 여기를 「내가 지어낸 형태」로 채웠고 그것이 블로커가 됐다**(검수관,
  // 2026-08-22). 지금은 `git log` 에서 뽑은 실물이다.
  //   `7551a3ab` → `게이트 8종 통과 · 테스트 4,424건 통과.`   ← `/ N파일` **없음**
  //   `d32b47c1` → `… 테스트 4,398건 / 207파일 · CI …`
  // 검수관이 권한 C1(`N건 / N파일`)은 **첫째를 못 잡는다** — 그 실측이 정규식을 A 중심으로
  // 바꾼 근거다.
  const BLOCKED = [
    '게이트 8종 통과 · 테스트 4,424건 통과. 검수관 재확인 대기.',
    '게이트 8종 통과 · 테스트 4,398건 / 207파일 · CI `verify`·`smoke`·`check` 전부 초록.',
    '게이트 8종 통과 · 테스트 4,452건 통과',                    // 1차 사고(amend 로 사라진 표기)
    '테스트 4,437건 / 208파일',
    '수정\n\n본문 여러 줄\n게이트 8종 통과 · 테스트 4417건\n\n꼬리말',
    '4,398건 / 207파일',                                        // 「테스트」 없이 결합만
  ];

  for (const msg of BLOCKED) {
    it(`차단: ${msg.split('\n')[0]!.slice(0, 44)}`, () => {
      const r = run(msg);
      expect(r.code, '★ 막아야 할 형태가 통과했다').toBe(1);
      expect(r.err, '★ 왜 막혔는지를 안 말한다 — 차단만 하면 막다른 길이다').toMatch(/차단/);
      expect(r.err, '★ 처방을 안 알려준다').toMatch(/빼라|처방/);
    });
  }

  it('🔴 차단 메시지가 **우회로를 안내한다** — 탈출로 없는 차단은 세션을 잠근다', () => {
    expect(run('테스트 4,417건').err).toMatch(/SKIP_MSG_HOOK/);
  });
});


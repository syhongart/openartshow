// @vitest-environment node
//
// **탭 개편의 정량 근거가 자기 열거와 맞는가** — 검수관 3차 권고 P-2 (2026-08-19).
//
// ── 왜 이 파일이 생겼나 ─────────────────────────────────────────────────────
// `decide/edit-tabs.ts` 헤더의 「개편 전 컨트롤 N개」는 이 개편 전체의 **유일한 정량
// 근거**다. 그런데 그 수를 **두 번 틀렸다**:
//
//   1판 «32개»  → 검수관 재검수 ⑤-a 가 반려. 바로 아래 열거를 더하면 32 가 아니었다
//   2판 «55개»  → 검수관 3차 P-2 가 반려. 열거 합은 **54** 였다. ⚠ **1판을 고치는 바로
//                 그 커밋에서 재발했다** — 사람이 손으로 더했기 때문이다
//
// 두 번 다 **산술**에서 틀렸다. 그래서 세 번째 판본은 문장을 고치는 데서 멈추지 않는다 —
// 산술을 **기계가 한다.** 이 저장소가 게이트를 `npm run gate` 하나로 만든 것과 같은
// 처방이다: 매번 손으로 조립하니 매번 다르게 틀렸고, 조립을 없애면 틀릴 자리가 없다.
//
// ── 이 파일이 **못** 재는 것 (통과를 그 근거로 쓰지 않는다) ─────────────────
// · **그 수가 참인가** — 열거의 「팔레트 10」이 실제로 10인지는 여기서 안 본다. 재려면
//   개편 전 커밋(`afb215c`)의 `panel/dom.ts` 를 jsdom 에 태워야 하고, 그 시점 모듈은
//   지금 트리와 import 경로가 갈린다. **내부 정합성만** 본다 — 그래도 두 번의 실제
//   실패는 전부 이 축에서 났다.
// · **「조작 컨트롤」의 정의** — 숨은 `input[type=file]` 을 세는가 같은 판단은 사람 몫이다.

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';

const SRC = readFileSync('frontend/js/world2/decide/edit-tabs.ts', 'utf8');

/**
 * 열거 블록만 잘라낸다 — 첫 항목(`팔레트`)이 있는 줄부터 마지막 항목(`내보내기`)이
 * 있는 줄까지. 항목 이름이 바뀌어 못 찾으면 **빨간불이 되는 것이 옳다**: 그때는 열거가
 * 개편된 것이고, 사람이 이 검사를 다시 봐야 한다.
 */
function enumBlock(): string {
  const from = SRC.indexOf('//   팔레트 ');
  const toAt = SRC.indexOf('내보내기 ', from);
  expect(from, '★ 열거의 시작(「팔레트 N」)을 못 찾았다 — 헤더가 개편됐다').toBeGreaterThan(0);
  expect(toAt, '★ 열거의 끝(「내보내기 N」)을 못 찾았다').toBeGreaterThan(from);
  return SRC.slice(from, SRC.indexOf('\n', toAt));
}

/**
 * 텍스트 안의 **모든** 수를 더한다.
 *
 * ⚠ **그래서 항목 이름에 수가 들어가면 합이 오염된다**(검수관 재확인 R3) — 지금 열거에
 * 「격자 0.5m」 같은 형태가 들어오면 `0`·`5` 가 함께 더해진다. 현재 열거에는 없고(전부
 * 「이름 + 개수」), 오염되면 **합이 안 맞아 빨간불이 되므로 조용히 통과하지는 않는다.**
 * 그때 할 일은 이 함수를 정교하게 만드는 것이 아니라 **열거에서 이름과 수를 분리**하는
 * 것이다 — 열거는 사람이 읽는 것이 먼저다.
 */
const sum = (text: string): number =>
  [...text.matchAll(/(\d+)/g)].reduce((a, m) => a + Number(m[1]), 0);

describe('★ 컨트롤 개수 — 선언한 총합과 열거가 맞는가', () => {
  it('🔴 열거의 합이 헤더가 선언한 총합과 같다 (두 번 어긋났던 그 축)', () => {
    const m = SRC.match(/\*\*조작 가능한 컨트롤 (\d+)개\*\*/);
    expect(m, '★ 총합 선언을 못 찾았다 — 「조작 가능한 컨트롤 N개」 형식이어야 한다').not.toBeNull();
    const declared = Number(m![1]);

    // 괄호 안은 **세부 내역**이라 바깥 수와 중복된다 — 먼저 걷어내고 더한다.
    const outer = sum(enumBlock().replace(/\([^)]*\)/g, ''));
    expect(outer, `🔴 열거 합 ${outer} ≠ 선언 ${declared} — 세 번째 어긋남이다`).toBe(declared);
  });

  it('🔴 괄호 안 세부 내역도 바깥 수와 맞는다 — 「팔레트 10(1+8+1)」', () => {
    // 2판이 틀린 자리는 바깥이었지만, 안쪽이 어긋나도 근거가 무너지는 것은 같다.
    const pairs = [...enumBlock().matchAll(/(\d+)\(([^)]+)\)/g)];
    expect(pairs.length, '★ 세부 내역이 하나도 없다 — 열거 형식이 바뀌었다').toBeGreaterThan(0);
    for (const p of pairs) {
      const outer = Number(p[1]);
      expect(sum(p[2]), `🔴 세부 합 ≠ ${outer} — 「${p[0]}」`).toBe(outer);
    }
  });

  it('★ 줄 수는 **컨트롤 수와 다른 단위**라고 밝힌다 — 「한 줄에 하나」가 아니다', () => {
    // 1판이 «세로로 한 줄씩 32개» 라고 두 단위를 한 문장에 뭉쳤고, 그것이 첫 반려였다.
    expect(SRC, '🔴 줄 수 단위가 헤더에서 사라졌다').toMatch(/직계 자식으로 \*\*\d+줄/);
  });
});

//   예전에는 활성 경계 수가 B(4,0.6) 이라 평균 2.4방향이었는데 이제 대부분 사거리라
//   파셀당 도로 조각이 늘었다(+4,833 = 파셀당 평균 2.6조각). 늘어난 것은 **도로뿐이다** —
//   대표 파셀 (3,-7,near) 에서 건물 3채·나무 3그루·가로등 3개의 좌표가 소수점 여섯 자리까지
//   그대로다. 도로 방향은 건물 배치의 입력이므로 위치가 바뀔 수도 있었는데, 사분면 1:1
//   배정이 방향과 무관하게 동작해 그렇지 않았다. 격자화가 도로만 건드렸다는 증거다.

// 이 파일이 증명했다. 배치를 의도적으로 바꿀 때는 이 값을 함께 갱신하는 것이 맞다 —
// 그때 갱신은 "바꿨다"는 명시적 선언이 된다.
//
// ── 갱신 이력 ────────────────────────────────────────────────────────────────
// · 28,358 → 28,193 — **중앙 광장 고정**(감독 지시 *"중앙은 중앙광장으로 하고 분수대

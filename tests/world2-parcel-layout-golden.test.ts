//   칸의 건물·도로중심 조각이 빠졌다. (b) 분수대·시계탑이 **동네 광장마다 확률 반반으로
//   서던 것을 중앙 광장에만** 세웠다 — 두 블록마다 분수대가 있으면 중앙이 특별할 이유가
//   없고, 그건 랜드마크가 아니라 가로수와 같은 반복 요소다.
//   광장 아닌 곳은 안 건드렸다는 증거는 아래 **대표 파셀 (3,-7,near) 테스트가 그대로

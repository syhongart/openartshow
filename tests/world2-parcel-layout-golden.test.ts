// 파셀 배치 골든 스냅샷 — **리팩터 안전망**.
//
// ── 왜 성질 테스트만으로는 부족한가 ──────────────────────────────────────────
// `world2-parcel-layout.test.ts`는 배치의 *성질*을 본다 — 결정론이다, tier 포함관계가
// 성립한다, 셀 경계를 안 넘는다. 그 성질들은 배치 규칙을 다시 써도 **여전히 성립한다.**
// 즉 "같은 입력 → 같은 출력"은 검사하지만 "리팩터 전후 같은 출력"은 아무도 안 본다.
//
// 그래서 구조를 바꿀 때는 그것만으로 부족하다. 난수 소비 순서가 한 번만 어긋나도 세상
// 전체가 다른 모습이 되는데, 위 테스트는 전부 통과한다. 눈으로 봐야 알고, 눈으로 보면
// "달라 보이는데 원래 저랬나?"에서 멈춘다.
//
// 여기서는 배치 결과 자체를 고정한다. 파츠 레지스트리로 옮기는 작업이 **행동 무변경**임을
// 이 파일이 증명한다. 배치를 의도적으로 바꿀 때는 이 값을 함께 갱신하는 것이 맞다 —
// 그때 갱신은 "바꿨다"는 명시적 선언이 된다.

import { describe, it, expect } from 'vitest';
import { createHash } from 'node:crypto';
import { parcelLayout, type PlacedPart } from '../frontend/js/world2/decide/parcel-layout.js';

/** 부동소수 표기 흔들림을 막으려 자릿수를 고정한다 */
function ser(p: PlacedPart): string {
  const f = (n: number) => n.toFixed(6);
  return `${p.kind}|${f(p.x)}|${f(p.z)}|${f(p.y)}|${f(p.ry)}|${f(p.sx)}|${f(p.sy)}|${f(p.sz)}|${p.tone}`;
}

const TIERS = ['near', 'mid', 'far'] as const;

/** 25×25 격자 × 3 tier. 좁은 표본은 우연히 같을 수 있다 */
function gridDigest(): { hash: string; parts: number } {
  const lines: string[] = [];
  let parts = 0;
  for (let px = -12; px <= 12; px++) {
    for (let pz = -12; pz <= 12; pz++) {
      for (const t of TIERS) {
        const placed = parcelLayout(px, pz, t);
        parts += placed.length;
        lines.push(`${px},${pz},${t}:${placed.map(ser).join(';')}`);
      }
    }
  }
  return { hash: createHash('sha256').update(lines.join('\n')).digest('hex'), parts };
}

describe('배치 골든 — 리팩터가 세상을 바꾸지 않았다', () => {
  it('25×25 격자 × 3 tier 의 배치가 고정값과 일치한다', () => {
    const { hash, parts } = gridDigest();
    // 해시가 어긋나면 무엇이 달라졌는지 알 수 없으므로, 파츠 총수를 함께 본다 —
    // "개수가 같은데 해시만 다르다"와 "개수부터 다르다"는 원인이 전혀 다르다.
    expect(parts).toBe(15660);
    expect(hash).toBe('6a3d7a387ed2973926ed6cc72c108b0141b3a56add91c31b13c2bae6253519f8');
  });

  // 해시 불일치는 "어딘가 다르다"까지만 말해준다. 한 파셀을 통째로 박아 두면
  // 실패했을 때 **어느 필드가 어떻게** 달라졌는지 diff 로 바로 읽힌다.
  it('대표 파셀 (3,-7,near) 의 배치가 항목까지 일치한다', () => {
    expect(parcelLayout(3, -7, 'near').map(ser)).toEqual([
      'ground|0.000000|0.000000|0.000000|0.000000|32.000000|0.100000|32.000000|1',
      'building|5.828020|5.601782|0.000000|1.570796|5.357569|13.268912|5.675308|0',
      'building|-7.506766|-3.550875|0.000000|0.000000|5.925041|18.303893|6.831725|3',
      'building|-1.911656|6.132247|0.000000|0.000000|5.692229|17.587753|7.748437|0',
      'building|4.749412|2.138962|0.000000|3.141593|5.853057|10.462601|3.686781|0',
      'building|-4.998916|1.795105|0.000000|0.000000|4.858752|18.808860|7.237231|3',
      'tree|-7.917445|-3.108276|0.000000|0.000000|1.035126|1.591620|1.035126|1',
      'tree|4.093893|-2.521831|0.000000|0.000000|1.378102|2.197229|1.378102|1',
      'tree|-8.778767|5.820699|0.000000|3.141593|1.418147|2.207026|1.418147|1',
      'lamp|4.074909|-1.861691|0.000000|4.712389|1.000000|1.000000|1.000000|0',
      'lamp|-9.908131|3.729157|0.000000|1.570796|1.000000|1.000000|1.000000|0',
      'lamp|-0.809118|-2.805790|0.000000|0.000000|1.000000|1.000000|1.000000|0',
    ]);
  });
});
